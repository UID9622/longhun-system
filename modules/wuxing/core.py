# ═ 指令① · 五行强度权重计分 ═
def 计算五行强度(四柱: dict) -> dict:
    """
    输入：{"年柱":{"天干":"甲","地支":"子"}, "月柱":..., "日柱":..., "时柱":...}
    输出：{五行得分, 最强, 最弱, 均衡指数, 缺失五行}
    """
    得分: dict[str, float] = {"金": 0.0, "木": 0.0, "水": 0.0, "火": 0.0, "土": 0.0}
    for 柱位, 干支 in 四柱.items():
        权重 = 位置权重表[柱位]
        天干 = 干支.get("天干", "")
        地支 = 干支.get("地支", "")
        if 天干 in 天干五行表:
            得分[天干五行表[天干]] += 权重["天干"]
        if 地支 in 地支五行表:
            得分[地支五行表[地支]] += 权重["地支"]
    总分 = sum(得分.values())
    均值 = 总分 / 5 if 总分 else 0.0
    方差 = sum((v - 均值) ** 2 for v in 得分.values()) / 5
    均衡指数 = max(0.0, round(1.0 - (方差 ** 0.5) / (均值 + 0.001), 3))
    缺失 = [k for k, v in 得分.items() if v == 0.0]
    return {
        "五行得分": 得分,
        "最强": max(得分, key=得分.get),
        "最弱": min(得分, key=得分.get),
        "均衡指数": 均衡指数,
        "缺失五行": 缺失,
    }


# ═ 指令② · 五行动态链路分析 ═
def 完整链路分析(得分: dict) -> dict:
    """
    输入：五行得分字典
    输出：{链路健康度(0-100), 状态, 断链预警[]}
    """
    相生顺序 = ["金", "水", "木", "火", "土"]
    断链预警: list[str] = []
    健康度 = 100
    for i in range(5):
        来源 = 相生顺序[i]
        目标 = 相生顺序[(i + 1) % 5]
        if 得分.get(来源, 0) > 0 and 得分.get(目标, 0) == 0:
            断链预警.append(f"🔴 断链：{来源}({得分[来源]:.1f})有力但生不出{目标}(0分)·循环裂断")
            健康度 -= BREAK_PENALTY
    总分 = sum(得分.values()) + 0.001
    for 五行名, 分值 in 得分.items():
        if 分值 / 总分 > OVERWHELM_THRESHOLD:
            断链预警.append(f"🟡 过旺：{五行名}占{分值/总分:.0%}·需疏导→引生{五行相生[五行名]}")
            健康度 -= OVERWHELM_PENALTY
    链路健康度 = max(0, 健康度)
    状态 = ("🟢 健康" if 链路健康度 >= 80
               else ("🟡 待关注" if 链路健康度 >= 50 else "🔴 需干预"))
    return {"链路健康度": 链路健康度, "状态": 状态, "断链预警": 断链预警}


# ═ H分项内部计算 ═
def _归一化(v) -> float:
    if v is None: return 0.0
    return max(0.0, min(1.0, v / 100.0 if v > 1 else float(v)))

def _克制衡分(得分: dict) -> float:
    总 = sum(得分.values()) + 0.001
    过旺 = [(k, v) for k, v in 得分.items() if v / 总 > OVERWHELM_THRESHOLD]
    if not 过旺: return 1.0
    命中 = sum(
        1 for 元, _ in 过旺
        if (next((s for s, t in 五行相克.items() if t == 元), None) or "") and
           得分.get(next((s for s, t in 五行相克.items() if t == 元), ""), 0) > 0
    )
    return round(命中 / len(过旺), 3)

def _疏导分(得分: dict) -> float:
    总 = sum(得分.values()) + 0.001
    过旺 = [(k, v) for k, v in 得分.items() if v / 总 > OVERWHELM_THRESHOLD]
    if not 过旺: return 1.0
    命中 = sum(1 for 元, _ in 过旺 if 得分.get(五行相生[元], 0) > 0)
    return round(命中 / len(过旺), 3)

def _补益分(强度: dict) -> float:
    n = len(强度.get("缺失五行", []))
    return 1.0 if n == 0 else round(max(0.0, 1.0 - n / 5.0), 3)


# ═ 指令②.5 · 五行对冲指数 H（焊死公式） ═
def 计算五行对冲指数(强度结果: dict, 链路结果: dict) -> dict:
    """
    H = 克制衡x0.30 + 疏导x0.25 + 补益x0.20 + 均衡x0.15 + 链路x0.10
    🟢 H>=0.80 / 🟡 0.50<=H<0.80 / 🔴 H<0.50
    """
    d = 强度结果["五行得分"]
    克 = _克制衡分(d)
    疏 = _疏导分(d)
    补 = _补益分(强度结果)
    均 = _归一化(强度结果.get("均衡指数", 0))
    链 = _归一化(链路结果.get("链路健康度", 0))
    H = round(
        克 * H权重["克制衡分"] + 疏 * H权重["疏导分"] +
        补 * H权重["补益分"] + 均 * H权重["均衡指数"] + 链 * H权重["链路健康度"],
        3,
    )
    if H >= H_THRESHOLD_GREEN:
        三色, action = "🟢 对冲充分", "enter"
    elif H >= H_THRESHOLD_YELLOW:
        三色, action = "🟡 对冲不足，需补", "hold"
    else:
        三色, action = "🔴 对冲失败，熔断或重算", "fuse"
    return {
        "对冲指数H": H, "三色": 三色, "action": action,
        "分项": {"克制衡分": 克, "疏导分": 疏, "补益分": 补, "均衡指数": 均, "链路健康度": 链},
        "DNA追溯": "#龍芯⚡️2026-08-31-五行计算器-v4.0-WELD-UID9622",
    }


# ═ 指令③ · 四柱补益建议 ═
def 生成补益建议(强度结果: dict) -> list:
    建议: list[dict] = []
    for 五行名 in 强度结果["缺失五行"]:
        补 = 五行补益表[五行名]
        建议.append({"级别": "🔴 紧急补", "五行": 五行名,
                      "颜色": "·".join(补["颜色"]), "方位": 补["方位"],
                      "数字": str(补["数字"]), "行动": 补["建议"], "龍魂": 补["龍魂映射"]})
    最弱 = 强度结果["最弱"]
    if 最弱 not in 强度结果["缺失五行"]:
        补 = 五行补益表[最弱]
        建议.append({"级别": "🟡 建议补", "五行": 最弱,
                      "颜色": "·".join(补["颜色"]), "方位": 补["方位"],
                      "数字": str(补["数字"]), "行动": 补["建议"], "龍魂": 补["龍魂映射"]})
    最强 = 强度结果["最强"]
    总 = sum(强度结果["五行得分"].values()) + 0.001
    if 强度结果["五行得分"][最强] / 总 > OVERWHELM_THRESHOLD:
        目 = 五行相生[最强]
        补 = 五行补益表[目]
        建议.append({"级别": "🟢 疏导", "五行": f"{最强}（过旺→引生{目}）",
                      "颜色": "·".join(补["颜色"]), "方位": 补["方位"],
                      "数字": str(补["数字"]), "行动": f"{最强}过旺·{补['建议']}",
                      "龍魂": 补["龍魂映射"]})
    return 建议


