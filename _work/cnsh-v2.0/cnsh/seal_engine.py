def 計算數字根(文本: str) -> int:
    """提取數字相加·無數字則用 md5·遞歸求 dr"""
    數字 = [int(c) for c in 文本 if c.isdigit()]
    if not 數字:
        h = hashlib.md5(文本.encode("utf-8")).hexdigest()
        數字 = [int(c, 16) for c in h]
    總和 = sum(數字)
    while 總和 >= 10:
        總和 = sum(int(c) for c in str(總和))
    return 總和


