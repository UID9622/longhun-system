def match_policy(user_types: list[Any], user_crowds: list[Any], user_funds: list[Any]) -> list[Any]:
    """按 行业/人群/资金 维度匹配政策（LIB级）"""
    tags = set(user_types) | set(user_crowds) | set(user_funds)
    out = []
    for p in POLICY_LIB:
        if set(p["who"]) & tags:
            out.append(p)
    return out


def match_custom(location_text: str) -> dict[str, Any]:
    """按地区关键词匹配地域风俗（LIB级）"""
    for c in CUSTOM_LIB:
        if any(k in location_text for k in c["kw"]):
            return c
    return {"name": "通用·未识别具体地域",
            "taste": "请以实地调研为准，系统未识别到明确地域关键词。",
            "rest": "—", "custom": "—",
            "basis": "未匹配地域库", "ref": "—"}


