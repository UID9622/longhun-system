/** 同义词扩展：检索时一并计分 */
export function scoreEntry(entry: KnowledgeEntry, question: string): number {
  const q = question.toLowerCase()
  let score = 0
  for (const kw of entry.keywords) {
    if (q.includes(kw.toLowerCase())) score += 3
  }
  for (const syn of entry.synonyms) {
    if (q.includes(syn.toLowerCase())) score += 1
  }
  return score
}

/** 知识检索：关键词 + 同义词计分，返回 top3（零分不返回） */
export function searchKnowledge(question: string, top = 3): KnowledgeEntry[] {
  return KNOWLEDGE.map((e) => ({ e, s: scoreEntry(e, question) }))
    .filter((x) => x.s > 0)
    .sort((a, b) => b.s - a.s)
    .slice(0, top)
    .map((x) => x.e)
}
