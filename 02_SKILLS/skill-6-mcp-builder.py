import json
import os
from datetime import datetime
from typing import Dict, List, Optional

class MCPBuilder:
    """MCP 服务器快速构建器"""
    
    def __init__(self, name: str, version: str = "1.0.0"):
        self.name = name
        self.version = version
        self.tools: List[Dict] = []
        self.resources: List[Dict] = []
        self.created_at = datetime.now().isoformat()
    
    def add_tool(self, name: str, description: str, params: Dict = None) -> None:
        """添加工具定义"""
        tool = {
            "name": name,
            "description": description,
            "parameters": params or {},
            "created_at": datetime.now().isoformat()
        }
        self.tools.append(tool)
        print(f"✅ 工具已添加: {name}")
    
    def add_resource(self, uri: str, name: str, mime_type: str = "text/plain") -> None:
        """添加资源定义"""
        resource = {
            "uri": uri,
            "name": name,
            "mime_type": mime_type,
            "created_at": datetime.now().isoformat()
        }
        self.resources.append(resource)
        print(f"✅ 资源已添加: {uri}")
    
    def generate_server_code(self) -> str:
        """生成 FastMCP 服务器代码"""
        code = f'''#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
{self.name} MCP Server v{self.version}
Auto-generated by LongHun MCP Builder
"""

from fastmcp import Server

# 创建服务器实例
server = Server("{self.name}")

# 工具定义
'''
        
        for tool in self.tools:
            code += f'''
@server.call_tool("{tool['name']}")
async def tool_{tool['name'].replace('-', '_')}(request):
    """
    {tool['description']}
    """
    return {{"status": "success", "result": "Tool executed"}}
'''
        
        code += f'''

# 资源定义
'''
        
        for resource in self.resources:
            code += f'''
@server.read_resource("{resource['uri']}")
async def read_{resource['name'].replace('-', '_')}():
    """
    {resource['name']}
    """
    return """{resource['name']} content"""
'''
        
        code += f'''

# 服务器初始化
if __name__ == "__main__":
    print("🚀 {self.name} MCP Server started")
    print(f"📊 Tools: {len(server.tools)}")
    print(f"📁 Resources: {len(server.resources)}")
    server.run()
'''
        return code
    
    def generate_config(self) -> Dict:
        """生成 MCP 配置"""
        return {
            "name": self.name,
            "version": self.version,
            "created_at": self.created_at,
            "tools": self.tools,
            "resources": self.resources,
            "metadata": {
                "author": "LongHun MCP Builder",
                "dna": "#龍芯⚡️丙午·甲午·壬子·丙午·䷙大畜-MCP-BUILDER-v1.0",
                "status": "🟢 ready"
            }
        }
    
    def generate_requirements(self) -> str:
        """生成 requirements.txt"""
        return """fastmcp>=0.1.0
pydantic>=2.0.0
httpx>=0.24.0
"""
    
    def generate_dockerfile(self) -> str:
        """生成 Dockerfile"""
        return f"""FROM python:3.11-slim

WORKDIR /app

COPY requirements.txt .
RUN pip install -r requirements.txt

COPY . .

EXPOSE 8000

CMD ["python", "server.py"]
"""
    
    def save_project(self, output_dir: str = ".") -> None:
        """保存完整项目"""
        os.makedirs(output_dir, exist_ok=True)
        
        # 保存服务器代码
        with open(f"{output_dir}/server.py", "w", encoding="utf-8") as f:
            f.write(self.generate_server_code())
        print(f"✅ 服务器代码已保存: {output_dir}/server.py")
        
        # 保存配置
        with open(f"{output_dir}/mcp_config.json", "w", encoding="utf-8") as f:
            json.dump(self.generate_config(), f, indent=2, ensure_ascii=False)
        print(f"✅ 配置已保存: {output_dir}/mcp_config.json")
        
        # 保存 requirements
        with open(f"{output_dir}/requirements.txt", "w", encoding="utf-8") as f:
            f.write(self.generate_requirements())
        print(f"✅ 依赖已保存: {output_dir}/requirements.txt")
        
        # 保存 Dockerfile
        with open(f"{output_dir}/Dockerfile", "w", encoding="utf-8") as f:
            f.write(self.generate_dockerfile())
        print(f"✅ Dockerfile 已保存: {output_dir}/Dockerfile")
        
        # 保存 README
        readme = f"""# {self.name}

MCP Server 自动生成项目

## 快速开始

```bash
pip install -r requirements.txt
python server.py
```

## 工具列表

"""
        for tool in self.tools:
            readme += f"- **{tool['name']}**: {tool['description']}\n"
        
        readme += f"\n## 资源列表\n\n"
        for resource in self.resources:
            readme += f"- **{resource['uri']}**: {resource['name']}\n"
        
        readme += f"\n---\n\nDNA: #龍芯⚇️2026-06-07-MCP-BUILDER-v1.0\n"
        
        with open(f"{output_dir}/README.md", "w", encoding="utf-8") as f:
            f.write(readme)
        print(f"✅ README 已保存: {output_dir}/README.md")


# 示例使用
if __name__ == "__main__":
    print("🐉 龍魂 MCP 服务器构建工具 v1.0")
    print("=" * 50)
    
    # 创建构建器
    builder = MCPBuilder("longhun-mcp-service", "1.0.0")
    
    # 添加工具
    builder.add_tool(
        "execute-skill",
        "执行龍魂技能",
        {
            "skill_id": {"type": "string"},
            "params": {"type": "object"}
        }
    )
    
    builder.add_tool(
        "query-dna",
        "查询 DNA 链信息",
        {
            "query": {"type": "string"}
        }
    )
    
    builder.add_tool(
        "get-status",
        "获取系统状态"
    )
    
    # 添加资源
    builder.add_resource(
        "dna://chain",
        "DNA Chain Resource",
        "application/json"
    )
    
    builder.add_resource(
        "skills://list",
        "Skills List",
        "application/json"
    )
    
    # 显示配置
    print("\n📋 MCP 配置:")
    print(json.dumps(builder.generate_config(), indent=2, ensure_ascii=False))
    
    # 显示代码预览
    print("\n📝 服务器代码预览:")
    print(builder.generate_server_code()[:500] + "...\n")
    
    # 保存项目
    print("\n💾 保存项目...")
    builder.save_project("./longhun-mcp-service")
    
    print("\n✅ 项目创建完成！")
    print("📂 目录: ./longhun-mcp-service")
    print("🚀 运行: cd longhun-mcp-service && python server.py")
