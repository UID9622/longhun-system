#!/bin/bash
# ╔══════════════════════════════════════════════════════════════╗
# ║  龍魂系统·一键安装 v3.0                                    ║
# ║  DNA: #龍芯⚡️丙午·癸巳·癸卯·戊午·䷚颐-安装脚本-v3.0                       ║
# ╚══════════════════════════════════════════════════════════════╝

set -e

系统目录="$HOME/龍魂系统"
虚拟环境="$系统目录/运行环境"
ZSHRC="$HOME/.zshrc"
别名片段="$系统目录/快捷命令/zshrc别名片段.sh"

echo ""
echo "╔══════════════════════════════════════════════════════════════╗"
echo "║  龍魂系统·一键安装 v3.0                                    ║"
echo "╚══════════════════════════════════════════════════════════════╝"
echo ""

# ── Step 1: 目录 ──────────────────────────────────────────────
echo "📁 Step 1: 创建目录..."
mkdir -p "$系统目录/核心引擎"
mkdir -p "$系统目录/快捷命令"
mkdir -p "$系统目录/语言修正"
mkdir -p "$系统目录/协议文档/中文版"
mkdir -p "$系统目录/协议文档/English"
mkdir -p "$HOME/.cnsh/数据账本"
mkdir -p "$HOME/.cnsh/日志输出"
echo "   ✅ 完成"

# ── Step 2: 虚拟环境 ──────────────────────────────────────────
echo "🐍 Step 2: 虚拟环境..."
if [ ! -d "$虚拟环境" ]; then
    python3 -m venv "$虚拟环境"
    echo "   ✅ 已创建：$虚拟环境"
else
    echo "   ✅ 已存在，跳过"
fi
source "$虚拟环境/bin/activate"
pip install --quiet pyyaml requests 2>&1 | tail -1
echo "   ✅ 依赖安装完成"

# ── Step 3: 复制文件 ──────────────────────────────────────────
echo "📦 Step 3: 部署文件..."
脚本目录="$(cd "$(dirname "$0")" && pwd)"

for 文件 in "核心引擎/规则引擎.py" "快捷命令/启动人格代理.py" \
             "语言修正/漂移词修正器.py" "语言修正/规则导出工具.py" \
             "协议文档/中文版/龍魂协议.md" "协议文档/English/LONGHUN_PROTOCOL.md"; do
    if [ -f "$脚本目录/$文件" ]; then
        cp "$脚本目录/$文件" "$系统目录/$文件"
        echo "   ✅ $文件"
    fi
done

# ── Step 4: 写 alias ──────────────────────────────────────────
echo "⚡ Step 4: 配置快捷命令..."
cat > "$别名片段" << 'ALIASES'
# ══════════════════════════════════════════════════════
# 龍魂系统·快捷命令 v3.0
# DNA: #龍芯⚡️丙午·癸巳·癸卯·戊午·䷚颐-快捷命令-v3.0
# ══════════════════════════════════════════════════════
龍魂目录="$HOME/龍魂系统"
龍魂环境="$龍魂目录/运行环境/bin/activate"

alias 宝宝='cd "$龍魂目录" && source "$龍魂环境" && python3 快捷命令/启动人格代理.py'
alias kimi='cd "$龍魂目录" && source "$龍魂环境" && python3 语言修正/漂移词修正器.py'
alias 导航='cat "$龍魂目录/系统导航.md"'
alias 状态='cd "$龍魂目录" && source "$龍魂环境" && python3 核心引擎/规则引擎.py --report'
alias 打包='cd "$龍魂目录" && source "$龍魂环境" && python3 语言修正/规则导出工具.py'
alias 加账='cd "$龍魂目录" && source "$龍魂环境" && python3 核心引擎/规则引擎.py --add'
alias 查账='cd "$龍魂目录" && source "$龍魂环境" && python3 核心引擎/规则引擎.py --report'
alias 验链='cd "$龍魂目录" && source "$龍魂环境" && python3 核心引擎/规则引擎.py --verify'
# ══════════════════════════════════════════════════════
ALIASES

标记="# 龍魂系统·快捷命令入口"
if ! grep -q "$标记" "$ZSHRC" 2>/dev/null; then
    echo "" >> "$ZSHRC"
    echo "$标记" >> "$ZSHRC"
    echo "source \"$别名片段\"" >> "$ZSHRC"
    echo "   ✅ 已写入 ~/.zshrc"
else
    echo "   ✅ 已存在，跳过"
fi

# ── Step 5: 验证 ──────────────────────────────────────────────
echo ""
echo "🔍 Step 5: 验证..."
check() {
    [ -f "$系统目录/$1" ] && echo "   ✅ $1" || echo "   ⚠️  缺失: $1"
}
check "核心引擎/规则引擎.py"
check "快捷命令/启动人格代理.py"
check "语言修正/漂移词修正器.py"
check "语言修正/规则导出工具.py"

echo ""
echo "╔══════════════════════════════════════════════════════════════╗"
echo "║  ✅ 安装完成！                                              ║"
echo "╠══════════════════════════════════════════════════════════════╣"
echo "║  快捷命令：宝宝 / 状态 / 加账 / 查账 / 验链 / 导航 / 打包  ║"
echo "║  DNA: #龍芯⚡️丙午·癸巳·癸卯·戊午·䷚颐-安装完成-v3.0                       ║"
echo "╚══════════════════════════════════════════════════════════════╝"
