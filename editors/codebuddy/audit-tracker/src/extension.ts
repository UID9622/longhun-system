  // ── WebView ──
  showAuditView(): void {
    if (this.panel) {
      this.panel.reveal(vscode.ViewColumn.Beside);
      this.refreshWebview();
      return;
    }
    this.panel = vscode.window.createWebviewPanel(
      'longhunAudit', '龍魂 AI 代码审计日志', vscode.ViewColumn.Beside,
      { enableScripts: true, retainContextWhenHidden: true }
    );
    this.panel.onDidDispose(() => { this.panel = undefined; }, null, this.context.subscriptions);
    this.panel.webview.onDidReceiveMessage((msg) => this.handleWebviewMessage(msg), null, this.context.subscriptions);
    this.refreshWebview();
  }

  private refreshWebview(): void {
    if (!this.panel) { return; }
    this.panel.webview.html = this.buildHtml();
  }

  private handleWebviewMessage(msg: { type: string; id?: string; reason?: string }): void {
    if (!msg || typeof msg.type !== 'string') { return; }
    if (msg.type === 'markReviewed' && msg.id) {
      const e = this.entries.find((x) => x.id === msg.id);
      if (e) {
        e.reviewStatus = 'reviewed'; e.reviewTimestamp = nowIso(); e.reviewer = ATTRIBUTION;
        this.saveLog(); this.refreshWebview();
      }
    } else if (msg.type === 'markRejected' && msg.id) {
      const e = this.entries.find((x) => x.id === msg.id);
      if (e) {
        e.reviewStatus = 'rejected'; e.reviewTimestamp = nowIso(); e.reviewer = ATTRIBUTION;
        e.notes = msg.reason || undefined;
        this.saveLog(); this.refreshWebview();
      }
    } else if (msg.type === 'filter') {
      this.filter = (msg as { type: string; filter?: 'all' | ReviewStatus }).filter ?? 'all';
      this.refreshWebview();
    }
  }

