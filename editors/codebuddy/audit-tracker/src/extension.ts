function sha256(input: string): string {
  return crypto.createHash('sha256').update(input).digest('hex');
}

function nowIso(): string {
  return new Date().toISOString().replace('T', ' ').substring(0, 19);
}

function shortId(hash: string): string {
  return hash.substring(0, 8);
}

/** 逐条独立 DNA（v∞ 标准：干支四柱或 YYYY-MM-DD） */
function perEntryDna(codeHash: string): string {
  const date = new Date().toISOString().substring(0, 10);
  return `#龍芯⚡️${date}-AUDIT-TRACKER-${shortId(codeHash)}`;
}

/** 哈希链：prev_hash 由上一条决定，防篡改 */
function chainHash(codeHash: string, verdict: Verdict, prevHash: string, ts: string, confidence: number, review: ReviewStatus): string {
  // v2.0.1 加固: 纳入 timestamp/confidence/reviewStatus，改时间·改置信度·改复核状态均会破链（P77 审计）
  return sha256(`${codeHash}|${verdict}|${confidence}|${review}|${ts}|${prevHash}`).substring(0, 16);
}

/** Wilson 95% 置信区间（issue: 小样本必须附 CI） */
function wilsonCI(n: number, k: number): { low: number; high: number } {
  if (n === 0) { return { low: 0, high: 0 }; }
  const z = 1.96;
  const p = k / n;
  const z2 = z * z;
  const center = (p + z2 / (2 * n)) / (1 + z2 / n);
  const half = (z * Math.sqrt(p * (1 - p) / n + z2 / (4 * n * n))) / (1 + z2 / n);
  return { low: Math.max(0, center - half), high: Math.min(1, center + half) };
}

/** 洛书数字根（369 体系·各位相加递归到一位·P06 数学大师·议事会 v2.0） */
function luoshuRoot(value: number | string): number {
  const digits = String(value).replace(/\D/g, '');
  if (!digits) { return 0; }
  let s = digits;
  while (s.length > 1) {
    let sum = 0;
    for (const ch of s) { sum += Number(ch); }
    s = String(sum);
  }
  return Number(s);
}

/** 模型来源检测 */
function detectModelSource(text: string): string {
  const lowered = text.toLowerCase();
  for (const fp of MODEL_FINGERPRINTS) {
    for (const re of fp.patterns) {
      if (re.test(lowered)) { return fp.name; }
    }
  }
  return '未知';
}

/** 启发式三家族检测（issue: 关键词匹配/未明确判定/长度阈值） */
function detectEvidence(text: string, minChars: number, minLines: number): Evidence[] {
  const evidence: Evidence[] = [];
  // H1 关键词匹配
  const kw = AI_MARKERS.filter((m) => text.toLowerCase().includes(m.toLowerCase()));
  if (kw.length > 0) {
    evidence.push({ family: 'keyword', label: '关键词匹配', detail: `命中: ${kw.slice(0, 5).join(', ')}` });
  }
  // H2 未明确判定（中文 AI 写作特征）
  const pats = AI_PATTERNS.filter((re) => re.test(text));
  if (pats.length > 0) {
    evidence.push({ family: 'pattern', label: '未明确判定', detail: `命中模式 ${pats.length} 类` });
  }
  // H3 长度阈值（大段粘贴行为）
  const lines = text.split('\n').length;
  if (text.length > minChars || lines > minLines) {
    evidence.push({ family: 'length', label: '长度阈值', detail: `${text.length}字符/${lines}行` });
  }
  return evidence;
}

/** verdict 判定（issue: verdict 必须与 evidence 一致·未判定≠拒绝） */
function classifyVerdict(evidence: Evidence[]): { verdict: Verdict; color: ColorMark; confidence: number } {
  if (evidence.length >= 2) { return { verdict: 'confirmed', color: '🔴', confidence: 0.9 }; }
  if (evidence.length === 1) { return { verdict: 'flagged', color: '🟡', confidence: 0.6 }; }
  // v2.0.1 修复(P04): 无任何启发式命中 = clean（🟢 落库统计）· unverified 仅保留给"有行为信号但无法确证"
  return { verdict: 'clean', color: '🟢', confidence: 0.85 };
}

function colorForStatus(s: ReviewStatus): ColorMark {
  if (s === 'rejected') { return '🔴'; }
  if (s === 'reviewed') { return '🟢'; }
  return '🟡';
}

