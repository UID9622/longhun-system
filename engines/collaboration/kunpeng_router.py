def 运行测试(verbose=True):
    """12+3条测试向量"""
    路由器 = 鲲鹏路由器()
    通过 = 0
    总数 = len(测试用例)
    
    for i, (任务, 期望域) in enumerate(测试用例):
        结果 = 路由器.路由(任务)
        正确 = 结果.决策.任务域 == 期望域
        if 正确:
            通过 += 1
        
        if verbose:
            emoji = "✅" if 正确 else "❌"
            print(f"  测试{i+1:02d}/15 {emoji} 「{任务}」")
            print(f"     → {结果.决策.主人格} ({结果.决策.任务域.value})")
            print(f"     📋 {结果.决策.理由[:60]}...")
            if not 正确:
                print(f"     ⚠️ 期望={期望域.value} 实际={结果.决策.任务域.value}")
    
    print(f"\n{'='*60}")
    print(f"  路由准确率: {通过}/{总数} ({通过/总数*100:.0f}%)")
    return 通过 == 总数


