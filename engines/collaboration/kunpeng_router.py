# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

class 鲲鹏路由器:
    """共生体任务路由核心——分析任务→匹配人格→返回路由决策"""
    
    def __init__(self):
        self.版本 = "v1.0"
        self.DNA = "#龍芯⚡️丙午·乙未·丁酉·子时·☰乾-KUNPENG-ROUTER-v1.0"
    
    def 分析任务(self, 任务描述: str, 上下文: Optional[dict] = None) -> 任务域:
        """从自然语言任务描述中识别任务域"""
        if not 任务描述.strip():
            return 任务域.未知
        
        描述 = 任务描述.lower()
        
        # 1. 紧急安全检测
        for 词 in 紧急安全词:
            if 词 in 描述:
                return 任务域.安全审计
        
        # 2. 关键词计分（取最大权重，不累加，避免多关键词误判）
        得分 = {}
        for 关键词列表, 域, 权重 in 关键词域映射:
            for 词 in 关键词列表:
                if 词 in 描述:
                    得分[域] = max(得分.get(域, 0), 权重)
        
        if 得分:
            return max(得分, key=得分.get)
        
        # 3. 上下文推测
        if 上下文:
            ctx_type = 上下文.get("type", "")
            if ctx_type in ["code","工程"]:
                return 任务域.代码工程
            if ctx_type == "审计":
                return 任务域.安全审计
        
        return 任务域.未知
    
    def 路由(self, 任务描述: str, 上下文: Optional[dict] = None, 
             指定人格: Optional[str] = None) -> 路由结果:
        """
        核心路由方法
        参数:
            任务描述: 自然语言任务描述
            上下文: 可选上下文信息
            指定人格: 可选，用户指定人格则优先
        返回:
            路由结果
        """
        
        # 1. 紧急安全拦截
        描述_lower = 任务描述.lower()
        for 词 in 紧急安全词:
            if 词 in 描述_lower:
                return 路由结果(
                    决策=路由决策(
                        主人格="龍芯·黑天使",
                        副人格=["龍芯·龙盾", "龍芯·上帝之眼"],
                        理由=f"🔥 紧急安全触发词「{词}」→ 黑天使(P77)+龙盾(P72)立即响应",
                        优先级=1,
                        是否并行=True,
                        路由色=路由色.DENY if "入侵" in 词 or "泄露" in 词 else 路由色.DIRECT,
                        置信度=1.0,
                        任务域=任务域.安全审计,
                        成本层="鲲鹏"
                    ),
                    分析摘要=f"紧急安全：{词}"
                )
        
        # 2. 用户指定人格 → 直接路由
        if 指定人格:
            p = 龍芯人格.人格矩阵.get(指定人格)
            if p:
                return 路由结果(
                    决策=路由决策(
                        主人格=p["名"],
                        副人格=["龍芯·上帝之眼"],
                        理由=f"用户指定 {指定人格}({p['职能']})",
                        置信度=1.0,
                        任务域=任务域.未知,
                        成本层="本机"
                    ),
                    分析摘要=f"直接路由到 {p['名']}"
                )
        
        # 3. 任务域匹配
        域 = self.分析任务(任务描述, 上下文)
        
        # 4. 查路由表
        if 域 in 路由规则表:
            规则 = 路由规则表[域]
            主人格 = 龍芯人格.人格矩阵[规则["主"]]
            副人格_ids = 规则["副"]
            副人格_名 = [龍芯人格.人格矩阵[pid]["名"] for pid in 副人格_ids]
            
            决策 = 路由决策(
                主人格=主人格["名"],
                副人格=副人格_名,
                理由=规则["理由"],
                优先级=5,
                是否并行=域 in [任务域.安全审计, 任务域.系统巡检],
                置信度=0.85,
                任务域=域,
                成本层=规则.get("成本层", "本机")
            )
            
            return 路由结果(
                决策=决策,
                分析摘要=f"任务域「{域.value}」→ {主人格['名']}"
            )
        
        # 5. 兜底：P04 鲁班通用执行
        return 路由结果(
            决策=路由决策(
                主人格="龍芯·鲁班",
                副人格=["龍芯·上帝之眼"],
                理由="未匹配明确任务域，默认路由到通用执行(P04)+审计(P05)",
                优先级=8,
                置信度=0.5,
                任务域=任务域.未知,
                成本层="本机"
            ),
            分析摘要="兜底路由 → 龍芯·鲁班"
        )
    
    def 批量路由(self, 任务列表: List[str]) -> List[路由结果]:
        """批量任务路由"""
        return [self.路由(任务) for 任务 in 任务列表]
    
    def 统计(self, 路由结果列表: List[路由结果]) -> dict:
        """统计路由分析"""
        人格计数 = {}
        域计数 = {}
        for r in 路由结果列表:
            d = r.决策
            人格计数[d.主人格] = 人格计数.get(d.主人格, 0) + 1
            域计数[d.任务域.value] = 域计数.get(d.任务域.value, 0) + 1
        
        return {
            "总任务数": len(路由结果列表),
            "人格分布": dict(sorted(人格计数.items(), key=lambda x: x[1], reverse=True)),
            "任务域分布": dict(sorted(域计数.items(), key=lambda x: x[1], reverse=True)),
            "路由色": {
                "🟢": sum(1 for r in 路由结果列表 if r.决策.路由色 == 路由色.DIRECT),
                "🟡": sum(1 for r in 路由结果列表 if r.决策.路由色 == 路由色.CONFIRM),
                "🔴": sum(1 for r in 路由结果列表 if r.决策.路由色 == 路由色.DENY),
            },
            "成本分布": {
                "本机": sum(1 for r in 路由结果列表 if r.决策.成本层 == "本机"),
                "鲲鹏": sum(1 for r in 路由结果列表 if r.决策.成本层 == "鲲鹏"),
                "云端API": sum(1 for r in 路由结果列表 if r.决策.成本层 == "云端API"),
            }
        }
    
    def 生成DNA(self, 任务描述: str) -> str:
        """生成任务DNA追溯码"""
        时间戳 = datetime.now(timezone.utc).strftime("%Y%m%d%H%M%S")
        哈希 = hashlib.blake2b(任务描述.encode(), digest_size=4).hexdigest()
        return f"#龍芯⚡️{时间戳}-KUNPENG-ROUTE-{哈希}"


