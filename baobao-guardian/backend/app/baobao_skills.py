    def 四柱五行强度(self, 年柱天干: str = "甲", 年柱地支: str = "子",
                     月柱天干: str = "丙", 月柱地支: str = "寅",
                     日柱天干: str = "戊", 日柱地支: str = "午",
                     时柱天干: str = "庚", 时柱地支: str = "申") -> Dict[str, Any]:
        """
        四柱五行强度加权计算

        位置权重: 年柱(1.0/0.8)·月柱(1.5/1.2)·日柱(2.0/1.6)·时柱(1.2/1.0)
        日柱为本命主柱·权重最高

        Returns:
            五行得分·均衡指数·缺失五行·最强最弱
        """
        天干五行表 = {"甲": "木", "乙": "木", "丙": "火", "丁": "火", "戊": "土",
                    "己": "土", "庚": "金", "辛": "金", "壬": "水", "癸": "水"}
        地支五行表 = {"子": "水", "丑": "土", "寅": "木", "卯": "木",
                    "辰": "土", "巳": "火", "午": "火", "未": "土",
                    "申": "金", "酉": "金", "戌": "土", "亥": "水"}

        位置权重 = {
            "年柱": {"天干": 1.0, "地支": 0.8},
            "月柱": {"天干": 1.5, "地支": 1.2},
            "日柱": {"天干": 2.0, "地支": 1.6},
            "时柱": {"天干": 1.2, "地支": 1.0},
        }

        得分 = {"金": 0.0, "木": 0.0, "水": 0.0, "火": 0.0, "土": 0.0}

        # 年柱
        得分[天干五行表.get(年柱天干, "土")] += 位置权重["年柱"]["天干"]
        得分[地支五行表.get(年柱地支, "土")] += 位置权重["年柱"]["地支"]
        # 月柱
        得分[天干五行表.get(月柱天干, "土")] += 位置权重["月柱"]["天干"]
        得分[地支五行表.get(月柱地支, "土")] += 位置权重["月柱"]["地支"]
        # 日柱
        得分[天干五行表.get(日柱天干, "土")] += 位置权重["日柱"]["天干"]
        得分[地支五行表.get(日柱地支, "土")] += 位置权重["日柱"]["地支"]
        # 时柱
        得分[天干五行表.get(时柱天干, "土")] += 位置权重["时柱"]["天干"]
        得分[地支五行表.get(时柱地支, "土")] += 位置权重["时柱"]["地支"]

        总分 = sum(得分.values())
        均值 = 总分 / 5
        方差 = sum((v - 均值) ** 2 for v in 得分.values()) / 5
        均衡指数 = max(0.0, 1.0 - (方差 ** 0.5) / (均值 + 0.001))
        均衡指数 = round(均衡指数, 3)

        # 最强最弱
        排序项 = sorted(得分.items(), key=lambda x: x[1], reverse=True)
        最强 = 排序项[0][0]
        最弱 = 排序项[-1][0]
        缺失 = [k for k, v in 得分.items() if v == 0.0]

        # 健康判定
        if 均衡指数 >= 0.8:
            健康 = "🟢 五行平衡"
        elif 均衡指数 >= 0.5:
            健康 = "🟡 轻微偏颇·需调养"
        else:
            健康 = "🔴 五行失衡·急需调和"

        return {
            "四柱输入": f"年:{年柱天干}{年柱地支} 月:{月柱天干}{月柱地支} 日:{日柱天干}{日柱地支} 时:{时柱天干}{时柱地支}",
            "五行得分": {k: round(v, 2) for k, v in 得分.items()},
            "总分": round(总分, 2),
            "最强": f"{最强}({round(得分[最强], 1)})",
            "最弱": f"{最弱}({round(得分[最弱], 1)})",
            "均衡指数": 均衡指数,
            "健康状态": 健康,
            "缺失五行": 缺失 if 缺失 else "无·五行俱全",
            "哲学": "四柱定乾坤·日主为灵魂·天平地平均乃吉",
            "timestamp": datetime.now().isoformat(),
            "DNA": self.DNA,
        }

