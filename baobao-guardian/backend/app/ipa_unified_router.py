# 2. 别名→规范码 快速索引（自动构建）
# ═══════════════════════════════════════════════════════════

def _构建别名索引() -> Dict[str, str]:
    """从规范表自动构建 别名→规范码 索引"""
    索引: Dict[str, str] = {}
    for 规范码, 条目 in 人格名称规范表.items():
        for 别名 in 条目.get("所有别名", []):
            别名小写 = 别名.lower().strip()
            if 别名小写 in 索引:
                # 冲突：同一别名指向多个规范码
                existing = 索引[别名小写]
                if existing != 规范码:
                    # 保留先注册的（规范码靠前的优先）
                    pass
            else:
                索引[别名小写] = 规范码
    return 索引

_别名索引: Optional[Dict[str, str]] = None

def _获取别名索引() -> Dict[str, str]:
    global _别名索引
    if _别名索引 is None:
        _别名索引 = _构建别名索引()
    return _别名索引

