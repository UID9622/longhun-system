class 统一路由器:
    """
    IPA 统一路由器

    职责:
      1. 名称归一: 任意别名 → 规范名称
      2. 家族归属: 人格代码 → 家族层级/家族组
      3. 冲突检测: 扫描所有注册表·发现名称/归属冲突
      4. 分发执行: 技能 → 人格 → 执行
      5. 覆盖/新增策略: 有新人格时自动并入

    权威优先级（焊死）:
      龍魂家族花名册(93人格) > persona_registry.json > ipa_executor.py > AGENTS.md
    """

    DNA = "#龍芯⚡️2026-07-07-IPA-UNIFIED-ROUTER-v1.0"

    def __init__(self, 技能引擎: Any = None, persona_registry_path: Optional[Path] = None):
        self.技能引擎 = 技能引擎
        self.技能归属表 = dict(技能人格归属表)  # 可运行时扩展
        self.名称规范表 = dict(人格名称规范表)   # 可运行时扩展
        self._别名索引 = _获取别名索引()
        self._冲突记录: List[Dict[str, Any]] = []
        self._合并记录: List[Dict[str, Any]] = []

        # 加载 persona_registry.json（从文件中交叉验证）
        if persona_registry_path is None:
            persona_registry_path = Path(__file__).resolve().parent.parent.parent.parent / "persona" / "persona_registry.json"
        self._persona_registry_path = persona_registry_path
        self._persona_registry: Optional[Dict[str, Any]] = None

    # ═══════════════════════════════════════════════════════════
    # 5.1 名称归一
    # ═══════════════════════════════════════════════════════════

    def 名称归一(self, 输入名称: str) -> Dict[str, Any]:
        """
        任意别名 → 规范名称

        Args:
            输入名称: 可以是别名、简称、或规范名称本身

        Returns:
            {规范码, 规范名称, 家族层级, 家族组, 是否精确匹配}
        """
        输入小写 = 输入名称.lower().strip()
        别名索引 = _获取别名索引()

        # Step 1: 直接别名匹配
        规范码 = 别名索引.get(输入小写)
        if 规范码:
            条目 = 人格名称规范表[规范码]
            return {
                "输入": 输入名称,
                "规范码": 规范码,
                "规范名称": 条目["规范名称"],
                "家族层级": 条目["家族层级"],
                "家族组": 条目["家族组"],
                "角色": 条目.get("角色", ""),
                "所有别名": 条目.get("所有别名", []),
                "精确匹配": True,
            }

        # Step 2: 模糊匹配（子串）
        候选: List[Tuple[str, int]] = []
        for 别名, 码 in 别名索引.items():
            if 输入小写 in 别名 or 别名 in 输入小写:
                候选.append((码, len(别名)))
        if 候选:
            候选.sort(key=lambda x: x[1], reverse=True)
            最佳码 = 候选[0][0]
            条目 = 人格名称规范表[最佳码]
            return {
                "输入": 输入名称,
                "规范码": 最佳码,
                "规范名称": 条目["规范名称"],
                "家族层级": 条目["家族层级"],
                "家族组": 条目["家族组"],
                "角色": 条目.get("角色", ""),
                "所有别名": 条目.get("所有别名", []),
                "精确匹配": False,
                "匹配方式": "模糊匹配",
            }

        # Step 3: 未找到
        return {
            "输入": 输入名称,
            "规范码": None,
            "规范名称": None,
            "错误": f"未识别的名称: {输入名称}",
            "建议": "请检查名称拼写，或使用注册的人格别名",
            "可用别名总数": len(别名索引),
        }

    def 批量归一(self, 名称列表: List[str]) -> List[Dict[str, Any]]:
        """批量归一·返回每个名称的映射结果"""
        return [self.名称归一(n) for n in 名称列表]

