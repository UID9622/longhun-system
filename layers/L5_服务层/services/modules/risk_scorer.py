def scan(clauses: list[Any], full_text: str = "") -> list[Any]:
    """扫描条款列表。返回命中标签列表。"""
    hits = []
    corpus = full_text or " ".join(c["text"] for c in clauses)
    for tag, kws, level, scope, advice, law in TAG_LIB:
        for kw in kws:
            if kw in corpus:
                hits.append({
                    "tag": tag, "keyword": kw, "level": level, "scope": scope,
                    "advice": advice, "law": law,
                })
                break  # 每标签只报一次
    return hits


def score(hits: list[Any]) -> dict[str, Any]:
    red = [h for h in hits if h["level"] == "🔴"]
    yellow = [h for h in hits if h["level"] == "🟡"]
    risk_level = "🔴高危" if red else ("🟡中危" if yellow else "🟢低危")
    # 简化损失估算
    est_loss = len(red) * 12000 + len(yellow) * 3000
    return {
        "risk_level": risk_level,
        "red_count": len(red), "yellow_count": len(yellow),
        "est_loss": est_loss,
    }


