@dataclass
class 人格核心:
    """
    🧠 人格核心 - AI人格系统的基本单元

    六大人格体系:
    ┌─────────┬──────────┬──────────┬──────────┐
    │ 编号     │ 名称      │ 类型      │ 初始权重  │
    ├─────────┼──────────┼──────────┼──────────┤
    │ P01     │ 诸葛      │ 策略型    │ 0.22     │
    │ P02     │ 鲁班      │ 工程型    │ 0.18     │
    │ P03     │ 玄策      │ 风险型    │ 0.15     │
    │ P04     │ 墨子      │ 规则型    │ 0.20     │
    │ P05     │ 司命      │ 审计型    │ 0.15     │
    │ P06     │ 无名      │ 创造型    │ 0.10     │
    └─────────┴──────────┴──────────┴──────────┘
    """

    # 身份属性
    编号: 人格编号
    名称: str = ""
    类型: str = ""             # 策略型/工程型/风险型/规则型/审计型/创造型

    # 思维属性
    思维方式: 思维方式 = 思维方式.理性
    决策偏好: 决策偏好 = 决策偏好.折中
    冲突倾向: 冲突倾向 = 冲突倾向.中

    # 权重属性
    当前权重: float = 0.0       # 动态权重 (0.0 ~ 1.0)
    初始权重: float = 0.0       # 初始权重
    最低权重: float = 0.01      # 权重下限
    最高权重: float = 0.50      # 权重上限

    # 状态属性
    激活状态: bool = True
    休眠计数: int = 0           # 连续休眠次数
    失败计数: int = 0           # 连续失败次数
    成功计数: int = 0           # 连续成功次数

    # 记忆与历史
    记忆库: List[记忆片段] = field(default_factory=list)
    决策历史: List[决策记录] = field(default_factory=list)
    当前置信度: float = 0.5

    # 能力参数 (用于模拟不同人格的能力差异)
    战略视野: float = 0.5       # 0.0 ~ 1.0
    工程能力: float = 0.5
    风险感知: float = 0.5
    规则敏感度: float = 0.5
    审计严谨度: float = 0.5
    创造力指数: float = 0.5

    def __post_init__(self):
        """初始化后校验"""
        if self.初始权重 == 0.0:
            self.初始权重 = self.当前权重
        审计日志.审计(f"人格 [{self.编号.value}] {self.名称} 初始化完成，权重={self.当前权重:.2f}", "人格核心")

    def 思考(self, 任务: 任务包) -> 人格投票:
        """
        人格思考过程 - 根据任务类型和人格特性产生投票

        🟢 AI Truth Protocol: 每个人格的思考必须是确定性的
        """
        基础评分 = self._计算基础评分(任务)
        调整因子 = self._计算调整因子(任务)
        最终评分 = max(-1.0, min(1.0, 基础评分 * 调整因子))

        # 根据人格特性生成理由
        理由 = self._生成理由(任务, 最终评分)

        # 置信度与权重正相关，但受历史表现影响
        置信度 = self._计算置信度()

        return 人格投票(
            人格=self.编号,
            评分=最终评分,
            置信度=置信度,
            理由=理由,
            审计标记="🟢" if abs(最终评分) < 0.8 else "🟡"
        )

    def _计算基础评分(self, 任务: 任务包) -> float:
        """根据任务类型和人格能力计算基础评分"""
        类型匹配度 = {
            任务类型.战略推演: self.战略视野,
            任务类型.结构设计: self.工程能力,
            任务类型.风险判断: self.风险感知,
            任务类型.规则审计: self.规则敏感度,
            任务类型.质量检查: self.审计严谨度,
            任务类型.创意生成: self.创造力指数,
            任务类型.综合决策: (self.战略视野 + self.工程能力) / 2,
            任务类型.紧急响应: self.风险感知 * 0.5 + self.审计严谨度 * 0.5,
        }

        匹配度 = 类型匹配度.get(任务.任务类型, 0.5)

        # 加入人格决策偏好的影响
        偏好调整 = {
            决策偏好.激进: random.uniform(0.1, 0.5),
            决策偏好.折中: random.uniform(-0.1, 0.1),
            决策偏好.保守: random.uniform(-0.3, -0.1),
        }[self.决策偏好]

        return max(-1.0, min(1.0, (匹配度 - 0.5) * 2 + 偏好调整))

    def _计算调整因子(self, 任务: 任务包) -> float:
        """根据紧急度和复杂度调整评分"""
        紧急调整 = 1.0 + 任务.紧急度 * 0.2 if self.编号 == 人格编号.P05_司命 else 1.0
        复杂度调整 = 1.0 - 任务.复杂度 * 0.1 if self.编号 == 人格编号.P06_无名 else 1.0
        return 紧急调整 * 复杂度调整

    def _生成理由(self, 任务: 任务包, 评分: float) -> str:
        """根据人格特性生成决策理由"""
        理由模板 = {
            人格编号.P01_诸葛: f"从战略角度分析，{任务.任务描述[:20]}...的长远价值为{评分:+.2f}",
            人格编号.P02_鲁班: f"从工程实现角度，{任务.任务描述[:20]}...的可行性评分为{评分:+.2f}",
            人格编号.P03_玄策: f"风险评估结果：{任务.任务描述[:20]}...的风险等级对应评分{评分:+.2f}",
            人格编号.P04_墨子: f"规则合规性检查：{任务.任务描述[:20]}...的合规评分为{评分:+.2f}",
            人格编号.P05_司命: f"最终审计裁决：{任务.任务描述[:20]}...的综合评分为{评分:+.2f}",
            人格编号.P06_无名: f"直觉与灵感判断：{任务.任务描述[:20]}...的创造性评分为{评分:+.2f}",
        }
        return 理由模板.get(self.编号, f"综合评估：{评分:+.2f}")

    def _计算置信度(self) -> float:
        """基于历史表现计算当前置信度"""
        总决策 = self.成功计数 + self.失败计数
        if 总决策 == 0:
            return 0.5
        成功率 = self.成功计数 / 总决策
        权重因子 = self.当前权重 / max(self.初始权重, 0.01)
        return max(0.1, min(1.0, (成功率 * 0.6 + 权重因子 * 0.4)))

    def 记录决策(self, 记录: 决策记录) -> None:
        """记录决策结果到人格历史"""
        self.决策历史.append(记录)
        if len(self.决策历史) > 1000:
            self.决策历史 = self.决策历史[-800:]  # 保留最近800条

    def 添加记忆(self, 片段: 记忆片段) -> None:
        """添加记忆片段"""
        片段.关联人格 = self.编号
        self.记忆库.append(片段)
        if len(self.记忆库) > 500:
            self.记忆库 = self.记忆库[-400:]

    def 激活(self) -> None:
        """激活人格"""
        self.激活状态 = True
        self.休眠计数 = 0
        审计日志.通过(f"人格 [{self.编号.value}] {self.名称} 已激活", "人格核心")

    def 休眠(self) -> None:
        """让人格休眠"""
        self.休眠计数 += 1
        if self.休眠计数 >= 5:
            self.激活状态 = False
            审计日志.警告(f"人格 [{self.编号.value}] {self.名称} 连续休眠{self.休眠计数}次，已进入深度休眠", "人格核心")

    def 更新权重(self, 新权重: float) -> None:
        """更新当前权重（带边界限制）"""
        旧权重 = self.当前权重
        self.当前权重 = max(self.最低权重, min(self.最高权重, 新权重))
        审计日志.审计(
            f"权重调整: [{self.编号.value}] {旧权重:.3f} → {self.当前权重:.3f}",
            "人格核心"
        )

    def 序列化(self) -> Dict[str, Any]:
        """序列化为字典"""
        return {
            "编号": self.编号.value,
            "名称": self.名称,
            "类型": self.类型,
            "思维方式": self.思维方式.name,
            "决策偏好": self.决策偏好.name,
            "当前权重": round(self.当前权重, 4),
            "初始权重": self.初始权重,
            "激活状态": self.激活状态,
            "成功计数": self.成功计数,
            "失败计数": self.失败计数,
            "记忆数量": len(self.记忆库),
            "决策历史数量": len(self.决策历史),
        }


