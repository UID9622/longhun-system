class 演化引擎:
    """
    🧬 演化引擎 - 人格融合与分裂系统

    融合规则: 一致性 > 80% → 合并为新人格（如 P01+P02+P06 → P07混合型）
    分裂规则: 冲突 > 70% → 分裂（如 P06 → P06-A保守创意 + P06-B激进创意）
    创造规则: 创造性爆发 → 新人格诞生
    淘汰规则: 连续失败 → 权重归零 → 淘汰

    演化操作记录:
    - 每次融合/分裂/创造/淘汰都记录完整DNA追溯链
    """

    def __init__(self, 人格注册表: Dict[人格编号, 人格核心]):
        self.人格注册表 = 人格注册表
        self.演化历史: deque = deque(maxlen=200)
        self.已淘汰人格: List[人格核心] = []
        self.融合一致性阈值 = 0.80
        self.分裂冲突阈值 = 0.70
        self.淘汰失败阈值 = 10
        self.演化计数 = 0

        审计日志.通过("演化引擎初始化完成", "演化引擎")

    def 检测融合机会(self) -> List[Tuple[人格编号, 人格编号, float]]:
        """
        检测可以融合的人格对

        返回: [(人格A, 人格B, 一致性分数), ...]
        """
        可融合列表: List[Tuple[人格编号, 人格编号, float]] = []

        激活人格列表 = [
            (编号, 人格) for 编号, 人格 in self.人格注册表.items() 
            if 人格.激活状态
        ]

        for i, (编号A, 人格A) in enumerate(激活人格列表):
            for 编号B, 人格B in 激活人格列表[i+1:]:
                一致性 = self._计算一致性(人格A, 人格B)
                if 一致性 >= self.融合一致性阈值:
                    可融合列表.append((编号A, 编号B, 一致性))
                    审计日志.审计(
                        f"发现可融合对: [{编号A.value}]+[{编号B.value}] 一致性={一致性:.2%}",
                        "演化引擎"
                    )

        return 可融合列表

    def _计算一致性(self, 人格A: 人格核心, 人格B: 人格核心) -> float:
        """计算两个人格之间的一致性（0.0 ~ 1.0）"""
        # 思维方式一致性
        思维一致 = 1.0 if 人格A.思维方式 == 人格B.思维方式 else 0.0

        # 决策偏好一致性
        偏好一致 = 1.0 - abs(人格A.决策偏好.value - 人格B.决策偏好.value)

        # 历史投票一致性 (如果有共同决策历史)
        投票一致 = self._计算历史投票一致性(人格A, 人格B)

        # 权重相近性
        权重相近 = 1.0 - abs(人格A.当前权重 - 人格B.当前权重)

        return (思维一致 * 0.3 + 偏好一致 * 0.3 + 投票一致 * 0.2 + 权重相近 * 0.2)

    def _计算历史投票一致性(
        self, 
        人格A: 人格核心, 
        人格B: 人格核心
    ) -> float:
        """计算两个人格在历史投票中的一致性"""
        # 简化实现：基于决策偏好和能力参数的相似度
        能力差异 = abs(人格A.战略视野 - 人格B.战略视野) + \
                   abs(人格A.工程能力 - 人格B.工程能力) + \
                   abs(人格A.风险感知 - 人格B.风险感知)

        return max(0.0, 1.0 - 能力差异 / 3.0)

    def 执行融合(
        self, 
        源人格A: 人格编号, 
        源人格B: 人格编号
    ) -> Optional[人格核心]:
        """
        融合两个人格为一个新的人格

        示例: P01(策略) + P02(工程) → P07(混合策略-工程型)
        """
        人格A = self.人格注册表.get(源人格A)
        人格B = self.人格注册表.get(源人格B)

        if not 人格A or not 人格B:
            审计日志.否决("融合失败：源人格不存在", "演化引擎")
            return None

        self.演化计数 += 1
        新编号值 = f"P{7 + self.演化计数:02d}"
        新名称 = f"混{self.演化计数}"
        新类型 = f"{人格A.类型[:2]}-{人格B.类型[:2]}混合型"

        新人格 = 人格核心(
            编号=人格编号(新编号值),
            名称=新名称,
            类型=新类型,
            思维方式=人格A.思维方式 if random.random() > 0.5 else 人格B.思维方式,
            决策偏好=决策偏好.折中,  # 融合后偏向折中
            冲突倾向=冲突倾向.中,
            当前权重=人格A.当前权重 + 人格B.当前权重,
            初始权重=人格A.初始权重 + 人格B.初始权重,
            最高权重=min(人格A.最高权重 + 人格B.最高权重, 0.60),
            战略视野=max(人格A.战略视野, 人格B.战略视野) * 0.9,
            工程能力=max(人格A.工程能力, 人格B.工程能力) * 0.9,
            风险感知=max(人格A.风险感知, 人格B.风险感知) * 0.9,
            规则敏感度=max(人格A.规则敏感度, 人格B.规则敏感度) * 0.9,
            审计严谨度=max(人格A.审计严谨度, 人格B.审计严谨度) * 0.9,
            创造力指数=max(人格A.创造力指数, 人格B.创造力指数) * 0.9,
        )

        # 继承记忆
        新人格.记忆库 = (人格A.记忆库[-50:] + 人格B.记忆库[-50:]).copy()

        # 将源人格标记为融合源（休眠但保留记录）
        人格A.激活状态 = False
        人格B.激活状态 = False

        # 注册新人格
        self.人格注册表[新编号值] = 新人格  # type: ignore

        事件 = 演化事件(
            操作类型=演化操作.融合,
            源人格=[源人格A, 源人格B],
            目标人格=新编号值,  # type: ignore
            一致性=self._计算一致性(人格A, 人格B),
            触发原因=f"[{源人格A.value}]{人格A.名称} 与 [{源人格B.value}]{人格B.名称} 一致性超过阈值",
        )
        self.演化历史.append(事件)

        审计日志.通过(
            f"融合完成: [{源人格A.value}]+[{源人格B.value}] → [{新编号值}]{新名称}",
            "演化引擎"
        )
        return 新人格

    def 检测分裂需求(self, 目标人格编号: 人格编号) -> bool:
        """
        检测某个人格是否需要分裂

        分裂条件: 该人格内部冲突率 > 70%
        （通过分析该人格最近决策的方差来判断）
        """
        人格 = self.人格注册表.get(目标人格编号)
        if not 人格 or len(人格.决策历史) < 5:
            return False

        近期决策 = 人格.决策历史[-10:]
        评分列表 = [d.最终得分 for d in 近期决策]

        if len(评分列表) < 2:
            return False

        方差 = sum((x - sum(评分列表)/len(评分列表))**2 for x in 评分列表) / len(评分列表)
        冲突率 = min(1.0, 方差 * 2)  # 方差映射到冲突率

        if 冲突率 > self.分裂冲突阈值:
            审计日志.审计(
                f"[{目标人格编号.value}] 内部冲突率={冲突率:.2%}，建议分裂",
                "演化引擎"
            )
            return True

        return False

    def 执行分裂(self, 源人格编号: 人格编号) -> Optional[Tuple[人格核心, 人格核心]]:
        """
        将一个人格分裂为两个子人格

        示例: P06(创造) → P06-A保守创意 + P06-B激进创意
        """
        源人格 = self.人格注册表.get(源人格编号)
        if not 源人格:
            return None

        self.演化计数 += 1

        # 保守子人格
        保守子人格 = 人格核心(
            编号=人格编号(f"{源人格编号.value}-A"),
            名称=f"{源人格.名称}-A",
            类型=f"{源人格.类型}(保守)",
            思维方式=源人格.思维方式,
            决策偏好=决策偏好.保守,
            冲突倾向=冲突倾向.低,
            当前权重=源人格.当前权重 * 0.5,
            初始权重=源人格.初始权重 * 0.5,
            创造力指数=源人格.创造力指数 * 0.6,
            风险感知=min(1.0, 源人格.风险感知 + 0.3),
        )

        # 激进子人格
        激进子人格 = 人格核心(
            编号=人格编号(f"{源人格编号.value}-B"),
            名称=f"{源人格.名称}-B",
            类型=f"{源人格.类型}(激进)",
            思维方式=源人格.思维方式,
            决策偏好=决策偏好.激进,
            冲突倾向=冲突倾向.高,
            当前权重=源人格.当前权重 * 0.5,
            初始权重=源人格.初始权重 * 0.5,
            创造力指数=min(1.0, 源人格.创造力指数 + 0.1),
            风险感知=max(0.0, 源人格.风险感知 - 0.3),
        )

        # 源人格休眠
        源人格.激活状态 = False

        # 注册子人格
        self.人格注册表[保守子人格.编号] = 保守子人格
        self.人格注册表[激进子人格.编号] = 激进子人格

        事件 = 演化事件(
            操作类型=演化操作.分裂,
            源人格=[源人格编号],
            触发原因=f"[{源人格编号.value}] 内部冲突率过高，自动分裂",
        )
        self.演化历史.append(事件)

        审计日志.通过(
            f"分裂完成: [{源人格编号.value}] → [{保守子人格.编号.value}]+[{激进子人格.编号.value}]",
            "演化引擎"
        )
        return 保守子人格, 激进子人格

    def 检测淘汰需求(self) -> List[人格编号]:
        """检测需要淘汰的人格（连续失败过多）"""
        待淘汰: List[人格编号] = []

        for 编号, 人格 in self.人格注册表.items():
            if 人格.激活状态 and 人格.失败计数 >= self.淘汰失败阈值:
                待淘汰.append(编号)
                审计日志.警告(
                    f"[{编号.value}] {人格.名称} 连续失败{人格.失败计数}次，标记淘汰",
                    "演化引擎"
                )

        return 待淘汰

    def 执行淘汰(self, 目标编号: 人格编号) -> bool:
        """淘汰指定人格"""
        人格 = self.人格注册表.get(目标编号)
        if not 人格:
            return False

        人格.激活状态 = False
        人格.当前权重 = 0.0
        self.已淘汰人格.append(人格)

        事件 = 演化事件(
            操作类型=演化操作.淘汰,
            源人格=[目标编号],
            触发原因=f"[{目标编号.value}] {人格.名称} 连续失败{人格.失败计数}次，权重归零",
        )
        self.演化历史.append(事件)

        审计日志.否决(f"淘汰执行: [{目标编号.value}] {人格.名称} 已淘汰", "演化引擎")
        return True

    def 周期性演化检查(self) -> Dict[str, Any]:
        """
        周期性检查所有演化可能性

        返回演化报告
        """
        报告 = {
            "融合检测": [],
            "分裂检测": [],
            "淘汰检测": [],
            "执行的操作": [],
        }

        # 检测融合机会
        可融合 = self.检测融合机会()
        for A, B, 一致性 in 可融合:
            报告["融合检测"].append(f"[{A.value}]+[{B.value}] 一致性={一致性:.2%}")

        # 检测分裂需求
        for 编号 in list(self.人格注册表.keys()):
            if self.检测分裂需求(编号):
                报告["分裂检测"].append(f"[{编号.value}] 建议分裂")

        # 检测淘汰需求
        待淘汰 = self.检测淘汰需求()
        for 编号 in 待淘汰:
            报告["淘汰检测"].append(f"[{编号.value}] 标记淘汰")
            self.执行淘汰(编号)
            报告["执行的操作"].append(f"淘汰 [{编号.value}]")

        审计日志.审计(f"演化检查完成: {len(报告['执行的操作'])} 个操作执行", "演化引擎")
        return 报告

    def 获取演化统计(self) -> Dict[str, Any]:
        """获取演化历史统计"""
        操作统计 = defaultdict(int)
        for 事件 in self.演化历史:
            操作统计[事件.操作类型.name] += 1

        return {
            "演化事件总数": len(self.演化历史),
            "操作分布": dict(操作统计),
            "已淘汰人格数": len(self.已淘汰人格),
            "当前活跃人格": [
                f"{k.value}:{v.名称}" 
                for k, v in self.人格注册表.items() 
                if v.激活状态
            ],
            "融合一致性阈值": self.融合一致性阈值,
            "分裂冲突阈值": self.分裂冲突阈值,
            "淘汰失败阈值": self.淘汰失败阈值,
        }

