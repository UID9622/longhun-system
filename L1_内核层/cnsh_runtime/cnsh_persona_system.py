class 人格路由器:
    """
    🚦 PERSONA ROUTER - 任务→人格匹配系统

    路由规则:
    ┌──────────────┬─────────────────────────────┐
    │ 任务类型      │ 路由目标                     │
    ├──────────────┼─────────────────────────────┤
    │ 战略推演      │ P01 诸葛                     │
    │ 结构设计      │ P02 鲁班                     │
    │ 风险判断      │ P03 玄策                     │
    │ 规则审计      │ P04 墨子                     │
    │ 质量检查      │ P05 司命                     │
    │ 创意生成      │ P06 无名                     │
    │ 综合决策      │ 多人格协同 (P01+P02+P05)      │
    │ 紧急响应      │ P05 司命直接裁决               │
    └──────────────┴─────────────────────────────┘

    调度流程:
    输入任务 → 语义拆解 → 匹配人格 → 多人格并行执行 → 结果汇总 → 冲突检测 → 融合输出
    """

    def __init__(self, 人格注册表: Dict[人格编号, 人格核心]):
        self.人格注册表 = 人格注册表
        self.路由历史: deque = deque(maxlen=1000)
        self.默认路由组 = [
            人格编号.P01_诸葛,
            人格编号.P02_鲁班,
            人格编号.P05_司命,
        ]
        审计日志.通过("人格路由器初始化完成", "路由器")

    def 路由任务(self, 任务: 任务包) -> List[人格编号]:
        """
        将任务路由到最适合的人格组

        返回: 需要参与的人格编号列表
        """
        审计日志.审计(f"接收任务 [{任务.标识}]: {任务.任务描述[:40]}...", "路由器")

        # 如果任务指定了人格，直接使用
        if 任务.指定人格:
            审计日志.通过(f"使用指定人格: {[p.value for p in 任务.指定人格]}", "路由器")
            self._记录路由(任务, 任务.指定人格)
            return 任务.指定人格

        # 根据任务类型匹配人格
        目标人格组 = self._类型匹配(任务.任务类型)

        # 根据紧急度调整
        if 任务.紧急度 > 0.8:
            # 紧急任务加入司命
            if 人格编号.P05_司命 not in 目标人格组:
                目标人格组.append(人格编号.P05_司命)
            审计日志.警告(f"紧急任务! 路由到 {[p.value for p in 目标人格组]}", "路由器")

        # 根据复杂度调整
        if 任务.复杂度 > 0.7:
            # 复杂任务加入更多人格
            额外人格 = [人格编号.P03_玄策, 人格编号.P04_墨子]
            for p in 额外人格:
                if p not in 目标人格组:
                    目标人格组.append(p)
            审计日志.审计(f"复杂任务，扩展路由到 {[p.value for p in 目标人格组]}", "路由器")

        self._记录路由(任务, 目标人格组)
        return 目标人格组

    def _类型匹配(self, 类型: 任务类型) -> List[人格编号]:
        """基于任务类型匹配默认人格"""
        匹配表 = {
            任务类型.战略推演: [人格编号.P01_诸葛],
            任务类型.结构设计: [人格编号.P02_鲁班],
            任务类型.风险判断: [人格编号.P03_玄策],
            任务类型.规则审计: [人格编号.P04_墨子],
            任务类型.质量检查: [人格编号.P05_司命],
            任务类型.创意生成: [人格编号.P06_无名],
            任务类型.综合决策: self.默认路由组,
            任务类型.紧急响应: [人格编号.P05_司命, 人格编号.P01_诸葛],
        }
        return 匹配表.get(类型, self.默认路由组).copy()

    def 并行执行(self, 任务: 任务包) -> Dict[人格编号, 人格投票]:
        """
        多人格并行执行任务，返回各人格的投票结果

        执行流程:
        1. 路由到目标人格组
        2. 各人格独立思考
        3. 收集投票结果
        """
        目标人格组 = self.路由任务(任务)
        投票结果: Dict[人格编号, 人格投票] = {}

        审计日志.审计(f"开始并行执行，涉及{len(目标人格组)}个人格", "路由器")

        for 编号 in 目标人格组:
            人格 = self.人格注册表.get(编号)
            if 人格 and 人格.激活状态:
                投票 = 人格.思考(任务)
                投票结果[编号] = 投票
                审计日志.通过(
                    f"[{编号.value}] {人格.名称} 投票: {投票.评分:+.2f} (置信度{投票.置信度:.2f})",
                    "路由器"
                )
            else:
                审计日志.警告(f"[{编号.value}] 人格未激活或不存在", "路由器")

        return 投票结果

    def 融合输出(
        self, 
        投票结果: Dict[人格编号, 人格投票],
        权重配置: Dict[人格编号, float]
    ) -> Tuple[float, str, Dict[str, Any]]:
        """
        融合多人格的投票结果为统一输出

        返回: (综合评分, 综合结论, 详细数据)
        """
        if not 投票结果:
            审计日志.否决("无投票结果，无法融合", "路由器")
            return 0.0, "无投票结果", {}

        总权重 = 0.0
        加权总分 = 0.0
        所有理由: List[str] = []
        人格明细: Dict[str, Any] = {}

        for 编号, 投票 in 投票结果.items():
            权重 = 权重配置.get(编号, 0.1)
            有效权重 = 权重 * 投票.置信度
            加权总分 += 投票.评分 * 有效权重
            总权重 += 有效权重
            所有理由.append(f"[{编号.value}] {投票.理由}")

            人格明细[编号.value] = {
                "评分": round(投票.评分, 4),
                "置信度": round(投票.置信度, 4),
                "权重": round(权重, 4),
                "理由": 投票.理由,
                "标记": 投票.审计标记,
            }

        综合评分 = 加权总分 / 总权重 if 总权重 > 0 else 0.0

        # 生成综合结论
        if 综合评分 > 0.5:
            结论 = f"🟢 通过 (评分={综合评分:+.3f}) - 多数人格支持"
        elif 综合评分 < -0.5:
            结论 = f"🔴 否决 (评分={综合评分:+.3f}) - 多数人格反对"
        else:
            结论 = f"🟡 待定 (评分={综合评分:+.3f}) - 需进一步讨论或仲裁"

        详细 = {
            "综合评分": round(综合评分, 4),
            "参与人格数": len(投票结果),
            "总权重": round(总权重, 4),
            "人格明细": 人格明细,
            "所有理由": 所有理由,
        }

        审计日志.审计(f"融合完成: {结论}", "路由器")
        return 综合评分, 结论, 详细

    def _记录路由(self, 任务: 任务包, 目标组: List[人格编号]) -> None:
        """记录路由历史"""
        self.路由历史.append({
            "任务标识": 任务.标识,
            "任务类型": 任务.任务类型.name,
            "目标人格": [p.value for p in 目标组],
            "时间戳": time.time(),
        })

    def 获取路由统计(self) -> Dict[str, Any]:
        """获取路由统计信息"""
        if not self.路由历史:
            return {"状态": "无路由记录"}

        类型统计 = defaultdict(int)
        for 记录 in self.路由历史:
            类型统计[记录["任务类型"]] += 1

        return {
            "总路由次数": len(self.路由历史),
            "任务类型分布": dict(类型统计),
            "活跃人格": [
                p.value for p, core in self.人格注册表.items() if core.激活状态
            ],
        }

