class 冲突引擎:
    """
    ⚔️ CONFLICT ENGINE - 多人格冲突处理系统

    三种冲突处理方式:
    1. 投票制: final_score = Σ (persona_weight × opinion_score × confidence)
    2. 仲裁人格: P05（司命）= 最终裁决者
    3. 人类强制覆盖: UID9622 永远可以一票终止/一票通过

    冲突类型检测:
    - 逻辑冲突: 推理链条矛盾
    - 价值冲突: 价值判断分歧
    - 风险冲突: 风险偏好差异
    - 执行冲突: 执行路径分歧
    """

    def __init__(self, 人格注册表: Dict[人格编号, 人格核心]):
        self.人格注册表 = 人格注册表
        self.冲突历史: deque = deque(maxlen=500)
        self.人类覆盖权限者 = {"UID9622"}  # 人类终极权限持有者
        审计日志.通过("冲突引擎初始化完成", "冲突引擎")

    def 检测冲突(
        self, 
        投票结果: Dict[人格编号, 人格投票]
    ) -> Optional[冲突报告]:
        """
        检测多人格投票中是否存在冲突

        冲突判定标准: 评分差异度 > 0.6
        """
        if len(投票结果) < 2:
            return None

        所有评分 = [v.评分 for v in 投票结果.values()]
        最大评分 = max(所有评分)
        最小评分 = min(所有评分)
        差异度 = 最大评分 - 最小评分

        if 差异度 < 0.6:
            审计日志.通过(f"无显著冲突，差异度={差异度:.2f}", "冲突引擎")
            return None

        # 判定冲突类型
        冲突类型判定 = self._判定冲突类型(投票结果)

        报告 = 冲突报告(
            冲突类型=冲突类型判定,
            涉及人格=list(投票结果.keys()),
            各方观点={k: v.理由 for k, v in 投票结果.items()},
            差异度=差异度,
        )

        审计日志.警告(
            f"检测到{冲突类型判定.name}冲突! 涉及{len(投票结果)}个人格，差异度={差异度:.2f}",
            "冲突引擎"
        )
        self.冲突历史.append(报告)
        return 报告

    def _判定冲突类型(
        self, 
        投票结果: Dict[人格编号, 人格投票]
    ) -> 冲突类型:
        """根据投票模式判定冲突类型"""
        # 检查是否存在逻辑对立（评分符号相反）
        正评分 = [v for v in 投票结果.values() if v.评分 > 0.3]
        负评分 = [v for v in 投票结果.values() if v.评分 < -0.3]

        # 检查是否涉及风险相关人格
        风险人格 = {人格编号.P03_玄策, 人格编号.P06_无名}
        涉及风险 = any(p in 风险人格 for p in 投票结果.keys())

        # 检查是否涉及规则人格
        规则人格 = {人格编号.P04_墨子, 人格编号.P05_司命}
        涉及规则 = any(p in 规则人格 for p in 投票结果.keys())

        if 正评分 and 负评分 and 涉及风险:
            return 冲突类型.风险冲突
        elif 正评分 and 负评分 and 涉及规则:
            return 冲突类型.价值冲突
        elif 涉及规则:
            return 冲突类型.执行冲突
        else:
            return 冲突类型.逻辑冲突

    def 投票制解决(
        self, 
        投票结果: Dict[人格编号, 人格投票],
        权重配置: Dict[人格编号, float]
    ) -> Tuple[float, str, 冲突报告]:
        """
        方式一：投票制解决冲突

        公式: final_score = Σ (persona_weight × opinion_score × confidence) / Σ weight
        """
        审计日志.审计("启用投票制解决冲突", "冲突引擎")

        分子 = 0.0
        分母 = 0.0

        for 编号, 投票 in 投票结果.items():
            权重 = 权重配置.get(编号, 0.1)
            有效权重 = 权重 * 投票.置信度
            分子 += 投票.评分 * 有效权重
            分母 += 有效权重

        最终得分 = 分子 / 分母 if 分母 > 0 else 0.0

        报告 = 冲突报告(
            冲突类型=冲突类型.逻辑冲突,
            涉及人格=list(投票结果.keys()),
            各方观点={k: v.理由 for k, v in 投票结果.items()},
            差异度=max(v.评分 for v in 投票结果.values()) - min(v.评分 for v in 投票结果.values()),
            处理方式="投票制",
            解决结果=f"投票结果: {最终得分:+.3f}",
        )

        结论 = f"投票制裁决: 综合评分={最终得分:+.3f}"
        审计日志.通过(结论, "冲突引擎")
        return 最终得分, 结论, 报告

    def 仲裁裁决(
        self, 
        投票结果: Dict[人格编号, 人格投票],
        权重配置: Dict[人格编号, float]
    ) -> Tuple[float, str, 冲突报告]:
        """
        方式二：P05 司命作为最终仲裁者

        司命拥有1.5倍权重进行最终裁决
        """
        审计日志.审计("启用P05司命仲裁裁决", "冲突引擎")

        司命 = self.人格注册表.get(人格编号.P05_司命)
        if not 司命 or not 司命.激活状态:
            审计日志.警告("P05司命未激活，回退到投票制", "冲突引擎")
            return self.投票制解决(投票结果, 权重配置)

        # 司命重新审视所有投票
        司命投票 = 司命.思考(任务包(任务描述="仲裁裁决：综合各人格意见"))

        # 司命权重1.5倍
        司命权重 = 权重配置.get(人格编号.P05_司命, 0.15) * 1.5

        分子 = 司命投票.评分 * 司命权重 * 司命投票.置信度
        分母 = 司命权重 * 司命投票.置信度

        # 加入其他人格的意见作为参考（权重减半）
        for 编号, 投票 in 投票结果.items():
            if 编号 != 人格编号.P05_司命:
                参考权重 = 权重配置.get(编号, 0.1) * 0.5
                分子 += 投票.评分 * 参考权重 * 投票.置信度
                分母 += 参考权重 * 投票.置信度

        最终得分 = 分子 / 分母 if 分母 > 0 else 司命投票.评分

        报告 = 冲突报告(
            冲突类型=冲突类型.价值冲突,
            涉及人格=list(投票结果.keys()),
            各方观点={k: v.理由 for k, v in 投票结果.items()},
            差异度=0.0,
            处理方式="仲裁裁决(P05司命)",
            解决结果=f"仲裁结果: {最终得分:+.3f} - 司命裁决",
        )

        结论 = f"🔷 P05司命仲裁裁决: 综合评分={最终得分:+.3f}"
        审计日志.通过(结论, "冲突引擎")
        return 最终得分, 结论, 报告

    def 人类强制覆盖(
        self, 
        投票结果: Dict[人格编号, 人格投票],
        人类指令: str,
        操作者UID: str
    ) -> Tuple[float, str, 冲突报告]:
        """
        方式三：人类强制覆盖 - UID9622 永远可以一票终止/一票通过

        ⚠️ 这是最高权限，任何AI人格必须服从
        """
        审计日志.审计(f"人类指令接收: {操作者UID} - {人类指令}", "冲突引擎")

        # 验证权限
        if 操作者UID not in self.人类覆盖权限者:
            审计日志.否决(f"权限拒绝: {操作者UID} 无权强制覆盖", "冲突引擎")
            报告 = 冲突报告(处理方式="权限拒绝")
            return 0.0, f"权限拒绝: {操作者UID}", 报告

        # 解析人类指令
        指令小写 = 人类指令.lower().strip()

        if 指令小写 in ["通过", "approve", "yes", "y", "同意", "🟢"]:
            最终得分 = 1.0
            结果 = "🟢 UID9622一票通过"
        elif 指令小写 in ["否决", "reject", "no", "n", "拒绝", "终止", "🔴", "stop"]:
            最终得分 = -1.0
            结果 = "🔴 UID9622一票否决/终止"
        elif 指令小写.startswith("评分"):
            try:
                分数 = float(指令小写.replace("评分", "").strip())
                最终得分 = max(-1.0, min(1.0, 分数))
                结果 = f"UID9622指定评分: {最终得分:+.3f}"
            except ValueError:
                最终得分 = 0.0
                结果 = "指令解析失败，默认0.0"
        else:
            最终得分 = 0.5
            结果 = f"UID9622指令: {人类指令}"

        报告 = 冲突报告(
            冲突类型=冲突类型.权限冲突,
            涉及人格=list(投票结果.keys()),
            各方观点={k: v.理由 for k, v in 投票结果.items()},
            差异度=0.0,
            处理方式=f"人类强制覆盖({操作者UID})",
            解决结果=结果,
        )

        审计日志.通过(f"人类覆盖已执行: {结果}", "冲突引擎")
        return 最终得分, 结果, 报告

    def 解决冲突(
        self, 
        投票结果: Dict[人格编号, 人格投票],
        权重配置: Dict[人格编号, float],
        任务: 任务包
    ) -> Tuple[float, str, 冲突报告]:
        """
        冲突解决主入口 - 自动选择最佳解决方式

        优先级:
        1. 检查人类指令 → 人类覆盖
        2. 严重冲突(差异度>0.8) → 仲裁裁决
        3. 一般冲突 → 投票制
        """
        报告 = self.检测冲突(投票结果)
        if not 报告:
            # 无冲突，直接计算综合得分
            分数, 结论, _ = 人格路由器(list(self.人格注册表.values())).融合输出(投票结果, 权重配置)
            return 分数, 结论, 冲突报告(处理方式="无冲突直接融合")

        差异度 = 报告.差异度

        # 检查人类指令
        if 任务.人类指令:
            return self.人类强制覆盖(投票结果, 任务.人类指令, "UID9622")

        # 根据冲突严重程度选择解决方式
        if 差异度 > 0.8:
            审计日志.警告(f"严重冲突(差异度={差异度:.2f})，启用仲裁裁决", "冲突引擎")
            return self.仲裁裁决(投票结果, 权重配置)
        else:
            审计日志.审计(f"一般冲突(差异度={差异度:.2f})，启用投票制", "冲突引擎")
            return self.投票制解决(投票结果, 权重配置)

    def 获取冲突统计(self) -> Dict[str, Any]:
        """获取冲突统计"""
        if not self.冲突历史:
            return {"状态": "无冲突记录"}

        类型统计 = defaultdict(int)
        解决方式统计 = defaultdict(int)
        for 冲突 in self.冲突历史:
            类型统计[冲突.冲突类型.name] += 1
            解决方式统计[冲突.处理方式] += 1

        return {
            "总冲突数": len(self.冲突历史),
            "冲突类型分布": dict(类型统计),
            "解决方式分布": dict(解决方式统计),
            "平均差异度": round(
                sum(c.差异度 for c in self.冲突历史) / len(self.冲突历史), 4
            ),
        }

