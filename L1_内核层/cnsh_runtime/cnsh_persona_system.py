class 权重引擎:
    """
    ⚖️ 权重引擎 - 人格权重动态调整系统

    初始权重配置:
    ┌─────────┬──────────┐
    │ P01 诸葛 │ 0.22    │
    │ P02 鲁班 │ 0.18    │
    │ P03 玄策 │ 0.15    │
    │ P04 墨子 │ 0.20    │
    │ P05 司命 │ 0.15    │
    │ P06 无名 │ 0.10    │
    └─────────┴──────────┘

    调整规则:
    - 决策成功 → 权重 +0.01 ~ +0.03
    - 决策失败 → 权重 -0.02 ~ -0.05
    - 冲突胜出 → 权重 +0.02
    - 被否决   → 权重 -0.01
    - 连续成功 → 额外加成
    - 连续失败 → 加速衰减
    """

    def __init__(self, 人格注册表: Dict[人格编号, 人格核心]):
        self.人格注册表 = 人格注册表
        self.权重历史: deque = deque(maxlen=500)
        self.调整记录: deque = deque(maxlen=1000)

        # 调整参数
        self.成功增量 = 0.02
        self.失败减量 = 0.03
        self.冲突胜出增量 = 0.015
        self.被否决减量 = 0.01
        self.连续成功加成 = 0.01
        self.连续失败惩罚 = 0.02

        # 权重归一化阈值
        self.归一化阈值 = 0.02

        审计日志.通过("权重引擎初始化完成", "权重引擎")

    def 获取当前权重配置(self) -> Dict[人格编号, float]:
        """获取当前所有人格的权重配置"""
        return {
            编号: 人格.当前权重 
            for 编号, 人格 in self.人格注册表.items() 
            if 人格.激活状态
        }

    def 决策成功(self, 人格编号值: 人格编号) -> None:
        """决策成功 → 权重↑"""
        人格 = self.人格注册表.get(人格编号值)
        if not 人格:
            return

        增量 = self.成功增量
        if 人格.成功计数 >= 3:
            增量 += self.连续成功_bonus(人格.成功计数)

        旧权重 = 人格.当前权重
        人格.成功计数 += 1
        人格.失败计数 = 0
        人格.更新权重(旧权重 + 增量)

        self._记录调整(人格编号值, 旧权重, 人格.当前权重, "决策成功")
        审计日志.通过(f"[{人格编号值.value}] 决策成功，权重 {旧权重:.3f} → {人格.当前权重:.3f}", "权重引擎")

    def 决策失败(self, 人格编号值: 人格编号) -> None:
        """决策失败 → 权重↓"""
        人格 = self.人格注册表.get(人格编号值)
        if not 人格:
            return

        减量 = self.失败减量
        if 人格.失败计数 >= 3:
            减量 += self.连续失败惩罚

        旧权重 = 人格.当前权重
        人格.失败计数 += 1
        人格.成功计数 = 0
        人格.更新权重(旧权重 - 减量)

        self._记录调整(人格编号值, 旧权重, 人格.当前权重, "决策失败")
        审计日志.否决(f"[{人格编号值.value}] 决策失败，权重 {旧权重:.3f} → {人格.当前权重:.3f}", "权重引擎")

    def 冲突胜出(self, 人格编号值: 人格编号) -> None:
        """冲突中胜出 → 权重↑"""
        人格 = self.人格注册表.get(人格编号值)
        if not 人格:
            return

        旧权重 = 人格.当前权重
        人格.更新权重(旧权重 + self.冲突胜出增量)
        self._记录调整(人格编号值, 旧权重, 人格.当前权重, "冲突胜出")
        审计日志.通过(f"[{人格编号值.value}] 冲突胜出，权重 {旧权重:.3f} → {人格.当前权重:.3f}", "权重引擎")

    def 被否决(self, 人格编号值: 人格编号) -> None:
        """被否决 → 权重↓"""
        人格 = self.人格注册表.get(人格编号值)
        if not 人格:
            return

        旧权重 = 人格.当前权重
        人格.更新权重(旧权重 - self.被否决减量)
        self._记录调整(人格编号值, 旧权重, 人格.当前权重, "被否决")
        审计日志.警告(f"[{人格编号值.value}] 被否决，权重 {旧权重:.3f} → {人格.当前权重:.3f}", "权重引擎")

    def 连续成功_bonus(self, 连续次数: int) -> float:
        """连续成功的额外加成（递增但上限）"""
        return min(self.连续成功加成 * (连续次数 - 2), 0.05)

    def 权重归一化(self) -> None:
        """
        权重归一化 - 确保所有权重的和接近1.0
        只调整激活状态的人格
        """
        激活人格 = {
            编号: 人格 for 编号, 人格 in self.人格注册表.items() 
            if 人格.激活状态
        }

        if not 激活人格:
            return

        总权重 = sum(人格.当前权重 for 人格 in 激活人格.values())

        if abs(总权重 - 1.0) < self.归一化阈值:
            return

        归一化因子 = 1.0 / 总权重

        for 编号, 人格 in 激活人格.items():
            旧权重 = 人格.当前权重
            人格.当前权重 = max(人格.最低权重, min(人格.最高权重, 
                                      人格.当前权重 * 归一化因子))
            self._记录调整(编号, 旧权重, 人格.当前权重, "归一化")

        审计日志.审计(f"权重归一化完成: 总和 {总权重:.3f} → 1.0", "权重引擎")

    def 处理决策结果(
        self, 
        决策记录实例: 决策记录, 
        权重配置: Dict[人格编号, float]
    ) -> None:
        """
        根据决策结果批量调整权重

        分析决策记录中各人格的表现，进行相应调整
        """
        审计日志.审计(f"处理决策结果 [{决策记录实例.标识}]", "权重引擎")

        for 编号, 评分 in 决策记录实例.各人格评分.items():
            if 决策记录实例.执行结果 is True:
                # 执行成功
                if 评分 > 0.3:
                    self.决策成功(编号)
                elif 评分 < -0.3:
                    # 该人格反对但最终成功 → 轻微惩罚
                    self.被否决(编号)
            elif 决策记录实例.执行结果 is False:
                # 执行失败
                if 评分 > 0.3:
                    # 该人格支持但最终失败 → 惩罚
                    self.决策失败(编号)
                elif 评分 < -0.3:
                    # 该人格反对且确实失败 → 奖励（有预见性）
                    self.冲突胜出(编号)

        # 最后进行归一化
        self.权重归一化()

    def _记录调整(self, 编号: 人格编号, 旧值: float, 新值: float, 原因: str) -> None:
        """记录权重调整"""
        self.调整记录.append({
            "人格": 编号.value,
            "旧权重": round(旧值, 4),
            "新权重": round(新值, 4),
            "原因": 原因,
            "时间戳": time.time(),
        })

    def 获取权重报告(self) -> Dict[str, Any]:
        """获取完整的权重报告"""
        激活人格 = {k: v for k, v in self.人格注册表.items() if v.激活状态}

        return {
            "人格权重明细": {
                编号.value: {
                    "当前权重": round(人格.当前权重, 4),
                    "初始权重": 人格.初始权重,
                    "权重变化": round(人格.当前权重 - 人格.初始权重, 4),
                    "成功次数": 人格.成功计数,
                    "失败次数": 人格.失败计数,
                    "激活状态": 人格.激活状态,
                }
                for 编号, 人格 in 激活人格.items()
            },
            "总权重": round(sum(p.当前权重 for p in 激活人格.values()), 4),
            "权重调整次数": len(self.调整记录),
        }


