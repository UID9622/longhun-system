# 🟢 合規：核心矩陣定義 — 上古洛書數字排列
洛書矩陣 = [
    [4, 9, 2],
    [3, 5, 7],
    [8, 1, 6]
]

# 🟢 合規：太極常數 — 幻方魔數
太極數 = 15

# 🟢 合規：中宮數 — 宇宙中心
中宮數 = 5

# ═══════════════════════════════════════════════════
#  二、核心函數
