def 取行(矩陣, 行索引):
    """
    🟢 合規：提取指定行的元素
    【輸入】矩陣, 行索引(0-based)
    【返回】該行元素列表
    """
    return 矩陣[行索引]


def 取列(矩陣, 列索引):
    """
    🟢 合規：提取指定列的元素
    【輸入】矩陣, 列索引(0-based)
    【返回】該列元素列表
    """
    return [行[列索引] for 行 in 矩陣]


def 取主對角線(矩陣):
    """
    🟢 合規：提取主對角線（左上到右下）
    【返回】主對角線元素列表
    """
    長度 = len(矩陣)
    return [矩陣[索引][索引] for 索引 in range(長度)]


def 取副對角線(矩陣):
    """
    🟢 合規：提取副對角線（右上到左下）
    【返回】副對角線元素列表
    """
    長度 = len(矩陣)
    return [矩陣[索引][長度 - 1 - 索引] for 索引 in range(長度)]


def 計算和(數組):
    """
    🟢 合規：計算數組元素之和
    """
    return sum(數組)


def 驗證幻方(矩陣, 期望和):
    """
    🔵 安全：驗證矩陣是否為幻方
    【定理 T1】所有行之和 = 太極數
    【定理 T2】所有列之和 = 太極數
    【定理 T3】主對角線之和 = 太極數
    【定理 T4】副對角線之和 = 太極數
    【返回】(是否通過, 詳細結果字典)
    """
    維度 = len(矩陣)
    結果 = {
        "行之和": [],
        "列之和": [],
        "主對角線和": None,
        "副對角線和": None,
        "是否幻方": False
    }

    # 驗證所有行
    for 行索引 in range(維度):
        行 = 取行(矩陣, 行索引)
        行和 = 計算和(行)
        結果["行之和"].append(行和)

    # 驗證所有列
    for 列索引 in range(維度):
        列 = 取列(矩陣, 列索引)
        列和 = 計算和(列)
        結果["列之和"].append(列和)

    # 驗證對角線
    結果["主對角線和"] = 計算和(取主對角線(矩陣))
    結果["副對角線和"] = 計算和(取副對角線(矩陣))

    # 判斷是否為幻方
    所有和 = 結果["行之和"] + 結果["列之和"] + [結果["主對角線和"], 結果["副對角線和"]]
    結果["是否幻方"] = all(和 == 期望和 for 和 in 所有和)

    return 結果["是否幻方"], 結果


def 建立數字位置映射(矩陣):
    """
    🟢 合規：建立數字到位置的映射
    【定理 T5】每個數字1-9在洛書中唯一出現
    【返回】字典 {數字: (行, 列)}
    """
    映射 = {}
    for 行索引, 行 in enumerate(矩陣):
        for 列索引, 數值 in enumerate(行):
            映射[數值] = (行索引, 列索引)
    return 映射


def 獲取中宮能量(矩陣):
    """
    🟢 合規：提取中宮能量值
    【定理 T6】中宮=5，為洛書能量核心
    """
    維度 = len(矩陣)
    中心 = 維度 // 2
    return 矩陣[中心][中心]


def 計算數字根(數值):
    """
    🟢 合規：計算數字根（digital root）
    【定理 T7】dr(n) = 1 + (n-1) % 9，當n>0時
    【注意】這是369引擎的核心數學工具
    """
    if 數值 <= 0:
        return 0
    return 1 + (數值 - 1) % 9


def 分析矩陣數字根分佈(矩陣):
    """
    🟢 合規：分析矩陣所有元素的數字根分佈
    【定理 T8】洛書矩陣數字根分佈遵循369規律
    【返回】分類結果字典
    """
    三類數字 = []
    六類數字 = []
    九類數字 = []
    其他數字 = []

    for 行 in 矩陣:
        for 數值 in 行:
            根 = 計算數字根(數值)
            if 根 == 3:
                三類數字.append(數值)
            elif 根 == 6:
                六類數字.append(數值)
            elif 根 == 9:
                九類數字.append(數值)
            else:
                其他數字.append((數值, 根))

    return {
        "三數": 三類數字,
        "六數": 六類數字,
        "九數": 九類數字,
        "其他": 其他數字,
        "三六九總數": len(三類數字) + len(六類數字) + len(九類數字)
    }


def 驗證洛書四方對稱(矩陣):
    """
    🟢 合規：驗證洛書四方的對稱性
    【定理 T9】洛書四對角數字之和 = 2×中宮
    【即】4+6=10, 2+8=10, 9+1=10, 7+3=10，皆=2×5
    """
    中宮 = 獲取中宮能量(矩陣)
    對稱對 = [
        (矩陣[0][0], 矩陣[2][2]),  # 4與6
        (矩陣[0][2], 矩陣[2][0]),  # 2與8
        (矩陣[0][1], 矩陣[2][1]),  # 9與1
        (矩陣[1][0], 矩陣[1][2]),  # 3與7
    ]

    結果 = []
    for 數對 in 對稱對:
        和 = 數對[0] + 數對[1]
        是否對稱 = (和 == 2 * 中宮)
        結果.append({
            "數對": 數對,
            "和": 和,
            "預期和": 2 * 中宮,
            "是否對稱": 是否對稱
        })

    return all(項目["是否對稱"] for 項目 in 結果), 結果


