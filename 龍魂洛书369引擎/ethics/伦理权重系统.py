@dataclass
class 伦理维度权重:
    """
    单个伦理维度的权重配置
    
    属性:
        维度: 伦理维度枚举
        基础权重: 基于369规律分配的基础权重值
        当前评分: 该维度的实际评分 (0~1)
        可调节范围: 权重的上下界
    """
    维度: 伦理维度
    基础权重: float = 1.0
    当前评分: float = 0.0
    最低权重: float = 0.1
    最高权重: float = 3.0

    def __post_init__(self):
        """初始化验证 🟢"""
        if not (0 <= self.当前评分 <= 1):
            raise ValueError(f"🔴 当前评分必须在[0,1]区间，当前为{self.当前评分}")
        if not (self.最低权重 <= self.基础权重 <= self.最高权重):
            raise ValueError(f"🔴 基础权重必须在[{self.最低权重},{self.最高权重}]区间")

    @property
    def 数字根验证(self) -> int:
        """对基础权重进行数字根验证 🟢"""
        # 将权重放大100倍后取整进行数字根计算
        整数值 = int(round(self.基础权重 * 100))
        return 数字根(整数值)

    @property
    def 三色标记(self) -> str:
        """基于数字根的三色审计标记 🟢"""
        return 三色标记(self.数字根验证)

    @property
    def 加权评分(self) -> float:
        """计算加权后的评分 = 基础权重 × 当前评分 🟢"""
        return self.基础权重 * self.当前评分

    @property
    def 状态报告(self) -> Dict:
        """返回完整的状态报告 🟢"""
        return {
            "维度": self.维度.中文名,
            "英文名": self.维度.英文名,
            "描述": self.维度.描述,
            "基础权重": round(self.基础权重, 4),
            "当前评分": round(self.当前评分, 4),
            "加权评分": round(self.加权评分, 4),
            "数字根验证": self.数字根验证,
            "三色标记": self.三色标记,
        }

    def 更新评分(self, 新评分: float) -> None:
        """更新当前评分 🟢"""
        if not (0 <= 新评分 <= 1):
            raise ValueError(f"🔴 评分必须在[0,1]区间")
        self.当前评分 = 新评分

    def __repr__(self) -> str:
        return (f"伦理维度权重[{self.维度.中文名}] "
                f"权重={self.基础权重:.3f} 评分={self.当前评分:.3f} "
                f"{self.三色标记}")


