不动点集: set = {3, 6, 9}
"""369不动点集 🟢"""


def 数字根(数值: int) -> int:
    """计算数字根 — 各位数字反复相加至一位数 🟢"""
    if 数值 == 0:
        return 0
    余数 = 数值 % 9
    return 9 if 余数 == 0 else 余数


def 三色标记(数值: int) -> str:
    """
    三色审计系统核心函数
    🟢 绿色 = dr ∈ {3,6,9}（低风险，通过）
    🟡 黄色 = dr ∈ {1,2,4,5,7,8}（中风险，警告）
    🔴 红色 = dr = 0（高风险，阻断/冲突）
    """
    根 = 数字根(数值)
    if 根 in 不动点集:
        return "🟢"
    elif 根 == 0:
        return "🔴"
    else:
        return "🟡"


def 三色等级(数值: float) -> str:
    """
    连续值三色等级判定（用于0~1区间的评分）
    🟢 >= 0.7  通过
    🟡 0.3~0.7 警告
    🔴 < 0.3   阻断
    """
    if 数值 >= 0.7:
        return "🟢"
    elif 数值 >= 0.3:
        return "🟡"
    else:
        return "🔴"


