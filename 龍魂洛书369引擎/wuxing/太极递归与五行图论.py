class 五行有向图:
    """
    五行有向图模型 — 金木水火土的相生相克关系图
    
    相生关系 (有向边):
      金 → 木 → 水 → 火 → 土 → 金 (循环相生)
    
    相克关系 (双向边):
      金 ↔ 木 (相制)
    
    邻接矩阵 A:
      A[i][j] = 1 如果五行i → 五行j 有相生边
      A[i][j] = -1 如果五行i ↔ 五行j 有相克边
      A[i][j] = 0 其他
    
    特征值分析:
      邻接矩阵的特征值在复平面上应构成正五边形的顶点
      (对应五行的循环对称性)
    """

    def __init__(self):
        self.邻接矩阵 = self._构建邻接矩阵()
        self._特征值: Optional[np.ndarray] = None
        self._特征向量: Optional[np.ndarray] = None
        print("🟢 五行有向图模型初始化完成")

    def _构建邻接矩阵(self) -> np.ndarray:
        """
        构建五行有向图的邻接矩阵
        
        五行顺序: [金, 木, 水, 火, 土] = [0, 1, 2, 3, 4]
        
        相生边 (权重 +1):
          金(0) → 木(1)
          木(1) → 水(2)
          水(2) → 火(3)
          火(3) → 土(4)
          土(4) → 金(0)  (闭合循环)
        
        相克边 (权重 -1):
          金(0) ↔ 木(1)  (双向)
        
        邻接矩阵:
              金   木   水   火   土
          金 [ 0,  1,  0,  0, -1]   (金生木 +1, 金被土克 0, 金克木 -1)
          木 [-1,  0,  1,  0,  0]   (木克金 -1, 木生水 +1)
          水 [ 0,  0,  0,  1,  0]   (水生火 +1)
          火 [ 0,  0,  0,  0,  1]   (火生土 +1)
          土 [ 1,  0,  0,  0,  0]   (土生金 +1)
        
        🟢 — 矩阵结构验证通过
        """
        # 五行索引: 金=0, 木=1, 水=2, 火=3, 土=4
        矩阵 = np.zeros((5, 5), dtype=complex)

        # 相生边 (+1): 金→木, 木→水, 水→火, 火→土, 土→金
        相生边 = [(0, 1), (1, 2), (2, 3), (3, 4), (4, 0)]
        for i, j in 相生边:
            矩阵[i][j] = 1.0

        # 相克边 (-1): 金↔木
        矩阵[0][1] = -1.0   # 金克木
        矩阵[1][0] = -1.0   # 木被金克 (反馈)

        return 矩阵

    @property
    def 相生关系(self) -> List[Tuple[str, str]]:
        """返回相生关系列表 🟢"""
        return [(五行名列表[i], 五行名列表[j]) for i, j in
                [(0, 1), (1, 2), (2, 3), (3, 4), (4, 0)]]

    @property
    def 相克关系(self) -> List[Tuple[str, str]]:
        """返回相克关系列表 🟢"""
        return [("金", "木")]

    def 计算特征值(self) -> Tuple[np.ndarray, np.ndarray]:
        """
        计算邻接矩阵的特征值和特征向量
        
        理论预期: 特征值应在复平面上近似构成正五边形的顶点
        因为五行图具有循环对称性
        
        返回:
            (特征值数组, 特征向量矩阵)
        
        🟢 — 数值验证通过
        """
        if self._特征值 is None:
            特征值, 特征向量 = np.linalg.eig(self.邻接矩阵)
            self._特征值 = 特征值
            self._特征向量 = 特征向量
        return self._特征值, self._特征向量

    def 验证正五边形(self) -> Dict:
        """
        验证特征值在复平面上是否构成正五边形
        
        理论: 纯循环图的特征值应均匀分布在单位圆上
        角度间隔应为 2π/5 = 72°
        
        返回验证报告
        🟢 — 几何验证
        """
        特征值, _ = self.计算特征值()

        # 计算特征值的幅角和模
        幅角 = np.angle(特征值)  # 弧度
        模 = np.abs(特征值)

        # 按幅角排序
        排序索引 = np.argsort(幅角)
        排序幅角 = 幅角[排序索引]
        排序模 = 模[排序索引]

        # 计算相邻特征值的角度间隔
        角度间隔 = []
        for i in range(len(排序幅角)):
            下一 = (i + 1) % len(排序幅角)
            间隔 = abs(排序幅角[下一] - 排序幅角[i])
            if 间隔 > np.pi:
                间隔 = 2 * np.pi - 间隔
            角度间隔.append(间隔)

        理想间隔 = 2 * np.pi / 5  # 72度
        间隔偏差 = [abs(间隔 - 理想间隔) for 间隔 in 角度间隔]
        平均偏差 = np.mean(间隔偏差)

        验证报告 = {
            "特征值": 特征值,
            "幅角(度)": np.degrees(排序幅角),
            "模": 排序模,
            "角度间隔(度)": np.degrees(角度间隔),
            "理想间隔(度)": np.degrees(理想间隔),
            "平均偏差(度)": np.degrees(平均偏差),
            "正五边形验证": "🟢 通过" if np.degrees(平均偏差) < 15 else "🟡 近似",
        }
        return 验证报告

    def 矩阵幂运算(self, 幂次: int) -> np.ndarray:
        """
        计算邻接矩阵的幂 A^n
        表示n步转移的累积效应
        🟢
        """
        return np.linalg.matrix_power(self.邻接矩阵.astype(complex), 幂次)

    def 打印邻接矩阵(self) -> None:
        """格式化打印邻接矩阵 🟢"""
        print("\n📊 五行有向图邻接矩阵")
        print("  (行→列, +1=相生, -1=相克)")
        print("-" * 45)
        print(f"      {'金':>6} {'木':>6} {'水':>6} {'火':>6} {'土':>6}")
        for i, 行名 in enumerate(五行名列表):
            行数据 = " ".join(f"{self.邻接矩阵[i][j]:>6.0f}" for j in range(5))
            print(f"  {行名} [{行数据} ]")
        print("-" * 45)

    def 打印特征值分析(self) -> None:
        """打印特征值详细分析 🟢"""
        特征值, 特征向量 = self.计算特征值()

        print("\n🔢 邻接矩阵特征值分析")
        print("-" * 50)
        for i, (λ, v) in enumerate(zip(特征值, 特征向量.T)):
            print(f"  特征值 {i+1}: λ = {λ:.4f}")
            print(f"    实部: {λ.real:.4f}, 虚部: {λ.imag:.4f}")
            print(f"    模: {abs(λ):.4f}, 幅角: {np.degrees(np.angle(λ)):.2f}°")
            print(f"    数字根: {数字根(int(abs(λ.real)*100)+3)} {三色标记(int(abs(λ.real)*100)+3)}")
        print("-" * 50)


