class 太极递归生成器:
    """
    太极递归生成器 — 从简单基元（阴阳）递归构建复杂结构
    
    递归规则（基于易经）:
      层级0: 太极 (一元)
      层级1: 两仪 — 阴(0), 阳(1) (二元)
      层级2: 四象 — 太阴(00), 少阳(01), 少阴(10), 太阳(11) (四元)
      层级3: 八卦 — 000, 001, 010, 011, 100, 101, 110, 111 (八元)
      层级N: 2^N 种状态
    
    每个层级通过在前一层级每个元素的阴阳状态后追加0(阴)或1(阳)生成。
    
    与369的关联:
      - 层级3 (八卦) 是易经的基本单位
      - 层级6 (64卦) 是易经全书
      - 3和6都是369不动点
    """

    def __init__(self):
        self.递归历史: Dict[int, List[str]] = {}
        print("🟢 太极递归生成器初始化完成")

    def 生成层级(self, 层级: int) -> List[str]:
        """
        生成指定层级的太极递归结构
        
        参数:
            层级: 递归层级 (0=太极, 1=两仪, 2=四象, 3=八卦, ...)
        
        返回:
            该层级所有状态的二进制字符串列表
        
        🟢 — 递归算法验证通过
        """
        if 层级 < 0:
            raise ValueError("🔴 层级不能为负数")
        if 层级 == 0:
            return ["太极"]

        # 递归生成: 层级N = 层级(N-1)每个元素后追加0和1
        前层 = self.生成层级(层级 - 1) if 层级 - 1 > 0 else [""]
        当前层 = []
        for 状态 in 前层:
            当前层.append(状态 + "0")  # 追加阴
            当前层.append(状态 + "1")  # 追加阳

        self.递归历史[层级] = 当前层
        return 当前层

    def 快速生成层级(self, 层级: int) -> List[str]:
        """
        使用迭代法快速生成 (非递归实现，避免栈溢出)
        🟢
        """
        if 层级 < 0:
            raise ValueError("🔴 层级不能为负数")
        if 层级 == 0:
            return ["太极"]

        结果 = [""]
        for _ in range(层级):
            新结果 = []
            for 状态 in 结果:
                新结果.append(状态 + "0")
                新结果.append(状态 + "1")
            结果 = 新结果

        self.递归历史[层级] = 结果
        return 结果

    def 获取状态名称(self, 二进制串: str) -> str:
        """
        将二进制状态串转换为易经名称
        🟢
        """
        if 二进制串 == "太极":
            return "太极"

        长度 = len(二进制串)
        if 长度 == 1:
            return "阳" if 二进制串 == "1" else "阴"
        elif 长度 == 2:
            四象映射 = {"00": "太阴", "01": "少阳", "10": "少阴", "11": "太阳"}
            return 四象映射.get(二进制串, "未知")
        elif 长度 == 3:
            八卦映射 = {
                "000": "☷ 坤", "001": "☶ 艮", "010": "☵ 坎", "011": "☴ 巽",
                "100": "☳ 震", "101": "☲ 离", "110": "☱ 兑", "111": "☰ 乾",
            }
            return 八卦映射.get(二进制串, "未知")
        else:
            return f"六十四卦[{二进制串}]"

    def 生成到指定层级(self, 最大层级: int) -> Dict[int, List[str]]:
        """
        生成从层级0到最大层级的所有结构
        
        返回字典: {层级: [状态列表]}
        🟢
        """
        结果 = {0: ["太极"]}
        for 层 in range(1, 最大层级 + 1):
            结果[层] = self.快速生成层级(层)
        return 结果

    def 打印层级结构(self, 层级: int) -> None:
        """格式化打印指定层级的结构 🟢"""
        状态列表 = self.快速生成层级(层级)
        状态数 = len(状态列表)

        print(f"\n📐 层级 {层级} (状态数: {状态数} = 2^{层级})")
        print("-" * 50)

        for i, 状态 in enumerate(状态列表):
            名称 = self.获取状态名称(状态)
            阴计数 = 状态.count("0")
            阳计数 = 状态.count("1")
            阴阳平衡 = 三色标记(abs(阴计数 - 阳计数) + 3) if 层级 > 0 else "🟢"
            print(f"  [{i:>3}] {状态:<12} → {名称:<12} "
                  f"(阴{阴计数}/阳{阳计数}) {阴阳平衡}")

    def 递归结构分析(self, 最大层级: int = 6) -> Dict:
        """
        分析递归结构的数学特性
        
        返回:
            - 各层级状态数
            - 总状态数 (应为 2^(N+1)-1)
            - 数字根验证
        
        🟢
        """
        分析结果 = {
            "各层级状态数": {},
            "总状态数": 0,
            "数字根": 0,
            "层级验证": {},
        }

        for 层 in range(最大层级 + 1):
            状态数 = 2 ** 层 if 层 > 0 else 1
            分析结果["各层级状态数"][层] = 状态数
            分析结果["总状态数"] += 状态数

            # 369验证
            根 = 数字根(状态数)
            分析结果["层级验证"][层] = {
                "状态数": 状态数,
                "数字根": 根,
                "三色标记": 三色标记(状态数),
            }

        分析结果["数字根"] = 数字根(分析结果["总状态数"])
        分析结果["总三色标记"] = 三色标记(分析结果["总状态数"])
        return 分析结果


