def check_py():
    v = sys.version_info
    if v.major < 3 or (v.major == 3 and v.minor < 8):
        er("Python " + str(v.major) + "." + str(v.minor) + " 太低，需要 3.8+")
        sys.exit(1)
    ok("Python " + str(v.major) + "." + str(v.minor) + "." + str(v.micro) + " ✓")

def install_deps():
    deps = ["watchdog", "requests", "python-dotenv", "mcp", "httpx"]
    info("正在安装依赖...")
    for d in deps:
        try:
            mod = d.replace("python-", "").replace("-", "_")
            __import__(mod); ok(d + " 已安装")
        except ImportError:
            wr(d + " 未安装，正在安装...")
            r = subprocess.run([sys.executable, "-m", "pip", "install", d],
                             capture_output=True, text=True)
            if r.returncode == 0: ok(d + " 安装成功")
            else: er(d + " 安装失败: " + r.stderr[:100])

