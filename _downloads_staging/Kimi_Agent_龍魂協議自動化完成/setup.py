def config_kimi_mcp(sysdir):
    info("配置Kimi Code MCP...")
    paths = [Path.home() / "Library/Application Support/kimi-code/mcp-config.json",
             Path.home() / ".config/kimi-code/mcp-config.json"]
    cfg_path = None
    for p in paths:
        if p.exists(): cfg_path = p; break
    if not cfg_path:
        wr("未找到Kimi Code MCP配置文件，跳过"); return
    try:
        with open(cfg_path, "r") as f: cfg = json.load(f)
        if "mcpServers" not in cfg: cfg["mcpServers"] = {}
        mcp_path = str(sysdir / "v4_mcp_server.py")
        cfg["mcpServers"]["cnsh"] = {"command": "python3", "args": [mcp_path],
                                       "env": {"CNSH_API_URL": "http://localhost:9000"}}
        with open(cfg_path, "w") as f: json.dump(cfg, f, indent=2, ensure_ascii=False)
        ok("已添加MCP服务器 'cnsh'")
    except Exception as e: er("MCP配置失败: " + str(e))

