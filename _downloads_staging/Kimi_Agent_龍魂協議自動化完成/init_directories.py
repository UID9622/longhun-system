def 获取用户家目录() -> Path:
    """获取当前用户的家目录路径"""
    return Path.home()


def 创建目录(目录路径: Path) -> bool:
    """
    创建目录（如果不存在）
    返回: True=新创建, False=已存在
    """
    try:
        if 目录路径.exists():
            日志.warning(f"目录已存在: {目录路径}")
            return False
        目录路径.mkdir(parents=True, exist_ok=True)
        日志.info(f"✅ 创建成功: {目录路径}")
        return True
    except PermissionError as 错误:
        日志.error(f"❌ 权限不足，无法创建目录 {目录路径}: {错误}")
        return False
    except OSError as 错误:
        日志.error(f"❌ 系统错误，无法创建目录 {目录路径}: {错误}")
        return False


def 写入文件(文件路径: Path, 内容: str) -> bool:
    """写入文本文件，返回是否成功"""
    try:
        文件路径.write_text(内容, encoding='utf-8')
        日志.info(f"  📝 写入文件: {文件路径}")
        return True
    except PermissionError as 错误:
        日志.error(f"  ❌ 权限不足，无法写入 {文件路径}: {错误}")
        return False
    except OSError as 错误:
        日志.error(f"  ❌ 系统错误，无法写入 {文件路径}: {错误}")
        return False


def 获取层Gitignore(层索引: int) -> str:
    """根据层索引返回对应的.gitignore内容"""
    if 层索引 == 0:
        return GITIGNORE_L0
    elif 层索引 == 4:
        return GITIGNORE_L4
    return GITIGNORE通用


