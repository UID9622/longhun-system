def 主函数():
    解析器 = argparse.ArgumentParser(
        description="龍魂体系 · 仓储AI标准检查引擎",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
示例:
    python audit_engine.py --system "XX仓储" --version "v2.0"
    python audit_engine.py --system "XX仓储" --dimensions core,ux
    python audit_engine.py --system "XX仓储" --format json
        """
    )
    
    解析器.add_argument("--system", required=True, help="被检查系统名称")
    解析器.add_argument("--version", default="unknown", help="系统版本号")
    解析器.add_argument(
        "--dimensions",
        default="all",
        help="检查维度：all/core/integration/ux/performance/data/wenzhou"
    )
    解析器.add_argument("--output", default="./report", help="输出目录")
    解析器.add_argument("--format", default="markdown", choices=["markdown", "json", "all"], help="输出格式")
    解析器.add_argument("--mode", default="standard", choices=["standard", "longhun"], help="输出模式：standard标准模式 / longhun龍魂模式")
    
    参数 = 解析器.parse_args()
    
    # 创建维度
    全部维度 = {
        "core": 创建核心功能维度(),
        "integration": 创建系统集成维度(),
        "ux": 创建用户体验维度(),
        "performance": 创建性能压力维度(),
        "data": 创建数据分析维度(),
        "wenzhou": 创建温州合规维度()
    }
    
    # 选择维度
    if 参数.dimensions == "all":
        选中维度 = [全部维度[k] for k in ["core", "integration", "ux", "performance", "data"]]
        温州维度 = 全部维度["wenzhou"]
    elif 参数.dimensions == "wenzhou":
        选中维度 = []
        温州维度 = 全部维度["wenzhou"]
    else:
        维度键列表 = 参数.dimensions.split(",")
        选中维度 = [全部维度[k] for k in 维度键列表 if k in 全部维度 and k != "wenzhou"]
        温州维度 = 全部维度["wenzhou"] if "wenzhou" in 维度键列表 else 创建温州合规维度()
    
    # 生成报告
    os.makedirs(参数.output, exist_ok=True)
    
    if 参数.format in ("markdown", "all"):
        md报告 = 生成Markdown报告(参数.system, 参数.version, 选中维度, 温州维度, 参数.output, 参数.mode)
        md路径 = os.path.join(参数.output, f"仓储检查报告_{参数.system}_{datetime.now().strftime('%Y%m%d')}.md")
        with open(md路径, "w", encoding="utf-8") as f:
            f.write(md报告)
        print(f"✅ Markdown报告已生成: {md路径}")
    
    if 参数.format in ("json", "all"):
        json报告 = 生成JSON报告(参数.system, 参数.version, 选中维度, 温州维度)
        json路径 = os.path.join(参数.output, f"仓储检查报告_{参数.system}_{datetime.now().strftime('%Y%m%d')}.json")
        with open(json路径, "w", encoding="utf-8") as f:
            f.write(json报告)
        print(f"✅ JSON报告已生成: {json路径}")
    
    # 打印摘要
    加权总分 = sum(维度.计算得分() * 维度.权重 for 维度 in 选中维度)
    总权重 = sum(维度.权重 for 维度 in 选中维度)
    综合得分 = 加权总分 / 总权重 if 总权重 > 0 else 0
    
    print(f"\n{'='*50}")
    print(f"  龍魂体系 · 仓储AI标准检查完成")
    print(f"{'='*50}")
    print(f"  系统: {参数.system} {参数.version}")
    print(f"  综合得分: {综合得分:.1f}分")
    print(f"  评级: {生成评级(综合得分)}")
    print(f"{'='*50}")


if __name__ == "__main__":
    主函数()
