def 生成JSON报告(
    系统名: str,
    版本: str,
    维度列表: List[检查维度],
    温州维度: 检查维度
) -> str:
    
    数据 = {
        "系统名": 系统名,
        "版本": 版本,
        "检查日期": datetime.now().isoformat(),
        "DNA": 生成DNA签名(系统名, 版本),
        "维度结果": []
    }
    
    for 维度 in 维度列表:
        维度.计算得分()
        数据["维度结果"].append({
            "名称": 维度.名称,
            "权重": 维度.权重,
            "得分": round(维度.得分, 1),
            "检查项": [
                {
                    "名称": 项.名称,
                    "满分": 项.满分,
                    "得分": 项.得分,
                    "评级": 项.评级.value,
                    "风险": 项.风险等级.value
                }
                for 项 in 维度.检查项列表
            ]
        })
    
    return json.dumps(数据, ensure_ascii=False, indent=2)


