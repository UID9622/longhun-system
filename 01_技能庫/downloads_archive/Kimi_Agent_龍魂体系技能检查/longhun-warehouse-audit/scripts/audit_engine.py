def 生成Markdown报告(
    系统名: str,
    版本: str,
    维度列表: List[检查维度],
    温州维度: 检查维度,
    输出目录: str,
    模式: str = "standard"
) -> str:
    
    是龍魂模式 = (模式 == "longhun")
    DNA = 生成DNA签名(系统名, 版本) if 是龍魂模式 else f"<!-- 审计报告 · {系统名} {版本} -->"
    日期 = datetime.now().strftime("%Y-%m-%d %H:%M")
    
    # 计算综合得分
    加权总分 = 0
    总权重 = 0
    for 维度 in 维度列表:
        维度.计算得分()
        加权总分 += 维度.得分 * 维度.权重
        总权重 += 维度.权重
    
    综合得分 = 加权总分 / 总权重 if 总权重 > 0 else 0
    综合评级 = 生成评级(综合得分)
    综合色 = 生成审计色图标(综合得分)
    
