class 航标灯:
    """
    航标灯 - 数字人的方向感单元
    
    每个航标灯维护一个方向向量，指向特定的目标锚点。
    持续监测实际运行方向与预期方向的偏差，发出校正信号。
    """

    def __init__(
        self,
        航标ID: str,
        名称: str,
        初始方向: Optional[方向向量] = None,
        目标锚点: Optional[锚点] = None,
        偏差阈值: float = 0.3             # 约17度的偏差阈值
    ) -> None:
        self.航标ID = 航标ID
        self.名称 = 名称
        self.当前方向: 方向向量 = 初始方向 or 方向向量(1.0, 0.0, 0.0, 0.0)
        self.目标锚点: Optional[锚点] = 目标锚点
        self.偏差阈值: float = 偏差阈值   # 弧度
        self.状态: 航标状态 = 航标状态.正常
        self.偏差历史: List[偏差记录] = []
        self.校正信号列表: List[Dict[str, Any]] = []
        self.累计偏差: float = 0.0
        self.最后检测时间: float = time.time()
        self.方向监听器: List[Callable[[航标状态, 偏差记录], None]] = []

    @property
    def 朝向目标(self) -> 方向向量:
        """获取当前朝向目标的理想方向向量"""
        if self.目标锚点 is None:
            return 方向向量(1.0, 0.0, 0.0, 0.0)
        return self.目标锚点.坐标.归一化()

    def 检测偏差(self) -> Optional[偏差记录]:
        """
        🔴 核心架构：偏差检测
        
        比较当前方向与理想方向的偏差，
        如果超出阈值则记录偏差并更新状态。
        """
        理想方向 = self.朝向目标
        偏差角 = self.当前方向.与夹角(理想方向)

        if 偏差角 > self.偏差阈值:
            严重度 = "严重" if 偏差角 > 1.0 else "高" if 偏差角 > 0.5 else "中"
            记录 = 偏差记录(
                时间戳=time.time(),
                预期方向=理想方向,
                实际方向=方向向量(self.当前方向.x, self.当前方向.y,
                               self.当前方向.z, self.当前方向.t),
                偏差角度=偏差角,
                严重程度=严重度
            )
            self.偏差历史.append(记录)
            self.累计偏差 += 偏差角
            self.最后检测时间 = time.time()

            # 🟡 状态控制：根据偏差更新状态
            if 偏差角 > 1.0:  # > 57度
                self.状态 = 航标状态.迷航
            elif 偏差角 > 0.5:  # > 28度
                self.状态 = 航标状态.偏差
            else:
                self.状态 = 航标状态.校正

            self._通知监听器(self.状态, 记录)
            return 记录

        # 偏差在可接受范围内
        self.状态 = 航标状态.正常
        return None

    def 计算校正信号(self, 策略: 校正策略 = 校正策略.渐进) -> 方向向量:
        """
        🔴 核心架构：计算校正信号
        
        根据当前偏差计算需要施加的校正方向向量。
        """
        理想方向 = self.朝向目标
        偏差角 = self.当前方向.与夹角(理想方向)

        if 偏差角 < 0.01:
            return 方向向量()  # 无需校正

        # 校正方向 = 理想方向 - 当前方向（简化）
        校正 = 方向向量(
            理想方向.x - self.当前方向.x,
            理想方向.y - self.当前方向.y,
            理想方向.z - self.当前方向.z,
            理想方向.t - self.当前方向.t
        )

        if 策略 == 校正策略.渐进:
            # 渐进校正：只校正一部分
            校正.x *= 0.3
            校正.y *= 0.3
            校正.z *= 0.3
            校正.t *= 0.3
        elif 策略 == 校正策略.环绕:
            # 环绕校正：增加一个垂直分量
            校正.y += 0.1

        self.状态 = 航标状态.校正

        # 记录校正信号
        信号 = {
            "时间": time.time(),
            "策略": 策略.name,
            "校正向量": 校正,
            "偏差角": 偏差角
        }
        self.校正信号列表.append(信号)

        return 校正

    def 应用校正(self, 校正向量: 方向向量) -> None:
        """
        🟢 数据流：应用校正向量到当前方向
        
        将校正向量叠加到当前方向上，然后归一化。
        """
        self.当前方向 = 方向向量(
            self.当前方向.x + 校正向量.x,
            self.当前方向.y + 校正向量.y,
            self.当前方向.z + 校正向量.z,
            self.当前方向.t + 校正向量.t
        ).归一化()

        # 校正后重新检测
        self.检测偏差()

    def 设置目标(self, 新锚点: 锚点) -> None:
        """🟡 设置新的目标锚点"""
        self.目标锚点 = 新锚点
        print(f"  [航标灯] {self.名称} 目标更新 -> {新锚点.名称}")

    def 注册监听器(self, 回调: Callable[[航标状态, 偏差记录], None]) -> None:
        """注册方向变化监听器"""
        self.方向监听器.append(回调)

    def _通知监听器(self, 状态: 航标状态, 记录: 偏差记录) -> None:
        """通知所有监听器"""
        for 回调 in self.方向监听器:
            try:
                回调(状态, 记录)
            except Exception:
                pass

    def 获取统计(self) -> Dict[str, Any]:
        """获取航标灯统计"""
        return {
            "航标ID": self.航标ID,
            "名称": self.名称,
            "状态": self.状态.name,
            "当前方向": str(self.当前方向),
            "目标": self.目标锚点.名称 if self.目标锚点 else "无",
            "偏差次数": len(self.偏差历史),
            "累计偏差": f"{self.累计偏差:.4f}rad",
            "校正次数": len(self.校正信号列表)
        }


