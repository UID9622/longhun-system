class 导航系统:
    """
    导航系统 - 龍魂数字人的方向感中枢
    
    管理航标灯阵列，负责：
    - 路径规划：从当前位置到目标的路径计算
    - 迷航检测：检测是否严重偏离预定路线
    - 自动回正：偏离时自动校正方向
    """

    def __init__(self) -> None:
        self.航标灯字典: Dict[str, 航标灯] = {}
        self.锚点字典: Dict[str, 锚点] = {}
        self.当前路径: List[锚点] = []
        self.路径索引: int = 0
        self.迷航检测阈值: float = 1.2     # 约69度
        self.自动回正: bool = True
        self.导航历史: List[Dict[str, Any]] = []
        self.校正间隔: float = 2.0          # 秒
        self.运行中: bool = False

    def 注册航标灯(self, 航标: 航标灯) -> None:
        """注册一个航标灯到系统"""
        self.航标灯字典[航标.航标ID] = 航标
        print(f"  [导航] 航标灯注册: {航标.名称}")

    def 注册锚点(self, 新锚点: 锚点) -> None:
        """注册一个目标锚点"""
        self.锚点字典[新锚点.锚点ID] = 新锚点

    def 规划路径(self, 起点锚点ID: str, 终点锚点ID: str) -> List[锚点]:
        """
        🔴 核心架构：路径规划
        
        根据锚点之间的方向关系规划路径。
        简化实现：按优先级排序的锚点序列。
        """
        if 终点锚点ID not in self.锚点字典:
            print(f"❌ 锚点 {终点锚点ID} 不存在")
            return []

        终点 = self.锚点字典[终点锚点ID]

        # 简单路径规划：直接指向终点
        # 实际实现可使用A*等算法
        路径 = [终点]

        # 如果起点存在，构建从起点到终点的路径
        if 起点锚点ID in self.锚点字典:
            起点 = self.锚点字典[起点锚点ID]
            # 插入中间锚点（按方向接近度排序）
            中间锚点 = [
                a for aid, a in self.锚点字典.items()
                if aid not in (起点锚点ID, 终点锚点ID)
            ]
            中间锚点.sort(key=lambda a: a.优先级, reverse=True)
            路径 = 中间锚点[:2] + [终点]  # 最多2个中间点

        self.当前路径 = 路径
        self.路径索引 = 0

        起点锚点 = self.锚点字典.get(起点锚点ID)
        起点名 = 起点锚点.名称 if 起点锚点 else "未知起点"
        print(f"  [路径规划] {起点名} "
              f"-> {终点.名称}")
        print(f"    路径点: {' -> '.join(a.名称 for a in 路径)}")

        return 路径

    def 检测迷航(self) -> List[str]:
        """
        🟡 状态控制：迷航检测
        
        检查所有航标灯的状态，返回迷航的航标灯ID列表。
        """
        迷航列表 = []
        for 航标ID, 航标 in self.航标灯字典.items():
            记录 = 航标.检测偏差()
            if 记录 and 记录.偏差角度 > self.迷航检测阈值:
                迷航列表.append(航标ID)
                self.导航历史.append({
                    "时间": time.time(),
                    "事件": "迷航",
                    "航标": 航标.名称,
                    "偏差角": f"{记录.偏差角度:.4f}rad"
                })
                print(f"  🚨 [迷航检测] {航标.名称} 严重偏离！偏差: {记录.偏差角度:.4f}rad")

        return 迷航列表

    def 执行自动回正(self) -> int:
        """
        🔴 核心架构：自动回正
        
        对所有偏离航向的航标灯执行校正。
        返回成功校正的航标灯数量。
        """
        校正计数 = 0

        for 航标 in self.航标灯字典.values():
            if 航标.状态 in (航标状态.偏差, 航标状态.迷航, 航标状态.校正):
                校正 = 航标.计算校正信号(校正策略.渐进)
                航标.应用校正(校正)
                校正计数 += 1

        if 校正计数 > 0:
            print(f"  🧭 [自动回正] 已校正 {校正计数} 个航标灯")

        return 校正计数

    def 获取当前目标(self) -> Optional[锚点]:
        """获取当前路径点的目标锚点"""
        if not self.当前路径 or self.路径索引 >= len(self.当前路径):
            return None
        return self.当前路径[self.路径索引]

    def 前进到下一节点(self) -> bool:
        """路径前进到下一个锚点"""
        if self.路径索引 < len(self.当前路径) - 1:
            self.路径索引 += 1
            下一目标 = self.当前路径[self.路径索引]
            print(f"  [路径] 前进到下一节点: {下一目标.名称}")

            # 更新所有航标灯的目标
            for 航标 in self.航标灯字典.values():
                航标.设置目标(下一目标)

            return True
        return False

    def 获取全局统计(self) -> Dict[str, Any]:
        """获取导航系统全局统计"""
        return {
            "航标灯数量": len(self.航标灯字典),
            "锚点数量": len(self.锚点字典),
            "路径节点数": len(self.当前路径),
            "当前节点索引": self.路径索引,
            "自动回正": self.自动回正,
            "各航标统计": {aid: a.获取统计() for aid, a in self.航标灯字典.items()}
        }

    def 显示导航面板(self) -> None:
        """显示导航系统状态面板"""
        print("\n" + "="*70)
        print("🧭 导航系统状态面板")
        print("="*70)
        print(f"{'航标ID':<10}{'名称':<10}{'状态':<8}{'目标':<12}{'偏差次数':<8}")
        print("-"*70)

        for 航标 in self.航标灯字典.values():
            状态标 = {"正常": "🟢", "偏差": "🟡", "迷航": "🔴",
                     "校正": "🔵", "失效": "⚫"}.get(航标.状态.name, "❓")
            目标名 = 航标.目标锚点.名称 if 航标.目标锚点 else "无"
            print(f"{航标.航标ID:<10}{航标.名称:<10}{状态标}{航标.状态.name:<6}{目标名:<12}{len(航标.偏差历史):<8}")

        print("="*70)


