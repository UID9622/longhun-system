@dataclass
class 方向向量:
    """多维方向向量"""
    x: float = 0.0      # 前进/后退
    y: float = 0.0      # 左/右
    z: float = 0.0      # 上/下
    t: float = 0.0      # 时间维度

    def 模长(self) -> float:
        """计算向量模长"""
        return math.sqrt(self.x**2 + self.y**2 + self.z**2 + self.t**2)

    def 归一化(self) -> 方向向量:
        """向量归一化"""
        模 = self.模长()
        if 模 == 0:
            return 方向向量()
        return 方向向量(self.x/模, self.y/模, self.z/模, self.t/模)

    def 与夹角(self, 其他: 方向向量) -> float:
        """计算两向量夹角（弧度）"""
        模积 = self.模长() * 其他.模长()
        if 模积 == 0:
            return 0.0
        点积 = self.x*其他.x + self.y*其他.y + self.z*其他.z + self.t*其他.t
        return math.acos(max(-1.0, min(1.0, 点积 / 模积)))

    def __repr__(self) -> str:
        return f"方向向量({self.x:.2f}, {self.y:.2f}, {self.z:.2f}, {self.t:.2f})"


@dataclass
class 锚点:
    """导航目标锚点"""
    锚点ID: str
    名称: str
    坐标: 方向向量
    描述: str = ""
    优先级: int = 50                    # 1-100
    可接受半径: float = 0.1             # 到达判定半径


@dataclass
class 偏差记录:
    """一次偏差检测记录"""
    时间戳: float
    预期方向: 方向向量
    实际方向: 方向向量
    偏差角度: float                     # 弧度
    严重程度: str                       # 低/中/高/严重


