class 人格:
    """
    单一数字人格 - 71人格体系中的一个独立人格
    
    每个人格拥有独立的激活条件、权限边界和行为特征，
    可以独立响应外部输入并做出决策。
    """

    def __init__(self, 档案: 人格档案) -> None:
        self.档案 = 档案
        self.回调函数: Optional[Callable[..., Any]] = None
        self.关联人格: Set[int] = set()     # 关联的其他人格ID
        self.互斥人格: Set[int] = set()     # 互斥的人格ID
        self.版本号: str = "1.0"

    @property
    def 人格ID(self) -> int:
        return self.档案.人格ID

    @property
    def 人格名称(self) -> str:
        return self.档案.人格名称

    @property
    def 当前状态(self) -> 人格状态:
        return self.档案.状态

    def 设置回调(self, 回调: Callable[..., Any]) -> None:
        """设置人格激活时的回调函数"""
        self.回调函数 = 回调

    def 激活(self, 触发原因: str = "") -> bool:
        """
        🔴 核心架构：激活人格
        
        将人格从休眠/待机状态转为激活状态，
        记录激活时间和原因。
        """
        if self.档案.状态 == 人格状态.静默:
            return False

        旧状态 = self.档案.状态
        self.档案.状态 = 人格状态.激活
        self.档案.激活时间戳 = time.time()
        self.档案.激活次数 += 1
        self.档案.历史记录.append({
            "时间": datetime.now().isoformat(),
            "事件": "激活",
            "从": 旧状态.name,
            "原因": 触发原因
        })

        print(f"  [人格激活] #{self.人格ID} {self.人格名称} | 原因: {触发原因}")

        # 执行回调
        if self.回调函数:
            try:
                self.回调函数(self)
            except Exception as e:
                print(f"  [回调错误] {e}")

        return True

    def 休眠(self, 原因: str = "") -> None:
        """
        🟡 状态控制：使人格进入休眠
        
        结算激活时长，记录历史。
        """
        if self.档案.状态 == 人格状态.激活 and self.档案.激活时间戳 > 0:
            本次时长 = time.time() - self.档案.激活时间戳
            self.档案.累计激活时长 += 本次时长

        self.档案.状态 = 人格状态.休眠
        self.档案.历史记录.append({
            "时间": datetime.now().isoformat(),
            "事件": "休眠",
            "原因": 原因
        })
        print(f"  [人格休眠] #{self.人格ID} {self.人格名称} | 原因: {原因}")

    def 待机(self) -> None:
        """🟡 进入待机状态（低功耗监听）"""
        if self.档案.状态 == 人格状态.激活:
            本次时长 = time.time() - self.档案.激活时间戳
            self.档案.累计激活时长 += 本次时长

        self.档案.状态 = 人格状态.待机
        print(f"  [人格待机] #{self.人格ID} {self.人格名称}")

    def 静默(self, 原因: str = "") -> None:
        """🟡 强制静默（最高权限操作）"""
        self.档案.状态 = 人格状态.静默
        self.档案.历史记录.append({
            "时间": datetime.now().isoformat(),
            "事件": "静默",
            "原因": 原因
        })
        print(f"  [人格静默] #{self.人格ID} {self.人格名称} | 原因: {原因}")

    def 检查激活条件(self, 输入文本: str, 上下文: Dict[str, Any]) -> float:
        """
        🟢 数据流：检查输入是否满足激活条件
        
        返回匹配度 0.0-1.0，越高越匹配。
        """
        匹配度 = 0.0
        条件 = self.档案.激活条件

        # 关键词匹配
        if 条件.关键词列表:
            文本小写 = 输入文本.lower()
            匹配数 = sum(1 for k in 条件.关键词列表 if k.lower() in 文本小写)
            匹配度 += (匹配数 / len(条件.关键词列表)) * 0.5

        # 场景标签匹配
        if 条件.场景标签 and "场景" in 上下文:
            场景匹配 = len(条件.场景标签 & set(上下文["场景"]))
            匹配度 += (场景匹配 / max(len(条件.场景标签), 1)) * 0.3

        # 优先级加成
        匹配度 += (条件.优先级 / 100.0) * 0.2

        return min(1.0, 匹配度)

    def 获取统计(self) -> Dict[str, Any]:
        """获取人格统计信息"""
        return {
            "ID": self.人格ID,
            "名称": self.人格名称,
            "类型": self.档案.人格类型.name,
            "状态": self.当前状态.name,
            "激活次数": self.档案.激活次数,
            "累计时长": f"{self.档案.累计激活时长:.1f}s",
            "关键词数": len(self.档案.激活条件.关键词列表),
            "优先级": self.档案.激活条件.优先级
        }


