class 人格状态机:
    """
    人格状态机 - 管理人格切换和冲突解决
    
    负责：
    - 当前激活人格管理
    - 切换队列管理
    - 冲突检测与解决
    - 主控权仲裁
    """

    def __init__(self) -> None:
        self.当前人格ID: Optional[int] = None
        self.切换队列: List[int] = []       # 待切换人格ID队列
        self.冲突记录: List[Dict[str, Any]] = []
        self.仲裁规则: Dict[str, Any] = {
            "主导优先": True,
            "最近使用": True,
            "最大激活时间": 300,              # 秒
            "冲突解决策略": "优先级优先"
        }
        self.切换历史: List[Dict[str, Any]] = []
        self.监听器列表: List[Callable[[int, int], None]] = []

    def 获取当前人格(self, 人格仓库: Dict[int, 人格]) -> Optional[人格]:
        """获取当前激活的人格"""
        if self.当前人格ID is None:
            return None
        return 人格仓库.get(self.当前人格ID)

    def 请求切换(self, 目标ID: int, 人格仓库: Dict[int, 人格],
                 模式: 切换模式 = 切换模式.平滑) -> bool:
        """
        🟡 状态控制：请求切换到目标人格
        
        会检查冲突、权限，并进行仲裁。
        """
        if 目标ID not in 人格仓库:
            print(f"❌ 人格#{目标ID}不存在")
            return False

        目标人格 = 人格仓库[目标ID]

        # 检查是否已在激活中
        if self.当前人格ID == 目标ID:
            return True

        # 🔴 冲突检测
        if self._检测冲突(目标ID, 人格仓库):
            print(f"⚠️ 人格冲突检测: #{目标ID} 与当前人格存在冲突")
            解决结果 = self._解决冲突(目标ID, 人格仓库)
            if not 解决结果:
                self.切换队列.append(目标ID)
                print(f"📋 已将 #{目标ID} 加入切换队列(位置:{len(self.切换队列)})")
                return False

        # 执行切换
        return self._执行切换(目标ID, 人格仓库, 模式)

    def _检测冲突(self, 目标ID: int, 人格仓库: Dict[int, 人格]) -> bool:
        """检测目标人格是否与当前人格冲突"""
        if self.当前人格ID is None:
            return False

        当前人格 = 人格仓库.get(self.当前人格ID)
        目标人格 = 人格仓库.get(目标ID)

        if 当前人格 is None or 目标人格 is None:
            return False

        # 检查互斥关系
        if 目标ID in 当前人格.互斥人格:
            return True
        if self.当前人格ID in 目标人格.互斥人格:
            return True

        # 检查资源竞争
        if 当前人格.当前状态 == 人格状态.激活 and \
           目标人格.档案.人格类型 == 人格类型.主导:
            return True

        return False

    def _解决冲突(self, 目标ID: int, 人格仓库: Dict[int, 人格]) -> bool:
        """
        🔴 核心架构：冲突解决
        
        根据仲裁规则决定谁获得主控权。
        """
        if self.当前人格ID is None:
            return True

        当前人格 = 人格仓库[self.当前人格ID]
        目标人格 = 人格仓库[目标ID]

        策略 = self.仲裁规则["冲突解决策略"]

        if 策略 == "优先级优先":
            当前优先级 = 当前人格.档案.激活条件.优先级
            目标优先级 = 目标人格.档案.激活条件.优先级

            # 应急人格有额外加成
            if 目标人格.档案.人格类型 == 人格类型.应急:
                目标优先级 += 30
            if 当前人格.档案.人格类型 == 人格类型.应急:
                当前优先级 += 30

            if 目标优先级 > 当前优先级:
                print(f"  [仲裁] #{目标ID} 优先级更高({目标优先级}>{当前优先级})，获得主控权")
                return True
            else:
                print(f"  [仲裁] #{self.当前人格ID} 保留主控权({当前优先级}>={目标优先级})")
                return False

        return False

    def _执行切换(self, 目标ID: int, 人格仓库: Dict[int, 人格],
                  模式: 切换模式) -> bool:
        """执行实际的人格切换"""
        旧ID = self.当前人格ID

        # 停用当前人格
        if 旧ID is not None and 旧ID in 人格仓库:
            人格仓库[旧ID].待机()

        # 激活新人格
        目标人格 = 人格仓库[目标ID]
        切换原因 = f"状态机切换(模式:{模式.name})"
        目标人格.激活(切换原因)

        self.当前人格ID = 目标ID

        # 记录切换历史
        记录 = {
            "时间": datetime.now().isoformat(),
            "从": 旧ID,
            "到": 目标ID,
            "模式": 模式.name
        }
        self.切换历史.append(记录)

        print(f"✅ 人格切换完成: #{旧ID} -> #{目标ID} ({目标人格.人格名称})")

        # 通知监听器
        for 监听器 in self.监听器列表:
            try:
                监听器(旧ID or 0, 目标ID)
            except Exception:
                pass

        return True

    def 处理队列(self, 人格仓库: Dict[int, 人格]) -> None:
        """
        🟢 数据流：处理切换队列中的人格请求
        
        当当前人格待机时，尝试激活队列中的人格。
        """
        if not self.切换队列:
            return

        # 取出队列中优先级最高的
        最佳ID = None
        最佳优先级 = -1

        for 人格ID in list(self.切换队列):
            if 人格ID in 人格仓库:
                优先级 = 人格仓库[人格ID].档案.激活条件.优先级
                if 优先级 > 最佳优先级:
                    最佳优先级 = 优先级
                    最佳ID = 人格ID

        if 最佳ID is not None:
            self.切换队列.remove(最佳ID)
            self._执行切换(最佳ID, 人格仓库, 切换模式.平滑)

    def 注册监听器(self, 监听器: Callable[[int, int], None]) -> None:
        """注册人格切换监听器"""
        self.监听器列表.append(监听器)

    def 获取统计(self) -> Dict[str, Any]:
        """获取状态机统计"""
        return {
            "当前人格ID": self.当前人格ID,
            "切换队列长度": len(self.切换队列),
            "总切换次数": len(self.切换历史),
            "冲突记录数": len(self.冲突记录),
            "最近5次切换": self.切换历史[-5:] if self.切换历史 else []
        }


