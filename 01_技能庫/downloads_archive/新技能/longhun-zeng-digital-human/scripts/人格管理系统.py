    def _生成关键词(self, 名称: str, 描述: str) -> List[str]:
        """为一个人格生成激活关键词"""
        关键词 = [名称]
        if "师" in 名称:
            关键词.append("师")
        if "家" in 名称:
            关键词.append("家")
        关键词.extend(描述.split("，")[0].split("、")[:2])
        return 关键词

    def 检索人格(self, 查询: str) -> List[人格]:
        """
        🟢 数据流：根据查询检索匹配的人格
        
        支持按名称、ID、类型、关键词检索。
        """
        结果 = []
        查询小写 = 查询.lower()

        for 人格实例 in self.人格仓库.values():
            # 按名称匹配
            if 查询小写 in 人格实例.人格名称.lower():
                结果.append(人格实例)
                continue

            # 按ID匹配
            if str(人格实例.人格ID) == 查询:
                结果.append(人格实例)
                continue

            # 按关键词匹配
            if 查询小写 in [k.lower() for k in 人格实例.档案.激活条件.关键词列表]:
                结果.append(人格实例)
                continue

        return 结果

    def 按标签获取(self, 标签: str) -> List[人格]:
        """按预设标签获取人格组"""
        人格ID列表 = self.预设标签.get(标签, [])
        return [self.人格仓库[i] for i in 人格ID列表 if i in self.人格仓库]

    def 获取所有统计(self) -> Dict[str, Any]:
        """获取全部人格统计"""
        return {
            "总数": len(self.人格仓库),
            "按类型": {
                "主导": sum(1 for p in self.人格仓库.values() if p.档案.人格类型 == 人格类型.主导),
                "辅助": sum(1 for p in self.人格仓库.values() if p.档案.人格类型 == 人格类型.辅助),
                "应急": sum(1 for p in self.人格仓库.values() if p.档案.人格类型 == 人格类型.应急),
                "守护": sum(1 for p in self.人格仓库.values() if p.档案.人格类型 == 人格类型.守护),
            },
            "按状态": {
                "休眠": sum(1 for p in self.人格仓库.values() if p.当前状态 == 人格状态.休眠),
                "待机": sum(1 for p in self.人格仓库.values() if p.当前状态 == 人格状态.待机),
                "激活": sum(1 for p in self.人格仓库.values() if p.当前状态 == 人格状态.激活),
                "静默": sum(1 for p in self.人格仓库.values() if p.当前状态 == 人格状态.静默),
            },
            "各人格统计": [p.获取统计() for p in self.人格仓库.values()]
        }


