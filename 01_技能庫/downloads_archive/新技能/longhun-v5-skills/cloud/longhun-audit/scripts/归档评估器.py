    def _计算文件哈希(self, 文件路径: Path, 算法: str = "md5") -> Optional[str]:
        """计算文件哈希值"""
        try:
            哈希对象 = hashlib.md5()
            with open(文件路径, "rb") as f:
                while True:
                    块 = f.read(8192)
                    if not 块:
                        break
                    哈希对象.update(块)
            return 哈希对象.hexdigest()
        except Exception:
            return None
    
    def _格式化大小(self, 字节: int) -> str:
        """格式化字节为可读大小"""
        if 字节 >= 1024 * 1024 * 1024:
            return f"{字节 / (1024*1024*1024):.1f}G"
        elif 字节 >= 1024 * 1024:
            return f"{字节 / (1024*1024):.1f}M"
        elif 字节 >= 1024:
            return f"{字节 / 1024:.1f}K"
        return f"{字节}B"
    
