class 归档决策(Enum):
    永久保留 = "keep_forever"           # C >= 80
    保留 = "keep"                        # 60 <= C < 80
    再评估 = "re_evaluate"              # 30 <= C < 60
    建议删除 = "delete_suggested"       # 15 <= C < 30
    强烈建议删除 = "delete_strong"      # C < 15

class 归档类别(Enum):
    历史版本 = "history"
    协议备份 = "protocol"
    清理备份 = "cleanup"
    旧系统 = "legacy_system"
    临时文件 = "temp"
    其他 = "other"

