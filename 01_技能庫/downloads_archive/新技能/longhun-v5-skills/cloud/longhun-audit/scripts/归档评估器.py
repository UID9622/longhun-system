@dataclass
class 归档条目:
    """单个归档条目的评估数据"""
    目录路径: str
    文件数量: int
    总大小字节: int
    创建时间: str                          # ISO格式
    最后修改: str                          # ISO格式
    归档类别: str                          # 归档类别枚举值
    用途描述: str                          # 用途说明
    内容描述: str                          # 内容说明
    
    # 评估分数 (0-100)
    保留价值分: int = 0                     # R: 是否对当前系统有帮助 (40%)
    创新度分: int = 0                       # I: 是否包含独特思路 (30%)
    时间衰减分: int = 0                     # T: 年代久远程度 (30%)
    
    # 评估结果
    综合得分: float = 0.0                   # C = R*40% + I*30% + T*30%
    决策建议: str = ""                      # 归档决策
    决策理由: str = ""                      # 决策理由
    
    # DNA与安全标记
    包含脱氧核糖核酸签名: bool = False
    脱氧核糖核酸签名列表: List[str] = field(default_factory=list)
    安全标记: List[str] = field(default_factory=list)  # 如 "禁止删除"
    
    # 元数据
    评估时间: str = ""
    优先级: str = "P2"                     # P0/P1/P2/P3
    备注: str = ""
    
    def __post_init__(self):
        if not self.评估时间:
            self.评估时间 = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        self.计算综合得分()
    
    def 计算综合得分(self) -> float:
        """
        计算综合得分: C = R*40% + I*30% + T*30%
        """
        self.综合得分 = (
            self.保留价值分 * 0.40 +
            self.创新度分 * 0.30 +
            self.时间衰减分 * 0.30
        )
        self.决策建议 = self._计算决策建议()
        return self.综合得分
    
    def _计算决策建议(self) -> str:
        if self.安全标记 and "禁止删除" in self.安全标记:
            return 归档决策.永久保留.value
        if self.综合得分 >= 80:
            return 归档决策.永久保留.value
        elif self.综合得分 >= 60:
            return 归档决策.保留.value
        elif self.综合得分 >= 30:
            return 归档决策.再评估.value
        elif self.综合得分 >= 15:
            return 归档决策.建议删除.value
        else:
            return 归档决策.强烈建议删除.value
    
    @property
    def 格式化大小(self) -> str:
        """格式化文件大小显示"""
        字节 = self.总大小字节
        if 字节 >= 1024 * 1024 * 1024:
            return f"{字节 / (1024*1024*1024):.1f}G"
        elif 字节 >= 1024 * 1024:
            return f"{字节 / (1024*1024):.1f}M"
        elif 字节 >= 1024:
            return f"{字节 / 1024:.1f}K"
        else:
            return f"{字节}B"
    
    def 转字典(self) -> Dict:
        数据 = asdict(self)
        数据["格式化大小"] = self.格式化大小
        数据["综合得分显示"] = f"{self.综合得分:.1f}"
        return 数据


@dataclass
class 完整性检查结果:
    """归档完整性检查结果"""
    目录路径: str
    检查时间: str
    
    # 文件统计
    总文件数: int = 0
    可读文件数: int = 0
    不可读文件数: int = 0
    空文件数: int = 0
    损坏文件数: int = 0
    
    # DNA签名检查
    包含脱氧核糖核酸文件数: int = 0
    脱氧核糖核酸签名列表: List[str] = field(default_factory=list)
    
    # 重复检查
    重复文件组: List[List[str]] = field(default_factory=list)
    重复占用空间: int = 0
    
    # 完整性评分
    完整性评分: float = 100.0               # 0-100
    健康状态: str = "🟢 健康"               # 🟢/🟡/🔴
    
    # 问题列表
    问题列表: List[Dict] = field(default_factory=list)
    
    def __post_init__(self):
        if not self.检查时间:
            self.检查时间 = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        self._计算健康状态()
    
    def _计算健康状态(self):
        if self.完整性评分 >= 90:
            self.健康状态 = "🟢 健康"
        elif self.完整性评分 >= 70:
            self.健康状态 = "🟡 警告"
        else:
            self.健康状态 = "🔴 受损"
    
    def 转字典(self) -> Dict:
        return asdict(self)


# ═══════════════════════════════════════════════════════════
# 核心类: 归档评估器
# ═══════════════════════════════════════════════════════════

class 归档评估器:
    """
    龍魂归档评估器核心
    
    功能:
    1. 归档扫描与评估
    2. 价值计算 (C = R*40% + I*30% + T*30%)
    3. 完整性检查
    4. 决策建议生成
    5. 磁盘空间分析
    6. 归档报告生成
    """
    
    DNA = "#龍芯⚡️2026-06-19-LONGHUN-ARCHIVE-EVALUATOR-v5.1"
    版本 = "5.1.0"
    
    # 评估公式权重
    权重配置 = {
        "保留价值": 0.40,       # R
        "创新度": 0.30,         # I
        "时间衰减": 0.30,       # T
    }
    
    # 决策阈值
    决策阈值 = {
        "永久保留": 80,
        "保留": 60,
        "再评估": 30,
        "建议删除": 15,
    }
    
    def __init__(self, 数据目录: str = None):
        self.数据目录 = Path(数据目录) if 数据目录 else Path.home() / ".龍魂" / "archive_eval"
        self.数据目录.mkdir(parents=True, exist_ok=True)
        
        self.归档条目池: Dict[str, 归档条目] = {}
        self.完整性检查池: Dict[str, 完整性检查结果] = {}
        
        # 加载历史评估
        self._加载历史数据()
    
    def _加载历史数据(self):
        """加载历史评估数据"""
        评估文件 = self.数据目录 / "归档评估.json"
        if 评估文件.exists():
            with open(评估文件, "r", encoding="utf-8") as 文件:
                数据 = json.load(文件)
                for 路径, 条目数据 in 数据.items():
                    self.归档条目池[路径] = 归档条目(**条目数据)
    
    def _保存评估数据(self):
        """保存评估数据到磁盘"""
        数据 = {路径: 条目.转字典() for 路径, 条目 in self.归档条目池.items()}
        with open(self.数据目录 / "归档评估.json", "w", encoding="utf-8") as 文件:
            json.dump(数据, 文件, ensure_ascii=False, indent=2)
    
    def _生成时间戳(self) -> str:
        return datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    def _扫描目录(self, 目录路径: str) -> Dict:
        """
        扫描目录获取文件统计
        
        返回: {
            "文件数量": int,
            "总大小": int,
            "创建时间": str,
            "最后修改": str,
            "脱氧核糖核酸签名": List[str]
        }
        """
        路径 = Path(目录路径)
        if not 路径.exists():
            return {"文件数量": 0, "总大小": 0, "创建时间": "", "最后修改": "", "脱氧核糖核酸签名": []}
        
        文件数量 = 0
        总大小 = 0
        创建时间 = None
        最后修改 = None
        脱氧核糖核酸签名列表 = []
        
        for 根, 目录列表, 文件列表 in os.walk(路径):
            for 文件名 in 文件列表:
                文件路径 = Path(根) / 文件名
                try:
                    统计信息 = 文件路径.stat()
                    文件数量 += 1
                    总大小 += 统计信息.st_size
                    
                    文件修改 = datetime.datetime.fromtimestamp(统计信息.st_mtime)
                    if 最后修改 is None or 文件修改 > 最后修改:
                        最后修改 = 文件修改
                    
                    文件创建 = datetime.datetime.fromtimestamp(统计信息.st_ctime)
                    if 创建时间 is None or 文件创建 < 创建时间:
                        创建时间 = 文件创建
                    
                    # 检查DNA签名
                    if 文件路径.stat().st_size < 1024 * 1024:  # 只检查小于1M的文件
                        try:
                            with open(文件路径, "r", encoding="utf-8", errors="ignore") as f:
                                内容 = f.read(5000)
                                if "#龍芯⚡️" in 内容:
                                    for 行 in 内容.split("\n"):
                                        if "#龍芯⚡️" in 行:
                                            签名 = 行.strip().split("#龍芯⚡️")[-1].strip()
                                            if 签名 and 签名 not in 脱氧核糖核酸签名列表:
                                                脱氧核糖核酸签名列表.append(f"#龍芯⚡️{签名}")
                                if "#CONFIRM" in 内容:
                                    for 行 in 内容.split("\n"):
                                        if "#CONFIRM" in 行:
                                            确认码 = 行.strip()
                                            if 确认码 and 确认码 not in 脱氧核糖核酸签名列表:
                                                脱氧核糖核酸签名列表.append(确认码)
                        except Exception:
                            pass
                except (OSError, PermissionError):
                    continue
        
        return {
            "文件数量": 文件数量,
            "总大小": 总大小,
            "创建时间": 创建时间.strftime("%Y-%m-%d %H:%M:%S") if 创建时间 else "",
            "最后修改": 最后修改.strftime("%Y-%m-%d %H:%M:%S") if 最后修改 else "",
            "脱氧核糖核酸签名": 脱氧核糖核酸签名列表
        }
    
    # ═══════════════════════════════════════════════════
    # 公开API: 归档评估
    # ═══════════════════════════════════════════════════
    
    def 评估归档目录(self, 目录路径: str, 用途描述: str = "", 
                  内容描述: str = "", 归档类别: str = "other",
                  保留价值分: int = 50, 创新度分: int = 50,
                  时间衰减分: int = 50,
                  安全标记: List[str] = None,
                  备注: str = "") -> 归档条目:
        """
        评估归档目录价值
        
        参数:
            目录路径: 归档目录路径
            用途描述: 目录用途说明
            内容描述: 内容说明
            归档类别: history/protocol/cleanup/legacy_system/temp/other
            保留价值分: R分数 (0-100)，是否对当前系统有帮助
            创新度分: I分数 (0-100)，是否包含独特思路
            时间衰减分: T分数 (0-100)，年代久远程度(越新分数越高)
            安全标记: 如 ["禁止删除", "DNA签署"]
            备注: 额外备注
        """
        print(f"[归档评估] 📂 正在评估: {目录路径}")
        
        # 扫描目录
        扫描结果 = self._扫描目录(目录路径)
        
        # 创建归档条目
        条目 = 归档条目(
            目录路径=目录路径,
            文件数量=扫描结果["文件数量"],
            总大小字节=扫描结果["总大小"],
            创建时间=扫描结果["创建时间"],
            最后修改=扫描结果["最后修改"],
            归档类别=归档类别,
            用途描述=用途描述,
            内容描述=内容描述,
            保留价值分=保留价值分,
            创新度分=创新度分,
            时间衰减分=时间衰减分,
            包含脱氧核糖核酸签名=len(扫描结果["脱氧核糖核酸签名"]) > 0,
            脱氧核糖核酸签名列表=扫描结果["脱氧核糖核酸签名"],
            安全标记=安全标记 or [],
            备注=备注
        )
        
        # 计算决策
        条目.计算综合得分()
        
        # 生成决策理由
        理由 = []
        if 条目.安全标记:
            理由.append(f"安全标记: {', '.join(条目.安全标记)}")
        理由.append(f"保留价值(R): {保留价值分}/100 → 权重 {保留价值分*0.4:.1f}")
        理由.append(f"创新度(I): {创新度分}/100 → 权重 {创新度分*0.3:.1f}")
        理由.append(f"时间衰减(T): {时间衰减分}/100 → 权重 {时间衰减分*0.3:.1f}")
        理由.append(f"综合得分: {条目.综合得分:.1f}/100")
        条目.决策理由 = " | ".join(理由)
        
        self.归档条目池[目录路径] = 条目
        self._保存评估数据()
        
        print(f"[归档评估] ✅ 评估完成: {条目.格式化大小} | 得分: {条目.综合得分:.1f} | 决策: {条目.决策建议}")
        
        return 条目
    
    def 批量评估(self, 评估列表: List[Dict]) -> List[归档条目]:
        """
        批量评估多个归档目录
        
        参数:
            评估列表: [{
                "目录路径": "...",
                "用途描述": "...",
                "保留价值分": 65,
                "创新度分": 55,
                "时间衰减分": 85,
                ...
            }, ...]
        """
        结果 = []
        for 配置 in 评估列表:
            条目 = self.评估归档目录(**配置)
            结果.append(条目)
        return 结果
    
    def 计算可释放空间(self) -> Dict:
        """
        计算按建议删除可释放的磁盘空间
        
        返回: {"可释放空间": int, "可释放格式化": str, "目录列表": [...]}
        """
        可释放 = 0
        目录列表 = []
        
        for 路径, 条目 in self.归档条目池.items():
            if 条目.决策建议 in [归档决策.建议删除.value, 归档决策.强烈建议删除.value]:
                可释放 += 条目.总大小字节
                目录列表.append({
                    "路径": 路径,
                    "大小": 条目.格式化大小,
                    "得分": f"{条目.综合得分:.1f}",
                    "理由": 条目.决策理由[:100] + "..."
                })
        
        return {
            "可释放空间": 可释放,
            "可释放格式化": self._格式化大小(可释放),
            "目录列表": 目录列表,
            "目录数": len(目录列表)
        }
    
    def 按决策分组(self) -> Dict[str, List[归档条目]]:
        """按决策建议分组"""
        分组 = {}
        for 条目 in self.归档条目池.values():
            if 条目.决策建议 not in 分组:
                分组[条目.决策建议] = []
            分组[条目.决策建议].append(条目)
        return 分组
    
    # ═══════════════════════════════════════════════════
    # 公开API: 完整性检查
    # ═══════════════════════════════════════════════════
    
    def 执行完整性检查(self, 目录路径: str, 检查重复: bool = True) -> 完整性检查结果:
        """
        执行归档完整性检查
        
        检查项:
        1. 文件可读性
        2. 空文件检测
        3. DNA签名验证
        4. 重复文件检测
        5. 完整性评分
        """
        print(f"[完整性检查] 🔍 检查目录: {目录路径}")
        
        路径 = Path(目录路径)
        结果 = 完整性检查结果(
            目录路径=目录路径,
            检查时间=self._生成时间戳()
        )
        
        if not 路径.exists():
            结果.完整性评分 = 0
            结果.健康状态 = "🔴 目录不存在"
            结果.问题列表.append({"级别": "致命", "描述": "目录不存在"})
            return 结果
        
        文件哈希字典: Dict[str, List[str]] = {}  # 哈希 -> [文件路径列表]
        
        for 根, 目录列表, 文件列表 in os.walk(路径):
            for 文件名 in 文件列表:
                文件路径 = Path(根) / 文件名
                结果.总文件数 += 1
                
                try:
                    统计信息 = 文件路径.stat()
                    
                    # 检查空文件
                    if 统计信息.st_size == 0:
                        结果.空文件数 += 1
                        结果.问题列表.append({"级别": "警告", "描述": f"空文件: {文件路径}"})
                        continue
                    
                    # 检查可读性
                    try:
                        with open(文件路径, "rb") as f:
                            内容 = f.read(1024)
                        结果.可读文件数 += 1
                        
                        # DNA签名检查
                        if 统计信息.st_size < 1024 * 1024:
                            try:
                                with open(文件路径, "r", encoding="utf-8", errors="ignore") as f:
                                    文本 = f.read(5000)
                                    if "#龍芯⚡️" in 文本:
                                        结果.包含脱氧核糖核酸文件数 += 1
                                        for 行 in 文本.split("\n"):
                                            if "#龍芯⚡️" in 行:
                                                签名 = 行.strip()
                                                if 签名 not in 结果.脱氧核糖核酸签名列表:
                                                    结果.脱氧核糖核酸签名列表.append(签名)
                            except Exception:
                                pass
                        
                        # 重复检测
                        if 检查重复 and 统计信息.st_size > 0:
                            完整哈希 = self._计算文件哈希(文件路径)
                            if 完整哈希:
                                if 完整哈希 not in 文件哈希字典:
                                    文件哈希字典[完整哈希] = []
                                文件哈希字典[完整哈希].append(str(文件路径))
                        
                    except PermissionError:
                        结果.不可读文件数 += 1
                        结果.问题列表.append({"级别": "错误", "描述": f"无读取权限: {文件路径}"})
                    except Exception as e:
                        结果.不可读文件数 += 1
                        结果.问题列表.append({"级别": "错误", "描述": f"读取失败: {文件路径} - {str(e)}"})
                
                except OSError:
                    结果.不可读文件数 += 1
        
        # 处理重复文件
        for 哈希值, 文件列表 in 文件哈希字典.items():
            if len(文件列表) > 1:
                结果.重复文件组.append(文件列表)
                try:
                    文件大小 = Path(文件列表[0]).stat().st_size
                    结果.重复占用空间 += 文件大小 * (len(文件列表) - 1)
                except:
                    pass
        
        # 计算完整性评分
        if 结果.总文件数 > 0:
            可读率 = 结果.可读文件数 / 结果.总文件数
            空文件率 = 1 - (结果.空文件数 / 结果.总文件数)
            结果.完整性评分 = min(100, max(0, (可读率 * 70 + 空文件率 * 30)))
        
        结果._计算健康状态()
        self.完整性检查池[目录路径] = 结果
        
