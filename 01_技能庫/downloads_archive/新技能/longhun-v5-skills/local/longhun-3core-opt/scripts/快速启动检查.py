    def 檢查粒子創建(self) -> List[檢查項]:
        """🟢 檢查1: 認知粒子創建"""
        開始 = time.time()
        引擎 = 認知DNA引擎()
        情感向量 = {e: 0.1 for e in 情感狀態}
        情感向量[情感狀態.平靜] = 0.8
        粒子 = 引擎.創建認知粒子(認知狀態.清醒, 情感向量, 0.6)
        耗時 = (time.time() - 開始) * 1000
        if 粒子.校驗和 and 粒子.情感強度() > 0:
            return [檢查項(self.模塊名, "粒子創建", 檢查狀態.通過,
                          f"校驗和={粒子.校驗和}, 情感強度={粒子.情感強度():.4f}", 耗時)]
