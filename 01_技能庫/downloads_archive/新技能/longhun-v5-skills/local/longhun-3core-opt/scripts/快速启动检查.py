class 檢查狀態(Enum):
    """單項檢查狀態"""
    通過 = "PASS"      # 🟢
    警告 = "WARN"      # 🟡
    失敗 = "FAIL"      # 🔴
    跳過 = "SKIP"      # ⚪


@dataclass
class 檢查項:
    """單個檢查項"""
    模塊: str
    名稱: str
    狀態: 檢查狀態
    詳情: str = ""
    耗時毫秒: float = 0.0
    建議: str = ""

    def 轉字典(self) -> Dict[str, Any]:
        return {
            "模塊": self.模塊,
            "名稱": self.名稱,
            "狀態": self.狀態.value,
            "詳情": self.詳情,
            "耗時毫秒": round(self.耗時毫秒, 3),
            "建議": self.建議,
        }


@dataclass
class 檢查報告:
    """完整檢查報告"""
    DNA: str
    版本: str
    檢查時間: float
    總項數: int
    通過數: int
    警告數: int
    失敗數: int
    總耗時毫秒: float
    檢查項: List[檢查項]
    系統就緒: bool

    def 轉字典(self) -> Dict[str, Any]:
        return {
            "DNA": self.DNA,
            "版本": self.版本,
            "檢查時間": self.檢查時間,
            "總項數": self.總項數,
            "通過數": self.通過數,
            "警告數": self.警告數,
            "失敗數": self.失敗數,
            "總耗時毫秒": round(self.總耗時毫秒, 3),
            "系統就緒": self.系統就緒,
            "檢查項": [i.轉字典() for i in self.檢查項],
        }


