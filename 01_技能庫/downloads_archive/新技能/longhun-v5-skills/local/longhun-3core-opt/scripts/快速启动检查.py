def 主函數():
    """快速啟動檢查入口"""
    import argparse
    解析器 = argparse.ArgumentParser(description="龍魂三核心快速啟動檢查表 v5.2")
    解析器.add_argument("--json", action="store_true", help="輸出JSON格式報告")
    解析器.add_argument("--靜默", action="store_true", help="僅輸出結果摘要")
    解析器.add_argument("--模塊", type=str, default="",
                        help="指定檢查模塊 (三才/七因子/認知DNA/執行路由/人格路由)")
    參數 = 解析器.parse_args()

    if not 參數.靜默:
        print(f"\n{'='*70}")
        print(f"  龍魂三核心快速啟動檢查表 v{__version__}")
        print(f"  DNA: {__dna__}")
        print(f"{'='*70}\n")

    檢查器 = 快速啟動檢查器()
    報告 = 檢查器.執行全部檢查()

    if 參數.json:
        print(json.dumps(報告.轉字典(), ensure_ascii=False, indent=2))
    elif not 參數.靜默:
        檢查器.打印報告(報告)
    else:
        狀態 = "PASS" if 報告.系統就緒 else "FAIL"
        print(f"STATUS={狀態} 通過={報告.通過數} 警告={報告.警告數} 失敗={報告.失敗數} "
              f"耗時={報告.總耗時毫秒:.2f}ms")

    # 返回退出碼
    sys.exit(0 if 報告.系統就緒 else 1)


