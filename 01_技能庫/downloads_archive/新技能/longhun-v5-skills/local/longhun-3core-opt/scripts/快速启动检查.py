class 三才檢查器:
    """三才主權指數系統檢查"""

    def __init__(self):
        self.模塊名 = "三才主權指數 (SI)"

    def 執行全部檢查(self) -> List[檢查項]:
        """執行三才系統的全部檢查項"""
        結果 = []
        結果.extend(self.檢查配置驗證())
        結果.extend(self.檢查主權計算())
        結果.extend(self.檢查狀態判定())
        結果.extend(self.檢查自適應調整())
        結果.extend(self.檢查趨勢預測())
        結果.extend(self.檢查壓縮恢復())
        return 結果

    def 檢查配置驗證(self) -> List[檢查項]:
        """🟢 檢查1: 配置合法性驗證"""
        開始 = time.time()
        配置 = 三才配置()
        合法, 錯誤 = 配置.驗證()
        耗時 = (time.time() - 開始) * 1000
        if 合法:
            return [檢查項(self.模塊名, "配置合法性驗證", 檢查狀態.通過,
                          f"權重總和=1.0, 人={配置.人權重}, 地={配置.地權重}, 天={配置.天權重}",
                          耗時)]
        return [檢查項(self.模塊名, "配置合法性驗證", 檢查狀態.失敗,
                      f"錯誤: {', '.join(錯誤)}", 耗時, "修正配置參數")]

    def 檢查主權計算(self) -> List[檢查項]:
        """🟢 檢查2: 主權指數計算準確性"""
        開始 = time.time()
        引擎 = 三才主權引擎()
        # 測試用例: 全部為1.0應該得到1.0
        SI = 引擎.計算主權指數(1.0, 1.0, 1.0)
        耗時 = (time.time() - 開始) * 1000
        if abs(SI - 1.0) < 0.001:
            return [檢查項(self.模塊名, "主權指數計算", 檢查狀態.通過,
                          f"全1.0輸入 → SI={SI:.6f} (正確)", 耗時)]
        return [檢查項(self.模塊名, "主權指數計算", 檢查狀態.失敗,
                      f"全1.0輸入 → SI={SI:.6f} (期望=1.0)", 耗時, "檢查計算公式")]

    def 檢查狀態判定(self) -> List[檢查項]:
        """🟢 檢查3: 錨定狀態判定"""
        開始 = time.time()
        引擎 = 三才主權引擎()
        檢查項列表 = []
        測試用例 = [
            (0.85, 錨定狀態.激活, "高SI應激活"),
            (0.60, 錨定狀態.削弱, "中SI應削弱"),
            (0.30, 錨定狀態.失錨, "低SI應失錨"),
        ]
        全部通過 = True
        for SI值, 期望狀態, 描述 in 測試用例:
            實際狀態 = 引擎.判定錨定狀態(SI值)
            if 實際狀態 == 期望狀態:
                pass
            else:
                全部通過 = False
        耗時 = (time.time() - 開始) * 1000
        if 全部通過:
            return [檢查項(self.模塊名, "錨定狀態判定", 檢查狀態.通過,
                          f"激活/削弱/失錨三態判定正確", 耗時)]
        return [檢查項(self.模塊名, "錨定狀態判定", 檢查狀態.失敗,
                      "狀態判定邏輯有誤", 耗時, "檢查閾值設定")]

    def 檢查自適應調整(self) -> List[檢查項]:
        """🟡 檢查4: 自適應權重調整"""
        開始 = time.time()
        引擎 = 三才主權引擎()
        # 模擬多次更新觸發自適應調整
        for i in range(15):
            引擎.更新三才(0.8 + i*0.01, 0.7, 0.6, f"測試_{i}")
        耗時 = (time.time() - 開始) * 1000
        調整歷史長度 = len(引擎.權重歷史)
        if 調整歷史長度 > 0:
            return [檢查項(self.模塊名, "自適應權重調整", 檢查狀態.通過,
                          f"已記錄{調整歷史長度}次權重調整", 耗時)]
        return [檢查項(self.模塊名, "自適應權重調整", 檢查狀態.警告,
                      "未觸發自適應調整 (可能需要更多樣本)", 耗時,
                      "確保歷史深度>=3且自適應調整開啟")]

    def 檢查趨勢預測(self) -> List[檢查項]:
        """🟢 檢查5: 趨勢預測功能"""
        開始 = time.time()
        引擎 = 三才主權引擎()
        # 填充歷史數據
        for i in range(5):
            引擎.更新三才(0.5 + i*0.05, 0.6, 0.7)
        預測 = 引擎.預測下一狀態()
        耗時 = (time.time() - 開始) * 1000
        if "預測狀態" in 預測 and "預測SI" in 預測:
            return [檢查項(self.模塊名, "趨勢預測", 檢查狀態.通過,
                          f"預測狀態={預測['預測狀態']}, 預測SI={預測['預測SI']}", 耗時)]
        return [檢查項(self.模塊名, "趨勢預測", 檢查狀態.失敗,
                      "預測結果格式異常", 耗時)]

    def 檢查壓縮恢復(self) -> List[檢查項]:
        """🟢 檢查6: 歷史壓縮與恢復"""
        開始 = time.time()
        引擎 = 三才主權引擎()
        for i in range(5):
            引擎.更新三才(0.8, 0.7, 0.6)
        壓縮數據 = 引擎.壓縮歷史()
        新引擎 = 三才主權引擎()
        恢復數 = 新引擎.恢復歷史(壓縮數據)
        耗時 = (time.time() - 開始) * 1000
        if 恢復數 >= 5:
            return [檢查項(self.模塊名, "壓縮/恢復", 檢查狀態.通過,
                          f"壓縮{len(引擎.歷史粒子)}個粒子 → 恢復{恢復數}個粒子", 耗時)]
        return [檢查項(self.模塊名, "壓縮/恢復", 檢查狀態.失敗,
                      f"恢復數量不足: {恢復數}", 耗時)]


class 七因子檢查器:
    """F1-F7七因子驗證系統檢查"""

    def __init__(self):
        self.模塊名 = "F1-F7七因子驗證"

    def 執行全部檢查(self) -> List[檢查項]:
        """執行七因子系統的全部檢查項"""
        結果 = []
        結果.extend(self.檢查配置())
        結果.extend(self.檢查指紋生成())
        結果.extend(self.檢查批量指紋())
        結果.extend(self.檢查行為一致性())
        結果.extend(self.檢查乘積置信度())
        結果.extend(self.檢查快速驗證())
        結果.extend(self.檢查完整驗證流程())
        return 結果

    def 檢查配置(self) -> List[檢查項]:
        """🟢 檢查1: 配置與權重"""
        開始 = time.time()
        配置 = 七因子配置()
        權重和 = sum(配置.因子權重.values())
        耗時 = (time.time() - 開始) * 1000
        if abs(權重和 - 1.0) < 0.001 and len(配置.因子權重) == 7:
            return [檢查項(self.模塊名, "配置與權重", 檢查狀態.通過,
                          f"7個因子, 權重和={權重和:.4f}", 耗時)]
        return [檢查項(self.模塊名, "配置與權重", 檢查狀態.失敗,
                      f"權重和={權重和:.4f}, 因子數={len(配置.因子權重)}", 耗時)]

    def 檢查指紋生成(self) -> List[檢查項]:
        """🟢 檢查2: 行為指紋生成"""
        開始 = time.time()
        引擎 = 七因子驗證引擎()
        指紋1 = 引擎.密碼學引擎.生成行為指紋("測試數據A")
        指紋2 = 引擎.密碼學引擎.生成行為指紋("測試數據A")
        指紋3 = 引擎.密碼學引擎.生成行為指紋("測試數據B")
        耗時 = (time.time() - 開始) * 1000
        if 指紋1 == 指紋2 and 指紋1 != 指紋3 and len(指紋1) == 32:
            return [檢查項(self.模塊名, "行為指紋生成", 檢查狀態.通過,
                          f"相同輸入→相同指紋, 不同輸入→不同指紋, 長度={len(指紋1)}", 耗時)]
        return [檢查項(self.模塊名, "行為指紋生成", 檢查狀態.失敗,
                      f"指紋一致性或長度異常", 耗時)]

    def 檢查批量指紋(self) -> List[檢查項]:
        """🟢 檢查3: 批量指紋生成"""
        開始 = time.time()
        引擎 = 七因子驗證引擎()
        數據列表 = [f"數據_{i}" for i in range(20)]
        指紋列表 = 引擎.密碼學引擎.批量生成指紋(數據列表)
        耗時 = (time.time() - 開始) * 1000
        if len(指紋列表) == 20 and all(len(f) == 32 for f in 指紋列表):
            return [檢查項(self.模塊名, "批量指紋生成", 檢查狀態.通過,
                          f"20個指紋全部生成, 耗時={耗時:.2f}ms", 耗時)]
        return [檢查項(self.模塊名, "批量指紋生成", 檢查狀態.失敗,
                      f"生成數量或格式異常", 耗時)]

    def 檢查行為一致性(self) -> List[檢查項]:
        """🟢 檢查4: 行為一致性驗證"""
        開始 = time.time()
        引擎 = 七因子驗證引擎()
        指紋 = 引擎.密碼學引擎.生成行為指紋("一致性測試")
        一致, 相似度 = 引擎.密碼學引擎.驗證行為一致性(指紋, "一致性測試")
        耗時 = (time.time() - 開始) * 1000
        if 一致 and 相似度 == 1.0:
            return [檢查項(self.模塊名, "行為一致性驗證", 檢查狀態.通過,
                          f"相同行為→一致性驗證通過, 相似度={相似度}", 耗時)]
        return [檢查項(self.模塊名, "行為一致性驗證", 檢查狀態.失敗,
                      f"一致性驗證失敗", 耗時)]

    def 檢查乘積置信度(self) -> List[檢查項]:
        """🟢 檢查5: 乘積置信度計算"""
        開始 = time.time()
        引擎 = 七因子驗證引擎()
        樣本列表 = [
            因子樣本(因子=因子類型.F1_行為一致性, 原始值=0.9, 置信度=0.9, 時間戳=time.time()),
            因子樣本(因子=因子類型.F2_認知清晰度, 原始值=0.8, 置信度=0.8, 時間戳=time.time()),
        ]
        結果 = 引擎.置信度引擎.計算乘積置信度(樣本列表)
