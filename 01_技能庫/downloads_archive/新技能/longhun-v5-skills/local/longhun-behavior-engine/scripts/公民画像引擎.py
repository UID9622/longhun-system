import json, hashlib, time, os
from datetime import datetime
from typing import Dict, List, Optional, Any
from dataclasses import dataclass, field, asdict

__dna__ = "#龍芯⚡️2026-06-20-LONGHUN-BEHAVIOR-v1.0"


# ═══════════════════════════════════════════
# 行为记录（最底层，不可篡改）
# ═══════════════════════════════════════════

@dataclass
class 行为记录:
    时间戳: str           # ISO格式时间
    行为类型: str         # 环保/信誉/互动/服务/习惯
    行为名称: str         # "点外卖-不要餐具"
    原始权重: float       # 基础分值（0.1~10）
    真实度: float         # 0~1，系统判定是否真心（非随手）
    来源: str             # 哪个平台/场景
    DNA: str = __dna__
    龍印: str = ""        # SHA256指纹

    def __post_init__(self):
        # 每条记录生成不可篡改指纹
        数据 = f"{self.时间戳}{self.行为类型}{self.行为名称}{self.原始权重}{self.DNA}"
        self.龍印 = hashlib.sha256(数据.encode()).hexdigest()[:16]


# ═══════════════════════════════════════════
# 六大维度评估引擎
# ═══════════════════════════════════════════

class 公民画像引擎:
    """
    六大维度：
    1. 环保贡献值 — 绿色行为（餐具/出行/节能）
    2. 信誉分 — 诚信历史（履约/承诺/无欺诈）
    3. 互动质量分 — 点赞评论是否真心（非随手）
    4. 服务分 — 为人民服务的行为
    5. 习惯分 — 长期行为模式
    6. 真实度总分 — 综合权重
    """

    def __init__(self, 用户ID: str):
        self.用户ID = 用户ID
        self.行为库: List[行为记录] = []
        self.亮灯设置 = {
            "环保贡献": True,
            "信誉分": True,
            "互动质量": False,   # 默认不亮，隐私
            "服务分": True,
            "习惯分": False,
            "真实度总分": True,
        }
        self._加载()

    # ── 六大维度 ──
    def 记录环保行为(self, 行为: str, 权重: float = 1.0):
        """记录环保行为：点外卖不要餐具、绿色出行等"""
        记录 = 行为记录(
            时间戳=datetime.now().isoformat(),
            行为类型="环保",
            行为名称=行为,
            原始权重=权重,
            真实度=1.0,  # 环保行为默认真实（有成本）
            来源="手动记录"
        )
        self.行为库.append(记录)
        self._保存()
        return f"🟢 环保行为已记录: {行为} (+{权重}分) 龍印:{记录.龍印}"

    def 记录信誉行为(self, 行为: str, 权重: float = 2.0, 真实度: float = 1.0):
        """记录信誉行为：履约、承诺兑现"""
        记录 = 行为记录(
            时间戳=datetime.now().isoformat(),
            行为类型="信誉",
            行为名称=行为,
            原始权重=权重,
            真实度=真实度,
            来源="系统判定"
        )
        self.行为库.append(记录)
        self._保存()
        return f"🟢 信誉行为已记录: {行为} (+{权重}分)"

    def 记录互动质量(self, 行为: str, 权重: float = 0.5, 真实度: float = 0.8):
        """
        记录互动质量：点赞/评论/评价的真实度
        真实度判定：
        - 1.0 = 真心（详细评价+多次互动）
        - 0.5 = 一般（简单评论）
        - 0.1 = 敷衍（随手点/刷量）
        """
        记录 = 行为记录(
            时间戳=datetime.now().isoformat(),
            行为类型="互动",
            行为名称=行为,
            原始权重=权重 * 真实度,  # 敷衍的行为权重打折
            真实度=真实度,
            来源="互动分析"
        )
        self.行为库.append(记录)
        self._保存()
        质量标 = "真心" if 真实度 >= 0.8 else "一般" if 真实度 >= 0.5 else "敷衍"
        return f"{'🟢' if 真实度>=0.8 else '🟡' if 真实度>=0.5 else '🔴'} 互动记录: {行为} 真实度:{真实度}({质量标})"

    def 记录服务行为(self, 行为: str, 权重: float = 5.0):
        """记录为人民服务的行为：真心帮助他人"""
        记录 = 行为记录(
            时间戳=datetime.now().isoformat(),
            行为类型="服务",
            行为名称=行为,
            原始权重=权重,
            真实度=1.0,  # 服务行为权重最高
            来源="社区认证"
        )
        self.行为库.append(记录)
        self._保存()
        return f"🟢 服务行为已记录: {行为} (+{权重}分) — 为人民服务"

    def 记录习惯(self, 行为: str, 连续天数: int = 1):
        """记录习惯行为：连续天数越多权重越高"""
        权重 = min(连续天数 * 0.3, 5.0)  # 连续习惯加分，封顶5分
        记录 = 行为记录(
            时间戳=datetime.now().isoformat(),
            行为类型="习惯",
            行为名称=行为,
            原始权重=round(权重, 2),
            真实度=1.0,
            来源="习惯追踪"
        )
        self.行为库.append(记录)
        self._保存()
        return f"🟢 习惯记录: {行为} 连续{连续天数}天 (+{round(权重,2)}分)"

    # ── 六大维度分数计算 ──
    def 计算六大维度(self) -> Dict[str, Any]:
        """计算六大维度分数"""
        维度 = {
            "环保贡献": {"分": 0, "条": 0, "亮灯": self.亮灯设置["环保贡献"]},
            "信誉分": {"分": 0, "条": 0, "亮灯": self.亮灯设置["信誉分"]},
            "互动质量": {"分": 0, "条": 0, "亮灯": self.亮灯设置["互动质量"]},
            "服务分": {"分": 0, "条": 0, "亮灯": self.亮灯设置["服务分"]},
            "习惯分": {"分": 0, "条": 0, "亮灯": self.亮灯设置["习惯分"]},
        }

        for 记录 in self.行为库:
            类型映射 = {
                "环保": "环保贡献",
                "信誉": "信誉分",
                "互动": "互动质量",
                "服务": "服务分",
                "习惯": "习惯分",
            }
            维度名 = 类型映射.get(记录.行为类型)
            if 维度名:
                维度[维度名]["分"] += 记录.原始权重
                维度[维度名]["条"] += 1

        # 计算真实度总分（各维度加权）
        总分 = sum(v["分"] for v in 维度.values())
        加权 = (
            维度["环保贡献"]["分"] * 0.15 +
            维度["信誉分"]["分"] * 0.25 +
            维度["互动质量"]["分"] * 0.15 +
            维度["服务分"]["分"] * 0.30 +
            维度["习惯分"]["分"] * 0.15
        )

        return {
            "六大维度": 维度,
            "原始总分": round(总分, 2),
            "真实度加权总分": round(加权, 2),
            "行为总数": len(self.行为库),
            "用户ID": self.用户ID,
            "DNA": __dna__,
        }

    # ── 亮灯控制（用户自主）──
    def 设置亮灯(self, 维度: str, 开关: bool):
        """用户自主控制哪个维度对外亮灯"""
        if 维度 in self.亮灯设置:
            self.亮灯设置[维度] = 开关
            self._保存()
            return f"{'🟢' if 开关 else '🔴'} {维度}: {'已亮灯' if 开关 else '已熄灯'}"
        return f"🟡 未知维度: {维度}"

    def 获取亮灯展示(self) -> str:
        """获取对外展示的亮灯信息"""
        分数 = self.计算六大维度()
        展示 = []
        for 维度名, 数据 in 分数["六大维度"].items():
            if 数据["亮灯"]:
                灯 = "🟢" if 数据["分"] > 0 else "⚪"
                展示.append(f"{灯} {维度名}: {round(数据['分'],1)}分 ({数据['条']}条)")
        展示.append(f"⭐ 真实度加权总分: {分数['真实度加权总分']}")
        return "\n".join(展示)

    # ── 排名（龍魂系统内）──
    def 获取排名(self, 全局数据: List[Dict]) -> int:
        """在龍魂系统中排名"""
        我的分 = self.计算六大维度()["真实度加权总分"]
        所有人 = sorted([d.get("真实度加权总分", 0) for d in 全局数据], reverse=True)
        try:
            return 所有人.index(我的分) + 1
        except ValueError:
            return len(所有人) + 1

    # ── 存取 ──
    def _保存(self):
        数据 = {
            "用户ID": self.用户ID,
            "行为库": [asdict(r) for r in self.行为库],
            "亮灯设置": self.亮灯设置,
            "DNA": __dna__,
        }
        路径 = f"/tmp/longhun_behavior_{self.用户ID}.json"
        with open(路径, "w", encoding="utf-8") as f:
            json.dump(数据, f, ensure_ascii=False, indent=2)

    def _加载(self):
        路径 = f"/tmp/longhun_behavior_{self.用户ID}.json"
        if os.path.exists(路径):
            with open(路径, "r", encoding="utf-8") as f:
                数据 = json.load(f)
            self.亮灯设置 = 数据.get("亮灯设置", self.亮灯设置)


