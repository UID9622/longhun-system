"""
龍魂版本向量时钟 — 双设备并发控制与一致性保证
================================================
DNA: #龍芯⚡️2026-06-19-SYNC-MSG-v1.0
致敬: #致敬⚡️SteveJobs+Concept·跨平台互通

原理: 版本向量(Version Vector)是分布式系统中跟踪数据版本、
      检测并发冲突的经典算法。每个设备维护一个计数器，
      同步时通过比较向量判断数据先后顺序或并发关系。

三色审计:
🟢 向量一致 — 版本对齐，无冲突
🟡 并发冲突 — 双设备同时修改，需解决
🔴 时钟异常 — 向量格式错误或版本不兼容
"""

import json
import time
import copy
import logging
from typing import Dict, Optional, Tuple, Any
from enum import Enum
from dataclasses import dataclass, field

logger = logging.getLogger("版本向量时钟")


# ============================================================
# 君子协议
# ============================================================
君子协议 = """
================================================================================
龍魂版本向量时钟 · 君子协议
================================================================================
1. 版本向量是数据一致性的核心保障，禁止绕过直接修改数据
2. 冲突解决优先保留双方数据，删除需人工确认
3. 版本向量必须在每次数据修改时递增
4. 同步时必须比较版本向量，不能覆盖式写入
5. 并发冲突必须记录日志，不可静默丢弃任一方数据
================================================================================
"""


class 时钟状态(Enum):
    """版本比较结果状态"""
    之前 = "before"        # 本地数据比远程旧
    之后 = "after"         # 本地数据比远程新
    相等 = "equal"         # 数据一致
    并发 = "concurrent"    # 并发冲突！


@dataclass
class 版本快照:
    """数据版本快照"""
    数据: Dict[str, Any]
    向量: Dict[str, int]
    时间戳: int = 0
    设备: str = ""
    dna: str = ""


class 版本向量时钟:
    """
    龍魂版本向量时钟
    
    职责:
    1. 维护每个设备的版本计数器
    2. 比较数据版本先后关系
    3. 检测并发修改冲突
    4. 合并版本向量
    5. 为冲突解决提供依据
    """
    
    DNA = "#龍芯⚡️2026-06-19-SYNC-MSG-v1.0"
    
    def __init__(self, 设备A: str = "harmonyos", 设备B: str = "ios"):
        print(君子协议)
        
        # 版本向量: {设备名: 计数器}
        self.向量: Dict[str, int] = {设备A: 0, 设备B: 0}
        self.设备A = 设备A
        self.设备B = 设备B
        self.本机标识: Optional[str] = None
        
        # 历史版本记录（用于追溯）
        self._历史: list = []
        
        logger.info("🟢 [初始化] 版本向量时钟")
        logger.info("🟢 [设备] %s ↔ %s", 设备A, 设备B)
    
    # ============================================================
    # 核心API
    # ============================================================
    
    def 递增(self, 设备: str) -> Dict[str, int]:
        """
        指定设备的版本计数器递增
        
        每次本地修改数据前必须调用此方法
        
        Args:
            设备: 设备标识，如 "harmonyos" 或 "ios"
        
        Returns:
            递增后的完整向量
        """
        if 设备 not in self.向量:
            self.向量[设备] = 0
            logger.info("🟢 [时钟] 新设备 '%s' 已加入向量", 设备)
        
        self.向量[设备] += 1
        
        # 记录历史
        self._历史.append({
            "操作": "递增",
            "设备": 设备,
            "新值": self.向量[设备],
            "时间": int(time.time() * 1000),
            "完整向量": copy.deepcopy(self.向量)
        })
        
        logger.info("🟢 [时钟] %s 计数器递增 → %d", 设备, self.向量[设备])
        return copy.deepcopy(self.向量)
    
    def 比较(self, 远程向量: Dict[str, int]) -> 时钟状态:
        """
        比较本地向量与远程向量
        
        判断数据先后关系:
        - 本地所有计数 >= 远程: 本地更新 (after)
        - 本地所有计数 <= 远程: 远程更新 (before)
        - 本地部分 > 远程部分 < : 并发冲突！ (concurrent)
        - 完全相等: 一致 (equal)
        
        Args:
            远程向量: 对端设备的版本向量
        
        Returns:
            时钟状态枚举
        """
        if not isinstance(远程向量, dict):
            logger.error("🔴 [时钟] 远程向量格式错误")
            return 时钟状态.并发  # 保守处理
        
        # 获取所有设备键
        所有键 = set(self.向量.keys()) | set(远程向量.keys())
        
        本地更大 = False
        远程更大 = False
        
        for 键 in 所有键:
            本地值 = self.向量.get(键, 0)
            远程值 = 远程向量.get(键, 0)
            
            if 本地值 > 远程值:
                本地更大 = True
            elif 本地值 < 远程值:
                远程更大 = True
        
        # 判断关系
        if 本地更大 and not 远程更大:
            return 时钟状态.之后
        elif 远程更大 and not 本地更大:
            return 时钟状态.之前
        elif not 本地更大 and not 远程更大:
            return 时钟状态.相等
        else:
            logger.warning("🟡 [时钟] ⚠️ 检测到并发冲突!")
            logger.warning("🟡 [时钟] 本地: %s", self.向量)
            logger.warning("🟡 [时钟] 远程: %s", 远程向量)
            return 时钟状态.并发
    
    def 合并(self, 远程向量: Dict[str, int]) -> Dict[str, int]:
        """
        合并远程向量到本地（逐元素取最大值）
        
        在成功同步后调用，更新本地版本向量
        
        Args:
            远程向量: 对端的版本向量
        
        Returns:
            合并后的向量
        """
        所有键 = set(self.向量.keys()) | set(远程向量.keys())
        
        for 键 in 所有键:
            本地值 = self.向量.get(键, 0)
            远程值 = 远程向量.get(键, 0)
            self.向量[键] = max(本地值, 远程值)
        
        logger.info("🟢 [时钟] 向量合并完成: %s", self.向量)
        return copy.deepcopy(self.向量)
    
    def 获取向量(self) -> Dict[str, int]:
        """获取当前版本向量的深拷贝"""
        return copy.deepcopy(self.向量)
    
    def 设置本机标识(self, 标识: str):
        """设置本机设备标识"""
        self.本机标识 = 标识
        if 标识 not in self.向量:
            self.向量[标识] = 0
        logger.info("🟢 [时钟] 本机标识设为 '%s'", 标识)
    
    # ============================================================
    # 冲突检测
    # ============================================================
    
    def 检测冲突(
        self,
        本地数据: Dict,
        远程数据: Dict,
        本地向量: Dict[str, int],
        远程向量: Dict[str, int]
    ) -> Tuple[bool, 时钟状态]:
        """
        检测两组数据是否存在冲突
        
        Args:
            本地数据: 本地数据
            远程数据: 远程数据
            本地向量: 本地版本向量
            远程向量: 远程版本向量
        
        Returns:
            (是否冲突, 状态)
        """
        状态 = self.比较(远程向量)
        
        if 状态 == 时钟状态.并发:
            # 进一步检查数据内容是否真的不同
            if 本地数据 == 远程数据:
                logger.info("🟢 [时钟] 向量显示并发，但数据内容一致，无需解决")
                return False, 时钟状态.相等
            
            logger.warning("🟡 [冲突] 数据内容不同且向量并发!")
            return True, 状态
        
        return False, 状态
    
    def 分析冲突细节(
        self,
        本地数据: Dict,
        远程数据: Dict
    ) -> Dict[str, Any]:
        """
        分析冲突的具体差异
        
        返回:
            {
                "冲突字段": [...],
                "仅本地有": [...],
                "仅远程有": [...],
                "共同字段": [...],
                "冲突摘要": str
            }
        """
        本地键 = set(本地数据.keys())
        远程键 = set(远程数据.keys())
        
        仅本地 = list(本地键 - 远程键)
        仅远程 = list(远程键 - 本地键)
        共同键 = 本地键 & 远程键
        
        冲突字段 = []
        for 键 in 共同键:
            if 本地数据[键] != 远程数据[键]:
                冲突字段.append({
                    "字段": 键,
                    "本地值": str(本地数据[键])[:100],  # 截断长值
                    "远程值": str(远程数据[键])[:100]
                })
        
        return {
            "冲突字段数": len(冲突字段),
            "冲突字段": 冲突字段,
            "仅本地有": 仅本地,
            "仅远程有": 仅远程,
            "共同字段": list(共同键),
            "冲突摘要": f"{len(冲突字段)}个字段冲突, {len(仅本地)}个仅本地, {len(仅远程)}个仅远程"
        }
    
    # ============================================================
    # 序列化
    # ============================================================
    
    def 向量转JSON(self) -> str:
        """将向量转为JSON字符串"""
        return json.dumps(self.向量, sort_keys=True)
    
    def JSON转向量(self, JSON字符串: str) -> Dict[str, int]:
        """从JSON字符串恢复向量"""
        向量 = json.loads(JSON字符串)
        return {k: int(v) for k, v in 向量.items()}
    
    # ============================================================
    # 诊断
    # ============================================================
    
    def 获取历史(self) -> list:
        """获取版本向量操作历史"""
        return copy.deepcopy(self._历史)
    
    def 获取诊断(self) -> Dict[str, Any]:
        """获取诊断信息"""
        return {
            "当前向量": self.向量,
            "设备A": self.设备A,
            "设备B": self.设备B,
            "本机标识": self.本机标识,
            "历史操作数": len(self._历史),
            "dna": self.DNA
        }
    
    def 打印状态(self):
        """打印当前状态"""
        print(f"\n{'='*50}")
        print("  版本向量时钟状态")
        print(f"{'='*50}")
        for 设备, 计数 in sorted(self.向量.items()):
            标记 = " ← 本机" if 设备 == self.本机标识 else ""
            print(f"  {设备}: {计数}{标记}")
        print(f"{'='*50}\n")


