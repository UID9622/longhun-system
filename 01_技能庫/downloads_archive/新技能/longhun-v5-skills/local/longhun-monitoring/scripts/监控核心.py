    def 評估系統健康(self) -> 系統健康狀態:
        """評估系統整體健康狀態"""
        組件分數 = {}

        # 基於15層狀態計算
        for 層級, 狀態 in self.層級狀態.items():
            層級名 = f"層級{層級}"
            if "✅" in 狀態["狀態"]:
                組件分數[層級名] = 100.0
            elif "⚠️" in 狀態["狀態"]:
                組件分數[層級名] = 60.0
            else:
                組件分數[層級名] = 30.0

        # 計算總分（加權平均）
        if 組件分數:
            總分 = sum(組件分數.values()) / len(組件分數)
        else:
            總分 = 0

        # 評估風險
        是否安全 = 總分 >= 70
        if 總分 >= 80:
            風險級別 = "🟢 安全"
        elif 總分 >= 60:
            風險級別 = "🟡 風險"
        else:
            風險級別 = "🔴 危險"

        # 計算趨勢
        if len(self.指標歷史) > 10:
            最近 = self.指標歷史[-5:]
            較早 = self.指標歷史[-10:-5]
            最近均值 = sum(m.數值 for m in 最近 if isinstance(m.數值, (int, float))) / max(len(最近), 1)
            較早均值 = sum(m.數值 for m in 較早 if isinstance(m.數值, (int, float))) / max(len(較早), 1)

            if 最近均值 > 較早均值 * 1.1:
                趨勢 = "↗️ 改善"
            elif 最近均值 < 較早均值 * 0.9:
                趨勢 = "↘️ 惡化"
            else:
                趨勢 = "→ 穩定"
        else:
            趨勢 = "→ 穩定"

        self.當前狀態 = 系統健康狀態(
            總分=round(總分, 2),
            組件分數=組件分數,
            是否安全=是否安全,
            風險級別=風險級別,
            上次告警=self.告警歷史[-1] if self.告警歷史 else None,
            趨勢=趨勢,
        )

        return self.當前狀態

