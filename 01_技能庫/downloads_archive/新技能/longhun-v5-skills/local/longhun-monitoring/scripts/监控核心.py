    # ======== 啟動/停止 ========

    def 啟動(self):
        """啟動監控系統"""
        if self.運行中:
            return {"狀態": "已在運行"}

        self.運行中 = True

        def 監控循環():
            while self.運行中:
                try:
                    self.執行完整監控()
                    time.sleep(30)  # 每30秒執行一次
                except Exception as e:
                    self.審計器.記錄(審計級別.紅, "監控循環異常", "系統", "失敗", {"錯誤": str(e)})

        self.監控線程 = threading.Thread(target=監控循環, daemon=True)
        self.監控線程.start()

        self.審計器.記錄(審計級別.紅, "監控系統啟動", "系統", "成功")

        return {
            "狀態": "✅ 已啟動",
            "監控間隔": "30秒",
            "DNA": self.DNA,
        }

    def 停止(self):
        """停止監控系統"""
        self.運行中 = False
        if self.監控線程:
            self.監控線程.join(timeout=5)

        self.審計器.記錄(審計級別.紅, "監控系統停止", "系統", "成功")

        return {"狀態": "✅ 已停止", "DNA": self.DNA}

