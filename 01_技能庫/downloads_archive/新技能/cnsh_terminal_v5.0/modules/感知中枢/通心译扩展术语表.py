# 铁律自审闸 —— 任何操作进中枢前必须先过闸
# Iron-Rule Self-Audit Gate —— every operation must pass the gate before entering hub
# =============================================================================
class 铁律自审闸:
    """
    铁律自审闸 —— 龍魂感知中枢的「安检门」
    Iron-Rule Self-Audit Gate —— the "security checkpoint" of LongHun perception hub

    闸的设计哲学：
    在任何感知操作执行之前，必须先经过这道铁律闸的审查。
    铁律是不可违反的硬性规则——一旦触发，操作直接被阻断。

    三条铁律（核心安全屏障——用中文注释阐述安全策略）：
    铁律一: 路径合法性检查——输入路径不能为空，不能包含路径遍历攻击字符
    铁律二: 文件可访问性检查——文件必须存在且可读
    铁律三: 文件类型安全检查——拒绝执行潜在危险的文件类型

    闸的理念——宁可错杀一千，不可放过一个。
    感知中枢处理的是外部输入，外部输入永远不可信任。
    """

    def __init__(self):
        # 危险扩展名列表——这些文件类型不允许进入感知中枢
        self.危险扩展名 = {
            '.exe', '.bat', '.cmd', '.sh', '.py', '.js',
            '.vbs', '.ps1', '.php', '.jsp', '.asp',
        }
        self.审查次数 = 0
        self.拦截次数 = 0

    def 审查(self, 输入路径: str) -> Dict[str, Any]:
        """
        审查输入路径是否通过三条铁律
        Check if input path passes all three iron rules
        """
        self.审查次数 += 1
        违规项 = []

        # 铁律一: 路径合法性检查
        if not 输入路径 or not isinstance(输入路径, str):
            违规项.append("铁律一-路径为空或非字符串")
        if 输入路径 and ('..' in 输入路径 or '~' in 输入路径):
            违规项.append("铁律一-路径包含遍历攻击字符")

        # 铁律二: 文件可访问性检查（仅检查非空路径）
        if 输入路径 and not os.path.exists(输入路径):
            # 注意: 文件不存在不直接阻断——可能是一个URL或未来要创建的路径
            pass  # 不将此视为违规，留给上层处理

        # 铁律三: 文件类型安全检查
        if 输入路径:
            扩展名 = os.path.splitext(输入路径)[1].lower()
            if 扩展名 in self.危险扩展名:
                违规项.append(f"铁律三-危险文件类型: {扩展名}")

        通过 = len(违规项) == 0
        if not 通过:
            self.拦截次数 += 1

        return {
            "通过": 通过,
            "违规项": 违规项,
            "审查编号": self.审查次数,
            "累计拦截": self.拦截次数,
        }

    def 获取统计(self) -> Dict[str, int]:
        return {"审查次数": self.审查次数, "拦截次数": self.拦截次数}


