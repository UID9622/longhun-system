    def 翻译(self, 文本: str, 方向: str = "英到中") -> str:
        """
        翻译文本中的术语——将已知术语替换为目标语言
        Translate known terms in text to target language

        参数:
            文本: 待翻译的文本
            方向: "英到中" 或 "中到英"

        实现原理: 按术语长度降序替换——先替换长的术语，再替换短的
        这样可以避免短术语的误匹配（例如先替换 "Token" 再替换 "Attention"
        而不会把 "Attention" 中的 "ten" 错误匹配到 "Token"）
        """
        结果 = 文本
        if 方向 == "英到中":
            # 英到中: 按英文术语长度降序，先替换长的
            for 英文, 中文 in sorted(self.英文到中文.items(), key=lambda x: len(x[0]), reverse=True):
                结果 = 结果.replace(英文, 中文)
        elif 方向 == "中到英":
            # 中到英: 按中文术语长度降序，先替换长的
            for 中文, 英文 in sorted(self.中文到英文.items(), key=lambda x: len(x[0]), reverse=True):
                结果 = 结果.replace(中文, 英文)
        else:
            raise ValueError(f"不支持的翻译方向: {方向}，仅支持 '英到中' 或 '中到英'")

        self.审计日志.append(审计结果(
            颜色=审计颜色.绿色通过,
            置信度=1.0,
            原因=f"翻译完成: {方向}, 文本长度={len(文本)}",
            建议=""
        ))
        return 结果

    def 翻译文本块(self, 文本块: str) -> str:
        """智能判断文本块的主要语言并翻译——自动方向检测"""
        # 启发式判断: 如果英文字母比例超过50%，认为是英文文本
        英文字母数 = sum(1 for c in 文本块 if c.isascii() and c.isalpha())
        总字母数 = sum(1 for c in 文本块 if c.isalpha())

        if 总字母数 == 0:
            方向 = "英到中"  # 默认方向
        elif 英文字母数 / 总字母数 > 0.5:
            方向 = "英到中"
        else:
            方向 = "中到英"

        return self.翻译(文本块, 方向)

