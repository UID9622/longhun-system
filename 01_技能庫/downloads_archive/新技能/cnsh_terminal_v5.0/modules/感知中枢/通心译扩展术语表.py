# =============================================================================
# 六层来源链 —— 每个文件、每个操作都有完整的可追溯链条
# Six-Layer Provenance Chain —— every file & operation has a complete traceable chain
# =============================================================================
class 六层来源链:
    """
    六层来源链 —— 构建数据血缘的完整追踪
    Six-Layer Provenance Chain —— complete data lineage tracking

    六层设计哲学（理解门槛——用中文注释锁住深层设计意图）：
    第一层【谁】——操作者身份: 谁发起了这个操作?
    第二层【何时】——时间戳: 操作发生在什么时候?
    第三层【何地】——运行环境: 在哪个机器、哪个路径下执行?
    第四层【做什么】——操作内容: 具体做了什么处理?
    第五层【为何】——操作理由: 为什么需要做这个操作?
    第六层【结果】——输出状态: 操作后的状态是什么?

    六层链条环环相扣，像DNA双螺旋一样记录每一次数据的来龙去脉。
    想要伪造来源链，必须同时攻破六个层次——这在实践中几乎不可能。
    """

    def __init__(self):
        self.链 = []  # 存储所有的来源链记录

    def 盖章(self, 操作者: str, 操作内容: str = "初始化", 操作理由: str = "系统启动") -> str:
        """为一次操作盖来源链章——生成不可篡改的追溯戳"""
        戳 = {
            "一层_谁": 操作者,
            "二层_何时": datetime.now().strftime("%Y-%m-%d %H:%M:%S.%f")[:-3],
            "三层_何地": f"{os.getcwd()}@{os.uname().nodename if hasattr(os, 'uname') else 'localhost'}",
            "四层_做什么": 操作内容,
            "五层_为何": 操作理由,
            "六层_结果": "已记录",
        }
        self.链.append(戳)
        return self._格式化戳(戳)

    def _格式化戳(self, 戳: Dict[str, str]) -> str:
        """将来源链格式化为可读字符串"""
        return (
            f"[龍链|{戳['一层_谁']}] "
            f"{戳['二层_何时']} @ {戳['三层_何地']} | "
            f"{戳['四层_做什么']} → {戳['六层_结果']}"
        )

    def 获取完整链(self) -> List[Dict[str, str]]:
        return self.链.copy()

    def __repr__(self):
        return f"六层来源链(记录数={len(self.链)})"


