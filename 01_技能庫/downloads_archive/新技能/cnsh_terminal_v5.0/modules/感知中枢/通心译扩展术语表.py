    def _获取分类(self, 术语: str) -> str:
        """根据术语查找其所属分类"""
        for 分类名, 术语列表 in self.分类.items():
            if 术语 in 术语列表:
                return 分类名
        # 反向查找——可能是中文术语
        英文术语 = self.中文到英文.get(术语, 术语)
        for 分类名, 术语列表 in self.分类.items():
            if 英文术语 in 术语列表:
                return 分类名
        return "未分类"

    # =========================================================================
    # 批量查询方法 —— 术语表的整体操作
    # Batch query methods —— operations on the entire terminology table
    # =========================================================================

    def 获取全部术语(self) -> Dict[str, Any]:
        """获取术语表的整体统计信息"""
        return {
            "总数": len(self.英文到中文),
            "分类统计": {k: len(v) for k, v in self.分类.items()},
            "分类": self.分类,
        }

    def 搜索术语(self, 关键词: str) -> List[Dict[str, str]]:
        """模糊搜索术语——支持中英文关键词"""
        结果 = []
        关键词小写 = 关键词.lower()

        for 英文, 中文 in self.英文到中文.items():
            if 关键词小写 in 英文.lower() or 关键词 in 中文:
                结果.append({"英文": 英文, "中文": 中文, "分类": self._获取分类(英文)})

        return 结果

    def 获取分类术语(self, 分类名: str) -> List[str]:
        """获取某个分类下的所有术语"""
        return self.分类.get(分类名, [])

    def 添加术语(self, 英文: str, 中文: str, 分类: str = "未分类") -> bool:
        """动态添加新术语到术语表——保持术语表的可扩展性"""
        if 英文 in self.英文到中文:
            self.审计日志.append(审计结果(
                颜色=审计颜色.黄色警告,
                置信度=0.5,
                原因=f"术语 '{英文}' 已存在，跳过添加",
                建议="如需要更新，请先删除旧术语再添加"
            ))
            return False

        self.英文到中文[英文] = 中文
        self.中文到英文[中文] = 英文

        if 分类 not in self.分类:
            self.分类[分类] = []
        self.分类[分类].append(英文)

        self.审计日志.append(审计结果(
            颜色=审计颜色.绿色通过,
            置信度=1.0,
            原因=f"术语添加成功: {英文} → {中文} [{分类}]",
            建议=""
        ))
        return True

    def 获取审计日志(self) -> List[审计结果]:
        return self.审计日志.copy()

    def __repr__(self):
        return f"通心译扩展术语引擎(术语数={len(self.英文到中文)}, 分类={list(self.分类.keys())})"


