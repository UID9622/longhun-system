"""
【龍魂实名证书】

这个类的作用：
用户绑定了手机号/支付宝/微信之后，需要有个"证明"给第三方平台看。
这个证明就是"龍魂实名证书"。

证书包含什么：
  - 龍魂ID（谁的身份）
  - 绑定了哪些实名信息（脱敏显示）
  - 绑定时间（什么时候绑的）
  - 签名（防止伪造，用的是国密SM2）
  - 有效期（证书有效期限）

第三方怎么验证：
  1. 拿到证书文件或二维码
  2. 调用验证接口
  3. 系统检查签名和有效期
  4. 返回验证结果（有效/无效 + 原因）
"""

