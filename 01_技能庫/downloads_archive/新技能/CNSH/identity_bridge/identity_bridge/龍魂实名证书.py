class 国密SM2工具:
    """
    【国密SM2工具】
    
    SM2是中国自己的加密算法，比国外的RSA/ECC更安全。
    这里用hash模拟签名过程，实际生产环境应该调用国密库。
    
    SM2的特点：
      - 密钥短，安全性高
      - 中国国家密码管理局发布
      - 金融、政务系统强制使用
    """

    def __init__(self):
        # 模拟SM2密钥对
        # 实际应该用 gmssl 或类似的国密库生成
        self.私钥 = self._生成模拟密钥("龍魂实名认证系统私钥")
        self.公钥 = self._生成模拟密钥("龍魂实名认证系统公钥")

    def _生成模拟密钥(self, 种子):
        """用种子生成模拟密钥"""
        return hashlib.sha256(种子.encode("utf-8")).hexdigest()

    def 签名(self, 数据):
        """
        🟡 用私钥对数据进行签名
        
        实际SM2签名过程很复杂，这里用简化版模拟：
          1. 把数据转成字符串
          2. 加上私钥一起哈希
          3. 返回签名值
        """
        数据字符串 = json.dumps(数据, sort_keys=True, ensure_ascii=False)
        签名输入 = f"{self.私钥}:{数据字符串}"
        签名值 = hashlib.sha256(签名输入.encode("utf-8")).hexdigest()
        return 签名值

    def 验证签名(self, 数据, 签名值):
        """
        🟢 用公钥验证签名
        
        验证过程：
          1. 重新计算签名
          2. 跟传入的签名比较
          3. 一样就是真的，不一样就是伪造的
        """
        期望签名 = self.签名(数据)
        return 签名值 == 期望签名


class 证书验证器:
    """
    【证书验证器】
    
    第三方平台用这个东西来验证龍魂实名证书。
    只要调用验证方法，就能知道证书是真是假。
    """

    def __init__(self):
        self.SM2 = 国密SM2工具()

    def 验证(self, 证书):
        """
        🟢 验证证书是否有效
        
        检查项：
          1. 证书格式对不对
          2. 签名是否有效（没被篡改）
          3. 证书是否过期
          4. 绑定信息是否完整
        
        参数：
            证书: 证书字典
        
        返回：
            {
                "有效": True/False,
                "原因": "...",
                "龍魂ID": "...",
                "认证等级": "...",
                "绑定信息": [...],
            }
        """
        # 检查1：格式
        if not isinstance(证书, dict):
            return self._失败("证书格式不对，应该是一个字典")

        必填字段 = ["证书ID", "龍魂ID", "版本", "绑定信息", "签名", "生成时间", "过期时间"]
        for 字段 in 必填字段:
            if 字段 not in 证书:
                return self._失败(f"证书缺少必填字段: {字段}")

        # 检查2：签名
        签名数据 = {
            "证书ID": 证书["证书ID"],
            "龍魂ID": 证书["龍魂ID"],
            "版本": 证书["版本"],
            "绑定信息": 证书["绑定信息"],
            "生成时间": 证书["生成时间"],
            "过期时间": 证书["过期时间"],
        }
        if not self.SM2.验证签名(签名数据, 证书["签名"]):
            return self._失败("证书签名无效，证书可能被篡改")

        # 检查3：有效期
        try:
            过期时间 = datetime.fromisoformat(证书["过期时间"])
            if datetime.now() > 过期时间:
                return self._失败(f"证书已过期（过期时间: {证书['过期时间']}）")
        except ValueError:
            return self._失败("证书过期时间格式不对")

        # 检查4：绑定信息不能为空
        if not 证书["绑定信息"]:
            return self._失败("证书中没有绑定信息")

        # 全部通过，证书有效
        认证等级 = self._计算认证等级(证书["绑定信息"])
        return {
            "有效": True,
            "原因": "证书有效",
            "龍魂ID": 证书["龍魂ID"],
            "证书ID": 证书["证书ID"],
            "认证等级": 认证等级,
            "绑定信息": [b["类型"] for b in 证书["绑定信息"]],
            "生成时间": 证书["生成时间"],
            "过期时间": 证书["过期时间"],
            "剩余天数": (过期时间 - datetime.now()).days,
        }

    def _失败(self, 原因):
        """返回验证失败结果"""
        return {
            "有效": False,
            "原因": 原因,
            "龍魂ID": None,
            "认证等级": None,
            "绑定信息": [],
        }

    def _计算认证等级(self, 绑定信息列表):
        """根据绑定信息计算认证等级"""
        类型集合 = set()
        for 绑定 in 绑定信息列表:
            类型集合.add(绑定["类型"])

        if len(类型集合) >= 3:
            return "完全认证"
        elif len(类型集合) >= 2:
            return "高级认证"
        elif len(类型集合) >= 1:
            return "基础认证"
        return "未认证"


class 龍魂实名证书:
    """
    【龍魂实名证书】
    
    核心类。负责：
      1. 生成证书 — 用户绑定完成后生成
      2. 验证证书 — 第三方平台调用
      3. 导出二维码 — 方便扫码验证
      4. 导出链接 — 方便点击验证
    
    使用方法：
        证书工具 = 龍魂实名证书()
        证书 = 证书工具.生成证书("UID9622", [绑定凭证1, 绑定凭证2])
        结果 = 证书工具.验证证书(证书, "UID9622")
    """

    def __init__(self):
        self.SM2 = 国密SM2工具()
        self.验证器 = 证书验证器()
        self.证书存储 = {}  # 证书ID → 证书

    def _生成证书ID(self, 龍魂ID):
        """生成唯一的证书ID"""
        时间戳 = str(int(time.time()))
        随机数 = hashlib.sha256(os.urandom(32)).hexdigest()[:8]
        return f"CERT-{龍魂ID}-{时间戳}-{随机数}"

    def 生成证书(self, 龍魂ID, 绑定信息列表, 有效期天数=30):
        """
        🟡 生成龍魂实名证书
        
        参数：
            龍魂ID: 用户的龍魂ID，如 "UID9622"
            绑定信息列表: 绑定凭证列表（从实名绑定器获取）
            有效期天数: 证书有效期，默认30天
        
        返回：
            证书字典
        """
        # 证书ID
        证书ID = self._生成证书ID(龍魂ID)
        
        # 当前时间
        现在 = datetime.now()
        过期时间 = 现在 + timedelta(days=有效期天数)

        # 提取绑定信息（脱敏）
        证书绑定信息 = []
        for 绑定 in 绑定信息列表:
            脱敏标识 = 绑定.get("脱敏手机号") or 绑定.get("脱敏账号") or 绑定.get("脱敏OPENID", "****")
            证书绑定信息.append({
                "类型": 绑定["类型"],
                "脱敏标识": 脱敏标识,
                "绑定时间": 绑定["绑定时间"],
                "运营商": 绑定.get("运营商", ""),
                "实名状态": 绑定.get("实名状态", ""),
            })

        # 证书内容
        证书 = {
            "证书ID": 证书ID,
            "龍魂ID": 龍魂ID,
            "版本": "1.0",
            "绑定信息": 证书绑定信息,
            "生成时间": 现在.strftime("%Y-%m-%d %H:%M:%S"),
            "过期时间": 过期时间.strftime("%Y-%m-%d %H:%M:%S"),
            "签名": "",  # 后面填充
        }

        # 生成签名（对证书内容签名）
        签名数据 = {
            "证书ID": 证书["证书ID"],
            "龍魂ID": 证书["龍魂ID"],
            "版本": 证书["版本"],
            "绑定信息": 证书["绑定信息"],
            "生成时间": 证书["生成时间"],
            "过期时间": 证书["过期时间"],
        }
        证书["签名"] = self.SM2.签名(签名数据)

        # 存入存储
        self.证书存储[证书ID] = 证书

        return 证书

    def 验证证书(self, 证书, 龍魂ID):
        """
        🟢 验证证书是否有效
        
        参数：
            证书: 证书字典
            龍魂ID: 期望的龍魂ID（防止调包）
        
        返回：
            {
                "有效": True/False,
                "原因": "...",
                "龍魂ID": "...",
                "认证等级": "...",
            }
        """
        # 先检查龍魂ID是否匹配
        if 证书.get("龍魂ID") != 龍魂ID:
            return {
                "有效": False,
                "原因": f"龍魂ID不匹配（证书里是 {证书.get('龍魂ID')}，你传的是 {龍魂ID}）",
                "龍魂ID": 龍魂ID,
                "认证等级": None,
                "绑定信息": [],
            }

        # 调用验证器
        return self.验证器.验证(证书)

    def 导出为JSON(self, 证书):
        """
        🟢 把证书导出为JSON字符串
        
        方便存储或传输
        """
        return json.dumps(证书, ensure_ascii=False, indent=2)

    def 导出为二维码内容(self, 证书):
        """
        🟢 把证书导出为二维码内容
        
        二维码里放的是一个验证链接，
        扫码后可以直接跳转到验证页面。
        
        返回：
            一个字符串，可以生成二维码
        """
        证书ID = 证书["证书ID"]
        龍魂ID = 证书["龍魂ID"]
        # 格式：龍魂://验证/证书ID/龍魂ID
        return f"龍魂://verify/{证书ID}/{龍魂ID}"

    def 导出为链接(self, 证书):
        """
        🟢 把证书导出为验证链接
        
        可以分享给第三方平台点击验证
        """
        证书ID = 证书["证书ID"]
        龍魂ID = 证书["龍魂ID"]
        # 实际应该是一个HTTPS链接
        return f"https://龍魂实名认证中心.cn/verify?id={证书ID}&uid={龍魂ID}"

    def 导出为文本证书(self, 证书):
        """
        🟢 把证书导出为可读文本格式
        
        方便用户查看和保存
        """
        绑定列表 = []
        for 绑定 in 证书["绑定信息"]:
            绑定列表.append(f"  ✓ {绑定['类型']}: {绑定['脱敏标识']}")

        文本 = f"""
╔══════════════════════════════════════════╗
║          龍 魂 实 名 证 书              ║
╠══════════════════════════════════════════╣
║ 证书编号: {证书['证书ID'][:30]}... ║
║ 龍魂ID:   {证书['龍魂ID']:<30} ║
║ 证书版本: {证书['版本']:<30} ║
╠══════════════════════════════════════════╣
║ 已绑定实名信息:                          ║
{chr(10).join(绑定列表):<42} ║
╠══════════════════════════════════════════╣
║ 生成时间: {证书['生成时间']:<30} ║
║ 过期时间: {证书['过期时间']:<30} ║
╠══════════════════════════════════════════╣
║ 签名: {证书['签名'][:36]}...          ║
║ (国密SM2算法签名，第三方可验证)          ║
╚══════════════════════════════════════════╝
"""
        return 文本

    def 撤销证书(self, 证书ID, 撤销原因=""):
        """
        🔴 撤销证书（危险操作）
        
        用户解除绑定后，对应的证书应该被撤销。
        
        参数：
            证书ID: 要撤销的证书ID
            撤销原因: 为什么撤销
        """
        if 证书ID in self.证书存储:
            self.证书存储[证书ID]["状态"] = "已撤销"
            self.证书存储[证书ID]["撤销原因"] = 撤销原因
            self.证书存储[证书ID]["撤销时间"] = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
            return True, f"证书 {证书ID[:16]}... 已撤销"
        return False, "证书不存在"


