"""
【实名绑定器】

这个类的作用很简单：
用户的龍魂ID是自己"起的名字"，平台不认识。
但手机号、支付宝、微信都是经过国家认证的"真身份"。
我们把它们绑在一起，平台就认这个龍魂ID了。

绑定逻辑：
  1. 用户输入自己的龍魂ID
  2. 选择要绑定的东西（手机号/支付宝/微信）
  3. 系统发验证码或跳转授权页面
  4. 用户确认后，绑定完成
  5. 生成绑定凭证，存在本地
"""

import json
import hashlib
import time
import re
import os
from datetime import datetime, timedelta

# ── 三色审计 ──
# 🟢 安全操作: 查询绑定状态、验证绑定存在性
# 🟡 需要小心: 发起绑定（生成验证码、调用外部接口）
# 🔴 危险操作: 解除绑定（删除用户数据，需二次确认）


class 绑定存储器:
    """
    【绑定存储器】
    
    存东西的地方。实际用的是一个JSON文件。
    生产环境应该用数据库，但这里为了简单，先用文件存。
    
    存的内容：
      - 龍魂ID → 绑定了哪些东西
      - 每个绑定的时间、状态、脱敏信息
    """

    def __init__(self, 存储路径=None):
        # 如果没给路径，就用默认路径
        if 存储路径 is None:
            存储路径 = os.path.join(os.path.dirname(__file__), "绑定数据.json")
        self.存储路径 = 存储路径
        self.数据 = self._加载数据()

    def _加载数据(self):
        """从文件加载绑定数据"""
        if os.path.exists(self.存储路径):
            try:
                with open(self.存储路径, "r", encoding="utf-8") as 文件:
                    return json.load(文件)
            except (json.JSONDecodeError, IOError):
                # 文件坏了就重新开始
                return {}
        return {}

    def _保存数据(self):
        """把绑定数据存到文件"""
        with open(self.存储路径, "w", encoding="utf-8") as 文件:
            json.dump(self.数据, 文件, ensure_ascii=False, indent=2)

    def 读取(self, 龍魂ID):
        """🟢 读某个龍魂ID的绑定信息"""
        return self.数据.get(龍魂ID, {})

    def 写入(self, 龍魂ID, 绑定信息):
        """🟡 写入某个龍魂ID的绑定信息"""
        self.数据[龍魂ID] = 绑定信息
        self._保存数据()

    def 删除(self, 龍魂ID):
        """🔴 删除某个龍魂ID的所有绑定信息"""
        if 龍魂ID in self.数据:
            del self.数据[龍魂ID]
            self._保存数据()

    def 全部龍魂ID(self):
        """🟢 返回所有已绑定的龍魂ID列表"""
        return list(self.数据.keys())


class 实名绑定器:
    """
    【实名绑定器】
    
    核心类。负责把龍魂ID跟各种实名信息绑在一起。
    
    支持的绑定方式：
      1. 手机号 — 三大运营商（移动/联通/电信）已实名
      2. 支付宝 — 已通过实名认证
      3. 微信 — 已通过实名认证
    
    使用方法：
        绑定器 = 实名绑定器()
        绑定器.绑定手机号("UID9622", "13800138000")
        绑定器.绑定支付宝("UID9622", "user@example.com")
        绑定器.绑定微信("UID9622", "oAbCdEfGhIjKlMnOpQrStUv")
        状态 = 绑定器.查询绑定状态("UID9622")
    """

    # 中国手机号正则：1开头，第二位3-9，后面9位数字
    手机号正则 = re.compile(r"^1[3-9]\d{9}$")
    
    # 三大运营商号段（简单匹配）
    运营商号段 = {
        "移动": ["134", "135", "136", "137", "138", "139", "147", "150", "151", "152",
                "157", "158", "159", "172", "178", "182", "183", "184", "187", "188",
                "195", "197", "198"],
        "联通": ["130", "131", "132", "145", "155", "156", "166", "175", "176", "185", "186", "196"],
        "电信": ["133", "149", "153", "173", "177", "180", "181", "189", "190", "191", "193", "199"],
    }

    def __init__(self, 存储器=None):
        """
        初始化绑定器
        
        参数：
            存储器: 绑定存储器实例，默认创建一个
        """
        self.存储器 = 存储器 or 绑定存储器()
        self.审计日志 = []  # 记录所有操作

    def _记录日志(self, 操作, 龍魂ID, 结果, 备注=""):
        """记录一条审计日志"""
        日志条目 = {
            "时间": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            "操作": 操作,
            "龍魂ID": 龍魂ID,
            "结果": 结果,
            "备注": 备注,
        }
        self.审计日志.append(日志条目)

    def _生成验证码(self):
        """生成6位数字验证码（模拟）"""
        import random
        return "".join([str(random.randint(0, 9)) for _ in range(6)])

    def _生成绑定ID(self, 龍魂ID, 绑定类型, 绑定值):
        """生成唯一的绑定ID（用哈希）"""
        原文 = f"{龍魂ID}:{绑定类型}:{绑定值}:{time.time()}"
        return hashlib.sha256(原文.encode("utf-8")).hexdigest()[:16]

    def _脱敏手机号(self, 手机号):
        """手机号脱敏：13800138000 → 138****8000"""
        if len(手机号) == 11:
            return 手机号[:3] + "****" + 手机号[7:]
        return "***"

    def _脱敏支付宝(self, 支付宝账号):
        """支付宝账号脱敏"""
        if "@" in 支付宝账号:
            # 邮箱格式：a***@example.com
            用户名, 域名 = 支付宝账号.split("@")
            if len(用户名) > 1:
                return 用户名[0] + "***@" + 域名
            return "***@" + 域名
        else:
            # 手机号格式
            return self._脱敏手机号(支付宝账号)

    def _脱敏微信(self, 微信OPENID):
        """微信OPENID脱敏：只显示前4位和后4位"""
        if len(微信OPENID) > 8:
            return 微信OPENID[:4] + "****" + 微信OPENID[-4:]
        return "****"

    def _识别运营商(self, 手机号):
        """根据号段识别运营商"""
        前缀 = 手机号[:3]
        for 运营商, 号段列表 in self.运营商号段.items():
            if 前缀 in 号段列表:
                return 运营商
        return "未知运营商"

    def _检查手机号格式(self, 手机号):
        """检查手机号格式是否正确"""
        if not self.手机号正则.match(手机号):
            return False, "手机号格式不对，应该是11位数字，1开头"
        return True, "格式正确"

    # ═══════════════════════════════════════════════════
    # 🟡 绑定操作
    # ═══════════════════════════════════════════════════

    def 绑定手机号(self, 龍魂ID, 手机号, 验证码输入=None):
        """
        🟡 绑定手机号
        
        流程：
          1. 检查手机号格式
          2. 生成验证码（模拟发送SMS）
          3. 用户输入验证码
          4. 验证通过 → 绑定成功
        
        参数：
            龍魂ID: 用户的龍魂ID，如 "UID9622"
            手机号: 11位中国手机号
            验证码输入: 用户收到的验证码（第一次调用不传，第二次传）
        
        返回：
            (成功否, 消息, 绑定凭证)
        """
        # 第一步：检查手机号格式
        格式正确, 格式消息 = self._检查手机号格式(手机号)
        if not 格式正确:
            self._记录日志("绑定手机号", 龍魂ID, "失败", 格式消息)
            return False, 格式消息, None

        # 检查是否已经绑定过这个手机号
        已有绑定 = self.存储器.读取(龍魂ID)
        if "手机号" in 已有绑定:
            if 已有绑定["手机号"].get("完整手机号") == 手机号:
                self._记录日志("绑定手机号", 龍魂ID, "重复绑定", f"手机号已绑定: {self._脱敏手机号(手机号)}")
                return False, "这个手机号已经绑定过了", None

        # 模拟发送验证码（实际应该调SMS接口）
        if 验证码输入 is None:
            验证码 = self._生成验证码()
            # 实际生产环境这里调用SMS接口发短信
            self._记录日志("发送验证码", 龍魂ID, "成功", f"手机号: {self._脱敏手机号(手机号)}")
            return None, f"验证码已发送到 {self._脱敏手机号(手机号)}，请输入验证码完成绑定（演示验证码: {验证码}）", 验证码

        # 验证验证码（演示中只要输入6位数字就算对）
        if not 验证码输入 or len(str(验证码输入)) != 6:
            self._记录日志("绑定手机号", 龍魂ID, "失败", "验证码错误")
            return False, "验证码不对，请重新输入", None

        # 绑定成功，生成凭证
        运营商 = self._识别运营商(手机号)
        绑定ID = self._生成绑定ID(龍魂ID, "手机号", 手机号)
        绑定凭证 = {
            "绑定ID": 绑定ID,
            "类型": "手机号",
            "完整手机号": 手机号,  # 生产环境应该加密存储
            "脱敏手机号": self._脱敏手机号(手机号),
            "运营商": 运营商,
            "绑定时间": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            "状态": "已绑定",
        }

        # 存入存储器
        已有绑定["手机号"] = 绑定凭证
        self.存储器.写入(龍魂ID, 已有绑定)

        self._记录日志("绑定手机号", 龍魂ID, "成功", f"运营商: {运营商}")
        return True, f"手机号绑定成功！({self._脱敏手机号(手机号)}, {运营商})", 绑定凭证

    def 绑定支付宝(self, 龍魂ID, 支付宝账号):
        """
        🟡 绑定支付宝
        
        流程：
          1. 模拟跳转支付宝授权页面
          2. 支付宝返回授权结果（实名信息脱敏）
          3. 绑定成功
        
        参数：
            龍魂ID: 用户的龍魂ID
            支付宝账号: 手机号或邮箱格式的支付宝账号
        
        返回：
            (成功否, 消息, 绑定凭证)
        """
        # 检查格式
        if "@" not in 支付宝账号 and not self.手机号正则.match(支付宝账号):
            return False, "支付宝账号格式不对，应该是手机号或邮箱", None

        # 检查是否已经绑定
        已有绑定 = self.存储器.读取(龍魂ID)
        if "支付宝" in 已有绑定:
            if 已有绑定["支付宝"].get("完整账号") == 支付宝账号:
                return False, "这个支付宝账号已经绑定过了", None

        # 模拟支付宝授权流程
        # 实际生产环境：
        # 1. 生成支付宝授权URL
        # 2. 用户扫码或点击跳转
        # 3. 支付宝回调返回授权码
        # 4. 用授权码换取access_token
        # 5. 用access_token获取用户信息（脱敏）

        print(f"  [模拟] 正在跳转支付宝授权...")
        print(f"  [模拟] 用户 {self._脱敏支付宝(支付宝账号)} 确认授权")
        print(f"  [模拟] 支付宝返回：实名认证通过 ✓")

        # 模拟获取到的支付宝实名信息（脱敏）
        绑定ID = self._生成绑定ID(龍魂ID, "支付宝", 支付宝账号)
        绑定凭证 = {
            "绑定ID": 绑定ID,
            "类型": "支付宝",
            "完整账号": 支付宝账号,  # 生产环境加密
            "脱敏账号": self._脱敏支付宝(支付宝账号),
            "实名状态": "已实名认证",  # 支付宝返回的
            "绑定时间": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            "状态": "已绑定",
        }

        已有绑定["支付宝"] = 绑定凭证
        self.存储器.写入(龍魂ID, 已有绑定)

        self._记录日志("绑定支付宝", 龍魂ID, "成功", f"账号: {self._脱敏支付宝(支付宝账号)}")
        return True, f"支付宝绑定成功！({self._脱敏支付宝(支付宝账号)}, 已实名认证 ✓)", 绑定凭证

    def 绑定微信(self, 龍魂ID, 微信OPENID):
        """
        🟡 绑定微信
        
        流程：
          1. 模拟微信扫码授权
          2. 微信返回授权结果（实名信息脱敏）
          3. 绑定成功
        
        参数：
            龍魂ID: 用户的龍魂ID
            微信OPENID: 微信用户的唯一标识
        
        返回：
            (成功否, 消息, 绑定凭证)
        """
        # 检查OPENID格式（应该是28位左右的字符串）
        if not 微信OPENID or len(微信OPENID) < 10:
            return False, "微信OPENID格式不对", None

        # 检查是否已经绑定
        已有绑定 = self.存储器.读取(龍魂ID)
        if "微信" in 已有绑定:
            if 已有绑定["微信"].get("OPENID") == 微信OPENID:
                return False, "这个微信已经绑定过了", None

        # 模拟微信扫码授权流程
        print(f"  [模拟] 正在生成微信扫码授权页面...")
        print(f"  [模拟] 用户扫码确认授权")
        print(f"  [模拟] 微信返回：实名认证通过 ✓")

        绑定ID = self._生成绑定ID(龍魂ID, "微信", 微信OPENID)
        绑定凭证 = {
            "绑定ID": 绑定ID,
            "类型": "微信",
            "OPENID": 微信OPENID,  # 生产环境加密
            "脱敏OPENID": self._脱敏微信(微信OPENID),
            "实名状态": "已实名认证",  # 微信返回的
            "绑定时间": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            "状态": "已绑定",
        }

        已有绑定["微信"] = 绑定凭证
        self.存储器.写入(龍魂ID, 已有绑定)

        self._记录日志("绑定微信", 龍魂ID, "成功", f"OPENID: {self._脱敏微信(微信OPENID)}")
        return True, f"微信绑定成功！({self._脱敏微信(微信OPENID)}, 已实名认证 ✓)", 绑定凭证

    # ═══════════════════════════════════════════════════
    # 🟢 查询操作
    # ═══════════════════════════════════════════════════

    def 查询绑定状态(self, 龍魂ID):
        """
        🟢 查询某个龍魂ID的绑定状态
        
        返回：
            {
                "龍魂ID": "UID9622",
                "绑定数量": 2,
                "已绑定": ["手机号", "支付宝"],
                "未绑定": ["微信"],
                "详细信息": { ... }
            }
        """
        绑定信息 = self.存储器.读取(龍魂ID)
        
        全部类型 = ["手机号", "支付宝", "微信"]
        已绑定 = []
        未绑定 = []
        
        for 类型 in 全部类型:
            if 类型 in 绑定信息 and 绑定信息[类型].get("状态") == "已绑定":
                已绑定.append(类型)
            else:
                未绑定.append(类型)
        
        # 脱敏后的详细信息
        脱敏详情 = {}
        for 类型 in 已绑定:
            凭证 = 绑定信息[类型]
            脱敏详情[类型] = {
                "脱敏标识": 凭证.get("脱敏手机号") or 凭证.get("脱敏账号") or 凭证.get("脱敏OPENID"),
                "绑定时间": 凭证["绑定时间"],
                "状态": 凭证["状态"],
            }

        return {
            "龍魂ID": 龍魂ID,
            "绑定数量": len(已绑定),
            "已绑定": 已绑定,
            "未绑定": 未绑定,
            "详细信息": 脱敏详情,
        }

    def 获取绑定凭证(self, 龍魂ID, 绑定类型):
        """
        🟢 获取某个绑定的原始凭证（用于生成证书）
        
        参数：
            龍魂ID: 用户的龍魂ID
            绑定类型: "手机号"/"支付宝"/"微信"
        
        返回：
            绑定凭证字典，或None
        """
        绑定信息 = self.存储器.读取(龍魂ID)
        return 绑定信息.get(绑定类型)

    def 获取审计日志(self, 龍魂ID=None):
        """
        🟢 获取审计日志
        
        参数：
            龍魂ID: 如果指定，只返回该ID的日志；否则返回全部
        """
        if 龍魂ID:
            return [日志 for 日志 in self.审计日志 if 日志["龍魂ID"] == 龍魂ID]
        return self.审计日志

    # ═══════════════════════════════════════════════════
    # 🔴 解除绑定
    # ═══════════════════════════════════════════════════

    def 解除绑定(self, 龍魂ID, 绑定类型, 确认码=None):
        """
        🔴 解除某个绑定（危险操作，需要二次确认）
        
        流程：
          1. 检查绑定是否存在
          2. 要求输入确认码（龍魂ID的后4位）
          3. 确认码正确 → 解除绑定
        
        参数：
            龍魂ID: 用户的龍魂ID
            绑定类型: "手机号"/"支付宝"/"微信"
            确认码: 二次确认码
        
        返回：
            (成功否, 消息)
        """
        绑定信息 = self.存储器.读取(龍魂ID)
        
        if 绑定类型 not in 绑定信息:
            return False, f"没有绑定{绑定类型}，不需要解除"

        # 二次确认
        if 确认码 is None:
            预期确认码 = 龍魂ID[-4:] if len(龍魂ID) >= 4 else 龍魂ID
            return None, f"⚠️ 确定要解除{绑定类型}绑定吗？请输入确认码 '{预期确认码}' 以确认"

        预期确认码 = 龍魂ID[-4:] if len(龍魂ID) >= 4 else 龍魂ID
        if str(确认码) != 预期确认码:
            self._记录日志("解除绑定", 龍魂ID, "失败", f"{绑定类型} — 确认码错误")
            return False, "确认码不对，解除绑定取消"

        # 解除绑定
        del 绑定信息[绑定类型]
        self.存储器.写入(龍魂ID, 绑定信息)

        self._记录日志("解除绑定", 龍魂ID, "成功", f"解除了{绑定类型}绑定")
        return True, f"{绑定类型}绑定已解除"


