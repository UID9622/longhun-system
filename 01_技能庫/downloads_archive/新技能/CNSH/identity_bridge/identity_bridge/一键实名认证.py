class 认证等级评估器:
    """
    【认证等级评估器】
    
    根据用户的绑定情况，给出认证等级。
    等级越高，平台越信任这个龍魂ID。
    """

    def __init__(self):
        pass

    def 评估(self, 绑定状态):
        """
        🟢 评估认证等级
        
        参数：
            绑定状态: 实名绑定器.查询绑定状态() 的返回值
        
        返回：
            {
                "等级": "完全认证",
                "等级码": 3,  # 0=未认证, 1=基础, 2=高级, 3=完全
                "图标": "🟢",
                "描述": "...",
                "下一步": "...",
            }
        """
        已绑定 = 绑定状态.get("已绑定", [])
        绑定数量 = len(已绑定)

        if 绑定数量 >= 3:
            return {
                "等级": "完全认证",
                "等级码": 3,
                "图标": "🟢",
                "描述": "你的龍魂ID已绑定手机号、支付宝、微信，认证最完整！",
                "下一步": "可以生成实名证书，所有平台都会信任你的身份",
            }
        elif 绑定数量 >= 2:
            return {
                "等级": "高级认证",
                "等级码": 2,
                "图标": "🟢",
                "描述": "你的龍魂ID已绑定两项实名信息，大部分平台都认。",
                "下一步": f"再绑定{'微信' if '微信' not in 已绑定 else '支付宝' if '支付宝' not in 已绑定 else '手机号'}可升级为完全认证",
            }
        elif 绑定数量 >= 1:
            return {
                "等级": "基础认证",
                "等级码": 1,
                "图标": "🟢",
                "描述": "你的龍魂ID已绑定手机号，基础身份已确认。",
                "下一步": "建议绑定支付宝或微信，提升认证等级",
            }
        else:
            return {
                "等级": "未认证",
                "等级码": 0,
                "图标": "🟡",
                "描述": "你的龍魂ID还没有绑定任何实名信息。",
                "下一步": "请先绑定手机号（推荐）",
            }


class 一键实名认证:
    """
    【一键实名认证】
    
    引导式认证流程。用户跟着提示一步一步做就行。
    
    使用方法：
        认证 = 一键实名认证()
        认证.开始认证("UID9622")
    """

    def __init__(self):
        self.绑定器 = 实名绑定器()
        self.证书工具 = 龍魂实名证书()
        self.评估器 = 认证等级评估器()
        self.龍魂ID = None

    def _打印标题(self, 标题):
        """打印一个好看的标题"""
        print(f"\n{'─' * 50}")
        print(f"  {标题}")
        print(f"{'─' * 50}")

    def _打印成功(self, 消息):
        """打印成功消息"""
        print(f"  ✅ {消息}")

    def _打印警告(self, 消息):
        """打印警告消息"""
        print(f"  ⚠️  {消息}")

    def _打印错误(self, 消息):
        """打印错误消息"""
        print(f"  ❌ {消息}")

    def _打印信息(self, 消息):
        """打印普通信息"""
        print(f"  ℹ️  {消息}")

    def _打印分隔线(self):
        """打印分隔线"""
        print(f"  {'─' * 46}")

    def 开始认证(self, 龍魂ID):
        """
        🟡 开始认证流程
        
        引导用户完成实名认证。支持交互式和一键式。
        
        参数：
            龍魂ID: 用户的龍魂ID
        """
        self.龍魂ID = 龍魂ID

        print("\n")
        print("╔" + "═" * 48 + "╗")
        print("║" + " " * 10 + "龍 魂 实 名 认 证 系 统" + " " * 13 + "║")
        print("║" + " " * 14 + "龍芯⚡️2026  中国" + " " * 15 + "║")
        print("╚" + "═" * 48 + "╝")

        print(f"\n  你的龍魂ID: {龍魂ID}")
        
        # 先查当前状态
        状态 = self.绑定器.查询绑定状态(龍魂ID)
        评估 = self.评估器.评估(状态)

        print(f"\n  当前认证等级: {评估['图标']} {评估['等级']}")
        print(f"  {评估['描述']}")

        if 评估['等级码'] >= 3:
            self._打印成功("你已经完全认证了！可以生成证书。")
            return self._生成证书步骤()

        print(f"\n  💡 {评估['下一步']}")

        # 显示菜单
        self._打印分隔线()
        print("  请选择要绑定的认证方式：")
        print()
        if "手机号" not in 状态["已绑定"]:
            print("    [1] 📱 手机号认证（推荐）")
        else:
            print("    [1] 📱 手机号认证 ✅ 已完成")
        
        if "支付宝" not in 状态["已绑定"]:
            print("    [2] 💰 支付宝认证")
        else:
            print("    [2] 💰 支付宝认证 ✅ 已完成")
        
        if "微信" not in 状态["已绑定"]:
            print("    [3] 💬 微信认证")
        else:
            print("    [3] 💬 微信认证 ✅ 已完成")
        
        print("    [4] 📊 查看认证报告")
        print("    [5] 📜 生成实名证书")
        print("    [0] 🚪 退出")
        self._打印分隔线()

        # 演示模式：自动完成所有绑定
        print("\n  [演示模式] 自动完成所有认证...")
        print()

        全部成功 = True

        # 绑定手机号
        if "手机号" not in 状态["已绑定"]:
            self._打印标题("步骤 1/3: 绑定手机号")
            成功, 消息, 凭证 = self.绑定器.绑定手机号(龍魂ID, "13800138000")
            if 成功 is None:
                # 需要验证码
                print(f"  {消息}")
                成功, 消息, 凭证 = self.绑定器.绑定手机号(龍魂ID, "13800138000", "123456")
            if 成功:
                self._打印成功(消息)
            else:
                self._打印错误(消息)
                全部成功 = False

        # 绑定支付宝
        if "支付宝" not in 状态["已绑定"]:
            self._打印标题("步骤 2/3: 绑定支付宝")
            成功, 消息, 凭证 = self.绑定器.绑定支付宝(龍魂ID, "13800138000")
            if 成功:
                self._打印成功(消息)
            else:
                self._打印错误(消息)
                全部成功 = False

        # 绑定微信
        if "微信" not in 状态["已绑定"]:
            self._打印标题("步骤 3/3: 绑定微信")
            成功, 消息, 凭证 = self.绑定器.绑定微信(龍魂ID, "oAbCdEfGhIjKlMnOpQrStUvWxYz12345")
            if 成功:
                self._打印成功(消息)
            else:
                self._打印错误(消息)
                全部成功 = False

        # 检查最终状态
        最终状态 = self.绑定器.查询绑定状态(龍魂ID)
        最终评估 = self.评估器.评估(最终状态)

        self._打印标题("认证结果")
        print(f"\n  龍魂ID: {龍魂ID}")
        print(f"  认证等级: {最终评估['图标']} {最终评估['等级']}")
        print(f"  已绑定: {', '.join(最终状态['已绑定']) if 最终状态['已绑定'] else '无'}")
        print(f"  绑定数量: {最终状态['绑定数量']}/3")

        if 最终评估['等级码'] >= 3:
            self._打印成功("恭喜你！已完成完全认证！")
            return self._生成证书步骤()
        elif 全部成功:
            self._打印成功("认证完成！")
        else:
            self._打印警告("部分认证未完成，请重试")

        return 最终评估

    def _生成证书步骤(self):
        """
        🟡 生成实名证书的步骤
        """
        self._打印标题("生成龍魂实名证书")

        # 获取所有绑定凭证
        凭证列表 = []
        for 类型 in ["手机号", "支付宝", "微信"]:
            凭证 = self.绑定器.获取绑定凭证(self.龍魂ID, 类型)
            if 凭证:
                凭证列表.append(凭证)

        if not 凭证列表:
            self._打印错误("没有绑定信息，无法生成证书")
            return None

        # 生成证书
        证书 = self.证书工具.生成证书(self.龍魂ID, 凭证列表, 有效期天数=30)
        self._打印成功("证书生成成功！")

        # 显示证书
        print("\n" + self.证书工具.导出为文本证书(证书))

        # 显示验证方式
        self._打印分隔线()
        print("  第三方验证方式：")
        print(f"    1. 扫码验证: {self.证书工具.导出为二维码内容(证书)}")
        print(f"    2. 链接验证: {self.证书工具.导出为链接(证书)}")
        print(f"    3. JSON验证: 导出证书文件给对方系统")
        self._打印分隔线()

        return 证书

    def 认证等级评估(self, 龍魂ID):
        """
        🟢 评估认证等级
        
        参数：
            龍魂ID: 用户的龍魂ID
        
        返回：
            评估结果字典
        """
        状态 = self.绑定器.查询绑定状态(龍魂ID)
        return self.评估器.评估(状态)

    def 生成认证报告(self, 龍魂ID):
        """
        🟢 生成完整的认证报告
        
        包含：
          - 龍魂ID基本信息
          - 认证等级
          - 已绑定的实名信息（脱敏）
          - 绑定时间线
          - 审计日志
          - 安全建议
        
        参数：
            龍魂ID: 用户的龍魂ID
        
        返回：
            报告文本
        """
        状态 = self.绑定器.查询绑定状态(龍魂ID)
        评估 = self.评估器.评估(状态)
        审计日志 = self.绑定器.获取审计日志(龍魂ID)

        报告 = f"""
╔══════════════════════════════════════════════════╗
║          龍 魂 实 名 认 证 报 告                ║
╠══════════════════════════════════════════════════╣
║ 龍魂ID:     {龍魂ID:<37} ║
║ 生成时间:   {datetime.now().strftime('%Y-%m-%d %H:%M:%S'):<37} ║
║ 系统版本:   龍芯⚡️2026 CNSH v1.0{' '*18} ║
╠══════════════════════════════════════════════════╣
║ 认证等级:   {评估['图标']} {评估['等级']:<33} ║
║ 绑定数量:   {状态['绑定数量']}/3{' '*36} ║
╠══════════════════════════════════════════════════╣
║ 已绑定的实名信息:                                ║"""

        if 状态['详细信息']:
            for 类型, 详情 in 状态['详细信息'].items():
                报告 += f"\n║   ✓ {类型}: {详情['脱敏标识']:<32} ║"
                报告 += f"\n║     绑定时间: {详情['绑定时间']:<28} ║"
        else:
            报告 += "\n║   （未绑定任何实名信息）                        ║"

        报告 += """
╠══════════════════════════════════════════════════╣
║ 审计日志:                                        ║"""

        if 审计日志:
            for 日志 in 审计日志[-5:]:  # 只显示最近5条
                操作 = 日志['操作'][:20]
                结果 = 日志['结果'][:10]
                报告 += f"\n║   [{日志['时间'][11:]}] {操作:<16} {结果:<6} ║"
        else:
            报告 += "\n║   （暂无操作记录）                              ║"

        报告 += """
╠══════════════════════════════════════════════════╣
║ 安全建议:                                        ║"""

        if 评估['等级码'] >= 3:
            报告 += "\n║   ✅ 认证完整，建议定期更新证书                 ║"
            报告 += "\n║   ✅ 证书有效期30天，过期前请重新生成           ║"
        elif 评估['等级码'] >= 1:
            报告 += "\n║   ⚠️  建议完成全部三项认证以获得最大信任度       ║"
        else:
            报告 += "\n║   ⚠️  强烈建议至少绑定手机号                     ║"

        报告 += """
╚══════════════════════════════════════════════════╝
"""
        return 报告

    def 快速认证(self, 龍魂ID, 手机号, 支付宝账号=None, 微信OPENID=None):
        """
        🟡 快速认证（一步完成多项绑定）
        
        适合知道所有信息的用户，一次性提交全部资料。
        
        参数：
            龍魂ID: 用户的龍魂ID
            手机号: 中国手机号（必填）
            支付宝账号: 支付宝账号（可选）
            微信OPENID: 微信OPENID（可选）
        
        返回：
            (成功否, 结果消息, 证书)
        """
        print(f"\n  正在为 {龍魂ID} 进行快速认证...")
        
        成功列表 = []
        
        # 绑定手机号
        if 手机号:
            成功, 消息, 凭证 = self.绑定器.绑定手机号(龍魂ID, 手机号, "123456")
            if 成功:
                成功列表.append("手机号")
                self._打印成功(消息)
            else:
                self._打印错误(消息)

        # 绑定支付宝
        if 支付宝账号:
            成功, 消息, 凭证 = self.绑定器.绑定支付宝(龍魂ID, 支付宝账号)
            if 成功:
                成功列表.append("支付宝")
                self._打印成功(消息)
            else:
                self._打印错误(消息)

        # 绑定微信
        if 微信OPENID:
            成功, 消息, 凭证 = self.绑定器.绑定微信(龍魂ID, 微信OPENID)
            if 成功:
                成功列表.append("微信")
                self._打印成功(消息)
            else:
                self._打印错误(消息)

        if not 成功列表:
            return False, "所有绑定都失败了", None

        # 生成证书
        凭证列表 = []
        for 类型 in 成功列表:
            凭证 = self.绑定器.获取绑定凭证(龍魂ID, 类型)
            if 凭证:
                凭证列表.append(凭证)

        if 凭证列表:
            证书 = self.证书工具.生成证书(龍魂ID, 凭证列表)
            return True, f"快速认证完成！已绑定: {', '.join(成功列表)}", 证书

        return True, f"绑定成功但未生成证书: {', '.join(成功列表)}", None


