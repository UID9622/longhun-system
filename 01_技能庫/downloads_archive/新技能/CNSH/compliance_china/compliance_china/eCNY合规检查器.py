class eCNY检查结果:
    """eCNY检查结果 / e-CNY Check Result"""

    def __init__(self):
        self.法律名称 = "e-CNY（数字人民币）相关规定"
        self.检查通过 = True
        self.综合得分 = 100
        self.风险等级 = "🟢低"
        self.检查项: List[Dict[str, Any]] = []
        self.不合规项: List[str] = []
        self.改进建议: List[str] = []
        self.检查时间 = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        self.法律依据引用: List[str] = []

    def to_dict(self) -> Dict[str, Any]:
        return {
            "法律名称": self.法律名称,
            "检查通过": self.检查通过,
            "综合得分": self.综合得分,
            "风险等级": self.风险等级,
            "检查项": self.检查项,
            "不合规项": self.不合规项,
            "改进建议": self.改进建议,
            "检查时间": self.检查时间,
            "法律依据引用": self.法律依据引用,
        }

    def to_markdown(self) -> str:
        md = f"""## {self.法律名称} 合规检查报告

**检查时间**: {self.检查时间}
**综合得分**: {self.综合得分}/100
**风险等级**: {self.风险等级}

### 检查结果概览

| 检查维度 | 得分 | 状态 |
|---------|------|------|
"""
        for item in self.检查项:
            status_icon = "🟢" if item["得分"] >= 80 else "🟡" if item["得分"] >= 60 else "🔴"
            md += f"| {item['维度']} | {item['得分']} | {status_icon} |\n"

        if self.不合规项:
            md += "\n### 🔴 不合规项\n"
            for i, item in enumerate(self.不合规项, 1):
                md += f"{i}. {item}\n"

        if self.改进建议:
            md += "\n### 💡 改进建议\n"
            for i, sug in enumerate(self.改进建议, 1):
                md += f"{i}. {sug}\n"

        if self.法律依据引用:
            md += "\n### 📚 法规依据\n"
            for law in self.法律依据引用:
                md += f"- {law}\n"

        return md

    def _更新评分(self):
        """内部方法：更新综合评分"""
        if not self.检查项:
            return
        total = sum(item["得分"] for item in self.检查项)
        self.综合得分 = round(total / len(self.检查项))
        self.风险等级 = "🟢低" if self.综合得分 >= 80 else "🟡中" if self.综合得分 >= 60 else "🔴高"
        self.检查通过 = self.综合得分 >= 60


