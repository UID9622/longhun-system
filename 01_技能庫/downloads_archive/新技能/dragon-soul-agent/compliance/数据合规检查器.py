class 传输影响评估:
    """
    传输影响评估 (Transfer Impact Assessment)
    GDPR Article 46传输要求的必要评估
    
    核心问题：
    1. 传输的数据类型和敏感度？
    2. 接收国的法律环境？
    3. 接收方的数据保护水平？
    4. 是否需要补充措施？
    """
    
    def __init__(self):
        self.数据库 = 跨境传输机制数据库()
        self.评估记录 = []
    
    def 执行评估(self, 传输配置: Dict[str, Any]) -> Dict[str, Any]:
        """
        执行传输影响评估
        
        Args:
            传输配置: {
                "数据类型": list of data classification,
                "传输目的": str,
                "接收国": str,
                "接收方类型": str,
                "传输频率": str (持续/定期/一次性),
                "数据量": str,
                "现有机制": str,
            }
        """
        结果 = {
            "评估ID": f"TIA-{datetime.now().strftime('%Y%m%d')}-{hashlib.sha256(str(传输配置).encode()).hexdigest()[:8]}",
            "评估时间": datetime.now().isoformat(),
            "传输配置": 传输配置,
            "评估维度": {},
            "风险评级": "",
            "建议措施": [],
            "是否可传输": False,
        }
        
        # 1. 数据敏感度评估
        敏感度分数 = self._评估数据敏感度(传输配置.get("数据类型", []))
        结果["评估维度"]["数据敏感度"] = {
            "分数": 敏感度分数,
            "等级": "高" if 敏感度分数 > 0.7 else "中" if 敏感度分数 > 0.4 else "低",
            "说明": f"涉及{len(传输配置.get('数据类型', []))}类数据",
        }
        
        # 2. 接收国风险评估
        国风险 = self._评估接收国风险(传输配置.get("接收国", ""))
        结果["评估维度"]["接收国风险"] = 国风险
        
        # 3. 传输机制充分性评估
        机制评估 = self._评估传输机制(传输配置)
        结果["评估维度"]["传输机制"] = 机制评估
        
        # 4. 综合评级
        综合分数 = (敏感度分数 + 国风险.get("分数", 0.5) + 
                     (0.0 if 机制评估.get("充分") else 0.5)) / 3
        
        if 综合分数 < 0.3:
            结果["风险评级"] = "🟢 低风险"
            结果["是否可传输"] = True
        elif 综合分数 < 0.6:
            结果["风险评级"] = "🟡 中风险"
            结果["是否可传输"] = True
            结果["建议措施"].append("建议实施补充技术措施")
        else:
            结果["风险评级"] = "🔴 高风险"
            结果["是否可传输"] = False
            结果["建议措施"].append("不建议传输，考虑替代方案")
        
        # 5. 生成补充措施建议
        if 国风险.get("等级") == "高":
            结果["建议措施"].extend([
                "实施端到端加密",
                "数据传输前假名化处理",
                "建立数据最小化策略",
                "考虑在接收国部署本地服务器",
            ])
        
        if 敏感度分数 > 0.7:
            结果["建议措施"].extend([
                "添加传输日志和审计",
                "建立数据泄露响应预案",
                "考虑数据本地化方案",
            ])
        
        self.评估记录.append(结果)
        return 结果
    
    def _评估数据敏感度(self, 数据类型: List[str]) -> float:
        """Evaluate data sensitivity score"""
        分数 = 0.0
        权重 = {
            "公开数据": 0.0,
            "个人数据": 0.3,
            "敏感个人数据": 0.8,
            "生物识别": 0.9,
            "健康数据": 0.9,
            "金融数据": 0.7,
            "位置数据": 0.5,
            "行为数据": 0.4,
            "重要数据": 0.95,
            "核心数据": 1.0,
        }
        for 类型 in 数据类型:
            分数 = max(分数, 权重.get(类型, 0.5))
        return 分数
    
    def _评估接收国风险(self, 接收国: str) -> Dict[str, Any]:
        """Evaluate recipient country risk"""
        for 等级, 国家列表 in self.数据库.接收国风险.items():
            if 接收国 in 国家列表:
                分数 = {"低": 0.2, "中": 0.5, "高": 0.8}.get(等级, 0.5)
                return {
                    "国家": 接收国,
                    "等级": 等级,
                    "分数": 分数,
                    "说明": f"该国家被评估为{等级}风险",
                }
        return {
            "国家": 接收国,
            "等级": "未知",
            "分数": 0.5,
            "说明": "未在风险数据库中找到该国家",
        }
    
    def _评估传输机制(self, 传输配置: Dict[str, Any]) -> Dict[str, Any]:
        """Evaluate transfer mechanism adequacy"""
        机制 = 传输配置.get("现有机制", "")
        充分机制 = ["充分性认定", "SCCs", "BCRs", "标准合同条款"]
        
        充分 = any(m in 机制 for m in 充分机制)
        
        return {
            "现有机制": 机制,
            "充分": 充分,
            "说明": "机制充分" if 充分 else "机制可能不充分",
            "建议": "无需额外机制" if 充分 else "建议采用SCCs或其他充分机制",
        }


