class 人工审核标记器:
    """
    第三层：人工审核标记
    Layer 3: Human review flagging
    
    对于前两层无法确定的内容，标记为需人工审核
    For content that cannot be determined by the first two layers,
    flag for human review
    """
    
    def __init__(self):
        self.待审核队列 = []
        self.DNA标识 = "#龍芯⚡️2026-06-18-CONTENT-FILTER"
    
    def 评估(self, 内容: str, 第一层结果: Dict[str, Any], 第二层结果: Dict[str, Any]) -> Dict[str, Any]:
        """
        评估是否需要人工审核
        Evaluate if human review is needed
        """
        风险分数 = 第二层结果.get("风险分数", 0)
        关键词命中 = bool(第一层结果.get("命中词"))
        
        # 决策逻辑
        if 风险分数 > 0.7 or (风险分数 > 0.4 and 关键词命中):
            # 需要人工审核
            审核项 = {
                "内容摘要": 内容[:100] + "..." if len(内容) > 100 else 内容,
                "风险分数": 风险分数,
                "关键词命中": 第一层结果.get("命中词", []),
                "风险类型": 第二层结果.get("风险类型", []),
                "提交时间": datetime.now().isoformat(),
                "审核ID": self._生成审核ID(内容),
                "优先级": "高" if 风险分数 > 0.85 else "中",
            }
            self.待审核队列.append(审核项)
            
            return {
                "层级": "第三层（人工审核）",
                "需要审核": True,
                "审核ID": 审核项["审核ID"],
                "优先级": 审核项["优先级"],
                "状态": "已提交人工审核队列",
            }
        
        return {
            "层级": "第三层（人工审核）",
            "需要审核": False,
            "状态": "自动处理完成",
        }
    
    def _生成审核ID(self, 内容: str) -> str:
        """Generate a unique review ID"""
        哈希 = hashlib.sha256(
            f"{内容}{datetime.now().isoformat()}".encode()
        ).hexdigest()[:12]
        return f"AUDIT-{哈希}"
    
    def 获取待审核队列(self) -> List[Dict]:
        """Get the pending review queue"""
        return self.待审核队列
    
    def 完成审核(self, 审核ID: str, 决定: str, 审核人: str):
        """Mark a review as completed"""
        for 项 in self.待审核队列:
            if 项["审核ID"] == 审核ID:
                项["审核结果"] = 决定
                项["审核人"] = 审核人
                项["完成时间"] = datetime.now().isoformat()
                break


