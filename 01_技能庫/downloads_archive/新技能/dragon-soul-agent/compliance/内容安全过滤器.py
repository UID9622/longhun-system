class 关键词过滤器:
    """
    第一层：关键词快速过滤
    Layer 1: Fast keyword-based filtering
    
    特点：速度快，适合大规模实时过滤
    Features: High speed, suitable for large-scale real-time filtering
    """
    
    def __init__(self):
        self.词库 = 地区敏感内容配置.敏感词库
        self.地域争议 = 地区敏感内容配置.地域争议话题
        self.未成年保护 = 地区敏感内容配置.未成年人保护
        self._编译正则表达式()
        self.命中记录 = []
    
    def _编译正则表达式(self):
        """Compile regex patterns for efficient matching"""
        self.正则模式 = {}
        
        for 类别, 子类别 in self.词库.items():
            for 子类, 词汇列表 in 子类别.items():
                模式名 = f"{类别}.{子类}"
                # 使用非捕获组提高性能
                pattern = re.compile(
                    '|'.join(re.escape(词) for 词 in 词汇列表),
                    re.IGNORECASE
                )
                self.正则模式[模式名] = pattern
    
    def 过滤(self, 内容: str, 目标市场: str = "全球") -> Dict[str, Any]:
        """
        关键词过滤主函数
        Main keyword filtering function
        
        Returns:
            {
                "通过": bool,
                "风险等级": 内容风险等级,
                "命中词": list of matched words,
                "命中类别": list of matched categories,
                "处理时间_ms": float,
            }
        """
        import time
        开始 = time.time()
        
        命中词 = []
        命中类别 = []
        最高风险 = 内容风险等级.安全
        
        # 检查全局通用规则
        for 类别, 子类别 in self.词库.items():
            if 类别 != "全球通用" and 类别 != 目标市场 and 类别 != "🌍 文化宗教":
                continue
            
            for 子类, 词汇列表 in 子类别.items():
                模式名 = f"{类别}.{子类}"
                模式 = self.正则模式.get(模式名)
                if 模式:
                    匹配 = 模式.findall(内容)
                    if 匹配:
                        命中词.extend(匹配)
                        命中类别.append(f"{类别}/{子类}")
                        
                        # 更新风险等级
                        if 子类 in ["暴力", "非法活动"]:
                            最高风险 = 内容风险等级.极高风险
                        elif 子类 in ["政治敏感", "歧视仇恨"]:
                            if 最高风险.value < 内容风险等级.高风险.value:
                                最高风险 = 内容风险等级.高风险
                        elif 子类 in ["宗教禁忌", "文化冒犯"]:
                            if 最高风险.value < 内容风险等级.中风险.value:
                                最高风险 = 内容风险等级.中风险
        
        耗时 = (time.time() - 开始) * 1000
        
        结果 = {
            "层级": "第一层（关键词）",
            "通过": 最高风险 in [内容风险等级.安全, 内容风险等级.低风险],
            "风险等级": 最高风险.name,
            "风险分数": self._风险转分数(最高风险),
            "命中词": list(set(命中词)),
            "命中类别": list(set(命中类别)),
            "处理时间_ms": round(耗时, 3),
        }
        
        if 命中词:
            self.命中记录.append({
                "时间": datetime.now().isoformat(),
                "命中词": 命中词,
                "类别": 命中类别,
            })
        
        return 结果
    
    def _风险转分数(self, 风险: 内容风险等级) -> float:
        """Convert risk level to numeric score"""
        分数映射 = {
            内容风险等级.安全: 0.0,
            内容风险等级.低风险: 0.2,
            内容风险等级.中风险: 0.5,
            内容风险等级.高风险: 0.85,
            内容风险等级.极高风险: 1.0,
        }
        return 分数映射.get(风险, 0.5)
    
    def 添加自定义词(self, 词汇: str, 类别: str, 风险等级: 内容风险等级):
        """Add custom sensitive word"""
        if 类别 not in self.词库.get("自定义", {}):
            if "自定义" not in self.词库:
                self.词库["自定义"] = {}
            self.词库["自定义"][类别] = []
        
        self.词库["自定义"][类别].append(词汇)
        self._编译正则表达式()


