#
# §鐵律: 此腳本是龍魂系統的主權錨點·任何AI不得擅自修改
# §用途: 一鍵初始化龍魂系統目錄結構 + 主權錨點 + 環境變量
# ═══════════════════════════════════════════════════════════════════════════

# §0 颜色定义·让输出好看
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
PURPLE='\033[0;35m'
NC='\033[0m' # 无颜色

# §1 基础变量·英文名保兼容·注释说人话
REPO_ROOT="${HOME}/longhun-system"          # 龍魂主仓库根目录·铁律锁定
USER_HOME="${HOME}"                          # 用户家目录
TIMESTAMP=$(date "+%Y-%m-%d_%H%M%S")         # 时间戳·用于备份和日志
LOG_FILE="${REPO_ROOT}/日志/初始化_${TIMESTAMP}.log"  # 日志文件路径

# §2 打印龍魂標識·儀式感
echo -e "${PURPLE}"
echo "═══════════════════════════════════════════════════════════════"
echo "    🐲 龍魂主權初始化 v1.0 · CNSH 語法 · UID9622"
echo "    理論指導: 曾仕強老師"
echo "═══════════════════════════════════════════════════════════════"
echo -e "${NC}"

# §3 函數·打印步驟標題
print_step() {
    # $1 = 步驟編號, $2 = 步驟名稱
    echo -e "\n${BLUE}🐉 [步驟 $1/7] §$2${NC}"
}

# §4 函數·打印成功信息
print_ok() {
    echo -e "${GREEN}   ✅ $1${NC}"
}

# §5 函數·打印警告信息
print_warn() {
    echo -e "${YELLOW}   ⚠️  $1${NC}"
}

# §6 函數·打印錯誤信息
print_err() {
    echo -e "${RED}   ❌ $1${NC}"
}

# ═══════════════════════════════════════════════════════════════════════════
# §步驟1·檢查主倉庫是否存在
# ═══════════════════════════════════════════════════════════════════════════
print_step "1" "檢查主倉庫"

if [ -d "${REPO_ROOT}" ]; then
    print_ok "主倉庫已存在: ${REPO_ROOT}"
else
    print_warn "主倉庫不存在·正在創建..."
    mkdir -p "${REPO_ROOT}"
    print_ok "主倉庫創建完成"
fi

# ═══════════════════════════════════════════════════════════════════════════
# §步驟2·創建核心目錄結構
# ═══════════════════════════════════════════════════════════════════════════
print_step "2" "創建核心目錄"

# 定義必須存在的目錄·中文目錄名是龍魂主權的一部分
CORE_DIRS=(
    "主控"           # 主控中心·調度核心
    "命令"           # 可執行命令·bin的中文映射
    "日志"           # 運行日志·審計留痕
    "文檔"           # 文檔庫
    "文件"           # 文件存儲
    "協議庫"         # 鐵律協議
    "引擎"           # 核心引擎
    "skills"        # 技能庫·英文兼容
    "CNSH"          # CNSH語義層
    "config"        # 配置文件
    "data"          # 數據目錄
)

for dir in "${CORE_DIRS[@]}"; do
    target="${REPO_ROOT}/${dir}"
    if [ -d "${target}" ]; then
        print_ok "目錄已存在: ${dir}"
    else
        mkdir -p "${target}"
        print_ok "目錄已創建: ${dir}"
    fi
done

# ═══════════════════════════════════════════════════════════════════════════
# §步驟3·創建主權錨點文件
# ═══════════════════════════════════════════════════════════════════════════
print_step "3" "焊接主權錨點"

ANCHOR_FILE="${REPO_ROOT}/.龍魂錨點"

# 用 heredoc 寫入錨點內容·錨點結束 是中文結束符
cat > "${ANCHOR_FILE}" << '錨點結束'
# ═══════════════════════════════════════════════════════════════════════════
# 🐲 龍魂主權錨點 · 此文件不可刪除
# ═══════════════════════════════════════════════════════════════════════════
#
# §鐵律聲明:
#   1. 此目錄是 UID9622 諸葛鑫 的唯一主倉庫
#   2. 任何 AI 不得在此目錄之外新建項目文件夾
#   3. 任何 AI 進入此項目·必須先讀 CLAUDE.md
#   4. 違反者進入「不尊重老大」黑名單
#
# §身份確認:
#   UID: 9622
#   確認碼: #CONFIRM🌌9622-ONLY-ONCE🧬LK9X-772Z
#   GPG: A2D0092CEE2E5BA87035600924C3704A8CC26D5F
#
# §理論指導: 曾仕強老師（永恆顯示）
#
# 「龍」是唯一精神坐標·繁體不可動
# ═══════════════════════════════════════════════════════════════════════════
錨點結束

print_ok "主權錨點已焊接: .龍魂錨點"

# ═══════════════════════════════════════════════════════════════════════════
# §步驟4·補充 .gitignore 規則
# ═══════════════════════════════════════════════════════════════════════════
print_step "4" "補充忽略規則"

GITIGNORE="${REPO_ROOT}/.gitignore"

# 需要追加的忽略規則
IGNORE_RULES=(
    "# §龍魂主權保護·以下不上傳"
    ".龍魂錨點"
    "*.log"
    "__pycache__/"
    ".DS_Store"
    "venv/"
    ".env"
    "*.pyc"
    "日志/"
)

# 檢查並追加規則
for rule in "${IGNORE_RULES[@]}"; do
    if ! grep -qF "${rule}" "${GITIGNORE}" 2>/dev/null; then
        echo "${rule}" >> "${GITIGNORE}"
        print_ok "追加忽略規則: ${rule}"
    fi
done

# ═══════════════════════════════════════════════════════════════════════════
# §步驟5·創建環境加載腳本
# ═══════════════════════════════════════════════════════════════════════════
print_step "5" "焊接環境腳本"

ENV_SCRIPT="${REPO_ROOT}/加載環境.sh"

cat > "${ENV_SCRIPT}" << '環境結束'
#!/bin/bash
# 龍魂環境加載腳本 · 在 .zshrc 或 .bashrc 中 source 此文件
# DNA: #龍芯⚡️2026-05-20-環境加載-v1.0

# §主倉庫路徑
export LONGHUN_ROOT="${HOME}/longhun-system"

# §命令路徑·加入 PATH
export PATH="${LONGHUN_ROOT}/命令:${PATH}"

# §別名·方便操作
alias lh="cd ${LONGHUN_ROOT}"
alias lhlog="cd ${LONGHUN_ROOT}/日志"
alias lhcmd="cd ${LONGHUN_ROOT}/命令"

# §提示加載成功
echo "🐲 龍魂環境已加載 · UID9622"
環境結束

chmod +x "${ENV_SCRIPT}"
print_ok "環境腳本已焊接: 加載環境.sh"

# ═══════════════════════════════════════════════════════════════════════════
# §步驟6·寫入初始化日志
# ═══════════════════════════════════════════════════════════════════════════
print_step "6" "寫入審計日志"

mkdir -p "${REPO_ROOT}/日志"

cat > "${LOG_FILE}" << 日志結束
