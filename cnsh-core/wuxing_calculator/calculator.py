def 打印标题(文本, 级别=1):
    """级别 1=大标题 2=中标题 3=小标题"""
    if 级别 == 1:
        print(f"\n{彩色.加粗}{彩色.青}{'='*60}{彩色.重置}")
        print(f"{彩色.加粗}{彩色.青}🐉 {文本}{彩色.重置}")
        print(f"{彩色.加粗}{彩色.青}{'='*60}{彩色.重置}\n")
    elif 级别 == 2:
        print(f"\n{彩色.加粗}{彩色.蓝}▸ {文本}{彩色.重置}")
        print(f"{彩色.蓝}{'-'*50}{彩色.重置}")
    else:
        print(f"  {彩色.加粗}• {文本}{彩色.重置}")

def 渲染进度条(标签, 值, 最大值=100, 宽度=30):
    """渲染百分比进度条"""
    百分比 = min(100, max(0, int(值 / (最大值 + 0.001) * 100)))
    填充 = int(宽度 * 百分比 / 100)
    条形 = "█" * 填充 + "░" * (宽度 - 填充)

    if 百分比 >= 80:
        颜色 = 彩色.绿
        符号 = "🟢"
    elif 百分比 >= 50:
        颜色 = 彩色.黄
        符号 = "🟡"
    else:
        颜色 = 彩色.红
        符号 = "🔴"

    print(f"  {标签:12s} {符号} {颜色}{条形}{彩色.重置} {百分比:3d}% ({值:.1f})")

def 渲染五行表格(得分):
    """渲染五行强度表格"""
    print(f"\n{彩色.加粗}  五行强度分布:{彩色.重置}")
    print(f"  {'-'*50}")
    print(f"  {'五行':<6} {'分值':>8} {'占比':>8} {'评估':>12}")
    print(f"  {'-'*50}")

    总分 = sum(得分.values()) + 0.001
    for 五行名 in ["金", "木", "水", "火", "土"]:
        分值 = 得分[五行名]
        占比 = 分值 / 总分

        if 占比 > 0.40:
            评估 = f"{彩色.红}过旺{彩色.重置}"
        elif 占比 > 0.20:
            评估 = f"{彩色.绿}适中{彩色.重置}"
        elif 占比 > 0:
            评估 = f"{彩色.黄}偏弱{彩色.重置}"
        else:
            评估 = f"{彩色.红}缺失{彩色.重置}"

        五行显示 = 五行颜色映射[五行名]
        print(f"  {五行显示:8s} {分值:8.2f} {占比:7.1%}  {评估}")

    print(f"  {'-'*50}")

