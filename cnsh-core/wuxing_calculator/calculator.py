# ========== 核心计算函数 ==========
def 计算数字根(文本):
    digits = [int(c) for c in str(文本) if c.isdigit()]
    if not digits: return 0
    n = sum(digits)
    while n >= 10:
        n = sum(int(c) for c in str(n))
    return n

def 三色审计(dr):
    if dr in [3,9]: return "🔴"
    if dr == 6: return "🟡"
    return "🟢"

def 计算五行强度(四柱):
    得分 = {"金":0.0,"木":0.0,"水":0.0,"火":0.0,"土":0.0}
    for 柱位, 干支 in 四柱.items():
        权重 = 位置权重表[柱位]
        if 干支["天干"] in 天干五行表:
            得分[天干五行表[干支["天干"]]] += 权重["天干"]
        if 干支["地支"] in 地支五行表:
            得分[地支五行表[干支["地支"]]] += 权重["地支"]
    总分 = sum(得分.values())
    均值 = 总分 / 5
    方差 = sum((v - 均值)**2 for v in 得分.values()) / 5
    均衡指数 = max(0.0, round(1.0 - (方差**0.5) / (均值 + 0.001), 3))
    缺失 = [k for k, v in 得分.items() if v == 0.0]
    return {
        "五行得分": 得分,
        "最强": max(得分, key=得分.get),
        "最弱": min(得分, key=得分.get),
        "均衡指数": 均衡指数,
        "缺失五行": 缺失
    }

def 完整链路分析(得分):
    相生顺序 = ["金","水","木","火","土"]
    断链预警 = []
    健康度 = 100
    for i in range(5):
        来源 = 相生顺序[i]
        目标 = 相生顺序[(i+1)%5]
        if 得分.get(来源,0)>0 and 得分.get(目标,0)==0:
            断链预警.append(f"🔴 断链：{来源}→{目标}")
            健康度 -= 15
    总分 = sum(得分.values()) + 0.001
    过旺 = [(k,v) for k,v in 得分.items() if v/总分 > 0.40]
    for 五行名, 分值 in 过旺:
        疏导目标 = 五行相生[五行名]
        断链预警.append(f"🟡 过旺：{五行名}占{分值/总分:.0%}→引生{疏导目标}")
        健康度 -= 10
    return {"链路健康度": max(0,健康度), "状态":"🟢健康" if 健康度>=80 else "🟡待关注" if 健康度>=50 else "🔴需干预", "断链预警":断链预警}

def 生成补益建议(强度结果):
    建议列表 = []
    for 五行名 in 强度结果["缺失五行"]:
        补 = 五行补益表[五行名]
        建议列表.append({"级别":"🔴紧急补","五行":五行名,"颜色":"·".join(补["颜色"]),"方位":补["方位"],"行动":补["建议"],"龍魂映射":补["龍魂映射"]})
    最弱 = 强度结果["最弱"]
    if 最弱 not in 强度结果["缺失五行"]:
        补 = 五行补益表[最弱]
        建议列表.append({"级别":"🟡建议补","五行":最弱,"颜色":"·".join(补["颜色"]),"方位":补["方位"],"行动":补["建议"],"龍魂映射":补["龍魂映射"]})
    return 建议列表

def 龍魂五行计算器_v2(年天干,年地支,月天干,月地支,日天干,日地支,时天干,时地支):
    四柱 = {
        "年柱":{"天干":年天干,"地支":年地支},
        "月柱":{"天干":月天干,"地支":月地支},
        "日柱":{"天干":日天干,"地支":日地支},
        "时柱":{"天干":时天干,"地支":时地支},
    }
    强度 = 计算五行强度(四柱)
    链路 = 完整链路分析(强度["五行得分"])
    补益 = 生成补益建议(强度)
    return {"版本":"v3.2","四柱":四柱,"五行强度":强度,"链路分析":链路,"补益建议":补益}

def 判断关系(a, b):
    if not b: return "起点"
    if a==b: return "比和"
    if 五行相生.get(b)==a: return "相生"
    if 五行相克.get(b)==a: return "相克"
    if 五行相生.get(a)==b: return "相泄"
    if 五行相克.get(a)==b: return "相耗"
    return "混合"

def 生成DNA(title):
    today = datetime.now().strftime("%Y-%m-%d")
    safe = title[:18].replace(" ","")
    return f"#龍芯⚡️{today}-{safe}-v1.0"

def 生成节点(text, title="未命名节点", prev_element=None, raw_type="text"):
    dr = 计算数字根(text)
    element = 数字根五行表[dr]
    audit = 三色审计(dr)
    relation = 判断关系(element, prev_element)
    hash8 = hashlib.sha256(str(text).encode()).hexdigest()[:8].upper()
    sancai = {"heaven":0.35,"earth":0.15,"human":0.50}
    if sancai["human"]<0.34: sancai["human"]=0.34
    action = "enter" if audit=="🟢" else "hold" if audit=="🟡" else "fuse"
    return {
        "node_id": f"FLOW-9622-{datetime.now().strftime('%Y%m%d')}-{hash8}",
        "title": title,
        "raw_type": raw_type,
        "digital_root": dr,
        "element": element,
        "relation": relation,
        "sancai": sancai,
        "audit": audit,
        "dna": 生成DNA(title),
        "visual": {"color":"auto","shape":"auto","motion":"auto"},
        "action": action,
        "note": "文化语义算法节点，不替代科学实验、法律程序、医学判断或金融判断。"
    }

