def 获取测试批次(维度: str = None):
    """
    获取测试批次

    Args:
        维度: 可选，指定某个维度，None表示全部

    Returns:
        测试用例列表
    """
    if 维度:
        return [t for t in 标准测试批次 if t["维度"] == 维度]
    return 标准测试批次


def 统计测试():
    """统计测试覆盖情况"""
    维度统计 = {}
    总数 = len(标准测试批次)

    for 测试 in 标准测试批次:
        维度 = 测试["维度"]
        if 维度 not in 维度统计:
            维度统计[维度] = 0
        维度统计[维度] += 1

    return {
        "总测试数": 总数,
        "维度覆盖": 维度统计,
        "维度总数": len(维度统计),
    }


