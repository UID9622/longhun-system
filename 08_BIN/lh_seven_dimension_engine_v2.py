class P06数字根:
    """P06数学大师·数字根+权重校验"""

    @classmethod
    def 计算数字根(cls, 数据: str) -> Tuple[int, str]:
        """369数字根计算"""
        哈希 = hashlib.sha256(数据.encode()).hexdigest()
        数字根 = sum(int(c, 16) for c in 哈希) % 9
        if 数字根 == 0:
            数字根 = 9

        # 369不动点
        if 数字根 in [3, 6, 9]:
            解读 = f"数字根={数字根}·369不动点·底座稳定"
        else:
            解读 = f"数字根={数字根}·非不动点·需关注"
        return 数字根, 解读

    @classmethod
    def 权重校验(cls, 权重: Dict[str, float]) -> Tuple[bool, str]:
        """权重归一化自动校验"""
        总和 = sum(权重.values())
        if abs(总和 - 1.0) > 0.02:
            return False, f"🟡 权重和={总和:.4f}·偏离1.0·已自动归一化"
        return True, f"🟢 权重和={总和:.4f}·归一化正确"


