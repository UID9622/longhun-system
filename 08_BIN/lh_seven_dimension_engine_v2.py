        总分 = 推演结果.get("综合得分", 0)
        if 总分 < 0.3:
            摘要.颜色 = 审计颜色.RED
            摘要.阻断项 += 1
            检测项.append(f"🔴 总分过低: {总分:.2f} < 0.3")
        elif 总分 < 0.5:
            摘要.颜色 = 审计颜色.YELLOW
            摘要.警告项 += 1
            检测项.append(f"🟡 总分偏低: {总分:.2f} < 0.5")
        else:
            摘要.通过项 += 1
            检测项.append(f"🟢 总分: {总分:.2f}")

        # 2. 单维度检查
        七维 = 推演结果.get("七维评分", {})
        for 维度, 分值 in 七维.items():
            if 分值 < 0.3:
                摘要.颜色 = 审计颜色.RED
                摘要.阻断项 += 1
                检测项.append(f"🔴 {维度}: {分值:.2f} < 0.3")
            elif 分值 < 0.5:
                摘要.警告项 += 1
                检测项.append(f"🟡 {维度}: {分值:.2f} < 0.5")
            else:
                摘要.通过项 += 1

        # 3. 向善滤波检查
        if not 向善结果.get("通过", True):
            摘要.颜色 = 审计颜色.RED
            摘要.阻断项 += 1
            检测项.append(f"🔴 向善滤波未通过: {向善结果.get('原因', '')}")

        # 4. 否决词复查
        for 词 in P72龍盾.一票否决词[:8]:
            if 词 in 问题:
                摘要.颜色 = 审计颜色.RED
                摘要.阻断项 += 1
                检测项.append(f"🔴 问题含否决词: {词}")

        摘要.检测项 = 检测项
        摘要.原因 = f"P05审计完成·{'🔴阻断' if 摘要.阻断项 > 0 else '🟡预警' if 摘要.警告项 > 0 else '🟢通过'}"
        return 摘要


