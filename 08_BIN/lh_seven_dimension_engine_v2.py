def main():
    parser = argparse.ArgumentParser(
        description="🐉 龍魂·太极易经七维人性推演引擎 v2.0",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
示例:
  # 交互模式 (推荐)
  python3 bin/lh_seven_dimension_engine_v2.py --interactive

  # 单次推演
  python3 bin/lh_seven_dimension_engine_v2.py --question "人机共生技术应该如何发展？"

  # 查看历史映射库
  python3 bin/lh_seven_dimension_engine_v2.py --history

  # CNSH代码编译测试
  python3 bin/lh_seven_dimension_engine_v2.py --cnsh "功能 测试() { 打印「你好」 }"

  # 四维沙盘可视化
  python3 bin/lh_seven_dimension_engine_v2.py --sandbox time

  # JSON输出
  python3 bin/lh_seven_dimension_engine_v2.py --question "问题" --json
        """
    )

    parser.add_argument("--interactive", "-i", action="store_true", help="交互模式")
    parser.add_argument("--question", "-q", type=str, help="推演问题")
    parser.add_argument("--history", "-H", action="store_true", help="查看历史映射库")
    parser.add_argument("--cnsh", "-c", type=str, help="CNSH代码编译")
    parser.add_argument("--sandbox", "-s", type=str, choices=["time", "human", "risk"], help="四维沙盘可视化")
    parser.add_argument("--report", "-r", action="store_true", help="生成推演报告")
    parser.add_argument("--json", "-j", action="store_true", help="JSON输出")

    args = parser.parse_args()

    引擎 = 七维推演引擎V2()

    # 历史映射库
    if args.history:
        统计 = 引擎.历史库.统计()
        print(json.dumps(统计, ensure_ascii=False, indent=2))
        return

    # CNSH编译
    if args.cnsh:
        审计 = 引擎.编译器.三色审计(args.cnsh)
        print(f"🎨 三色审计: {审计['颜色']} {审计['状态']}")
        print(f"📝 原因: {审计['原因']}")
        if 审计['颜色'] != "🔴":
            编译结果 = 引擎.编译器.编译(args.cnsh)
            print(f"\n💻 编译结果:\n{编译结果}")
        return

    # 四维沙盘
    if args.sandbox:
        if args.sandbox == "time":
            print(引擎.沙盘.时间维度())
        elif args.sandbox == "human":
            print(引擎.沙盘.人性维度())
        elif args.sandbox == "risk":
            print(引擎.沙盘.风险维度())
        return

    # 报告
    if args.report:
        if 引擎.推演历史:
            print(引擎.格式化报告())
        else:
            print("⚠️ 暂无推演历史，请先运行一次推演")
        return

    # 交互模式
    if args.interactive:
        print("\n" + "=" * 60)
        print(f"🐉 七维推演引擎 v2.0 · 龍魂对齐增强版")
        print(f"🧬 {DNA_V2}")
        print("=" * 60)
        print("命令: 推演 [问题] | 学习 | 历史 | 沙盘 | 报告 | stats | exit")
        print("─" * 60)

        while True:
            try:
                输入 = input("\n🤖 > ").strip()
                if not 输入:
                    continue
                if 输入.lower() == "exit":
                    break
                if 输入.lower() == "历史":
                    for h in 引擎.推演历史[-5:]:
                        p05 = h.P05审计摘要
                        色 = "🟢" if p05 and p05.颜色 == 审计颜色.GREEN else ("🟡" if p05 and p05.颜色 == 审计颜色.YELLOW else "🔴")
                        print(f"  {色} {h.DNA[-16:]} | {h.本卦符号} {h.本卦} | {h.综合得分:.2f}")
                    continue
                if 输入.lower() == "报告":
                    if 引擎.推演历史:
                        print(引擎.格式化报告())
                    else:
                        print("⚠️ 请先运行推演")
                    continue
                if 输入.lower() == "stats":
                    print(f"  推演历史: {len(引擎.推演历史)} 条")
                    print(f"  学习记录: {len(引擎.学习记录)} 条")
                    事件统计 = 引擎.历史库.统计()
                    print(f"  历史事件: {事件统计['总事件数']} 条·平均准确率 {事件统计['平均准确率']}")
                    continue
                if 输入.lower().startswith("沙盘"):
                    部分 = 输入[3:].strip() or "time"
                    if 部分 == "time":
                        print(引擎.沙盘.时间维度())
                    elif 部分 == "human":
                        print(引擎.沙盘.人性维度())
                    elif 部分 == "risk":
                        print(引擎.沙盘.风险维度())
                    continue
                if 输入.startswith("推演 "):
                    问题 = 输入[3:].strip()
                    print(f"\n🔄 P72预检中...")
                    结果 = 引擎.推演(问题)

                    if args.json:
                        # 转成可序列化
                        可序列化 = {
                            "状态": 结果["状态"],
                            "DNA": 结果["DNA"],
                            "推演结果": asdict(结果["推演结果"]),
                            "置信度": 结果["置信度"],
                            "P05审计": asdict(结果["P05审计"]) if 结果.get("P05审计") else None,
                            "P06数字根": 结果.get("P06数字根"),
                            "确认码": CONFIRM_CODE
                        }
                        可序列化["推演结果"]["P05审计摘要"] = None
                        可序列化["推演结果"]["P72预检摘要"] = None
                        print(json.dumps(可序列化, ensure_ascii=False, indent=2))
                    else:
                        t = 结果["推演结果"]
                        p05 = 结果.get("P05审计")
                        p06 = 结果.get("P06数字根", {})
                        色 = "🟢" if p05 and p05.颜色 == 审计颜色.GREEN else ("🟡" if p05 and p05.颜色 == 审计颜色.YELLOW else "🔴")

                        print(f"\n☯️ 卦象: {t.本卦符号} {t.本卦} → {t.变卦}")
                        print(f"📜 卦辞: {t.卦辞[:40]}...")
                        print(f"🔢 数字根: {p06.get('值', '?')} · {p06.get('解读', '')}")
                        print(f"\n📊 七维评分:")
                        for 维, 分 in t.七维评分.items():
                            c = '\033[92m' if 分 >= 0.7 else ('\033[93m' if 分 >= 0.5 else '\033[91m')
                            print(f"  {维}: {c}{分:.2f}\033[0m")
                        print(f"\n  综合得分: {t.综合得分:.2f}")
                        print(f"  置信度: {t.置信度}% {t.置信度等级}")
                        print(f"  P05审计: {色} {p05.原因 if p05 else '未审计'}")
                        print(f"\n💡 建议: {t.建议}")
                        print(f"🧬 DNA: {t.DNA}")
                    continue

                print("未知命令。可用: 推演 [问题] | 学习 | 历史 | 沙盘 | 报告 | stats | exit")

            except KeyboardInterrupt:
                break
        return

    # 单次推演
    if args.question:
        结果 = 引擎.推演(args.question)
        if args.json:
            可序列化 = {
                "状态": 结果["状态"],
                "DNA": 结果["DNA"],
                "推演结果": asdict(结果["推演结果"]),
                "置信度": 结果["置信度"],
                "P05审计": asdict(结果["P05审计"]) if 结果.get("P05审计") else None,
                "确认码": CONFIRM_CODE
            }
            可序列化["推演结果"]["P05审计摘要"] = None
