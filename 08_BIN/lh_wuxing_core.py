def 计算五行强度(四柱: Dict) -> Dict:
    """计算五行强度：输入四柱字典，返回得分、最强、最弱、均衡指数、缺失五行"""
    得分 = {"金": 0.0, "木": 0.0, "水": 0.0, "火": 0.0, "土": 0.0}

    for 柱位, 干支 in 四柱.items():
        权重 = 位置权重表[柱位]
        天干 = 干支["天干"]
        地支 = 干支["地支"]
        if 天干 in 天干五行表:
            得分[天干五行表[天干]] += 权重["天干"]
        if 地支 in 地支五行表:
            得分[地支五行表[地支]] += 权重["地支"]

    总分 = sum(得分.values()) + 0.001
    均值 = 总分 / 5
    方差 = sum((v - 均值) ** 2 for v in 得分.values()) / 5
    均衡指数 = round(max(0.0, 1.0 - (方差 ** 0.5) / (均值 + 0.001)), 3)

    缺失五行 = [k for k, v in 得分.items() if v == 0.0]
    最强 = max(得分, key=得分.get)
    最弱 = min(得分, key=得分.get)

    return {
        "五行得分": 得分,
        "最强": 最强,
        "最弱": 最弱,
        "均衡指数": 均衡指数,
        "缺失五行": 缺失五行
    }


