def 归一化比例(value, 制式: str = "auto") -> float:
    """把 0–100 或 0–1 统一压到 0–1。v4.0 显式化：制式=auto 保持 v3.1 行为。

    焊死规则（协议§六）：
      - value > 1 视为百分比制(0-100)，除以 100 压回 0-1
      - 0 ≤ value ≤ 1 视为比例制，原样返回
      - None / 负值 → 0.0；>100 → 截断 1.0
    """
    if value is None:
        return 0.0
    if 制式 == "percent" or (制式 == "auto" and value > 1):
        return max(0.0, min(1.0, value / 100))
    return max(0.0, min(1.0, value))


def 计算克制衡分(得分: Dict) -> float:
    """克制衡分：相克关系能否压住过旺"""
    总分 = sum(得分.values()) + 0.001
    过旺列表 = [k for k, v in 得分.items() if v / 总分 > 0.40]
    if not 过旺列表:
        return 1.0
    命中 = 0
    for 五行名 in 过旺列表:
        克制方 = None
        for source, target in 五行相克.items():
            if target == 五行名:
                克制方 = source
                break
        if 克制方 and 得分[克制方] > 0:
            命中 += 1
    return round(命中 / len(过旺列表), 3)


def 计算疏导分(得分: Dict) -> float:
    """疏导分：过旺五行能否顺着相生流出去"""
    总分 = sum(得分.values()) + 0.001
    过旺列表 = [k for k, v in 得分.items() if v / 总分 > 0.40]
    if not 过旺列表:
        return 1.0
    命中 = 0
    for 五行名 in 过旺列表:
        疏导目标 = 五行相生[五行名]
        if 得分[疏导目标] > 0:
            命中 += 1
    return round(命中 / len(过旺列表), 3)


def 计算补益分(强度结果: Dict) -> float:
    """补益分 v4.0：只按缺失数计（协议§六）。缺失0→1.0，缺失n→1-n/5。"""
    缺失数 = len(强度结果["缺失五行"])
    if 缺失数 == 0:
        return 1.0
    return round(max(0.0, 1.0 - 缺失数 / 5), 3)


