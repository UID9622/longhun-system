    相生顺序 = ["金", "水", "木", "火", "土"]
    断链预警 = []
    健康度 = 100

    for i in range(len(相生顺序)):
        来源 = 相生顺序[i]
        目标 = 相生顺序[(i + 1) % 5]
        if 得分.get(来源, 0) > 0 and 得分.get(目标, 0) == 0:
            断链预警.append(f"🔴 断链：{来源}({得分[来源]:.1f})有力但生不出{目标}(0分)·循环裂断")
            健康度 -= 15

    总分 = sum(得分.values()) + 0.001
    过旺 = [(k, v) for k, v in 得分.items() if v / 总分 > 0.40]
    for 五行名, 分値 in 过旺:
        疏导目标 = 五行相生[五行名]
