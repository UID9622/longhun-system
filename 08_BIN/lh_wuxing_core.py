def 归一化比例(value: Union[int, float, None]) -> float:
    """将0-100 或 0-1 的值统一压到 0-1"""
    if value is None:
        return 0.0
    if value > 1:
        return max(0.0, min(1.0, value / 100))
    return max(0.0, min(1.0, value))


