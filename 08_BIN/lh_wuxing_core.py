def 生成DNA(标题: str) -> str:
    """生成DNA追溯码"""
    今天 = datetime.now().strftime("%Y-%m-%d")
    安全标题 = 标题.replace(" ", "")[:18]
    return f"#龍芯⚡️{今天}-{安全标题}-v1.0"


def 生成节点ID(文本: str) -> str:
    """生成流场节点ID"""
    哈希 = hashlib.sha256(str(文本).encode()).hexdigest()[:8].upper()
    今天 = datetime.now().strftime("%Y%m%d")
    return f"FLOW-9622-{今天}-{哈希}"


def 生成流场节点(输入文本: str, 标题: str = "未命名节点",
                  前节点五行: Optional[str] = None,
                  输入类型: str = "text") -> Dict:
    """流场压缩核 v3.0 统一出口：输入文本 → 完整 Node"""
    数字根 = 计算数字根(输入文本)
    五行 = 数字根五行[数字根]
    审计 = 三色审计(数字根)
    关系 = 判断五行关系(五行, 前节点五行)

    if 审计 == "🟢":
        动作 = "enter"
    elif 审计 == "🟡":
        动作 = "hold"
    else:
        动作 = "fuse"

    视觉 = 五行视觉[五行]

    return {
        "node_id": 生成节点ID(输入文本),
        "标题": 标题,
        "输入类型": 输入类型,
        "数字根": 数字根,
        "五行": 五行,
        "关系": 关系,
        "三才": {"天": 0.35, "地": 0.15, "人": 0.50},
        "审计": 审计,
        "DNA": 生成DNA(标题),
        "视觉": 视觉,
        "动作": 动作,
        "备注": "文化语义算法节点，不替代科学实验、法律程序、医学判断或金融判断。"
    }


def 龍魂五行计算器(年天干: str, 年地支: str, 月天干: str, 月地支: str,
                  日天干: str, 日地支: str, 时天干: str, 时地支: str,
                  输入文本: Optional[str] = None) -> Dict:
    """统一入口 v4.0：传入8个干支 → 完整分析报告（可选输入文本联动翻译引擎第五维度）"""
    四柱 = {
        "年柱": {"天干": 年天干, "地支": 年地支},
        "月柱": {"天干": 月天干, "地支": 月地支},
        "日柱": {"天干": 日天干, "地支": 日地支},
        "时柱": {"天干": 时天干, "地支": 时地支},
    }

    强度 = 计算五行强度(四柱)
    链路 = 完整链路分析(强度["五行得分"])
    补益 = 生成补益建议(强度)
    对冲 = 计算五行对冲指数(强度, 链路)

    摘要文本 = 输入文本 if 输入文本 else 年天干 + 年地支 + 月天干 + 月地支 + 日天干 + 日地支 + 时天干 + 时地支
    节点 = 生成流场节点(摘要文本, "四柱八字摘要", None, "bazi")
    第五维 = 五行翻译引擎第五维度(摘要文本, 四柱)

    return {
        "版本": "v4.0",
        "四柱": 四柱,
        "五行强度": 强度,
        "链路分析": 链路,
        "补益建议": 补益,
        "对冲指数": 对冲,
        "翻译引擎第五维": 第五维,
        "流场节点": 节点,
        "DNA追溯": WUXING_CONSTANTS["DNA"],
        "确认码": WUXING_CONSTANTS["确认码"]
    }


