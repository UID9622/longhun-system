def 计算五行强度(四柱: Dict[str, Dict[str, str]]) -> Dict:
    """
    输入格式: {"年柱":{"天干":"甲","地支":"子"}, ...}
    返回: {五行得分, 最强, 最弱, 均衡指数, 缺失五行}
    """
    得分 = {k: 0.0 for k in 五行列表}

    for 柱位, 干支 in 四柱.items():
        权重 = 位置权重表[柱位]
        天干 = 干支.get("天干")
        地支 = 干支.get("地支")
        if 天干 in 天干五行表:
            得分[天干五行表[天干]] += 权重["天干"]
        if 地支 in 地支五行表:
            得分[地支五行表[地支]] += 权重["地支"]

    总分 = sum(得分.values())
    均値 = 总分 / 5
    方差 = sum((v - 均値) ** 2 for v in 得分.values()) / 5
    均衡指数 = max(0.0, round(1.0 - (方差 ** 0.5) / (均値 + 0.001), 3))
    缺失 = [k for k, v in 得分.items() if v == 0.0]
    最强 = max(得分, key=得分.get)
    最弱 = min(得分, key=得分.get)

    return {
        "五行得分": 得分,
        "最强": 最强,
        "最弱": 最弱,
        "均衡指数": 均衡指数,
        "缺失五行": 缺失
    }


