def 生成节点ID(文本: str) -> str:
    """生成流场节点ID"""
    哈希 = hashlib.sha256(str(文本).encode()).hexdigest()[:8].upper()
    今天 = datetime.now().strftime("%Y%m%d")
    return f"FLOW-9622-{今天}-{哈希}"


