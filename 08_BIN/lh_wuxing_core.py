def 计算数字根(text: Union[str, int]) -> int:
    """
    计算任意输入的数字根（0-9）
    兼容 Unicode 数字（如 ①、² 等）
    """
    s = str(text)
    digits = []
    for ch in s:
        if ch.isdigit():
            digits.append(int(ch))
    if not digits:
        return 0
    n = sum(digits)
    while n >= 10:
        n = sum(int(c) for c in str(n))
    return n


def 三色审计(dr: int) -> str:
    """根据数字根返回审计色"""
    if dr in [3, 9]:
        return "🔴"
    if dr == 6:
        return "🟡"
    return "🟢"


