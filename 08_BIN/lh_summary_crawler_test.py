    global 测试通过, 测试失败
    测试通过 = 0
    测试失败 = 0

    print("=" * 60)
    print("  龍魂摘要爬虫 · 12条测试向量")
    print(f"  DNA: #龍芯⚡️2026-07-21-SUMMARY-CRAWLER-SPLIT-V1.0-P0-TEST")
    print("=" * 60)

