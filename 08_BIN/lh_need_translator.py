def main():
    parser = argparse.ArgumentParser(
        description="🐉 龍魂·需求翻译引擎",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
示例:
  # 交互式模式（推荐）
  python3 lh_need_translator.py --interactive

  # 单次翻译
  python3 lh_need_translator.py "不知道干嘛"

  # 查看历史
  python3 lh_need_translator.py --history

  # 查看映射库
  python3 lh_need_translator.py --list
        """
    )

    parser.add_argument("表达", nargs="*", help="待翻译的表达")
    parser.add_argument("--interactive", "-i", action="store_true", help="交互模式")
    parser.add_argument("--history", "-H", action="store_true", help="查看历史")
    parser.add_argument("--list", "-l", action="store_true", help="查看映射库")
    parser.add_argument("--json", "-j", action="store_true", help="JSON格式输出")

    args = parser.parse_args()

    if args.list:
        print("\n📋 需求映射库:")
        print("-" * 50)
        for 模式, 数据 in 需求映射库.映射表.items():
            print(f"  {模式} → {数据['需求'][:30]}...")
            print(f"    人格: {数据['人格']} | 动作: {数据['动作']}")
        return

    if args.history:
        引擎 = 需求翻译引擎()
        历史 = 引擎.获取历史()
        if 历史:
            print("\n📋 翻译历史:")
            print("-" * 50)
            for h in 历史:
                print(f"  {h.原始表达[:30]}... → {h.翻译需求[:30]}...")
                print(f"   DNA: {h.dna} | 时间: {h.时间[:16]}")
                print()
        else:
            print("📭 暂无历史记录")
        return

    if args.interactive:
        交互模式.运行()
        return

    if args.表达:
        表达 = " ".join(args.表达)
        引擎 = 需求翻译引擎()
        结果 = 引擎.翻译(表达)

        if args.json:
            print(json.dumps(asdict(结果), ensure_ascii=False, indent=2))
