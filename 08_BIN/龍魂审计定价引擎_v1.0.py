# ============ 1. 用户等级枚举 ============
class 用户等级(Enum):
    个人体验级 = "个人体验级"    # 按次计费
    轻度使用级 = "轻度使用级"    # 9.9/月
    高频使用级 = "高频使用级"    # 99/月
