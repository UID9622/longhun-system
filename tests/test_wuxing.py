PASS, FAIL = "✅", "❌"
passed = 0
failed = 0


def assert_eq(name: str, actual, expected):
    global passed, failed
    if actual == expected:
        print(f"  {PASS} {name}: {actual}")
        passed += 1
    else:
        print(f"  {FAIL} {name}: got={actual!r}, want={expected!r}")
        failed += 1


def assert_in(name: str, container, item):
    global passed, failed
    if item in container:
        print(f"  {PASS} {name}: found {item!r}")
        passed += 1
    else:
        print(f"  {FAIL} {name}: {item!r} not in {container!r}")
        failed += 1


def assert_contains(name: str, container, substring: str):
    global passed, failed
    if substring in str(container):
        print(f"  {PASS} {name}: contains '{substring}'")
        passed += 1
    else:
        print(f"  {FAIL} {name}: '{substring}' not found in {str(container)[:200]}")
        failed += 1


