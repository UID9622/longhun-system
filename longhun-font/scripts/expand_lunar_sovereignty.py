def stroke_move(x, y):
    return {"类型": "移动到", "坐标": [x, y]}


def stroke_line(x, y):
    return {"类型": "直线段", "终点": [x, y]}


def polyline(points):
    strokes = [stroke_move(*points[0])]
    for p in points[1:]:
        strokes.append(stroke_line(*p))
    return strokes


def circle(cx, cy, r, segments=12):
    pts = []
    for i in range(segments + 1):
        a = 2 * math.pi * i / segments
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return polyline(pts)


def arc(cx, cy, r, start_angle, end_angle, segments=12):
    pts = []
    for i in range(segments + 1):
        a = start_angle + (end_angle - start_angle) * i / segments
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return polyline(pts)


def hline(y, x1, x2):
    return polyline([(x1, y), (x2, y)])


def vline(x, y1, y2):
    return polyline([(x, y1), (x, y2)])


def rect(x1, y1, x2, y2):
    return polyline([(x1, y1), (x2, y1), (x2, y2), (x1, y2), (x1, y1)])


def cross(cx, cy, arm):
    return polyline([(cx - arm, cy), (cx + arm, cy)]) + polyline([(cx, cy - arm), (cx, cy + arm)])


def star(cx, cy, outer_r, inner_r, points=5):
    """Simple even star polygon."""
    pts = []
    for i in range(points * 2 + 1):
        r = outer_r if i % 2 == 0 else inner_r
        a = -math.pi / 2 + math.pi * i / points
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return polyline(pts)


def drop(cx, cy, h):
    return polyline([(cx, cy - h), (cx + h * 0.4, cy), (cx, cy + h * 0.3), (cx - h * 0.4, cy), (cx, cy - h)])


def triangle(p1, p2, p3):
    return polyline([p1, p2, p3, p1])


