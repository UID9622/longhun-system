def refine(glyph_path: str):
    base_dir = Path(__file__).parent.parent
    glyph_path = Path(glyph_path) if glyph_path else base_dir / "glyphs" / "龍魂字元库_v0002_扩展.json"

    with open(glyph_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    refined_count = 0
    for char, strokes in REFINED_PATHS.items():
        if char in data["字符集_cnsh9622"]:
            data["字符集_cnsh9622"][char]["笔画路径_cnsh9622"] = strokes
            data["字符集_cnsh9622"][char]["精修"] = True
            data["字符集_cnsh9622"][char]["精修DNA"] = DNA
            refined_count += 1

    data["元数据"]["描述"] = "LonghunFont 扩展字元库，含 195 字，核心字形已精修"
    data["元数据"]["精修时间"] = datetime.now().isoformat()
    data["元数据"]["精修DNA"] = DNA

    with open(glyph_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"✅ 已精修 {refined_count} 个核心字形: {', '.join(REFINED_PATHS.keys())}")
    print(f"   保存至: {glyph_path}")
    return str(glyph_path)


