def expand(glyph_path: str):
    base_dir = Path(__file__).parent.parent
    glyph_path = Path(glyph_path) if glyph_path else base_dir / "glyphs" / "龍魂字元库_v0002_扩展.json"

    with open(glyph_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    existing = set(data["字符集_cnsh9622"].keys())
    added = 0

    for char in EXTRA_CHARS:
        if char in existing:
            continue
        # 跳过非汉字
        if not ("\u4e00" <= char <= "\u9fff"):
            continue
        data["字符集_cnsh9622"][char] = {
            "unicode": f"U+{ord(char):04X}",
            "笔画数": stroke_count_of(char),
            "结构": structure_of(char),
            "风格参数": {"力度": 0.8, "棱角": 0.3, "节奏": 0.6, "墨色": 0.9},
            "笔画路径_cnsh9622": generate_skeleton(char)
        }
        existing.add(char)
        added += 1

    data["元数据"]["版本"] = "v0003-千字符"
    data["元数据"]["描述"] = f"LonghunFont 千字符字元库，含 {len(existing)} 个汉字骨架"
    data["元数据"]["扩展时间"] = datetime.now().isoformat()
    data["元数据"]["扩展DNA"] = DNA

    new_path = base_dir / "glyphs" / "龍魂字元库_v0003_千字符.json"
    with open(new_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"✅ 已扩展字元库: {new_path}")
    print(f"   原有字元: {len(existing) - added}")
    print(f"   新增字元: {added}")
    print(f"   总字元数: {len(existing)}")
    return str(new_path)


if __name__ == "__main__":
    import sys
    path = sys.argv[1] if len(sys.argv) > 1 else None
    expand(path)
