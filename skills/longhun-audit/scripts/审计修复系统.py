        # 生成验证报告
        成功率 = (通过步骤 / 总步骤 * 100) if 总步骤 > 0 else 0
        
        if 失败步骤 == 0:
            总体结果 = 验证结果.通过.value
        elif 通过步骤 > 0:
            总体结果 = 验证结果.部分通过.value
        else:
            总体结果 = 验证结果.失败.value
        
