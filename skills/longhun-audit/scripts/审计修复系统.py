        print(f"{'='*50}")
        
        总步骤 = len(验证步骤列表)
        通过步骤 = 0
        失败步骤 = 0
        跳过步骤 = 0
        
        for 索引, 步骤 in enumerate(验证步骤列表, 1):
            print(f"\n[步骤 {索引}/{总步骤}] {步骤.步骤名称}")
