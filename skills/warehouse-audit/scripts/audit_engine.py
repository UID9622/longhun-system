class 审计等级(Enum):
    A = "A"  # 90-100 卓越
    B = "B"  # 75-89  良好
    C = "C"  # 60-74  合格
    D = "D"  # 40-59  待改进
    E = "E"  # 0-39   不合格


class 风险等级(Enum):
    P0 = "P0"  # 致命 24小时
    P1 = "P1"  # 严重 72小时
    P2 = "P2"  # 一般 1周
    P3 = "P3"  # 建议 1月


class 审计色(Enum):
    GREEN = "🟢"
    YELLOW = "🟡"
    RED = "🔴"


class 检查项:
    def __init__(self, 名称: str, 要求: str, 满分: int, 权重: float = 1.0, 证据键: str = ""):
        self.名称 = 名称
        self.要求 = 要求
        self.满分 = 满分
        self.权重 = 权重
        self.得分 = 0
        self.评级 = 审计等级.E
        self.审计色 = 审计色.RED
        self.风险等级 = 风险等级.P2
        self.证据 = ""
        self.改进建议 = ""
        self.是否检查 = False
        self.证据键 = 证据键 or 名称  # 用于匹配 WMS 证据提取函数

    def 评分(self, 得分: int, 证据: str = "", 改进建议: str = ""):
        self.得分 = min(max(得分, 0), self.满分)
        self.证据 = 证据
        self.改进建议 = 改进建议
        self.是否检查 = True
        
        # 计算评级
        得分率 = (self.得分 / self.满分) * 100 if self.满分 > 0 else 0
        if 得分率 >= 90:
            self.评级 = 审计等级.A
            self.审计色 = 审计色.GREEN
            self.风险等级 = 风险等级.P3
        elif 得分率 >= 75:
            self.评级 = 审计等级.B
            self.审计色 = 审计色.GREEN
            self.风险等级 = 风险等级.P3
        elif 得分率 >= 60:
            self.评级 = 审计等级.C
            self.审计色 = 审计色.YELLOW
            self.风险等级 = 风险等级.P2
        elif 得分率 >= 40:
            self.评级 = 审计等级.D
            self.审计色 = 审计色.YELLOW
            self.风险等级 = 风险等级.P1
        else:
            self.评级 = 审计等级.E
            self.审计色 = 审计色.RED
            self.风险等级 = 风险等级.P0 if 得分率 < 20 else 风险等级.P1


class 检查维度:
    def __init__(self, 名称: str, 标识: str, 权重: float):
        self.名称 = 名称
        self.标识 = 标识
        self.权重 = 权重
        self.检查项列表: List[检查项] = []
        self.得分 = 0
        self.满分 = 0

    def 添加检查项(self, 检查项实例: 检查项):
        self.检查项列表.append(检查项实例)
        self.满分 += 检查项实例.满分

    def 计算得分(self) -> float:
        总分 = sum(项.得分 for 项 in self.检查项列表)
        self.得分 = (总分 / self.满分 * 100) if self.满分 > 0 else 0
        return self.得分


