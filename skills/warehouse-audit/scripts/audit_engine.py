    def _系统成熟度评分(self, 项: 检查项, 依赖指标: List[str], 阈值: float):
        """当所有依赖指标均达到阈值时，按满分比例给分。"""
        命中数 = 0
        for 指标 in 依赖指标:
            值 = self.wms.取(指标)
            if 值 is None:
                return 0
            if 指标 in ("inventory_diff_rate", "query_p95_ms", "picking_steps",
                        "return_cycle_hours", "training_hours", "failover_seconds"):
                命中数 += 1 if 值 <= 阈值 else 0
            else:
                命中数 += 1 if 值 >= 阈值 else 0
        比例 = 命中数 / len(依赖指标)
        return int(项.满分 * 比例)

