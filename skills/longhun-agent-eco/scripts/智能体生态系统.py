def 主函數():
    """命令行入口"""
    if len(sys.argv) < 2:
        print("用法: python 智能体生态系统.py <命令> [選項]")
        print("")
        print("命令:")
        print("  init       初始化生態系統")
        print("  list       列出所有智能體")
        print("  status     查看系統狀態")
        print("  report     生成完整報告")
        print("  find <關鍵詞>  搜索智能體")
        print("  export     導出JSON數據")
        print("  exec <編號>  執行智能體")
        sys.exit(1)

    命令 = sys.argv[1]
    協調器 = 智能體協調器()

    if 命令 == "init":
        協調器.初始化()
        print(f"✅ {系統名稱} 初始化完成")
        print(f"   已註冊 15 個智能體")
        print(f"   DNA: {DNA標記}")

    elif 命令 == "list":
        協調器.初始化()
        for 智能體 in 協調器.獲取全部智能體().values():
            print(f"{智能體.編號}: {智能體.名稱} [{智能體.類型.value}] (評分: {智能體.評分})")

    elif 命令 == "status":
        協調器.初始化()
        狀態 = 協調器.獲取狀態()
        print(f"智能體總數: {狀態.智能體總數}")
        print(f"就緒: {狀態.就緒數} | 運行中: {狀態.運行中數} | 維護: {狀態.維護中數} | 離線: {狀態.離線數}")
        print(f"系統評分: {狀態.系統評分}/10")
        print(f"路由精確度: {狀態.路由精確度}%")
        print(f"DNA完整性: {'✅' if 狀態.DNA完整性 else '❌'}")

    elif 命令 == "report":
        協調器.初始化()
        print(協調器.生成報告())

    elif 命令 == "find":
        if len(sys.argv) < 3:
            print("請提供搜索關鍵詞")
            sys.exit(1)
        協調器.初始化()
        關鍵詞 = sys.argv[2]
        結果 = 協調器.按關鍵詞篩選(關鍵詞)
        if 結果:
            print(f"找到 {len(結果)} 個匹配智能體:")
            for 智能體 in 結果:
                print(f"  {智能體.編號}: {智能體.名稱} - {智能體.功能描述}")
        else:
            print("未找到匹配智能體")

    elif 命令 == "export":
        協調器.初始化()
        print(協調器.導出JSON())

    elif 命令 == "exec":
        if len(sys.argv) < 3:
            print("請提供智能體編號")
            sys.exit(1)
        協調器.初始化()
        編號 = sys.argv[2]
        結果 = 協調器.執行智能體(編號)
        print(json.dumps(結果, ensure_ascii=False, indent=2))

    else:
        print(f"未知命令: {命令}")
        sys.exit(1)


if __name__ == "__main__":
    主函數()
