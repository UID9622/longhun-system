# 智能體協調器
# ============================================================

class 智能體協調器:
    """15智能體協調管理器"""

    def __init__(self):
        self._智能體倉庫: Dict[str, 智能體定義] = {}
        self._狀態: 生態狀態 = 生態狀態()
        self._初始化時間 = datetime.datetime.now().isoformat()
        self._已初始化 = False

    def 初始化(self) -> bool:
        """初始化生態系統，註冊所有15個智能體"""
        if self._已初始化:
            return True

        工廠 = 智能體工廠()
        self._智能體倉庫 = 工廠.創建全部智能體()
        self._已初始化 = True
        self._更新狀態()

        return True

    def _更新狀態(self):
        """更新生態系統整體狀態"""
        全部智能體 = self._智能體倉庫.values()
        self._狀態.智能體總數 = len(全部智能體)
        self._狀態.就緒數 = sum(1 for a in 全部智能體 if a.狀態 == 智能體狀態.就緒)
        self._狀態.運行中數 = sum(1 for a in 全部智能體 if a.狀態 == 智能體狀態.運行中)
        self._狀態.維護中數 = sum(1 for a in 全部智能體 if a.狀態 == 智能體狀態.維護中)
        self._狀態.離線數 = sum(1 for a in 全部智能體 if a.狀態 == 智能體狀態.離線)
        self._狀態.系統評分 = round(
            sum(a.評分 for a in 全部智能體) / len(全部智能體), 2
        ) if 全部智能體 else 0.0
        self._狀態.最後更新 = datetime.datetime.now().isoformat()
        self._狀態.DNA完整性 = self._驗證DNA完整性()

    def _驗證DNA完整性(self) -> bool:
        """驗證所有智能體DNA鏈完整性"""
        for 智能體 in self._智能體倉庫.values():
            預期DNA = hashlib.sha256(
                f"{智能體.編號}:{智能體.名稱}:{智能體.類型.value}:{版本號}".encode()
            ).hexdigest()[:16]
            if 智能體.DNA鏈 != 預期DNA:
                return False
        return True

    # ---- 查詢接口 ----

    def 獲取全部智能體(self) -> Dict[str, 智能體定義]:
        """獲取所有智能體"""
        return self._智能體倉庫.copy()

    def 獲取智能體(self, 編號: str) -> Optional[智能體定義]:
        """按編號獲取智能體"""
        return self._智能體倉庫.get(編號)

    def 按類型篩選(self, 類型: 智能體類型) -> List[智能體定義]:
        """按類型篩選智能體"""
        return [a for a in self._智能體倉庫.values() if a.類型 == 類型]

    def 按標籤篩選(self, 標籤: str) -> List[智能體定義]:
        """按路由標籤篩選智能體"""
        return [a for a in self._智能體倉庫.values() if 標籤 in a.路由標籤]

    def 按關鍵詞篩選(self, 關鍵詞: str) -> List[智能體定義]:
        """按關鍵詞模糊匹配"""
        結果 = []
        for 智能體 in self._智能體倉庫.values():
            if any(關鍵詞 in k for k in 智能體.關鍵詞):
                結果.append(智能體)
            elif 關鍵詞 in 智能體.名稱 or 關鍵詞 in 智能體.功能描述:
                結果.append(智能體)
        return 結果

    def 獲取狀態(self) -> 生態狀態:
        """獲取生態系統狀態"""
        self._更新狀態()
        return self._狀態

    # ---- 操作接口 ----

    def 更新智能體狀態(self, 編號: str, 新狀態: 智能體狀態) -> bool:
        """更新智能體狀態"""
        if 編號 not in self._智能體倉庫:
            return False
        self._智能體倉庫[編號].狀態 = 新狀態
        self._更新狀態()
        return True

    def 執行智能體(self, 編號: str, 參數: Dict = None) -> Dict:
        """執行指定智能體"""
        智能體 = self._智能體倉庫.get(編號)
        if not 智能體:
            return {"成功": False, "錯誤": f"智能體 {編號} 不存在"}

        if 智能體.狀態 != 智能體狀態.就緒:
            return {"成功": False, "錯誤": f"智能體 {編號} 未就緒"}

        # 檢查依賴
        for 依賴 in 智能體.依賴項:
            if 依賴 in self._智能體倉庫:
                if self._智能體倉庫[依賴].狀態 not in [智能體狀態.就緒, 智能體狀態.運行中]:
                    return {"成功": False, "錯誤": f"依賴 {依賴} 未就緒"}

        # 模擬執行
        智能體.狀態 = 智能體狀態.運行中
        if "執行次數" in 智能體.統計數據:
            智能體.統計數據["執行次數"] += 1
        if "處理任務數" in 智能體.統計數據:
            智能體.統計數據["處理任務數"] += 1
        智能體.統計數據["最後執行"] = datetime.datetime.now().isoformat()
        智能體.狀態 = 智能體狀態.就緒

        self._更新狀態()
        return {
            "成功": True,
            "智能體": 編號,
            "名稱": 智能體.名稱,
            "執行時間": datetime.datetime.now().isoformat(),
            "參數": 參數 or {},
            "DNA": 智能體.DNA鏈,
        }

    # ---- 報告生成 ----

    def 生成報告(self) -> str:
        """生成生態系統報告"""
        self._更新狀態()
        狀態 = self._狀態

        報告 = []
        報告.append("=" * 60)
        報告.append(f"🐉 {系統名稱} v{版本號}")
        報告.append(f"DNA: {DNA標記}")
        報告.append(f"初始化時間: {self._初始化時間}")
        報告.append("=" * 60)
        報告.append("")
        報告.append("📊 生態系統狀態")
        報告.append(f"  智能體總數: {狀態.智能體總數}")
        報告.append(f"  🟢 就緒:     {狀態.就緒數}")
        報告.append(f"  🔵 運行中:   {狀態.運行中數}")
        報告.append(f"  🟡 維護中:   {狀態.維護中數}")
        報告.append(f"  🔴 離線:     {狀態.離線數}")
        報告.append(f"  系統評分:   {狀態.系統評分}/10")
        報告.append(f"  路由精確度: {狀態.路由精確度}%")
        報告.append(f"  DNA完整性: {'✅ 通過' if 狀態.DNA完整性 else '❌ 異常'}")
        報告.append("")

        # 按類型分組
        報告.append("🤖 智能體清單")
        for 類型 in 智能體類型:
            列表 = self.按類型篩選(類型)
            if 列表:
                報告.append(f"\n  [{類型.value.upper()}]")
                for 智能體 in 列表:
                    狀態圖標 = {
                        智能體狀態.就緒: "🟢",
                        智能體狀態.運行中: "🔵",
                        智能體狀態.維護中: "🟡",
                        智能體狀態.離線: "🔴",
                    }.get(智能體.狀態, "⚪")
                    報告.append(
                        f"    {狀態圖標} {智能體.編號} {智能體.名稱} "
                        f"(評分: {智能體.評分})"
                    )

        報告.append("")
        報告.append("=" * 60)
        報告.append(f"生成時間: {datetime.datetime.now().isoformat()}")
        報告.append("=" * 60)

        return "\n".join(報告)

    def 導出JSON(self) -> str:
        """導出完整生態系統數據為JSON"""
        數據 = {
            "系統": {
                "名稱": 系統名稱,
                "版本": 版本號,
                "DNA": DNA標記,
                "初始化時間": self._初始化時間,
            },
            "狀態": self._狀態.到字典(),
            "智能體": {k: v.到字典() for k, v in self._智能體倉庫.items()},
        }
        return json.dumps(數據, ensure_ascii=False, indent=2)


