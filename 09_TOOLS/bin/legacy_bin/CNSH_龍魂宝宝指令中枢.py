        执行结果: Dict[str, Any] = {}
        上一个结果: Optional[Dict[str, Any]] = None

        for 技能名 in 技能名列表:
            if 技能名 == "流场可视化":
                结果 = self._安全执行("流场可视化", self._执行流场动作, 意图)
            elif 技能名 == "国密加密":
                结果 = self._安全执行("国密加密", self._执行国密, 意图)
            elif 技能名 == "代码审计":
                结果 = self._安全执行("代码审计", self._执行代码审计, 意图)
            elif 技能名 == "目录审计":
                结果 = self._安全执行("目录审计", self._执行目录审计, 意图)
            elif 技能名 in ("内容加工", "文章加工"):
                结果 = self._安全执行("内容加工", self._执行内容加工, 意图)
            elif 技能名 == "知识库":
                结果 = self._安全执行("知识库归档", self._执行知识库归档, 意图, 上一个结果)
            elif 技能名 == "通知归档":
                结果 = self._安全执行("通知归档", self._执行通知归档, 意图, 上一个结果)
            else:
                continue

            执行结果[技能名] = 结果
            if 结果.get("ok") and "结果" in 结果:
                上一个结果 = {"动作": 技能名, "结果": 结果["结果"]}

        self._最后执行结果 = 上一个结果
        return 执行结果

