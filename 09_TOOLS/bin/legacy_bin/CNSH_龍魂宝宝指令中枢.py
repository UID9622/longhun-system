    # ============== 11. 执行入口 ==============
    def 执行(self, 用户输入: str) -> Dict[str, Any]:
        if not self._被唤醒(用户输入):
            return {
                "状态": "休眠",
                "说明": "未喊「宝宝」，普通对话模式。需要系统调度时请喊「宝宝」。",
            }

        意图 = self._拆解意图(用户输入)
        命中技能 = self._路由技能(意图)

        # 颜色不动点：任何输入先落一个颜色（ eyes first ）
        颜色状态报告 = self.颜色协议.生成报告(用户输入)

        合规审查 = self._合规审查(意图, 命中技能)

        if not 合规审查["通过"]:
            return {
                "状态": "合规阻断",
                "说明": "请求触碰底线，已拦截。",
                "风险": 合规审查["风险"],
                "DNA": self._生成DNA("BLOCK", SM3.hex_hash(用户输入), 颜色状态报告["主色"]),
            }

        # 多模型颜色一致性：交叉验证，取最高风险
        一致性报告 = self.多模型一致性.带DNA检测(用户输入)
        if 一致性报告["主色"] != 颜色状态报告["主色"]:
            # 以多模型最高风险为准
            颜色状态报告 = self.颜色协议.生成报告(用户输入)
            颜色状态报告["主色"] = 一致性报告["主色"]
            颜色状态报告["颜色名"] = {"R": "红色", "K": "黑色", "P": "紫色", "G": "绿色", "Y": "黄色", "B": "蓝色", "AU": "金色"}.get(一致性报告["主色"], "未知")
            颜色状态报告["emoji"] = {"R": "🔴", "K": "⚫", "P": "🟣", "G": "🟢", "Y": "🟡", "B": "🔵", "AU": "🟡"}.get(一致性报告["主色"], "⚪")
            颜色状态报告["多模型一致性"] = 一致性报告

        # 颜色历史记录
        self.颜色历史.记录(self.画像["UID"], 颜色状态报告["主色"], 用户输入)

        # 龍魂护盾联动：🔴/⚫/🟣 自动防御
        护盾结果 = self.护盾.检查人工智能("颜色引擎", 用户输入, 颜色状态报告["emoji"])

        # 生态监管：颜色权限检查
        颜色权限 = self.生态监管.颜色权限检查(self.画像["UID"], 颜色状态报告["主色"])

        计划 = self._生成执行计划(意图, 命中技能, 合规审查["建议"])
        DNA = self._生成DNA("EXECUTE", SM3.hex_hash(用户输入), 颜色状态报告["主色"])

        结果 = {
            "状态": "已唤醒",
            "唤醒词": "宝宝",
            "画像": self.画像["称呼"],
            "意图": 意图,
            "命中技能": 命中技能,
            "合规建议": 合规审查["建议"],
            "执行计划": 计划,
            "颜色状态": 颜色状态报告,
            "护盾联动": 护盾结果,
            "颜色权限": 颜色权限,
            "DNA": DNA,
            "输入SM3哈希": SM3.hex_hash(用户输入),
        }

        # 颜色红线熔断：如果颜色协议判定为红线，直接阻断
        if 颜色状态报告.get("红线"):
            结果["状态"] = "颜色红线阻断"
            结果["颜色熔断"] = True
            self.执行历史.append(结果)
            self._保存历史()
            return 结果

        # 第一关：流场可视化直接落地执行，不只做计划
        流场结果 = None
        if any(s["技能名"] == "流场可视化" for s in 命中技能[:3]):
            流场结果 = self._执行流场动作(意图)
            结果["流场结果"] = 流场结果
            if 流场结果.get("动作") != "流场动作跳过":
                结果["状态"] = "已唤醒·流场已执行"

        # 底座技能直接落地执行
        底座命中 = [s for s in 命中技能[:3] if s["技能名"] in {
            "国密加密", "代码审计", "目录审计", "内容加工", "文章加工", "知识库", "通知归档"
        }]
        if 底座命中:
            结果["执行结果"] = self._执行底座动作(意图, 命中技能)
            if 结果["状态"] == "已唤醒" or (流场结果 and 流场结果.get("动作") == "流场动作跳过"):
                结果["状态"] = "已唤醒·底座已执行"

        self.执行历史.append(结果)
        self._保存历史()
        return 结果

    # ============== 11. 学习优化（最小闭环） ==============
    def 反馈优化(self, 执行ID: int, 反馈: str) -> str:
        """根据用户反馈微调权重。"""
        if 执行ID < 0 or 执行ID >= len(self.执行历史):
            return "执行ID无效"
        记录 = self.执行历史[执行ID]
        技能名 = 记录["命中技能"][0]["技能名"] if 记录["命中技能"] else "未知"

        if any(k in 反馈 for k in ["准", "好", "对", "舒服", "厉害"]):
            调整 = +0.05
            结论 = f"{技能名} 权重 +0.05"
        elif any(k in 反馈 for k in ["不准", "错", "乱", "多余"]):
            调整 = -0.05
            结论 = f"{技能名} 权重 -0.05"
        else:
            调整 = 0
            结论 = "无调整"

        if 技能名 in self.技能:
            self.技能[技能名]["权重"] = max(0.1, min(2.0, self.技能[技能名]["权重"] + 调整))

        return 结论

