    def _提取可能路径(self, 输入: str) -> Optional[str]:
        """从输入里找第一个看起来像文件/目录的路径。"""
        # 先找引号里的
        for m in re.finditer(r'["\']([^"\']+)["\']', 输入):
            p = Path(m.group(1))
            if p.exists() or p.parent.exists():
                return str(p)
        # 再找 /xx/yy 或 ./xx 形式
        for m in re.finditer(r"(?:(?:\.\.?|[\w\-]+)?[/\\])+[\w\-./\\]*", 输入):
            p = Path(m.group())
            if p.exists() or p.parent.exists():
                return str(p)
        return None

