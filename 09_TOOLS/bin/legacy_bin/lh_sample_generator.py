def 生成样本集(真人数量: int = 1000, AI数量: int = 200, seed: int = 9622) -> Dict[str, Any]:
    """
    生成完整样本集
    返回: {"humans": [...], "ai": [...]}
    """
    rng = random.Random(seed)

    print(f"🧬 龍魂·样本生成器")
    print(f"  生成 {真人数量} 个模拟真人书写样本...")
    真人样本 = []
    for i in range(真人数量):
        # 每个人用自己的子seed在全局seed基础上偏移
        个人rng = random.Random(seed * 10000 + i)
        文本 = 生成真人书写(个人rng, i)
        if len(文本) > 20:  # 过滤太短的
            真人样本.append({
                "id": i,
                "person_seed": seed * 10000 + i,
                "text": 文本,
                "length": len(文本),
            })

    print(f"  生成 {AI数量} 个模拟AI生成样本...")
    AI样本 = []
    for i in range(AI数量):
        个人rng = random.Random(seed * 20000 + i)
        文本 = 生成AI书写(个人rng)
        AI样本.append({
            "id": i,
            "text": 文本,
            "length": len(文本),
        })

    print(f"  完成: {len(真人样本)} 真人 | {len(AI样本)} AI")
    return {"humans": 真人样本, "ai": AI样本}


