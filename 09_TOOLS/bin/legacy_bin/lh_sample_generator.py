def 生成真人书写(rng: random.Random, person_id: int) -> str:
    """
    模拟一个真人的书写行为。
    每个人有固定的"习惯指纹"参数（错别字率、标点癖、口头禅），
    但每次生成的具体内容是随机的不同场景。
    """
    # === 每个人的固定习惯（不动点） ===
    错别字率 = rng.uniform(0.01, 0.08)
    标点癖选择 = rng.sample(标点癖池, k=rng.randint(0, 3))
    口头禅选择 = rng.sample(口头禅池, k=rng.randint(0, 4))
    句长偏好 = rng.choice(["短句", "中句", "长句", "混合"])
    情绪强度 = rng.uniform(0.1, 1.0)

    # === 生成 3-5 个段落 ===
    段数 = rng.randint(3, 5)
    段落 = []
    for _ in range(段数):
        场景 = rng.choice(真人场景模板)
        主句 = rng.choice(场景["topics"])
        # 填入变量
        for key, val_list in 场景变量.items():
            if f"{{{key}}}" in 主句:
                主句 = 主句.replace(f"{{{key}}}", rng.choice(val_list), 1)

        # 连接这个场景的 2-3 个句式
        句子片段 = [主句]
        片段数 = rng.randint(1, 3)
        for _ in range(片段数):
            if rng.random() < 0.7:
                连接词 = rng.choice(场景["connectors"])
                扩展 = rng.choice(场景["topics"][1:]) if len(场景["topics"]) > 1 else ""
                for key, val_list in 场景变量.items():
                    if f"{{{key}}}" in 扩展:
                        扩展 = 扩展.replace(f"{{{key}}}", rng.choice(val_list), 1)
                if 扩展:
                    if 随机(rng, 0.5):
                        句子片段.append(连接词 + 扩展)
                    else:
                        句子片段[-1] += 连接词 + 扩展

        # 加入情绪词
        if rng.random() < 情绪强度:
            情绪 = rng.choice(场景["emotions"])
            句子片段.append(f"。{情绪}")

        # 组装段落
        段落文本 = "。".join(句子片段) if rng.random() < 0.3 else "，".join(句子片段)

        # 根据句长偏好拆分/合并
        if 句长偏好 == "短句" and len(段落文本) > 60:
            pass  # 短句就是短的
        elif 句长偏好 == "长句":
            段落文本 = 段落文本.replace("。", "，")

        段落.append(段落文本)

    # === 注入错别字 ===
    完整文本 = "\n".join(段落)
    字符列表 = list(完整文本)
    错别字字典池 = list(拼音错别字_池.keys())
    for i in range(len(字符列表)):
        if rng.random() < 错别字率:
            char = 字符列表[i]
            if char in 拼音错别字_池:
                字符列表[i] = 拼音错别字_池[char]

    # === 注入标点癖 ===
    完成文本 = "".join(字符列表)
    for 癖名, 癖符号 in 标点癖选择:
        if rng.random() < 0.4:
            # 在随机位置插入标点癖
            插入位置 = rng.randint(0, len(完成文本) - 1)
            完成文本 = 完成文本[:插入位置] + 癖符号 + 完成文本[插入位置:]

    # === 注入口头禅 ===
    for 口头禅 in 口头禅选择:
        if rng.random() < 0.3:
            插入位置 = rng.randint(0, len(完成文本) - 1)
            完成文本 = 完成文本[:插入位置] + 口头禅 + 完成文本[插入位置:]

    # === 清理异常重复 ===
    完成文本 = 完成文本.replace("。。。。", "。").replace("，，，，", "，")
    完成文本 = 完成文本.replace("。。", "。").replace("，，", "，")

    return 完成文本.strip()


