def 生成AI书写(rng: random.Random) -> str:
    """模拟 AI 生成的文本"""
    模板 = rng.choice(AI_语料模板)
    body_lines = []
    for line in 模板["body"]:
        for key, val_list in AI_变量.items():
            if f"{{{key}}}" in line:
                line = line.replace(f"{{{key}}}", rng.choice(val_list), 1)
        body_lines.append(line)

    prefix = 模板["prefix"]
    for key, val_list in AI_变量.items():
        if f"{{{key}}}" in prefix:
            prefix = prefix.replace(f"{{{key}}}", rng.choice(val_list), 1)

    suffix = 模板["suffix"]
    for key, val_list in AI_变量.items():
        if f"{{{key}}}" in suffix:
            suffix = suffix.replace(f"{{{key}}}", rng.choice(val_list), 1)

    完整文本 = prefix + " ".join(body_lines) + " " + suffix
    return 完整文本


