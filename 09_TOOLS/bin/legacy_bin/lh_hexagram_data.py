def get_hexagram(hex_id: int) -> Optional[Dict]:
    """通过ID获取卦象"""
    return HEXAGRAMS.get(hex_id)


def get_hexagram_by_name(name: str) -> Optional[Dict]:
    """通过名称获取卦象"""
    for h in HEXAGRAMS.values():
        if h["name"] == name:
            return h
    return None


def search_by_element(element: str) -> List[Dict]:
    """按五行属性搜索卦象"""
    return [h for h in HEXAGRAMS.values() if h["element"] == element]


def search_by_fortune(min_fortune: float = 0.0, max_fortune: float = 1.0) -> List[Dict]:
    """按运势范围搜索卦象"""
    return [
        h for h in HEXAGRAMS.values()
        if min_fortune <= h["fortune"] <= max_fortune
    ]


def get_solar_term_weight(term_name: str) -> float:
    """获取节气权重"""
    term = SOLAR_TERMS.get(term_name)
    return term["weight"] if term else 1.0


def get_wuxing_relation(element: str) -> Optional[Dict]:
    """获取五行关系"""
    sheng = WUXING_RELATION["生"].get(element)
    ke = WUXING_RELATION["克"].get(element)
    bei_sheng = [k for k, v in WUXING_RELATION["生"].items() if v == element]
    bei_ke = [k for k, v in WUXING_RELATION["克"].items() if v == element]
    return {
        "element": element,
        "生": sheng,
        "克": ke,
        "被生": bei_sheng[0] if bei_sheng else None,
        "被克": bei_ke[0] if bei_ke else None,
    }


