def 双验证(主权: Dict[str, Any], wai: Dict[str, Any]) -> Dict[str, Any]:
    """两公式交叉验证·出最终结论"""
    s_score = 主权["得分"]
    w_score = wai["得分"]
    avg = (s_score + w_score) / 2
    
    # 判定一致性
    if 主权["颜色"] == wai["颜色"]:
        一致性 = "一致"
    else:
        一致性 = "⚠️ 两公式判定不一致·需人工复核"
    
    if avg >= 0.75:
        final = "🟢 这个产品/服务确实为老百姓服务"
    elif avg >= 0.45:
        final = "🟡 骑墙状态·部分为民·部分为资本·保持警觉"
    elif avg >= 0.25:
        final = "🔴 装饰性为民·实质为资本·建议远离"
    else:
        final = "🔴 明确反人民·立即警惕·不要使用"
    
    return {
        "综合分": round(avg, 4),
        "最终判定": final,
        "双公式一致性": 一致性,
        "主权检验": 主权["得分"],
        "白皮书WAI": wai["得分"],
    }


