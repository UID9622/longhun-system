class 产品检测器:
    """输入产品特征→输出双公式验证结果"""
    
    def 检测(self, 主权参数: Dict[str, float], wai参数: Dict[str, float]) -> Dict[str, Any]:
        主权 = 算主权检验(
            用户付费占比=主权参数.get("付费", 0),
            数据可携度=主权参数.get("可携", 0),
            推荐透明度=主权参数.get("透明", 0),
            错误兜底度=主权参数.get("兜底", 0),
            退出自由度=主权参数.get("退出", 0),
        )
        wai = 算WAI(
            服务对象=wai参数.get("服务对象", 0.5),
            数据主权=wai参数.get("数据主权", 0.5),
            算法透明=wai参数.get("算法透明", 0.5),
            文化主权=wai参数.get("文化主权", 0.5),
            成本转嫁=wai参数.get("成本转嫁", 0.5),
            纠错机制=wai参数.get("纠错机制", 0.5),
            普惠落地=wai参数.get("普惠落地", 0.5),
        )
        综合 = 双验证(主权, wai)
        return {
            "主权检验": 主权,
            "白皮书WAI": wai,
            "综合判定": 综合,
        }
    
    def 快速检测(self, 产品名: str) -> Optional[Dict[str, Any]]:
        """用预置参数快速检测已知产品"""
        if 产品名 not in 预置产品库:
            return None
        参数 = 预置产品库[产品名]
        return self.检测(参数["主权"], 参数["WAI"])
    
    def 排行榜(self) -> List[Tuple[str, float]]:
        """所有预置产品按综合分排名"""
        排行 = []
        for 产品名, 参数 in 预置产品库.items():
            result = self.检测(参数["主权"], 参数["WAI"])
            排行.append((产品名, result["综合判定"]["综合分"]))
        排行.sort(key=lambda x: x[1], reverse=True)
        return 排行


