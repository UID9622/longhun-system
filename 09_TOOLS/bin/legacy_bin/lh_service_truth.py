def 算WAI(
    服务对象: float = 0.5,
    数据主权: float = 0.5,
    算法透明: float = 0.5,
    文化主权: float = 0.5,
    成本转嫁: float = 0.5,
    纠错机制: float = 0.5,
    普惠落地: float = 0.5,
) -> Dict[str, Any]:
    """
    WAI = Σ(维×权)
    源: IPA-DICT-035
    """
    weights = {
        "服务对象": (服务对象, 0.20, "谁出钱就为谁服务"),
        "数据主权": (数据主权, 0.20, "数据归谁·存哪里"),
        "算法透明": (算法透明, 0.15, "能审计吗"),
        "文化主权": (文化主权, 0.15, "中文思维还是英文翻译"),
        "成本转嫁": (成本转嫁, 0.10, "免费的东西谁买单"),
        "纠错机制": (纠错机制, 0.10, "出错怎么办"),
        "普惠落地": (普惠落地, 0.10, "老百姓能用吗"),
    }
    
    total = 0.0
    子项 = []
    for 名, (分, 权, 提示) in weights.items():
        total += 分 * 权
        子项.append({"项": 名, "得分": 分, "权重": 权, "提示": 提示})
    
    if total >= 0.8:
        等级 = "真白皮书"
        颜色 = "🟢"
    elif total >= 0.5:
        等级 = "半张白皮书"
        颜色 = "🟡"
    elif total >= 0.2:
        等级 = "装饰品"
        颜色 = "🔴"
    else:
        等级 = "反人民"
        颜色 = "🔴"
    
    return {
        "公式": "WAI",
        "IPA": "IPA-DICT-035",
        "得分": round(total, 4),
        "颜色": 颜色,
        "等级": 等级,
        "子项": 子项,
    }


