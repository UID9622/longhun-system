# ═══════════════════════════════════════════════════════════

class 焦虑检测器:
    """蚁群触角焦虑制造者识别引擎 v2.0"""

    def __init__(self):
        self._编译关键词库()

    def _编译关键词库(self):
        """预编译所有关键词为正则模式"""
        self._编译库 = {}
        for 规则名, 规则 in 焦虑关键词库.items():
            编译关键词 = []
            for kw in 规则["关键词"]:
                try:
                    编译关键词.append(re.compile(kw))
                except re.error:
                    编译关键词.append(re.compile(re.escape(kw)))
            self._编译库[规则名] = {
                **规则,
                "_编译关键词": 编译关键词,
            }

    def _剥离情绪词(self, 文本: str) -> str:
        """触角转换：剥离情绪词，提取逻辑骨架"""
        result = 文本
        for 词 in 情绪剥离词:
            result = re.sub(re.escape(词), "", result)
        return result.strip()

    def _匹配关键词(self, 文本: str) -> List[Tuple[str, str, List[str], Any]]:
        """
        匹配所有规则，返回命中的 (规则名, 类型编码, 匹配到的关键词列表)
        按毒性等级排序：四级 > 三级 > 二级 > 一级
        """
        命中列表 = []
        for 规则名, 规则 in self._编译库.items():
            匹配词 = []
            for idx, pattern in enumerate(规则["_编译关键词"]):
                if pattern.search(文本):
                    匹配词.append(焦虑关键词库[规则名]["关键词"][idx])
            if 匹配词:
                命中列表.append((规则名, 规则["类型"], 匹配词, 规则))

        # 按毒性排序
        def 毒性序(item):
            毒性 = item[3]["毒性"]
            _ordering = {信息素等级.四级_剧毒: 0, 信息素等级.三级_高毒: 1, 信息素等级.二级_中毒: 2, 信息素等级.一级_低毒: 3}
            return _ordering.get(毒性, 9)

        命中列表.sort(key=毒性序)
        return 命中列表

    def _构造本源追溯(self, 类型编码: str) -> 本源追溯报告:
        """根据类型编码构造三层本源追溯"""
        本源 = 本源矩阵.get(类型编码, {})
        if not 本源:
            return 本源追溯报告()
        return 本源追溯报告(
            文化根_根源=本源.get("文化根", {}).get("根源", ""),
            文化根_演化=本源.get("文化根", {}).get("演化", ""),
            心理根_机制=本源.get("心理根", {}).get("机制", ""),
            心理根_本质=本源.get("心理根", {}).get("本质", ""),
            权力根_结构=本源.get("权力根", {}).get("结构", ""),
            权力根_本质=本源.get("权力根", {}).get("本质", ""),
        )

    def _构造反制建议(self, 类型编码: str) -> 反制建议:
        """根据类型编码构造反制建议"""
        公式 = 反制公式库.get(类型编码, {})
        if not 公式:
            return 反制建议()
        return 反制建议(
            公式名称=公式.get("名称", ""),
            公式内容=公式.get("公式", ""),
            实战示例=公式.get("示例", ""),
            逻辑锚点=公式.get("锚点", ""),
        )

    def 检测(self, 文本: str) -> 触角检测结果:
        """
        触角感知：检测单条文本是否为焦虑制造话术

        参数:
            文本: 待检测文本
        返回:
            触角检测结果: 包含命中信息、类型、毒性、本源追溯、反制建议
        """
        文本 = 文本.strip()
        if not 文本:
            return 触角检测结果(命中=False, 原文=文本)

        剥离后 = self._剥离情绪词(文本)
        命中列表 = self._匹配关键词(文本)

        if not 命中列表:
            return 触角检测结果(命中=False, 原文=文本, 剥离后文本=剥离后)

        # 取最高毒性命中
        规则名, 类型编码, 匹配词, 规则 = 命中列表[0]
        类型中文 = 话术类型(类型编码).中文

        # 生成信息素ID
        from datetime import datetime
        日期部分 = datetime.now().strftime("%Y%m%d")
        信息素ID = f"{类型编码}-{日期部分}-ANXIETY-{规则名.upper()}"

        # 构造反制建议
        反制 = self._构造反制建议(类型编码)

        # 构造本源追溯
        本源 = self._构造本源追溯(类型编码)

        return 触角检测结果(
            命中=True,
            原文=文本,
            剥离后文本=剥离后,
            话术类型编码=类型编码,
            话术类型中文=类型中文,
            毒性等级=规则["毒性"],
            匹配关键词=匹配词,
            匹配规则名=规则名,
            隐含等式=规则.get("隐含等式", ""),
            信息素ID=信息素ID,
            本源追溯=本源,
            反制建议=反制,
            建议输出=f'反制公式「{反制.公式名称}」→ {反制.实战示例}',
        )

    def 批量检测(self, 文本列表: List[str]) -> List[触角检测结果]:
        """触角批量感知"""
        return [self.检测(文本) for 文本 in 文本列表]

    def 文件检测(self, 文件路径: str) -> List[触角检测结果]:
        """检测文件中的每一行"""
        with open(文件路径, 'r', encoding='utf-8') as f:
            行列表 = [line.strip() for line in f if line.strip()]
        return self.批量检测(行列表)

    def 统计报告(self, 结果列表: List[触角检测结果]) -> str:
        """批量检测的统计报告"""
        命中 = [r for r in 结果列表 if r.命中]
        未命中 = [r for r in 结果列表 if not r.命中]

        lines = [
            "╔═══════════════════════════════════════╗",
            "║   🐜 蚁群触角 · 批量检测统计报告       ║",
            "╚═══════════════════════════════════════╝",
            "",
            f"📊 总计: {len(结果列表)} 条",
            f"   🚨 命中焦虑话术: {len(命中)} 条 ({len(命中)/max(len(结果列表),1)*100:.1f}%)",
            f"   🟢 安全: {len(未命中)} 条",
            "",
        ]

        if 命中:
            类型统计 = {}
            for r in 命中:
                类型统计[r.话术类型中文] = 类型统计.get(r.话术类型中文, 0) + 1

            lines.append("📋 类型分布:")
            for 类型, 计数 in sorted(类型统计.items(), key=lambda x: x[1], reverse=True):
                lines.append(f"   {类型}: {计数} 条")
            lines.append("")

            lines.append("📋 详情:")
            for i, r in enumerate(命中, 1):
                lines.append(f"   {i}. {r.毒性等级.emoji} [{r.话术类型中文}] 「{r.原文[:50]}{'...' if len(r.原文)>50 else ''}」")
                lines.append(f"      → 反制: {r.反制建议.公式名称 if r.反制建议 else 'N/A'}")

        return "\n".join(lines)

    def 列出所有规则(self) -> str:
        """列出所有检测规则"""
        lines = [
            "╔═══════════════════════════════════════╗",
            "║   🐜 蚁群触角 · 全部检测规则           ║",
            "╚═══════════════════════════════════════╝",
            "",
        ]
        for 规则名, 规则 in 焦虑关键词库.items():
            lines += [
                f"┌─ {规则名} ───────────────────────────",
                f"│ 类型: {话术类型(规则['类型']).中文}",
                f"│ 毒性: {规则['毒性'].emoji} {规则['毒性'].name}",
                f"│ 关键词 ({len(规则['关键词'])}个): {', '.join(规则['关键词'][:8])}{'...' if len(规则['关键词'])>8 else ''}",
                f"│ 隐含等式: {规则['隐含等式']}",
                f"│ 反制: {规则['反制公式']}",
                f"│ 文化根: {规则['文化根']}",
                f"│ 心理根: {规则['心理根']}",
                f"│ 权力根: {规则['权力根']}",
                f"└──────────────────────────────────────",
                "",
            ]
        return "\n".join(lines)


