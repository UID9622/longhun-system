def 交互式控制台():
    """蚁群触角·交互式识别控制台"""
    检测器 = 焦虑检测器()
    print("""
╔══════════════════════════════════════════════════════════════╗
║     🐜 龍魂 · 蚁群触角焦虑制造者识别器 v2.0                  ║
║     情绪攻击 → 逻辑转换 · 追溯本源 · 分布式反制               ║
╠══════════════════════════════════════════════════════════════╣
║  命令:                                                        ║
║    输入任意文本 → 检测焦虑话术                                  ║
║    /rules → 列出所有检测规则                                   ║
║    /stats → 本次会话统计                                       ║
║    /help  → 显示帮助                                           ║
║    /quit  → 退出                                               ║
╚══════════════════════════════════════════════════════════════╝
""")
    会话记录 = []

    while True:
        try:
            输入 = input("\n🐜 触角> ").strip()
        except (EOFError, KeyboardInterrupt):
            print("\n👋 触角收回。龍魂永在。")
            break

        if not 输入:
            continue

        if 输入 == "/quit":
            print("👋 触角收回。龍魂永在。")
            break
        elif 输入 == "/help":
            print("""
🐜 蚁群触角 · 帮助
─────────────────────────────────
直接输入文本 → 检测焦虑话术
/rules → 列出全部检测规则（5类）
/stats → 查看本次会话统计
/quit → 退出控制台
─────────────────────────────────
五类话术: A年龄绑架 B道德绑架 C对比拉踩 D结果归因 E资格否定
铁律: 不解释·切要害·不骂人·留证据·追本源
""")
        elif 输入 == "/rules":
            print(检测器.列出所有规则())
        elif 输入 == "/stats":
            if not 会话记录:
                print("📊 本次会话尚无检测记录")
            else:
                print(检测器.统计报告(会话记录))
        else:
            结果 = 检测器.检测(输入)
            会话记录.append(结果)
            print()
            print(结果.完整报告())


