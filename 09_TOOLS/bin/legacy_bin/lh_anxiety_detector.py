# §9 CLI入口
# ═══════════════════════════════════════════════════════════

def main():
    if len(sys.argv) < 2:
        # 无参数 → 进入交互模式
        交互式控制台()
        return

    arg = sys.argv[1]
    检测器 = 焦虑检测器()

    if arg == "--interactive" or arg == "-i":
        交互式控制台()

    elif arg == "--rules" or arg == "-r":
        print(检测器.列出所有规则())

    elif arg == "--file" or arg == "-f":
        if len(sys.argv) < 3:
            print("❌ 请指定文件路径: --file 文件路径")
            sys.exit(1)
        文件路径 = sys.argv[2]
        print(f"🐜 触角感知文件: {文件路径}")
        结果列表 = 检测器.文件检测(文件路径)
        print(检测器.统计报告(结果列表))

    elif arg == "--json" or arg == "-j":
        if len(sys.argv) < 3:
            print("❌ 请指定待检测文本: --json 文本")
            sys.exit(1)
        文本 = " ".join(sys.argv[2:])
        结果 = 检测器.检测(文本)
        print(json.dumps(结果.json报告(), ensure_ascii=False, indent=2))

    elif arg == "--batch" or arg == "-b":
        # 从stdin读取多行
        lines = [line.strip() for line in sys.stdin if line.strip()]
        if not lines:
            print("❌ stdin无内容")
            sys.exit(1)
        结果列表 = 检测器.批量检测(lines)
        print(检测器.统计报告(结果列表))

    elif arg == "--help" or arg == "-h":
        print(__doc__)

    else:
        # 单次检测
        文本 = " ".join(sys.argv[1:])
        结果 = 检测器.检测(文本)
        print(结果.完整报告())


if __name__ == "__main__":
    main()
