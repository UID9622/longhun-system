class 习惯指纹提取器:
    """
    人物行为DNA不动点切割器
    从文本中提取5维度习惯指纹（D1-D5）
    """

    def __init__(self):
        self.指纹版本 = "1.0"

    def 提取(self, 文本: str) -> Dict[str, Any]:
        """完整提取习惯指纹"""
        if not 文本 or len(文本) < 10:
            return {"error": "文本太短·至少需要10个字符", "confidence": 0}

        return {
            "version": self.指纹版本,
            "D2_拼音错别字": self._提取错别字(文本),
            "D2_多音字偏好": self._提取多音字(文本),
            "D2_标点癖": self._提取标点癖(文本),
            "D2_口头禅": self._提取口头禅(文本),
            "D3_节奏微痕": self._提取节奏(文本),
            "D5_经历烙印": self._提取经历词(文本),
            "slices": self._生成切片码(文本),
            "wuxing": self._映射五行(文本),
        }

    # ── D2: 拼音错别字检测 ──

    def _提取错别字(self, 文本: str) -> Dict[str, Any]:
        """检测常见拼音错别字"""
        检测结果 = {}
        for 易错词, 纠错词 in 拼音错别字字典.items():
            出现次数 = len(re.findall(易错词, 文本))
            if 出现次数 > 0:
                检测结果[f"{易错词}/{纠错词}"] = 出现次数
        # 计算错别字密度
        总字符 = len(文本)
        错别字量 = sum(检测结果.values())
        密度 = round(错别字量 / 总字符, 5) if 总字符 > 0 else 0
        return {
            "检测到": 检测结果,
            "错别字总量": 错别字量,
            "密度": 密度,
            "稳定度": round(1.0 / (1.0 + abs(密度 - 0.015)), 4),  # 正常人类≈1.5%错别字率
        }

    # ── D2: 多音字偏好 ──

    def _提取多音字(self, 文本: str) -> Dict[str, Any]:
        """检测多音字使用频率"""
        偏好 = {}
        for 字 in 多音字映射:
            count = 文本.count(字)
            if count > 0:
                偏好[字] = {"出现次数": count, "密度": round(count / len(文本), 5)}
        return {"检测到": len(偏好), "偏好列表": 偏好}

    # ── D2: 标点癖 ──

    def _提取标点癖(self, 文本: str) -> Dict[str, Any]:
        """检测标点使用癖好"""
        癖好 = {}
        for 模式, 描述 in 标点癖模式:
            matches = re.findall(模式, 文本)
            if matches:
                癖好[描述] = {"匹配数": len(matches), "示例": matches[:3]}
        # 检测 ,,,, 连点特征
        连点逗号 = len(re.findall(r",{3,}", 文本))
        连点省略号 = len(re.findall(r"\.{3,}", 文本))
        return {"癖好": 癖好, "连点逗号": 连点逗号, "连点省略号": 连点省略号}

    # ── D2: 口头禅 N-gram ──

    def _提取口头禅(self, 文本: str) -> Dict[str, Any]:
        """N-gram 口头禅检测"""
        命中的 = {}
        for 口头禅 in 口头禅候选:
            count = 文本.count(口头禅)
            if count > 0:
                命中的[口头禅] = count
        return {"检测到": len(命中的), "口头禅列表": 命中的}

    # ── D3: 节奏微痕 (F7) ──

    def _提取节奏(self, 文本: str) -> Dict[str, Any]:
        """提取段落节奏微痕"""
        句子 = re.split(r'[。！？\n]', 文本)
        句子 = [s.strip() for s in 句子 if s.strip()]
        if not 句子:
            return {"error": "无有效句子"}

        句长列表 = [len(s) for s in 句子]
        n = len(句长列表)
        均值 = sum(句长列表) / n
        方差 = sum((x - 均值) ** 2 for x in 句长列表) / n
        标准差 = 方差 ** 0.5

        # 段间隔检测
        段落 = re.split(r'\n\s*\n', 文本)
        段数 = len(段落)

        return {
            "句子数": n,
            "平均句长": round(均值, 1),
            "句长方差": round(方差, 1),
            "句长标准差": round(标准差, 1),
            "段落数": 段数,
            "内联换行": 文本.count('\n') - (段数 - 1) if 段数 > 1 else 0,
            "节奏类型": self._分类节奏(标准差, 均值),
        }

    def _分类节奏(self, 标准差: float, 均值: float) -> str:
        """根据句长方差分类节奏类型"""
        if 标准差 < 10:
            return "稳定型（句长均匀）"
        elif 标准差 < 30:
            return "波动型（长短交替）"
        else:
            return "跳跃型（极度变化）"

    # ── D5: 经历烙印 ──

    def _提取经历词(self, 文本: str) -> Dict[str, Any]:
        """检测经历变故烙印词汇"""
        命中的 = {}
        for 词 in 经历词汇:
            count = 文本.count(词)
            if count > 0:
                命中的[词] = count
        return {"检测到": len(命中的), "烙印词": 命中的}

    # ── 习惯切片码 (L2) ──

    def _生成切片码(self, 文本: str) -> str:
        """生成习惯切片码: SHA256(D1‖D2‖D5) 前16位"""
        指纹素材 = f"{len(文本)}|{self._提取错别字(文本)['密度']}|{self._提取标点癖(文本)['连点逗号']}"
        哈希 = hashlib.sha256(指纹素材.encode()).hexdigest()
        return 哈希[:16]

    # ── §7 五行映射 ──

    def _映射五行(self, 文本: str) -> Dict[str, Any]:
        """习惯指纹 → 数字根 → 五行 → 平衡度"""
        指纹素材 = f"{len(文本)}{sum(ord(c) for c in 文本[:100])}"
        num = sum(int(c) for c in 指纹素材 if c.isdigit())
        dr = num % 9
        dr = 9 if dr == 0 else dr

        五行映射 = {1: "水", 2: "火", 3: "木", 4: "金", 5: "土", 6: "水", 7: "火", 8: "木", 9: "金", 0: "土"}

        # 五行平衡度：统计文本中各五行字符分布
        五行词映射 = {
            "金": ["金", "铁", "钢", "锋", "锁", "刚"],
            "木": ["木", "林", "森", "树", "生", "春"],
            "水": ["水", "河", "海", "流", "润", "冬"],
            "火": ["火", "炎", "焰", "热", "光", "夏"],
            "土": ["土", "地", "山", "石", "城", "中"],
        }
        五行频率 = {}
        for 五行, 字列 in 五行词映射.items():
            五行频率[五行] = sum(文本.count(字) for 字 in 字列)
        总数 = sum(五行频率.values()) or 1
        五行向量 = {k: round(v / 总数, 3) for k, v in 五行频率.items()}
        向量值 = list(五行向量.values())
        平衡度 = round(1.0 - sum((x - 0.2) ** 2 for x in 向量值) ** 0.5, 3)

        return {
            "数字根": dr,
            "五行": 五行映射[dr],
            "五行向量": 五行向量,
            "平衡度": 平衡度,
        }


