# ---------- RAG 引擎 ----------
class HerbalRAG:
    def __init__(self, db_path=None):
        self.db_path = db_path or HERBAL_DB_PATH
        self.client = chromadb.PersistentClient(path=str(self.db_path))
        self.embedding_fn = embedding_functions.DefaultEmbeddingFunction()
        self.collection = self._get_or_create_collection()
        self._ensure_data_indexed()

    def _get_or_create_collection(self):
        try:
            return self.client.get_collection("herbal_v1")
        except Exception:
            return self.client.create_collection(
                name="herbal_v1",
                embedding_function=self.embedding_fn
            )

    def _ensure_data_indexed(self):
        """如果数据库为空，建立索引"""
        if self.collection.count() == 0:
            print("📦 正在建立本草知识索引...")
            for idx, herb in enumerate(HERBAL_DATA):
                text = f"{herb['正名']} {herb['拉丁名']} {herb['性味归经']} {herb['功效主治']} {herb['现代应用']} {herb['用量用法']} {herb['注意事项']} {herb['地方土话']}"
                self.collection.add(
                    documents=[text],
                    metadatas=[{"正名": herb["正名"]}],
                    ids=[f"herb_{idx:03d}"]
                )
            print(f"✅ 索引完成: {self.collection.count()} 味药材")

    def search(self, query: str, n_results: int = 3) -> List[Dict[str, Any]]:
        """检索最相关药材：先关键词精确匹配，再向量检索兜底"""
        query = query.strip().lower()

        # 1. 关键词精确匹配（药名、别名、方言）
        for h in HERBAL_DATA:
            names = [h["正名"]]
            if h.get("alias"):
                names += [a.strip() for a in h["alias"].split(",") if a.strip()]
            dialects = [d.strip() for d in h["地方土话"].replace("（", "、").replace("）", "").split("、") if d.strip()]
            all_keys = set(n.lower() for n in names if n) | set(d.lower() for d in dialects if d)
            for key in all_keys:
                if key and (key in query or query in key) and len(key) >= 2:
                    return [self._herb_to_dict(h, 1.0)]

        # 2. 向量检索兜底
        results = self.collection.query(
            query_texts=[query],
            n_results=min(n_results * 2, len(HERBAL_DATA))
        )
        herbs = []
        seen = set()
        for idx, doc_id in enumerate(results['ids'][0]):
            herb_name = results['metadatas'][0][idx]['正名']
            if herb_name in seen:
                continue
            seen.add(herb_name)
            herb = next((h for h in HERBAL_DATA if h['正名'] == herb_name), None)
            if herb and len(herbs) < n_results:
                herbs.append(self._herb_to_dict(herb, results['distances'][0][idx] if results.get('distances') else 0))
        return herbs

    def _herb_to_dict(self, herb: Dict[str, str], score: float) -> Dict[str, Any]:
        return {
            "正名": herb["正名"],
            "拉丁名": herb["拉丁名"],
            "性味归经": herb["性味归经"],
            "功效主治": herb["功效主治"],
            "现代应用": herb["现代应用"],
            "用量用法": herb["用量用法"],
            "注意事项": herb["注意事项"],
            "地方土话": herb["地方土话"],
            "相似度": score
        }

