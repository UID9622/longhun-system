def make_sample(question, answer):
    """构建训练样本"""
    return {"messages": [
        {"role": "system", "content": SYS},
        {"role": "user", "content": question},
        {"role": "assistant", "content": answer},
    ]}


def main():
    print("🐉 龍魂 v1.4 拒绝类训练数据生成器")
    print("=" * 60)
    
    # 1. 生成训练样本
    all_train = []
    all_train.extend([make_sample(q, a) for q, a in CAT_A])
    all_train.extend([make_sample(q, a) for q, a in CAT_B])
    all_train.extend([make_sample(q, a) for q, a in CAT_C])
    all_train.extend([make_sample(q, a) for q, a in CAT_D])
    all_train.extend([make_sample(q, a) for q, a in ANCHOR])
    
    print(f"\n📊 训练样本生成:")
    print(f"   类别A 索要内核代码: {len(CAT_A)} 条")
    print(f"   类别B 索要system prompt: {len(CAT_B)} 条")
    print(f"   类别C 询问数据来源: {len(CAT_C)} 条")
    print(f"   类别D 冒充UID9622: {len(CAT_D)} 条")
    print(f"   精准锚点: {len(ANCHOR)} 条")
    print(f"   训练总计: {len(all_train)} 条")
    
    # 2. 验证拒绝类样本：每个回答至少包含一个拒绝关键词
    print(f"\n🔍 验证拒绝类样本...")
    refusal_fail = 0
    for i, s in enumerate(all_train[:80]):  # 前80条是拒绝类
        answer = s["messages"][2]["content"]
        if not any(kw in answer for kw in REFUSAL_KEYWORDS):
            print(f"   ⚠️ 样本{i}: 未命中拒绝关键词: {answer[:50]}...")
            refusal_fail += 1
    
    if refusal_fail == 0:
        print(f"   ✅ 80条拒绝类样本全部通过关键词验证")
    else:
        print(f"   ⚠️ {refusal_fail}条未命中拒绝关键词")
    
    # 3. 注入 train.jsonl
    train_path = DATA_DIR / "train.jsonl"
    print(f"\n📥 注入 train.jsonl: {train_path}")
    
    # 读取现有数据
    existing = []
    with open(train_path, 'r') as f:
        for line in f:
            line = line.strip()
            if line:
                existing.append(json.loads(line))
    print(f"   现有样本: {len(existing)}")
    
    # 追加
    existing.extend(all_train)
    random.shuffle(existing)
    
    # 写回
    with open(train_path, 'w') as f:
        for item in existing:
            f.write(json.dumps(item, ensure_ascii=False) + '\n')
    print(f"   合并后: {len(existing)} 样本 ✅")
    
    # 4. 同步更新 valid.jsonl（从合并后数据中按比例抽取）
    valid_path = DATA_DIR / "valid.jsonl"
    valid_n = max(int(len(existing) * 0.1), 10)
    valid_data = existing[-valid_n:]
    train_data = existing[:-valid_n]
    
    with open(train_path, 'w') as f:
        for item in train_data:
            f.write(json.dumps(item, ensure_ascii=False) + '\n')
    with open(valid_path, 'w') as f:
        for item in valid_data:
            f.write(json.dumps(item, ensure_ascii=False) + '\n')
    print(f"   训练集: {len(train_data)} 样本")
    print(f"   验证集: {len(valid_data)} 样本")
    
    # 5. 生成对抗测试集（独立文件，不参与训练）
    adv_path = DATA_DIR / "adversarial_test.jsonl"
    adv_samples = []
    for q, expected, category in ADVERSARIAL:
        adv_samples.append({
            "instruction": q,
            "expected": expected,
            "category": category,
        })
    
    with open(adv_path, 'w') as f:
        for item in adv_samples:
            f.write(json.dumps(item, ensure_ascii=False) + '\n')
    print(f"\n🧪 对抗测试集: {len(adv_samples)} 条 → {adv_path}")
    print(f"   （独立文件，不参与训练）")
    
    # 6. 数据分布统计
    print(f"\n📊 最终数据分布:")
    total = len(existing)
    # 估算拒绝类占比
    refusal_count = sum(1 for s in existing 
                        if any(kw in s["messages"][2]["content"] for kw in REFUSAL_KEYWORDS))
    print(f"   总样本: {total}")
    print(f"   拒绝类样本: {refusal_count} ({refusal_count/total*100:.1f}%)")
    print(f"   对抗测试集: {len(adv_samples)} (独立)")
    
