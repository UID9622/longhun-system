def 生成训练数据():
    """生成家法第一条训练样本并注入train.jsonl"""
    样本列表 = []
    for item in 家法训练样本:
        样本 = {
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": item["user"]},
                {"role": "assistant", "content": item["assistant"]},
            ]
        }
        样本列表.append(样本)

    # 读入现有训练数据
    现有数据 = []
    if TRAIN_FILE.exists():
        with open(TRAIN_FILE, 'r', encoding='utf-8') as f:
            for line in f:
                line = line.strip()
                if line:
                    try:
                        现有数据.append(json.loads(line))
                    except json.JSONDecodeError:
                        continue

    print(f"现有训练样本: {len(现有数据)}条")
    print(f"新增家法第一条样本: {len(样本列表)}条")

    # 合并（不重复）
    现有问题 = set()
    for item in 现有数据:
        msgs = item.get("messages", [])
        for m in msgs:
            if m.get("role") == "user":
                现有问题.add(m.get("content", ""))

    新样本 = []
    重复数 = 0
    for item in 样本列表:
        user_content = item["messages"][1]["content"]
        if user_content in 现有问题:
            重复数 += 1
        else:
            新样本.append(item)

    if 重复数 > 0:
        print(f"跳过重复: {重复数}条")

    # 备份
    if TRAIN_FILE.exists():
        backup = TRAIN_FILE.with_suffix(".jsonl.bak_jiafa")
        import shutil
        shutil.copy2(TRAIN_FILE, backup)
        print(f"已备份: {backup}")

    # 写入
    全部 = 现有数据 + 新样本
    with open(TRAIN_FILE, 'w', encoding='utf-8') as f:
        for item in 全部:
            f.write(json.dumps(item, ensure_ascii=False) + '\n')

    print(f"✅ 注入完成: {len(现有数据)} → {len(全部)}条 (+{len(新样本)}条新样本)")
    print(f"   跳过重复: {重复数}条")
    print(f"   总样本数: {len(全部)}条")
    return len(新样本)

