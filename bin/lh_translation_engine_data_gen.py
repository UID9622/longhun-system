def generate_training_data(output_dir: str):
    """生成训练数据JSONL文件"""
    
    train_data = []
    
    for qa in QA_PAIRS:
        entry = {
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": qa["q"]},
                {"role": "assistant", "content": qa["a"]}
            ]
        }
        train_data.append(entry)
    
    # 写入训练文件
    train_path = os.path.join(output_dir, "train_translation_engine.jsonl")
    with open(train_path, 'w', encoding='utf-8') as f:
        for entry in train_data:
            f.write(json.dumps(entry, ensure_ascii=False) + '\n')
    
    # 验证集（取后20%）
    split = int(len(train_data) * 0.8)
    valid_data = train_data[split:]
    train_data = train_data[:split]
    
    # 重写训练集
    with open(train_path, 'w', encoding='utf-8') as f:
        for entry in train_data:
            f.write(json.dumps(entry, ensure_ascii=False) + '\n')
    
    # 写入验证集
    valid_path = os.path.join(output_dir, "valid_translation_engine.jsonl")
    with open(valid_path, 'w', encoding='utf-8') as f:
        for entry in valid_data:
            f.write(json.dumps(entry, ensure_ascii=False) + '\n')
    
    print(f"✅ 翻译引擎训练数据生成完成！")
    print(f"   训练集: {len(train_data)} 条 → {train_path}")
    print(f"   验证集: {len(valid_data)} 条 → {valid_path}")
    print(f"   知识域: 翻译引擎数学基础（1650万路径·六维笛卡尔积）")
    
    return len(train_data), len(valid_data)


def merge_with_existing(output_dir: str):
    """将新数据合并到现有训练集中"""
    
    # 读取现有训练数据
    existing_train = os.path.join(output_dir, "train.jsonl")
    existing_valid = os.path.join(output_dir, "valid.jsonl")
    new_train = os.path.join(output_dir, "train_translation_engine.jsonl")
    new_valid = os.path.join(output_dir, "valid_translation_engine.jsonl")
    
    # 备份现有数据
    import shutil
    backup_suffix = ".v3.2_backup"
    for f in [existing_train, existing_valid]:
        if os.path.exists(f):
            shutil.copy2(f, f + backup_suffix)
            print(f"📦 备份: {f} → {f}{backup_suffix}")
    
    # 合并训练集
    all_train = []
    for fpath in [existing_train, new_train]:
        if os.path.exists(fpath):
            with open(fpath, 'r', encoding='utf-8') as f:
                for line in f:
                    line = line.strip()
                    if line:
                        all_train.append(line)
    
    with open(existing_train, 'w', encoding='utf-8') as f:
        for line in all_train:
            f.write(line + '\n')
    
    # 合并验证集
    all_valid = []
    for fpath in [existing_valid, new_valid]:
        if os.path.exists(fpath):
            with open(fpath, 'r', encoding='utf-8') as f:
                for line in f:
                    line = line.strip()
                    if line:
                        all_valid.append(line)
    
    with open(existing_valid, 'w', encoding='utf-8') as f:
        for line in all_valid:
            f.write(line + '\n')
    
    print(f"✅ 数据合并完成！")
    print(f"   总训练集: {len(all_train)} 条")
    print(f"   总验证集: {len(all_valid)} 条")
    print(f"   新增翻译引擎域: {len(QA_PAIRS)} 条 Q&A")


