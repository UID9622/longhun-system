class 数据守护:
    """
    第3重检测：是否可追溯（DNA追溯码、时间戳、操作人、数据来源）
    """

    # DNA格式正则
    DNA格式正则 = r"#ZHUGEXIN⚡️\d{4}-\d{2}-\d{2}-[A-Z0-9\-]+"

    @classmethod
    def 检测(cls, 元数据: Dict) -> 单重检测结果:
        """执行数据守护检测"""
        元数据 = 元数据 or {}

        # 检测1：DNA追溯码
        dna = 元数据.get("DNA", "")
        dna结果 = cls._检测DNA(dna)
        if not dna结果["有效"]:
            return 单重检测结果(
                通过=False,
                颜色="🔴",
                原因=f"DNA追溯码无效：{dna结果['原因']}",
                详细信息={"DNA检测": dna结果},
                建议="请添加有效的DNA追溯码，格式：#ZHUGEXIN⚡️YYYY-MM-DD-XXX"
            )

        # 检测2：时间戳
        时间戳 = 元数据.get("时间戳", "")
        时间结果 = cls._检测时间戳(时间戳)
        if not 时间结果["合格"]:
            return 单重检测结果(
                通过=False,
                颜色="🟡",
                原因=f"时间戳精度不足：{时间结果['建议']}",
                详细信息={"时间戳检测": 时间结果},
                建议="需要使用毫秒级精度的时间戳，格式：YYYY-MM-DDTHH:MM:SS.mmmZ"
            )

        # 检测3：操作人
        操作人 = 元数据.get("操作人", "")
        操作人结果 = cls._检测操作人(操作人)
        if not 操作人结果["有效"]:
            return 单重检测结果(
                通过=False,
                颜色="🔴",
                原因=f"操作人信息无效：{操作人结果['原因']}",
                详细信息={"操作人检测": 操作人结果},
                建议="请添加操作人UID，格式：XXX·UIDxxxx"
            )

        # 检测4：数据来源
        来源 = 元数据.get("数据来源", "")
        来源结果 = cls._检测数据来源(来源)
        if not 来源结果["清晰"]:
            return 单重检测结果(
                通过=False,
                颜色="🟡",
                原因=f"数据来源不清晰：缺失 {', '.join(来源结果['缺失'])}",
                详细信息={"数据来源检测": 来源结果},
                建议="请补充数据来源、采集时间、分析方法等关键信息"
            )

        # 通过检测
        return 单重检测结果(
            通过=True,
            颜色="🟢",
            原因="追溯信息完整：DNA有效、时间戳精确、操作人明确、数据来源清晰",
            详细信息={
                "DNA": dna,
                "时间戳": 时间戳,
                "操作人": 操作人,
                "数据来源": 来源
            }
        )

    @classmethod
    def _检测DNA(cls, dna: str) -> Dict:
        if not dna:
            return {"有效": False, "原因": "DNA追溯码为空"}
        if not re.match(cls.DNA格式正则, dna):
            return {"有效": False, "原因": f"DNA格式不规范，应为：{cls.DNA格式正则}"}
        return {"有效": True, "原因": ""}

    @classmethod
    def _检测时间戳(cls, 时间戳: str) -> Dict:
        if not 时间戳:
            return {"合格": False, "精度": "无", "建议": "请添加时间戳"}
        if "." in 时间戳 and len(时间戳) >= 20:
            return {"合格": True, "精度": "毫秒", "建议": ""}
        return {"合格": False, "精度": "秒", "建议": "需要毫秒级精度，格式：YYYY-MM-DDTHH:MM:SS.mmmZ"}

    @classmethod
    def _检测操作人(cls, 操作人: str) -> Dict:
        if not 操作人:
            return {"有效": False, "原因": "操作人为空"}
        if "UID" in 操作人:
            return {"有效": True, "原因": ""}
        return {"有效": False, "原因": f"操作人格式不规范，应包含UID：{操作人}"}

    @classmethod
    def _检测数据来源(cls, 来源: str) -> Dict:
        必需信息 = ["来源", "时间", "方法"]
        缺失 = []

        if not 来源:
            return {"清晰": False, "缺失": 必需信息}

        for 信息 in 必需信息:
            if 信息 not in 来源:
                缺失.append(信息)

        if 缺失:
            return {"清晰": False, "缺失": 缺失}

        return {"清晰": True, "缺失": []}


