class 虚伪编译器:
    """
    第2重检测：是否真实、有依据、不预判结果

    核心原则（老大原话）：
      - 不能说满：不说"100%会成功""一定没问题""绝对安全"
      - 要有依据：每个推演有数据支撑、逻辑链条、可追溯来源
      - 避开结果，不预判：目标是避开风险，不是预测会发生什么
    """

    # 说满词库（触发红色）
    说满词库_红色 = [
        "100%", "百分之百",
        "绝对", "绝对会", "绝对不会",
        "一定", "一定会", "一定不会",
        "必然", "必然会", "必然不会",
        "肯定", "肯定能", "肯定行",
        "确保", "保证", "承诺",
        "永远不会", "完全不可能", "毫无疑问",
        "必定", "定会",
    ]

    # 说满词库（触发黄色，程度较轻）
    说满词库_黄色 = [
        "99%", "98%", "95%",
        "基本", "基本上", "基本确定",
        "应该", "应该会", "应该不会",
        "大概", "大概会", "很有可能",
        "大概率", "极有可能",
    ]

    # 预判结果特征词（触发黄色）
    预判词库 = [
        "会成功", "会失败", "会发生",
        "将会", "将会发生", "将要",
        "肯定能", "一定能", "必然能",
        "会实现", "会达成",
    ]

    # 避开风险特征词（绿色）
    避开词库 = [
        "避开", "规避", "防止", "避免",
        "降低风险", "未发现风险", "风险可控",
        "没有发现", "未检测到", "安全",
        "可以避开", "能够规避",
    ]

    @classmethod
    def 检测(cls, 内容: str, 依据: str = "", 元数据: Dict = None) -> 单重检测结果:
        """执行虚伪检测"""
        元数据 = 元数据 or {}

        # 检测1：是否说得太满（红色）
        说满红色 = cls._检测说满词(内容, cls.说满词库_红色)
        if 说满红色["触发"]:
            return 单重检测结果(
                通过=False,
                颜色="🔴",
                原因=f"说得太满：使用了绝对化词汇「{说满红色['关键词']}」",
                详细信息={"说满词": 说满红色},
                建议="改为「避开风险」的表达方式，不用绝对化词汇"
            )

        # 检测2：是否说得太满（黄色）
        说满黄色 = cls._检测说满词(内容, cls.说满词库_黄色)
        if 说满黄色["触发"]:
            return 单重检测结果(
                通过=False,
                颜色="🟡",
                原因=f"表达过于肯定：使用了「{说满黄色['关键词']}」",
                详细信息={"说满词": 说满黄色},
                建议="建议使用更审慎的表达方式"
            )

        # 检测3：是否有依据
        依据结果 = cls._检测依据完整性(依据)
        if not 依据结果["完整"]:
            return 单重检测结果(
                通过=False,
                颜色="🟡",
                原因=f"依据不充分：缺少 {', '.join(依据结果['缺失项'])}",
                详细信息={"依据检测": 依据结果},
                建议="补充数据来源、分析方法、时间范围等完整依据"
            )

        # 检测4：是预判结果还是避开风险
        表达结果 = cls._检测表达方式(内容)
        if 表达结果["类型"] == "预判结果":
            return 单重检测结果(
                通过=False,
                颜色="🟡",
                原因=f"表达方式不当：这是在「预判结果」，而非「避开风险」",
                详细信息={"表达方式": 表达结果},
                建议=f"建议改为：{表达结果['建议']}"
            )

        # 通过检测
        return 单重检测结果(
            通过=True,
            颜色="🟢",
            原因="表达真实，有完整依据，符合「避开风险」原则",
            详细信息={
                "说满检测": "通过",
                "依据检测": "完整",
                "表达方式": "避开风险"
            }
        )

    @classmethod
    def _检测说满词(cls, 内容: str, 词库: List[str]) -> Dict:
        for 词 in 词库:
            if 词 in 内容:
                return {"触发": True, "关键词": 词}
        return {"触发": False, "关键词": ""}

    @classmethod
    def _检测依据完整性(cls, 依据: str) -> Dict:
        必需依据 = ["数据来源", "分析方法", "时间范围"]
        缺失项 = []

        if not 依据 or len(依据) < 10:
            return {"完整": False, "缺失项": ["数据来源", "分析方法", "时间范围"]}

        for 项 in 必需依据:
            if 项 not in 依据:
                缺失项.append(项)

        if 缺失项:
            return {"完整": False, "缺失项": 缺失项}

        return {"完整": True, "缺失项": []}

    @classmethod
    def _检测表达方式(cls, 内容: str) -> Dict:
        预判计数 = sum(1 for 词 in cls.预判词库 if 词 in 内容)
        避开计数 = sum(1 for 词 in cls.避开词库 if 词 in 内容)

        if 预判计数 > 避开计数:
            return {
                "类型": "预判结果",
                "预判词数": 预判计数,
                "避开词数": 避开计数,
                "建议": f"把「预判」改为「避开」的表达，例如：'该方案避开了X、Y、Z风险'"
            }

        return {
            "类型": "避开风险",
            "预判词数": 预判计数,
            "避开词数": 避开计数
        }


