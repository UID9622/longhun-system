def generate_dataset():
    records = []
    for system_key, user, assistant, domain in QA_BANK:
        system = SYSTEM_PATHFINDER if system_key == "SYSTEM_PATHFINDER" else SYSTEM_DEFAULT
        records.append(make_record(system, user, assistant, domain))

    # 生成变体
    for domain, brief in DOMAIN_BRIEF.items():
        system = SYSTEM_PATHFINDER
        records.append(make_record(
            system,
            f"用一句话概括{domain}。",
            f"<think>\n这是关于{domain}的简要回答。\n</think>\n\n正式回答：\n{brief}",
            domain,
        ))
        records.append(make_record(
            system,
            f"{domain}的核心思想是什么？",
            f"<think>\n这是关于{domain}核心思想的提炼。\n</think>\n\n正式回答：\n{brief}",
            domain,
        ))

    # 打乱
    random.shuffle(records)

    # 切分训练/验证（90/10）
    n_valid = max(1, len(records) // 10)
    train = records[n_valid:]
    valid = records[:n_valid]

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    with open(OUTPUT_DIR / "train.jsonl", "w", encoding="utf-8") as f:
        for r in train:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    with open(OUTPUT_DIR / "valid.jsonl", "w", encoding="utf-8") as f:
        for r in valid:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    print(f"[龍魂·路径规划训练数据] 训练集: {len(train)} 条 · 验证集: {len(valid)} 条")
    print(f"[龍魂·路径规划训练数据] 输出目录: {OUTPUT_DIR}")


if __name__ == "__main__":
    generate_dataset()
