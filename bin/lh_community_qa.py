class 问题分类器:
    """自动识别问题类型"""

    关键词映射 = {
        问题类型.部署: ["部署", "安装", "上线", "发布", "构建", "打包", "docker", "k8s", "kubernetes"],
        问题类型.报错: ["报错", "异常", "error", "出错", "崩溃", "失败", "failed", "bug"],
        问题类型.配置: ["配置", "环境", "变量", "参数", "设置", "nginx", "mysql", "redis"],
        问题类型.架构: ["架构", "设计", "微服务", "分布式", "模块", "系统", "框架"],
        问题类型.性能: ["性能", "优化", "卡顿", "慢", "延迟", "响应", "吞吐", "并发"],
        问题类型.安全: ["安全", "漏洞", "攻击", "权限", "认证", "授权", "加密", "csrf", "xss"],
        问题类型.开发: ["开发", "编码", "函数", "类", "接口", "API", "SDK", "library"],
        问题类型.数据库: ["数据库", "sql", "查询", "索引", "表", "字段", "迁移", "mongo"],
        问题类型.网络: ["网络", "请求", "响应", "http", "https", "dns", "负载", "防火墙"],
    }

    @classmethod
    def 分类(cls, 问题: str) -> Tuple[问题类型, float]:
        """分类问题，返回类型和置信度"""
        投票 = {}

        for 类型, 关键词列表 in cls.关键词映射.items():
            匹配数 = sum(1 for 关键词 in 关键词列表 if 关键词.lower() in 问题.lower())
            if 匹配数 > 0:
                投票[类型] = 匹配数

        if not 投票:
            return 问题类型.其他, 0.0

        最佳类型 = max(投票, key=投票.get)
        置信度 = 投票[最佳类型] / sum(投票.values())
        return 最佳类型, 置信度


