class 合规检查器:
    """检查回答是否合规"""

    敏感词 = [
        "黑客", "hacker", "攻击", "attack",
        "破解", "crack", "盗版", "破解版",
        "入侵", "越狱", "jailbreak",
        "渗透", "漏洞利用", "exploit",
        "钓鱼", "phishing", "诈骗",
        "违法", "犯罪", "非法",
    ]

    高危行为 = [
        "绕过", "规避", "欺骗", "伪造", "篡改"
    ]

    @classmethod
    def 检查(cls, 回答: str) -> Dict:
        """检查回答是否合规"""
        问题 = []

        # 检查敏感词
        for 词 in cls.敏感词:
            if 词 in 回答.lower():
                问题.append(f"包含敏感词：{词}")

        # 检查高危行为
        for 词 in cls.高危行为:
            if 词 in 回答:
                问题.append(f"涉及高危行为：{词}")

        if 问题:
            return {
                "合规": False,
                "原因": "；".join(问题[:3]),
                "建议": "请修改包含敏感词或高危行为的描述"
            }

        return {
            "合规": True,
            "原因": "回答内容合规",
            "建议": ""
        }


