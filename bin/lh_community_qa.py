# 七、命令行入口
# ============================================================

def main():
    parser = argparse.ArgumentParser(
        description="🐉 龍魂·社区问答回答生成器",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
示例:
  # 交互式生成
  python3 lh_community_qa.py --interactive

  # 快速生成
  python3 lh_community_qa.py "如何部署Django应用到生产环境？"

  # 查看历史
  python3 lh_community_qa.py --history

  # 导出JSON
  python3 lh_community_qa.py "如何优化数据库查询？" --json
        """
    )

    parser.add_argument("问题", nargs="*", help="技术问题")
    parser.add_argument("--interactive", "-i", action="store_true", help="交互模式")
    parser.add_argument("--history", "-H", action="store_true", help="查看历史")
    parser.add_argument("--json", "-j", action="store_true", help="JSON格式输出")

    args = parser.parse_args()

    # 交互模式
    if args.interactive:
        回答 = 交互式输入.引导()
        if 回答:
            print("\n" + "=" * 60)
            print(回答.回答文本)
            print("\n" + "=" * 60)
            print(f"🧬 DNA: {回答.dna}")
            print(f"📋 合规: {'✅ 通过' if 回答.合规状态 else '❌ 需检查'}")
            if not 回答.合规状态:
                print(f"   原因: {回答.合规原因}")
            print("=" * 60)
        return

    # 查看历史
    if args.history:
        生成器 = 回答生成器()
        历史 = 生成器.获取历史()
        if 历史:
            print("\n📋 回答历史:")
            print("-" * 50)
            for h in 历史:
                print(f"  {h.问题[:40]}...")
                print(f"   DNA: {h.dna}")
                print(f"   时间: {h.创建时间[:16]}")
                print()
        else:
            print("📭 暂无历史记录")
        return

    # 快速生成
    if args.问题:
        问题 = " ".join(args.问题)
        生成器 = 回答生成器()
        回答 = 生成器.生成(问题)

        if args.json:
            # 转换为可序列化格式
            输出 = {
                "问题": 回答.问题,
                "问题类型": 回答.问题类型.value,
                "问题分析": 回答.问题分析,
                "方案列表": [
                    {
                        "名称": s.名称,
                        "描述": s.描述,
                        "优点": s.优点,
                        "缺点": s.缺点,
                        "适用场景": s.适用场景,
                        "风险等级": s.风险等级.value,
                        "预计耗时": s.预计耗时,
                        "难度": s.难度
                    }
                    for s in 回答.方案列表
                ],
                "推荐方案": 回答.推荐方案,
                "注意事项": 回答.注意事项,
                "合规状态": 回答.合规状态,
                "回答文本": 回答.回答文本,
                "DNA": 回答.dna,
                "创建时间": 回答.创建时间
            }
            print(json.dumps(输出, ensure_ascii=False, indent=2))
        else:
            print("\n" + "=" * 60)
            print(回答.回答文本)
            print("\n" + "=" * 60)
            print(f"🧬 DNA: {回答.dna}")
            print(f"📋 合规: {'✅ 通过' if 回答.合规状态 else '❌ 需检查'}")
            if not 回答.合规状态:
                print(f"   原因: {回答.合规原因}")
            print("=" * 60)

            # 复制到剪贴板
            try:
                import subprocess
                subprocess.run(["pbcopy"], input=回答.回答文本.encode('utf-8'), check=True)
                print("📋 已复制回答到剪贴板")
            except:
                pass
        return

    # 无参数
    parser.print_help()


if __name__ == "__main__":
    main()
