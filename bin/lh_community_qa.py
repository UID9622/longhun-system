    """交互式引导"""

    @classmethod
    def 引导(cls) -> Optional[问答回答]:
        """引导用户输入问题"""
        print("\n" + "=" * 60)
        print("🐉 龙魂·社区问答回答生成器 - 交互模式")
        print("=" * 60)

        问题 = input("\n📌 请输入技术问题: ").strip()
        while not 问题:
            问题 = input("❌ 问题不能为空: ").strip()

        # 预览问题类型
        类型, 置信度 = 问题分类器.分类(问题)
        print(f"\n📋 识别问题类型: {类型.value} (置信度: {置信度:.0%})")

        确认 = input("\n✅ 确认生成回答? (y/n): ").strip().lower()
        if 确认 != 'y':
            print("❌ 已取消")
            return None

        生成器 = 回答生成器()
        return 生成器.生成(问题)


