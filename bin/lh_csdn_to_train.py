def main():
    existing = []
    if os.path.exists(OUT):
        with open(OUT) as f:
            for line in f:
                existing.append(json.loads(line.strip()))

    new_samples = []
    for pair in QA_PAIRS:
        sample = {
            "messages": [
                {"role": "system", "content": SYSTEM},
                {"role": "user", "content": pair["q"]},
                {"role": "assistant", "content": pair["a"]}
            ]
        }
        new_samples.append(sample)

    # 去重
    all_q = {json.dumps(s["messages"][1]["content"], ensure_ascii=False) for s in existing}
    added = 0
    for s in new_samples:
        q = json.dumps(s["messages"][1]["content"], ensure_ascii=False)
        if q not in all_q:
            existing.append(s)
            all_q.add(q)
            added += 1

    with open(OUT, "w") as f:
        for s in existing:
            f.write(json.dumps(s, ensure_ascii=False) + "\n")

    print(f"✅ 训练语料: {len(existing)} 条 (新增 {added} 条)")
    print(f"   输出: {OUT}")

if __name__ == "__main__":
    main()
