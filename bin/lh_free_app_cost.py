class 免费代价计算器:
    
    def 计算(self, **kwargs) -> Dict[str, Any]:
        return 算免费的真实价格(**kwargs)
    
    def 预设计算(self, app名: str) -> Optional[Dict[str, Any]]:
        if app名 not in 预置App参数:
            return None
        参数 = 预置App参数[app名]
        return 算免费的真实价格(
            注意评分=参数["注意评分"],
            隐私评分=参数["隐私评分"],
            试错评分=参数["试错评分"],
            环境评分=参数["环境评分"],
            就业评分=参数["就业评分"],
            每日使用小时=参数["每日使用小时"],
        )
    
    def 代价排行榜(self) -> List[Tuple[str, float, float]]:
        """按年度总代价排名·(App名, 综合代价度, 年度总代价)"""
        排行 = []
        for app名 in 预置App参数:
            result = self.预设计算(app名)
            if result:
                排行.append((app名, result["综合代价度"], result["年度总代价(元)"]))
        排行.sort(key=lambda x: x[2], reverse=True)
        return 排行


