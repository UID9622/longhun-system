# ===== 4. Notion 知识（全量33节） =====
def gen_notion():
    print("📓 Notion知识全量...")
    if not CORPUS_MD.exists():
        print("   ⚠️ 无语料文件，跳过")
        return []
    
    with open(CORPUS_MD, 'r', encoding='utf-8') as f:
        text = f.read()
    
    sections = re.split(r'\n##\s+', text)
    data = []
    
    for sec in sections[1:]:
        lines = sec.strip().split('\n')
        title = lines[0].strip() if lines else "未知"
        content = '\n'.join(lines[1:]).strip()
        if len(content) < 50:
            continue
        
        summary = content[:250].replace('\n', ' ')
        if summary:
            data.append(make_msg(
                f"请介绍龍魂系统中关于「{title}」的信息",
                f"关于「{title}」：{summary}"
            ))
        
        if len(content) > 300:
            detail = content[250:500].replace('\n', ' ')
            if detail:
                data.append(make_msg(
                    f"「{title}」的详细内容是什么？",
                    f"「{title}」的详细信息：{detail}"
                ))
        
        if len(content) > 600:
            extra = content[500:700].replace('\n', ' ')
            if extra:
                data.append(make_msg(
                    f"「{title}」还有哪些要点？",
                    f"「{title}」的更多要点：{extra}"
                ))
    
    all_titles = [s.strip().split('\n')[0].strip() for s in sections[1:] if s.strip()]
    data.append(make_msg(
        "龍魂系统的Notion工作间包含哪些内容？",
        f"龍魂系统Notion工作间包含{len(all_titles)}个板块：{'、'.join(all_titles[:30])}等。涵盖安全认证、AI智能体、龍魂核心、治理协议、论文白皮书、中国哲学、数字资产、CNSH编码、终端UI、审计模板等多个领域。"
    ))
    
    print(f"   Notion: {len(data)}条 ({len(sections)-1}节)")
    return data

