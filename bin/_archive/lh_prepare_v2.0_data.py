# ===== 1. CSDN全量文章 QA（每篇3题） =====
def gen_csdn():
    print("📚 CSDN全量文章 → 训练数据...")
    if not CSDN_CACHE.exists():
        print("   ⚠️ 无缓存，跳过")
        return []
    cache = json.load(open(CSDN_CACHE))
    valid = {k:v for k,v in cache.items() if v.get('content') and len(v['content'])>50}
    print(f"   有效文章: {len(valid)}篇")
    data = []
    for aid, a in valid.items():
        t, c, tags = a['title'], a['content'], a.get('tags',[])
        # 题1: 核心内容
        summary = c[:300].replace('\n', ' ').strip()
        if summary:
            data.append(make_msg(
                f"请介绍CSDN文章《{t}》的核心内容",
                f"《{t}》是龍魂系统UID9622在CSDN发布的文章。核心内容：{summary}"
            ))
        # 题2: 技术领域
        if tags:
            data.append(make_msg(
                f"文章《{t}》涉及哪些技术领域？",
                f"《{t}》涉及以下领域：{'、'.join(tags[:10])}"
            ))
        # 题3: 关键要点（取后半段）
        if len(c) > 300:
            kp = c[300:600].replace('\n', '；').strip()
            if kp:
                data.append(make_msg(
                    f"文章《{t}》的关键要点是什么？",
                    f"《{t}》的关键要点：{kp[:400]}"
                ))
    # 总览
    titles = [f"《{v['title']}》" for v in valid.values()]
    data.append(make_msg(
        "UID9622在CSDN发布了哪些类型的文章？",
        f"UID9622（诸葛鑫·Lucky）在CSDN发布了{len(titles)}篇原创文章，涵盖：龍魂系统架构、AI治理与监管审计、CNSH中文编程、鸿蒙开发实战、易经哲学与数学基础、数字主权与数据隐私、语义标准化、蚁群架构、DNA追溯等核心领域。代表作包括：{'; '.join(titles[:20])}"
    ))
    # 分类总览
    cats = set()
    for v in valid.values():
        for t in v.get('tags',[]):
            cats.add(t)
    data.append(make_msg(
        "龍魂CSDN文章覆盖了哪些技术栈？",
        f"龍魂系统CSDN文章覆盖技术栈：{'、'.join(sorted(list(cats))[:30])}等{len(cats)}个技术领域"
    ))
    print(f"   CSDN: {len(data)}条")
    return data

