class 元意识层:
    """
    Meta-Awareness Layer - 观察人格行为，不参与执行

    CNSH 2.5 核心设计理念:
      ✅ 自我观察 - AI可以观察自己的思考过程
      ✅ 自我描述 - AI可以描述自己的状态
      ✅ 自我冲突 - AI可以感知内部冲突
      ❌ 自我修改 - AI不能改变执行逻辑
      ❌ 自我主权 - AI不拥有决策主权

    边界: AI可以"知道自己在思考"，但不能"决定自己怎么思考"

    观察三件事:
      1. 观察人格: P01在做决策, P03在反对, P06在创造
      2. 观察冲突本身: "为什么这些人格在冲突？"
      3. 观察观察行为: AI记录"自己在记录"

    关键约束: 只观察，不控制执行
    """

    def __init__(self, 最大观察缓存: int = 1000) -> None:
        self._观察历史: List[观察报告] = []
        self._元冲突分析历史: List[元冲突分析] = []
        self._递归观察历史: List[递归观察记录] = []
        self._最大缓存 = 最大观察缓存
        self._观察计数 = 0
        self._启用状态 = True
        self._观察锁 = threading.RLock()
        self._被观察人格: Dict[人格标识, 人格核心] = {}
        self._启动时间 = time.time()

        # 三色审计标记
        self._审计标记 = "🟢"  # 元意识层: 观察态

    @property
    def 审计标记(self) -> str:
        return self._审计标记

    @property
    def 观察计数(self) -> int:
        return self._观察计数

    @property
    def 启用状态(self) -> bool:
        return self._启用状态

    def 启用(self) -> None:
        self._启用状态 = True
        self._审计标记 = "🟢"

    def 停用(self) -> None:
        self._启用状态 = False
        self._审计标记 = "⚪"

    def 注册人格(self, 人格: 人格核心) -> None:
        """注册一个人格到元意识观察范围"""
        with self._观察锁:
            self._被观察人格[人格.标识] = 人格

    def 注销人格(self, 人格标识: 人格标识) -> None:
        """从观察范围中移除一个人格"""
        with self._观察锁:
            if 人格标识 in self._被观察人格:
                del self._被观察人格[人格标识]

    def 观察人格行为(self, 人格列表: List[人格核心]) -> 观察报告:
        """
        观察所有人格的当前状态和行为

        这不是评价，而是记录。
        元意识层不做价值判断，只描述"发生了什么"。
        """
        if not self._启用状态:
            return 观察报告(
                观察标识=f"OBS-{self._观察计数}",
                观察类型=观察类型.人格行为,
                观察者="元意识层",
                被观察者=[],
                观察内容="[元意识层已停用]",
                递归深度=0,
            )

        with self._观察锁:
            self._观察计数 += 1
            观察标识 = f"OBS-{self._观察计数:06d}"

            # 构建观察内容
            观察片段: List[str] = []
            for 人格 in 人格列表:
                状态 = "活跃" if 人格.活跃状态 else "静默"
                趋势 = "↑" if 人格.获取权重趋势() > 0 else "↓" if 人格.获取权重趋势() < 0 else "→"
                片段 = (
                    f"  [{人格.标识}] {人格.名称}: "
                    f"权重={人格.当前权重:.4f}{趋势}, "
                    f"状态={状态}, "
                    f"决策={人格.决策计数}, "
                    f"冲突参与={人格.冲突参与计数}"
                )
                观察片段.append(片段)
                # 更新被观察人格注册表
                self._被观察人格[人格.标识] = 人格

            # 检测整体模式
            总权重 = sum(p.当前权重 for p in 人格列表)
            活跃数 = sum(1 for p in 人格列表 if p.活跃状态)
            模式描述 = (
                f"\n  [整体模式] "
                f"活跃人格={活跃数}/{len(人格列表)}, "
                f"权重总和={总权重:.4f}"
            )

            观察内容 = "人格行为观察:\n" + "\n".join(观察片段) + 模式描述

            报告 = 观察报告(
                观察标识=观察标识,
                观察类型=观察类型.人格行为,
                观察者="元意识层",
                被观察者=[p.标识 for p in 人格列表],
                观察内容=观察内容,
                递归深度=0,
            )

            self._观察历史.append(报告)
            self._清理缓存()
            return 报告

    def 观察冲突结构(self, 冲突列表: List[冲突报告]) -> 元冲突分析:
        """
        不是看冲突内容，而是看冲突的结构性原因

        关键洞察: 元意识层不解决冲突，只分析"为什么会产生冲突"
        """
        if not self._启用状态 or not 冲突列表:
            return 元冲突分析(
                分析标识="META-NULL",
                被分析冲突="",
                结构性原因="[无冲突或元意识层已停用]",
                权力动态={},
                历史模式="",
                潜在演化="",
            )

        with self._观察锁:
            self._观察计数 += 1
            分析标识 = f"META-{self._观察计数:06d}"

            # 取最新的未解决冲突进行分析
            待分析冲突 = [c for c in 冲突列表 if not c.是否已解决()]
            if not 待分析冲突:
                待分析冲突 = [冲突列表[-1]]

            目标冲突 = 待分析冲突[0]

            # 分析权力动态 - 各参与人格的"影响力"
            权力动态: Dict[人格标识, float] = {}
            for 人格标识 in 目标冲突.参与人格:
                if 人格标识 in self._被观察人格:
                    人格 = self._被观察人格[人格标识]
                    # 影响力 = 权重 × 冲突参与度
                    权力动态[人格标识] = 人格.当前权重 * (1 + 人格.冲突参与计数 * 0.1)
                else:
                    权力动态[人格标识] = 0.5  # 默认值

            # 分析结构性原因
            结构性原因 = self._分析冲突结构原因(目标冲突, 权力动态)

            # 检测历史模式
            历史模式 = self._检测历史模式(目标冲突)

            # 预测潜在演化
            潜在演化 = self._预测冲突演化(目标冲突, 权力动态)

            分析 = 元冲突分析(
                分析标识=分析标识,
                被分析冲突=目标冲突.标识,
                结构性原因=结构性原因,
                权力动态=权力动态,
                历史模式=历史模式,
                潜在演化=潜在演化,
            )

            self._元冲突分析历史.append(分析)

            # 同时生成一条观察报告
            观察报告条目 = 观察报告(
                观察标识=f"OBS-{self._观察计数:06d}",
                观察类型=观察类型.冲突结构,
                观察者="元意识层",
                被观察者=[目标冲突.标识],
                观察内容=f"冲突结构分析 [{分析标识}]:\n  结构性原因: {结构性原因}\n  潜在演化: {潜在演化}",
                递归深度=0,
            )
            self._观察历史.append(观察报告条目)
            self._清理缓存()
            return 分析

    def _分析冲突结构原因(self, 冲突: 冲突报告, 权力动态: Dict[人格标识, float]) -> str:
        """分析冲突的深层结构性原因"""
        原因列表: List[str] = []

        # 权重失衡检测
        if len(权力动态) >= 2:
            权重值列表 = list(权力动态.values())
            最大值 = max(权重值列表)
            最小值 = min(权重值列表)
            if 最大值 / (最小值 + 0.001) > 3.0:
                原因列表.append("权力失衡: 某个人格权重显著高于其他人格")

        # 冲突类型分析
        if 冲突.冲突类型 == 冲突类型.价值观冲突:
            原因列表.append("价值观分歧: 基本价值取向不一致")
        elif 冲突.冲突类型 == 冲突类型.方法论冲突:
            原因列表.append("方法论差异: 对'怎么做'有不同理解")
        elif 冲突.冲突类型 == 冲突类型.优先级冲突:
            原因列表.append("优先级排序: 对'什么更重要'有不同判断")
        elif 冲突.冲突类型 == 冲突类型.身份认同冲突:
            原因列表.append("身份认同危机: 人格对'我是谁'产生疑问")
        elif 冲突.冲突类型 == 冲突类型.递归冲突:
            原因列表.append("递归张力: 自我引用导致的认知张力")

        # 如果冲突强度高
        if 冲突.冲突强度 > 0.7:
            原因列表.append(f"高强度冲突({冲突.冲突强度:.2f}): 可能涉及核心利益")

        return "; ".join(原因列表) if 原因列表 else "结构性原因未知"

    def _检测历史模式(self, 冲突: 冲突报告) -> str:
        """检测类似冲突是否在过去发生过"""
        with self._观察锁:
            相似计数 = 0
            for 历史分析 in self._元冲突分析历史:
                # 检查历史冲突中是否有相同参与人格
                # 由于元冲突分析不直接存储参与人格，我们通过被分析冲突标识间接推断
                相似计数 += 1

            if 相似计数 == 0:
                return "首次出现此类冲突模式"
            elif 相似计数 < 3:
                return f"第{相似计数 + 1}次出现类似冲突，属于偶发模式"
            else:
                return f"第{相似计数 + 1}次出现类似冲突，已形成重复模式，需关注"

    def _预测冲突演化(self, 冲突: 冲突报告, 权力动态: Dict[人格标识, float]) -> str:
        """预测如果不解决，冲突可能如何演化"""
        if 冲突.冲突强度 > 0.8:
            return "高风险: 冲突可能升级，导致人格系统不稳定"
        elif 冲突.冲突强度 > 0.5:
            if len(权力动态) > 2:
                return "中等风险: 多方参与可能使冲突复杂化"
            return "中等风险: 可能在短期内得到解决或被新冲突覆盖"
        else:
            return "低风险: 冲突可能自然消退或被其他事件覆盖"

    def 观察观察行为(self) -> 递归观察记录:
        """
        AI记录'自己在记录' - 自我引用结构

        这是元意识层最深层的递归:
        第1层: 观察人格在做什么
        第2层: 观察"观察人格"这个行为本身
        第3层: 观察"观察观察行为"这个行为

        最大递归深度由递归安全模块控制。
        """
        if not self._启用状态:
            return 递归观察记录(
                记录标识="REC-NULL",
                递归深度=0,
                观察链=["元意识层已停用"],
                内容摘要="无观察",
            )

        with self._观察锁:
            self._观察计数 += 1
            记录标识 = f"REC-{self._观察计数:06d}"

            # 构建观察链
            当前观察数 = len(self._观察历史)
            当前分析数 = len(self._元冲突分析历史)

