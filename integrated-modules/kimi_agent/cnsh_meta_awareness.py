# 核心模块 4: 自我观察循环 (Meta-Loop)
# ═══════════════════════════════════════════════════════════

@dataclass
class 任务包:
    """任务包 - 元循环处理的基本单元"""
    任务标识: str
    原始输入: str
    目标描述: str
    优先级: int = 5  # 1-10
    创建时间: 时间戳 = field(default_factory=time.time)
    元数据: Dict[str, Any] = field(default_factory=dict)


class 元循环:
    """
    Meta-Loop: 执行任务 → 人格协作 → 冲突 → 解决 → Meta Layer启动 → 分析结构 → 反向影响

    完整循环:
      1. 执行任务
      2. 人格协作产生结果
      3. 冲突出现
      4. 冲突解决
      5. Meta Layer启动分析
      6. 分析"为什么会这样解决"
      7. 记录结构
      8. 反向影响人格权重（仅建议，不强制）

    关键: 第8步的"反向影响"仅是建议性反馈，不具有强制性。
         元意识层提供洞见，但不改变执行逻辑。
    """

    def __init__(
        self,
        元意识引用: Optional[元意识层] = None,
        身份追踪引用: Optional[身份追踪] = None,
        目标溯源引用: Optional[目标溯源] = None,
    ) -> None:
        self._元意识 = 元意识引用
        self._身份追踪 = 身份追踪引用
        self._目标溯源 = 目标溯源引用
        self._循环历史: List[元循环报告] = []
        self._循环锁 = threading.RLock()
        self._循环计数 = 0
        self._阶段记录: List[str] = []

    def 执行观察循环(
        self,
        任务: 任务包,
        人格列表: Optional[List[人格核心]] = None,
        冲突列表: Optional[List[冲突报告]] = None,
    ) -> 元循环报告:
        """
        执行完整的元观察循环

        这是元意识层的核心工作流。
        注意: 元意识层不参与实际任务执行，只在执行完成后进行观察。
        """
        循环开始时间 = time.time()
        self._阶段记录 = []

        with self._循环锁:
            self._循环计数 += 1
            报告标识 = f"LOOP-{self._循环计数:06d}"

            # 阶段1: 任务接收
            self._记录阶段("任务接收", f"任务[{任务.任务标识}]: {任务.目标描述[:50]}")

            # 阶段2: 人格协作观察
            self._记录阶段("人格协作观察")
            if self._元意识 is not None and 人格列表 is not None:
                人格观察报告 = self._元意识.观察人格行为(人格列表)

            # 阶段3: 冲突观察
            self._记录阶段("冲突观察")
            元分析: Optional[元冲突分析] = None
            if self._元意识 is not None and 冲突列表 is not None and len(冲突列表) > 0:
                元分析 = self._元意识.观察冲突结构(冲突列表)

            # 阶段4: 身份追踪
            self._记录阶段("身份追踪")
            稳定性分数: Dict[人格标识, float] = {}
            if self._身份追踪 is not None and 人格列表 is not None:
                for 人格 in 人格列表:
                    稳定性分数[人格.标识] = self._身份追踪.计算稳定性(人格)

            # 阶段5: 目标溯源
            self._记录阶段("目标溯源")
            目标漂移: Optional[漂移检测] = None
            if self._目标溯源 is not None:
                目标来源 = self._目标溯源.映射目标来源(任务.目标描述)
                # 如果有历史演化，检测漂移
                if len(目标来源.演化历史) > 0:
                    历史文本 = [目标来源.原始目标文本] + [t for _, t, _ in 目标来源.演化历史]
                    目标漂移 = self._目标溯源.检测目标漂移(历史文本)

            # 阶段6: 元意识自我观察
            self._记录阶段("元意识自我观察")
            递归记录: Optional[递归观察记录] = None
            if self._元意识 is not None:
                递归记录 = self._元意识.观察观察行为()

            # 阶段7: 生成权重调整建议（仅建议，不强制）
            self._记录阶段("权重调整建议（建议性）")
            权重建议 = self._生成权重建议(人格列表, 元分析, 稳定性分数)

            # 阶段8: 生成报告
            self._记录阶段("生成元循环报告")
            循环耗时 = time.time() - 循环开始时间

            人格参与: Dict[人格标识, float] = {}
            if 人格列表 is not None:
                for 人格 in 人格列表:
                    人格参与[人格.标识] = 人格.当前权重 * (1 + 人格.决策计数 * 0.01)

            报告 = 元循环报告(
                报告标识=报告标识,
                任务标识=任务.任务标识,
                循环阶段=list(self._阶段记录),
                人格参与=人格参与,
                冲突记录=[c.标识 for c in (冲突列表 or [])],
                元分析结果=[元分析.分析标识] if 元分析 is not None else [],
                权重调整建议=权重建议,
                循环耗时=循环耗时,
            )

            self._循环历史.append(报告)
            return 报告

    def _记录阶段(self, 阶段名: str, 详情: str = "") -> None:
        """记录一个循环阶段"""
        记录 = f"[{len(self._阶段记录)+1}] {阶段名}"
        if 详情:
            记录 += f" - {详情}"
        self._阶段记录.append(记录)

    def _生成权重建议(
        self,
        人格列表: Optional[List[人格核心]],
        元分析: Optional[元冲突分析],
        稳定性分数: Dict[人格标识, float],
    ) -> Dict[人格标识, float]:
        """
        生成权重调整建议 - 仅建议，不强制

        这些建议可以被上层系统参考，但元意识层本身不会强制改变任何权重。
        这是"观察不等于控制"原则的具体体现。
        """
        建议: Dict[人格标识, float] = {}

        if 人格列表 is None:
            return 建议

        for 人格 in 人格列表:
            建议调整 = 0.0

            # 如果人格稳定性低，建议适当降低权重
            稳定性 = 稳定性分数.get(人格.标识, 0.5)
            if 稳定性 < 0.3:
                建议调整 -= 0.05  # 轻微下调

            # 如果人格在冲突中过于强势，建议平衡
            if 元分析 is not None and 人格.标识 in 元分析.权力动态:
                权力值 = 元分析.权力动态[人格.标识]
                平均权力 = sum(元分析.权力动态.values()) / len(元分析.权力动态) if 元分析.权力动态 else 0
                if 权力值 > 平均权力 * 2:
                    建议调整 -= 0.03  # 轻微平衡

            建议[人格.标识] = 建议调整

        return 建议

    def 获取循环历史(self, 数量: Optional[int] = None) -> List[元循环报告]:
        """获取循环历史"""
        with self._循环锁:
            if 数量 is None:
                return list(self._循环历史)
            return list(self._循环历史[-数量:])

    def 生成循环摘要(self) -> str:
        """生成元循环系统的摘要"""
        with self._循环锁:
            总耗时 = sum(r.循环耗时 for r in self._循环历史)
            摘要 = (
                f"{'='*50}\n"
                f"  元循环系统摘要\n"
                f"{'='*50}\n"
                f"  总循环次数: {self._循环计数}\n"
                f"  总耗时: {总耗时:.3f}秒\n"
                f"  平均耗时: {总耗时 / max(self._循环计数, 1):.3f}秒\n"
            )
            if self._循环历史:
                最新 = self._循环历史[-1]
                摘要 += (
                    f"\n  最新循环 [{最新.报告标识}]:\n"
                    f"    任务: {最新.任务标识}\n"
                    f"    阶段: {' → '.join(l.split(' - ')[0] for l in 最新.循环阶段)}\n"
                    f"    参与人格: {len(最新.人格参与)}个\n"
                    f"    权重建议: {len(最新.权重调整建议)}条\n"
                    f"    耗时: {最新.循环耗时:.4f}秒\n"
                )
            摘要 += f"{'='*50}"
            return 摘要


