# ═══════════════════════════════════════════════════════════

class 目标溯源:
    """
    CNSH_GOAL_ORIGIN_MAP - 追踪目标的来源和演化

    核心洞察:
      原始目标 → 执行中 → 被人格重写 → 再解释原始目标
      系统发现: 目标不是固定的，是被"解释出来的"

    每一次对目标的"解释"都是一次潜在的漂移。
    目标溯源追踪这种解释链，使漂移可见。
    """

    # 语义相似度阈值
    _高相似度阈值 = 0.8
    _中相似度阈值 = 0.5

    def __init__(self, 元意识引用: Optional[元意识层] = None) -> None:
        self._目标库: Dict[str, 目标来源] = {}
        self._漂移检测历史: List[漂移检测] = []
        self._元意识 = 元意识引用
        self._溯源锁 = threading.RLock()
        self._溯源计数 = 0

    def 映射目标来源(self, 目标: str, 定义者: str = "用户") -> 目标来源:
        """
        追踪目标最初是谁定义的

        定义者可能是:
          - "用户": 用户直接输入的目标
          - 人格标识: 某个人格提出或重写的目标
          - "系统": 系统默认/推断的目标
        """
        with self._溯源锁:
            self._溯源计数 += 1
            目标标识 = f"GOAL-{self._溯源计数:06d}"

            # 检查是否已存在相似目标
            现有目标 = self._查找相似目标(目标)
            if 现有目标 is not None:
                return 现有目标

            来源 = 目标来源(
                目标标识=目标标识,
                原始目标文本=目标,
                定义者=定义者,
                定义时间=time.time(),
                演化历史=[],
                当前解释者=定义者,
            )

            self._目标库[目标标识] = 来源
            return 来源

    def _查找相似目标(self, 目标: str) -> Optional[目标来源]:
        """查找语义相似的目标"""
        # 简化的相似度检查 - 使用关键词重叠
        目标关键词 = set(目标.lower().split())
        for 现有目标 in self._目标库.values():
            现有关键词 = set(现有目标.原始目标文本.lower().split())
            if not 目标关键词 or not 现有关键词:
                continue
            交集 = 目标关键词 & 现有关键词
            并集 = 目标关键词 | 现有关键词
            if 并集 and len(交集) / len(并集) > self._高相似度阈值:
                return 现有目标
        return None

    def 记录目标演化(self, 目标标识: str, 新文本: str, 修改者: str, 修改原因: str) -> None:
        """记录目标的一次演化"""
        with self._溯源锁:
            if 目标标识 not in self._目标库:
                return

            来源 = self._目标库[目标标识]
            来源.演化历史.append((time.time(), 新文本, 修改原因))
            来源.当前解释者 = 修改者

    def 检测目标漂移(self, 目标历史: List[str]) -> 漂移检测:
        """
        检测目标在执行过程中的变化

        目标历史是按时间顺序的目标文本列表。
        系统检测原始目标与当前目标之间的语义偏离。
        """
        with self._溯源锁:
            self._溯源计数 += 1
            检测标识 = f"GDR-{self._溯源计数:06d}"

            if len(目标历史) < 2:
                return 漂移检测(
                    检测标识=检测标识,
                    原始目标=目标历史[0] if 目标历史 else "",
                    当前目标=目标历史[-1] if 目标历史 else "",
                    漂移方向=漂移方向.稳定,
                    漂移度量=0.0,
                    漂移节点=[],
                    是否可逆=True,
                )

            原始目标 = 目标历史[0]
            当前目标 = 目标历史[-1]

            # 计算漂移度量
            漂移度量 = self.计算漂移度(原始目标, 当前目标)

            # 构建漂移节点
            漂移节点: List[Tuple[时间戳, str]] = []
            for i, 目标文本 in enumerate(目标历史):
                # 使用递增的时间戳模拟
                漂移节点.append((time.time() - (len(目标历史) - i) * 60, 目标文本))

            # 确定漂移方向
            if 漂移度量 < 0.1:
                漂移方向结果 = 漂移方向.稳定
            elif 漂移度量 < 0.3:
                漂移方向结果 = 漂移方向.渐进偏移
            elif 漂移度量 < 0.6:
                漂移方向结果 = 漂移方向.跳跃偏移
            else:
                漂移方向结果 = 漂移方向.发散

            # 判断是否可逆
            是否可逆 = 漂移度量 < 0.5

            检测 = 漂移检测(
                检测标识=检测标识,
                原始目标=原始目标,
                当前目标=当前目标,
                漂移方向=漂移方向结果,
                漂移度量=漂移度量,
                漂移节点=漂移节点,
                是否可逆=是否可逆,
            )

            self._漂移检测历史.append(检测)
            return 检测

    def 计算漂移度(self, 原始目标: str, 当前目标: str) -> float:
        """
        计算目标偏离原始定义的程度 0-1

        0 = 完全相同
        1 = 完全不同

        使用简化的语义相似度计算:
          - 关键词重叠度
          - 长度变化率
          - 结构变化检测
        """
        if 原始目标 == 当前目标:
            return 0.0

        if not 原始目标 or not 当前目标:
            return 1.0

        # 关键词重叠度
        原始关键词 = set(原始目标.lower().split())
        当前关键词 = set(当前目标.lower().split())
        关键词并集 = 原始关键词 | 当前关键词
        关键词交集 = 原始关键词 & 当前关键词
        关键词相似度 = len(关键词交集) / len(关键词并集) if 关键词并集 else 0.0

        # 长度变化率
        长度比 = min(len(原始目标), len(当前目标)) / max(len(原始目标), len(当前目标))

        # 漂移度 = 1 - 综合相似度
        综合相似度 = 关键词相似度 * 0.7 + 长度比 * 0.3
        漂移度 = 1.0 - 综合相似度

        return min(1.0, max(0.0, 漂移度))

    def 获取目标演化链(self, 目标标识: str) -> Optional[目标来源]:
        """获取目标的完整演化链"""
        with self._溯源锁:
            return self._目标库.get(目标标识)

    def 生成目标溯源摘要(self) -> str:
        """生成目标溯源系统的摘要"""
        with self._溯源锁:
            摘要 = (
                f"{'='*50}\n"
                f"  目标溯源系统摘要\n"
                f"{'='*50}\n"
                f"  追踪目标: {len(self._目标库)}个\n"
                f"  漂移检测: {len(self._漂移检测历史)}次\n"
            )

            if self._漂移检测历史:
                最新检测 = self._漂移检测历史[-1]
                摘要 += (
                    f"\n  最新漂移检测:\n"
                    f"    原始目标: {最新检测.原始目标[:50]}...\n"
                    f"    当前目标: {最新检测.当前目标[:50]}...\n"
                    f"    漂移度量: {最新检测.漂移度量:.4f}\n"
                    f"    漂移方向: {最新检测.漂移方向.name}\n"
                    f"    是否可逆: {'是' if 最新检测.是否可逆 else '否'}\n"
                )

            for 目标标识, 来源 in list(self._目标库.items())[-5:]:
                演化次数 = len(来源.演化历史)
                摘要 += f"\n  目标 [{目标标识}]:\n"
                摘要 += f"    原文: {来源.原始目标文本[:60]}...\n"
                摘要 += f"    定义者: {来源.定义者}\n"
                摘要 += f"    演化次数: {演化次数}\n"
                if 演化次数 > 0:
                    摘要 += f"    当前解释者: {来源.当前解释者}\n"

            摘要 += f"{'='*50}"
            return 摘要


