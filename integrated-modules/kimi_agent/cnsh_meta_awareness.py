    def 获取观察历史(self, 数量: Optional[int] = None) -> List[观察报告]:
        """获取观察历史，数量为空则返回全部"""
        with self._观察锁:
            if 数量 is None:
                return list(self._观察历史)
            return list(self._观察历史[-数量:])

    def 获取元分析历史(self) -> List[元冲突分析]:
        """获取元冲突分析历史"""
        with self._观察锁:
            return list(self._元冲突分析历史)

    def 生成观察摘要(self) -> str:
        """生成当前观察状态的摘要"""
        with self._观察锁:
            运行时长 = time.time() - self._启动时间
            观察类型统计: Dict[str, int] = {}
            for 报告 in self._观察历史:
                类型名 = 报告.观察类型.name
                观察类型统计[类型名] = 观察类型统计.get(类型名, 0) + 1

            摘要 = (
                f"{'='*50}\n"
                f"  元意识层观察摘要 {self._审计标记}\n"
                f"{'='*50}\n"
                f"  运行时长: {运行时长:.1f}秒\n"
                f"  总观察数: {self._观察计数}\n"
                f"  观察报告: {len(self._观察历史)}条\n"
                f"  元分析: {len(self._元冲突分析历史)}条\n"
                f"  递归记录: {len(self._递归观察历史)}条\n"
                f"  被观察人格: {len(self._被观察人格)}个\n"
                f"  观察类型分布:\n"
            )
            for 类型名, 计数 in sorted(观察类型统计.items(), key=lambda x: -x[1]):
                摘要 += f"    - {类型名}: {计数}条\n"
            摘要 += f"{'='*50}"
            return 摘要

    def _清理缓存(self) -> None:
        """清理过旧的观察记录"""
        if len(self._观察历史) > self._最大缓存:
            self._观察历史 = self._观察历史[-self._最大缓存:]
        if len(self._元冲突分析历史) > self._最大缓存 // 4:
            self._元冲突分析历史 = self._元冲突分析历史[-(self._最大缓存 // 4):]
        if len(self._递归观察历史) > self._最大缓存 // 10:
            self._递归观察历史 = self._递归观察历史[-(self._最大缓存 // 10):]


