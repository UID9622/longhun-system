class 递归安全:
    """
    防止认知递归失控的安全机制

    递归结构: AI→观察AI→观察观察AI→观察观察观察AI
    如果没有限制，这个链条可能无限延伸，导致系统资源耗尽。

    安全措施:
      - 最大递归深度限制（默认3层）
      - Meta Layer不参与执行
      - 观察结果仅记录，不影响决策
      - 递归阻断机制

    这是元意识层的安全底线。违反递归安全等于允许系统自我失控。
    """

    最大递归深度: int = 3  # 最大允许的递归观察深度

    def __init__(self, 自定义最大深度: Optional[int] = None) -> None:
        if 自定义最大深度 is not None:
            self.最大递归深度 = max(1, min(自定义最大深度, 5))  # 限制在1-5之间

        self._当前递归深度 = 0
        self._阻断历史: List[Dict[str, Any]] = []
        self._安全锁 = threading.RLock()
        self._阻断计数 = 0

    def 检查递归深度(self, 观察链: List[Any]) -> bool:
        """
        检查是否超过最大递归深度

        返回True表示安全（未超过），False表示需要阻断。
        """
        with self._安全锁:
            self._当前递归深度 = len(观察链)
            return self._当前递归深度 <= self.最大递归深度

    def 阻断递归(self, 原因: str = "超过最大递归深度") -> None:
        """
        当递归过深时阻断

        阻断不是错误，而是安全机制的正常工作。
        被阻断的递归会被记录，用于后续分析。
        """
        with self._安全锁:
            self._阻断计数 += 1
            阻断记录 = {
                "时间": time.time(),
                "原因": 原因,
                "尝试深度": self._当前递归深度,
                "最大允许深度": self.最大递归深度,
            }
            self._阻断历史.append(阻断记录)

    def 获取当前深度(self) -> int:
        """获取当前递归深度"""
        with self._安全锁:
            return self._当前递归深度

    def 是否已阻断(self) -> bool:
        """检查是否发生过阻断"""
        with self._安全锁:
            return self._阻断计数 > 0

    @property
    def 阻断计数(self) -> int:
        return self._阻断计数

    def 安全观察包装(
        self,
        观察函数: Callable[..., Any],
        *参数: Any,
        **关键字参数: Any,
    ) -> Optional[Any]:
        """
        安全地执行观察函数，自动检查递归深度并在必要时阻断

        这是递归安全的主要API。所有元意识观察都应通过此包装器执行。
        """
        with self._安全锁:
            # 检查当前深度
            if not self.检查递归深度([self._当前递归_depth_marker()]):
                self.阻断递归("安全观察包装检测到递归过深")
                return None

            try:
                self._当前递归深度 += 1
                结果 = 观察函数(*参数, **关键字参数)
                return 结果
            finally:
                self._当前递归深度 -= 1

    def _当前递归_depth_marker(self) -> str:
        """生成当前深度的标记"""
        return f"depth-{self._当前递归深度}"

    def 生成递归安全摘要(self) -> str:
        """生成递归安全机制的摘要"""
        with self._安全锁:
            摘要 = (
                f"{'='*50}\n"
                f"  认知递归安全机制摘要\n"
                f"{'='*50}\n"
                f"  最大递归深度: {self.最大递归深度}\n"
                f"  当前递归深度: {self._当前递归深度}\n"
                f"  阻断次数: {self._阻断计数}\n"
                f"  安全状态: {'✅ 正常' if self._阻断计数 == 0 else '⚠️ 已发生阻断'}\n"
            )
            if self._阻断历史:
                摘要 += f"\n  阻断历史 (最近3次):\n"
                for 记录 in self._阻断历史[-3:]:
                    摘要 += (
                        f"    [{datetime.fromtimestamp(记录['时间']).strftime('%H:%M:%S')}] "
                        f"深度{记录['尝试深度']}/{记录['最大允许深度']}: {记录['原因']}\n"
                    )
            摘要 += f"{'='*50}"
            return 摘要


