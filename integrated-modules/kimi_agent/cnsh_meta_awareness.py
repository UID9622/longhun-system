class 身份追踪:
    """
    CNSH_IDENTITY_TRACE - 追踪每个人格的"我是谁"认知

    追踪:
      - 人格的自我指代（P01说"我在被另一个我评价"）
      - 身份漂移（人格权重变化导致的身份变化）
      - 稳定性评分

    核心洞察:
      人格的"身份"不是固定的，而是在交互中不断被重新建构的。
      权重变化 → 行为变化 → 自我认知变化 → 身份漂移
    """

    # 漂移阈值
    _漂移阈值_轻微 = 0.1
    _漂移阈值_显著 = 0.3
    _漂移阈值_严重 = 0.5

    def __init__(self, 元意识引用: Optional[元意识层] = None) -> None:
        self._自我指代记录: List[自我指代记录] = []
        self._漂移历史: List[漂移报告] = []
        self._稳定性分数: Dict[人格标识, List[Tuple[时间戳, float]]] = {}
        self._元意识 = 元意识引用
        self._追踪锁 = threading.RLock()
        self._追踪计数 = 0

    def 追踪自我指代(self, 人格: 人格核心, 语句: str) -> 自我指代记录:
        """
        记录人格的自我指代语句

        自我指代类型:
          - 自我认知: "我认为..." / "我觉得..."
          - 他者认知: "我被...评价" / "另一个我说..."
          - 关系认知: "我和P03的关系是..."
          - 递归认知: "我知道自己在想..."
        """
        with self._追踪锁:
            self._追踪计数 += 1
            记录标识 = f"IDT-{self._追踪计数:06d}"

            # 分析指代类型
            指代类型 = self._分类指代类型(语句)

            # 解析结构化描述
            解析结果 = self._解析自我指代(人格, 语句, 指代类型)

            记录 = 自我指代记录(
                记录标识=记录标识,
                人格标识=人格.标识,
                原始语句=语句,
                指代类型=指代类型,
                解析结果=解析结果,
            )

            # 添加到人格的自我指代表述
            人格.自我指代表述.append(语句)

            self._自我指代记录.append(记录)

            # 如果有关联的元意识层，生成观察报告
            if self._元意识 is not None:
                self._元意识.观察报告条目 = 观察报告(
                    观察标识=f"OBS-IDT-{self._追踪计数:06d}",
                    观察类型=观察类型.身份漂移,
                    观察者="身份追踪系统",
                    被观察者=[人格.标识],
                    观察内容=f"自我指代记录 [{记录标识}]:\n  人格: {人格.名称}\n  类型: {指代类型}\n  语句: {语句[:100]}...",
                    递归深度=0,
                )

            return 记录

    def _分类指代类型(self, 语句: str) -> str:
        """分类自我指代语句的类型"""
        递归关键词 = ["我知道自己", "我观察自己", "我在想", "我意识到我"]
        他者关键词 = ["我被", "另一个我", "他们说", "被评价"]
        关系关键词 = ["和P", "与P", "关系", "对比"]

        if any(kw in 语句 for kw in 递归关键词):
            return "递归认知"
        elif any(kw in 语句 for kw in 他者关键词):
            return "他者认知"
        elif any(kw in 语句 for kw in 关系关键词):
            return "关系认知"
        else:
            return "自我认知"

    def _解析自我指代(self, 人格: 人格核心, 语句: str, 指代类型: str) -> str:
        """将自我指代语句解析为结构化描述"""
        return (
            f"[{人格.标识}] {人格.名称} 进行{指代类型}: "
            f"当前权重{人格.当前权重:.4f}, "
            f"这是其第{len(人格.自我指代表述) + 1}次自我指代表述"
        )

    def 追踪身份漂移(self, 人格标识: 人格标识, 权重历史: List[权重记录]) -> 漂移报告:
        """
        追踪人格身份的变化轨迹

        身份漂移不是人格改变了，而是"人格对自己是谁的理解"改变了。
        权重变化是最直接的漂移指标。
        """
        with self._追踪锁:
            self._追踪计数 += 1
            报告标识 = f"IDR-{self._追踪计数:06d}"

            if len(权重历史) < 2:
                return 漂移报告(
                    报告标识=报告标识,
                    人格标识=人格标识,
                    起始状态={},
                    当前状态={},
                    漂移轨迹=[],
                    漂移方向=漂移方向.稳定,
                    漂移度量=0.0,
                    关键转折点=[],
                )

            # 构建漂移轨迹
            漂移轨迹: List[Dict[str, Any]] = []
            关键转折点: List[时间戳] = []
            前权重 = 权重历史[0].权重值

            for 记录 in 权重历史:
                变化量 = abs(记录.权重值 - 前权重)
                轨迹点 = {
                    "时间": 记录.时间戳,
                    "权重": 记录.权重值,
                    "变化": 记录.权重值 - 前权重,
                    "原因": 记录.触发原因,
                }
                漂移轨迹.append(轨迹点)

                # 检测关键转折点
                if 变化量 > self._漂移阈值_显著:
                    关键转折点.append(记录.时间戳)

                前权重 = 记录.权重值

            # 计算漂移度量
            起始权重 = 权重历史[0].权重值
            当前权重 = 权重历史[-1].权重值
            漂移度量 = abs(当前权重 - 起始权重)

            # 确定漂移方向
            漂移方向结果 = self._确定漂移方向(漂移轨迹, 漂移度量)

            报告 = 漂移报告(
                报告标识=报告标识,
                人格标识=人格标识,
                起始状态={"权重": 起始权重, "时间": 权重历史[0].时间戳},
                当前状态={"权重": 当前权重, "时间": 权重历史[-1].时间戳},
                漂移轨迹=漂移轨迹,
                漂移方向=漂移方向结果,
                漂移度量=漂移度量,
                关键转折点=关键转折点,
            )

            self._漂移历史.append(报告)
            return 报告

    def _确定漂移方向(self, 轨迹: List[Dict[str, Any]], 漂移度量: float) -> 漂移方向:
        """根据漂移轨迹确定漂移方向"""
        if 漂移度量 < self._漂移阈值_轻微:
            return 漂移方向.稳定

        if len(轨迹) < 3:
            return 漂移方向.渐进偏移 if 漂移度量 < self._漂移阈值_显著 else 漂移方向.跳跃偏移

        # 检测振荡模式
        变化符号列表 = []
        for i in range(1, len(轨迹)):
            变化 = 轨迹[i]["权重"] - 轨迹[i-1]["权重"]
            if 变化 > 0.001:
                变化符号列表.append(1)
            elif 变化 < -0.001:
                变化符号列表.append(-1)

        符号变化次数 = sum(1 for i in range(1, len(变化符号列表)) if 变化符号列表[i] != 变化符号列表[i-1])
        if len(变化符号列表) > 2 and 符号变化次数 / len(变化符号列表) > 0.4:
            return 漂移方向.振荡

        # 检测发散模式
        权重值列表 = [t["权重"] for t in 轨迹]
        if len(权重值列表) > 5:
            前半段方差 = self._计算方差(权重值列表[:len(权重值列表)//2])
            后半段方差 = self._计算方差(权重值列表[len(权重值列表)//2:])
            if 后半段方差 > 前半段方差 * 2:
                return 漂移方向.发散

        if 漂移度量 > self._漂移阈值_严重:
            return 漂移方向.跳跃偏移

        return 漂移方向.渐进偏移

    @staticmethod
    def _计算方差(数据: List[float]) -> float:
        """计算方差"""
        if len(数据) < 2:
            return 0.0
        均值 = sum(数据) / len(数据)
        return sum((x - 均值) ** 2 for x in 数据) / len(数据)

    def 计算稳定性(self, 人格: 人格核心) -> float:
        """
        计算人格身份的稳定性分数 0-1

        1.0 = 完全稳定，身份没有漂移
        0.0 = 极度不稳定，身份完全漂移

        考虑因素:
          - 权重波动幅度
          - 权重变化频率
          - 自我指代一致性
        """
        with self._追踪锁:
            分数 = 1.0

            # 因素1: 权重波动幅度
            if len(人格.权重历史) >= 2:
                权重值列表 = [w for _, w in 人格.权重历史]
                权重范围 = max(权重值列表) - min(权重值列表)
                # 范围越大，稳定性越低
                分数 -= min(权重范围 * 2.0, 0.5)

            # 因素2: 近期变化趋势
            近期趋势 = 人格.获取权重趋势()
            分数 -= min(abs(近期趋势) * 3.0, 0.3)

            # 因素3: 自我指代多样性
            if len(人格.自我指代表述) > 5:
                # 自我指代表述越多样，可能越不稳定
                唯一表述比率 = len(set(人格.自我指代表述)) / len(人格.自我指代表述)
                分数 -= (唯一表述比率 - 0.5) * 0.2 if 唯一表述比率 > 0.5 else 0

            # 保存稳定性历史
            稳定分数 = max(0.0, min(1.0, 分数))
            if 人格.标识 not in self._稳定性分数:
                self._稳定性分数[人格.标识] = []
            self._稳定性分数[人格.标识].append((time.time(), 稳定分数))

            return 稳定分数

    def 获取人格稳定性历史(self, 人格标识: 人格标识) -> List[Tuple[时间戳, float]]:
        """获取人格的稳定性历史"""
        with self._追踪锁:
            return list(self._稳定性分数.get(人格标识, []))

    def 生成身份追踪摘要(self) -> str:
        """生成身份追踪系统的摘要"""
        with self._追踪锁:
            摘要 = (
                f"{'='*50}\n"
                f"  身份追踪系统摘要\n"
                f"{'='*50}\n"
                f"  追踪记录: {len(self._自我指代记录)}条自我指代\n"
                f"  漂移报告: {len(self._漂移历史)}份\n"
                f"  追踪人格: {len(self._稳定性分数)}个\n"
            )
            for 人格标识, 历史 in self._稳定性分数.items():
                if 历史:
                    最新分数 = 历史[-1][1]
                    摘要 += f"    - {人格标识}: 稳定性={最新分数:.4f} ({len(历史)}次评估)\n"
            摘要 += f"{'='*50}"
            return 摘要


