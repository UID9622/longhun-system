@dataclass
class 人格核心:
    """人格核心 - 简化的人格表示，用于元意识层观察"""
    标识: 人格标识
    名称: str
    描述: str
    当前权重: 权重值
    权重历史: List[Tuple[时间戳, 权重值]] = field(default_factory=list)
    活跃状态: bool = True
    最后活跃时间: 时间戳 = field(default_factory=time.time)
    自我指代表述: List[str] = field(default_factory=list)
    决策计数: int = 0
    冲突参与计数: int = 0

    def 获取权重趋势(self, 窗口秒数: float = 300.0) -> float:
        """计算近期权重变化趋势，正值为上升，负值为下降"""
        当前时间 = time.time()
        近期记录 = [(t, w) for t, w in self.权重历史 if 当前时间 - t < 窗口秒数]
        if len(近期记录) < 2:
            return 0.0
        首权重 = 近期记录[0][1]
        尾权重 = 近期记录[-1][1]
        return 尾权重 - 首权重

    def 记录权重(self, 权重: 权重值) -> None:
        """记录当前权重到历史"""
        self.当前权重 = 权重
        self.权重历史.append((time.time(), 权重))
        # 保留最近1000条记录
        if len(self.权重历史) > 1000:
            self.权重历史 = self.权重历史[-1000:]

    def 序列化摘要(self) -> Dict[str, Any]:
        """获取人格摘要信息"""
        return {
            "标识": self.标识,
            "名称": self.名称,
            "当前权重": round(self.当前权重, 4),
            "活跃状态": self.活跃状态,
            "决策计数": self.决策计数,
            "冲突参与计数": self.冲突参与计数,
            "权重趋势": round(self.获取权重趋势(), 6),
            "自我指代表述数": len(self.自我指代表述),
        }


