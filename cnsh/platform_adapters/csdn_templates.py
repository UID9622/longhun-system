from datetime import datetime
from typing import List, Dict


def 生成DNA(项目: str, 模块: str, 版本: str = "v1.0") -> str:
    """生成标准 DNA 追溯码"""
    return f"#龍芯⚡️{datetime.now().strftime('%Y-%m-%d')}-{项目}-{模块}-{版本}"


def 单条消息模板(消息: Dict) -> str:
    """
    单条 CSDN 消息模板

    参数:
        消息: 包含 id/类型/用户/文章标题/文章链接/时间/DNA 的字典
    """
    类型 = 消息.get("类型", "消息")
    用户 = 消息.get("用户", "未知用户")
    文章标题 = 消息.get("文章标题", "")
    文章链接 = 消息.get("文章链接", "")
    时间 = 消息.get("时间", datetime.now().strftime("%Y-%m-%d"))
    DNA = 消息.get("DNA", 生成DNA("CSDN", f"MSG-{消息.get('id', '000')}"))

    lines = [
        f"### {类型} · {用户}",
        "",
        f"- **消息ID**: {消息.get('id', 'N/A')}",
        f"- **互动类型**: {类型}",
        f"- **互动用户**: {用户}",
    ]

    if 文章标题:
        lines.append(f"- **文章标题**: {文章标题}")
    if 文章链接:
        lines.append(f"- **文章链接**: {文章链接}")

    lines.extend([
        f"- **互动时间**: {时间}",
        f"- **DNA追溯**: `{DNA}`",
        "",
        "---",
        "",
    ])

    return "\n".join(lines)


def 消息日报模板(日期: str, 消息列表: List[Dict], 用户标识: str = "UID9622") -> str:
    """
    CSDN 消息日报模板

    参数:
        日期: 报告日期，如 2026-06-21
        消息列表: 消息字典列表
        用户标识: 默认 UID9622
    """
    DNA = 生成DNA("CSDN", "DAILY-REPORT")
    点赞数 = sum(1 for m in 消息列表 if m.get("类型") == "点赞")
    收藏数 = sum(1 for m in 消息列表 if m.get("类型") == "收藏")
    评论数 = sum(1 for m in 消息列表 if m.get("类型") in ["评论", "@我"])
    粉丝数 = sum(1 for m in 消息列表 if m.get("类型") == "新增粉丝")

    lines = [
        f"<!--{DNA}-->",
        "<!-- 君子协议: 本文件受龍魂DNA追溯保护 · CC BY-NC-SA 4.0 -->",
        "",
        f"# CSDN 消息日报 · {日期}",
        "",
        f"**用户标识**: {用户标识}",
        f"**生成时间**: {datetime.now().isoformat()}",
        f"**DNA追溯**: `{DNA}`",
        "",
        "## 数据概览",
        "",
        f"| 指标 | 数量 |",
        f"|------|------|",
        f"| 点赞 | {点赞数} |",
        f"| 收藏 | {收藏数} |",
        f"| 评论/@ | {评论数} |",
        f"| 新增粉丝 | {粉丝数} |",
        f"| 合计 | {len(消息列表)} |",
        "",
        "## 消息明细",
        "",
    ]

    for 消息 in 消息列表:
        lines.append(单条消息模板(消息))

    lines.extend([
        "## 创作者保护声明",
        "",
        "本日报由龍魂系统自动生成，遵循《龍魂创作者保护协议 v1.0》：",
        "- 所有消息来源保留 DNA 追溯链，不可删除；",
        "- 如需引用本日报内容，请注明来源：UID9622 · 龍魂体系；",
        "- 禁止商业售卖或删除 DNA 追溯后声称原创。",
        "",
    ])

    return "\n".join(lines)


def 消息周报模板(开始日期: str, 结束日期: str, 日报列表: List[str], 用户标识: str = "UID9622") -> str:
    """
    CSDN 消息周报模板

    参数:
        开始日期: 周报开始日期
        结束日期: 周报结束日期
        日报列表: 日报内容字符串列表（或日期列表）
        用户标识: 默认 UID9622
    """
    DNA = 生成DNA("CSDN", "WEEKLY-REPORT")

    lines = [
        f"<!--{DNA}-->",
        "<!-- 君子协议: 本文件受龍魂DNA追溯保护 · CC BY-NC-SA 4.0 -->",
        "",
        f"# CSDN 消息周报 · {开始日期} ~ {结束日期}",
        "",
        f"**用户标识**: {用户标识}",
        f"**生成时间**: {datetime.now().isoformat()}",
        f"**DNA追溯**: `{DNA}`",
        "",
        "## 周期范围",
        "",
        f"- 开始: {开始日期}",
        f"- 结束: {结束日期}",
        f"- 包含日报: {len(日报列表)} 份",
        "",
        "## 日报索引",
        "",
    ]

    for i, 日报 in enumerate(日报列表, 1):
        lines.append(f"{i}. {日报}")

    lines.extend([
        "",
        "## 创作者保护声明",
        "",
        "本周报由龍魂系统自动汇总，遵循《龍魂创作者保护协议 v1.0》：",
        "- 所有子日报的 DNA 追溯链保持完整；",
        "- 引用需标注 UID9622 与来源链接；",
        "- 禁止删除来源链或商业盗用。",
        "",
    ])

    return "\n".join(lines)


def 文章引用声明模板(文章标题: str, 文章链接: str, 作者: str = "UID9622",
                     来源协议: str = "CC BY-NC-SA 4.0") -> str:
    """
    CSDN 文章引用声明模板

    用于他处引用 CSDN 文章时，规范标注来源与授权。
    """
    DNA = 生成DNA("CSDN", "CITATION")

    return f"""<!--{DNA}-->
<!-- 君子协议: 本文件受龍魂DNA追溯保护 -->

## 引用声明

本文引用自 CSDN 文章：

- **标题**: {文章标题}
- **作者**: {作者}
- **原文链接**: {文章链接}
- **授权协议**: {来源协议}
- **DNA追溯**: `{DNA}`

### 引用规则

1. 保留作者署名与原文链接；
2. 非商业用途可免费引用、分享、改编；
3. 商业用途需获得 UID9622 书面授权；
4. 禁止删除 DNA 追溯码后声称原创。

> 用了龍魂的东西，吭一声，留个名，不丢人。
""".strip()


