def 导出标准抬头(消息类型: str, 用户标识: str = "UID9622") -> str:
    """
    CSDN 导出文件标准 Markdown 抬头

    用于任何从 CSDN 导出的 Markdown 文件顶部。
    """
    DNA = 生成DNA("CSDN", f"EXPORT-{消息类型.replace('/', '').replace(' ', '-')}")

    return f"""<!--{DNA}-->
<!-- 君子协议: 本文件受龍魂DNA追溯保护 · CC BY-NC-SA 4.0 -->
<!-- 来源: CSDN · 用户: {用户标识} · 生成时间: {datetime.now().isoformat()} -->

# CSDN {消息类型} 导出

**DNA追溯**: `{DNA}`
**用户标识**: {用户标识}
**生成时间**: {datetime.now().isoformat()}

---

""".strip()


