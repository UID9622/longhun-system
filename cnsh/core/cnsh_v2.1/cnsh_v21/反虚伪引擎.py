# ---------- 检测函数 ----------
def 检测一级(文本: str, 词库: Optional[List[str]] = None) -> List[str]:
    """检测一级禁用词，触发即熔断。"""
    词库 = 词库 if 词库 is not None else 一级禁用词
    命中列表 = []
    for 词 in 词库:
        if 词 in 文本:
            命中列表.append(词)
    return 命中列表


def 检测二级(文本: str, 词库: Optional[List[str]] = None) -> List[str]:
    """检测二级禁用词，触发即标记。"""
    词库 = 词库 if 词库 is not None else 二级禁用词
    命中列表 = []
    for 词 in 词库:
        if 词 in 文本:
            命中列表.append(词)
    return 命中列表


def 检测煽情密度(文本: str, 词库: Optional[List[str]] = None) -> int:
    """统计煽情词出现次数。"""
    词库 = 词库 if 词库 is not None else 煽情词
    计数 = 0
    for 词 in 词库:
        计数 += 文本.count(词)
    return 计数


def 检测句子长度(文本: str) -> int:
    """统计句子数量（按。！？分割）。"""
    句数 = 0
    for 分隔符 in [".", "!", "?", "。", "！", "？"]:
        句数 += 文本.count(分隔符)
    if 句数 == 0 and len(文本.strip()) > 0:
        return 1
    return 句数


def 检测虚伪句式(文本: str, 词库: Optional[List[str]] = None) -> List[str]:
    """用正则检测虚伪句式模式。"""
    词库 = 词库 if 词库 is not None else 虚伪句式
    命中 = []
    for 模式 in 词库:
        if re.search(模式, 文本):
            命中.append(模式)
    return 命中


# ---------- 评分与简化 ----------
def 计算虚伪度(
    文本: str,
    一级词库: Optional[List[str]] = None,
    二级词库: Optional[List[str]] = None,
    煽情词库: Optional[List[str]] = None,
    虚伪句式库: Optional[List[str]] = None,
) -> int:
    """计算虚伪度评分（0-100）。"""
    一级词库 = 一级词库 if 一级词库 is not None else 一级禁用词
    二级词库 = 二级词库 if 二级词库 is not None else 二级禁用词
    煽情词库 = 煽情词库 if 煽情词库 is not None else 煽情词
    虚伪句式库 = 虚伪句式库 if 虚伪句式库 is not None else 虚伪句式

    分数 = 0

    # 一级禁用词：每个 +20 分
    一级命中 = 检测一级(文本, 一级词库)
    分数 += len(一级命中) * 20

    # 二级禁用词：每个 +10 分
    二级命中 = 检测二级(文本, 二级词库)
    分数 += len(二级命中) * 10

    # 煽情词：每个 +5 分
    分数 += 检测煽情密度(文本, 煽情词库) * 5

    # 虚伪句式：每个 +15 分
    分数 += len(检测虚伪句式(文本, 虚伪句式库)) * 15

    # 句子长度：超过 5 句，每多 1 句 +3 分
    句数 = 检测句子长度(文本)
    if 句数 > 5:
        分数 += (句数 - 5) * 3

    # 字数：超过 200 字，每多 50 字 +5 分
    字数 = len(文本)
    if 字数 > 200:
        分数 += int((字数 - 200) / 50) * 5

    return min(分数, 100)


def 自动简化(文本: str) -> str:
    """删掉废话和修饰，返回简化后的文本。"""
    结果 = 文本
    for 旧词, 新词 in 替换表.items():
        结果 = 结果.replace(旧词, 新词)

    # 删除所有感叹号（煽情标志）
    结果 = 结果.replace("！", "。")
    结果 = 结果.replace("!", "。")

    # 删除多余空格（保留单行换行作为语句/语义分隔）
    while "  " in 结果 or "\t" in 结果:
        结果 = 结果.replace("  ", " ")
        结果 = 结果.replace("\t", " ")

    # 如果结果过短，返回默认
    if len(结果.strip()) < 5:
        return "收到。说具体点。"

    return 结果.strip()


