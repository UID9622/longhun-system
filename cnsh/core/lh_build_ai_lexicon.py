def 写入_cs_kb(词条):
    conn = sqlite3.connect(str(CS_KB_DB))
    cur = conn.cursor()
    cur.execute('SELECT MAX(CAST(card_id AS INTEGER)) FROM cs_kb')
    start_id = (cur.fetchone()[0] or 0) + 1
    inserted = 0
    for i, e in enumerate(词条):
        cid = str(start_id + i)
        row = {
            "card_id": cid,
            "name": f"{e['term_en']} · {e['term_cn']} · {e['cnsh_name']}",
            "category": "AI行业话术",
            "subcategory": e["category"],
            "description": e["plain_explanation"],
            "core_formula": f"{e['term_en']} = {e['base_tech']}",
            "misconceptions": f"常被 hype 等级 {e['hype_level']}/5 夸大；真实底座是 {e['base_tech']}",
            "status": "已完成",
            "difficulty": "L2 进阶",
            "priority": "高优先级",
            "context_trigger": f"{e['term_en']} {e['term_cn']} {' '.join(e['related_terms'])}",
            "persona_route": json.dumps({"route": "AI 术语翻译官"}, ensure_ascii=False),
            "architecture_layer": "L2 语义层",
            "is_core": "是",
            "is_in_system": "是",
            "dr_wuxing_gong": _dr(i),
            "alpha_san yi": "",
            "short_dna": e["dna"],
            "ipa_abbr": e["term_en"],
            "tri_color_audit": "🟢概念🟡 hype🔴误用",
            "related_knowledge": ", ".join(e["related_terms"]),
            "source_ref": "AI 行业话术 · 龍文语义映射词典",
            "formula": "",
            "routing_params": json.dumps({
                "skill": "longhun-ai-lexicon",
                "action": "lookup",
                "term": e["term_en"],
            }, ensure_ascii=False),
            "py_example": f"# {e['term_en']} = {e['cnsh_name']}\n# 真实底座: {e['base_tech']}\n# 龍魂映射: {e['longwen_mapping']}",
        }
        cols = ", ".join(f'"{k}"' for k in row.keys())
        placeholders = ", ".join(["?"] * len(row))
        cur.execute(f"INSERT OR REPLACE INTO cs_kb ({cols}) VALUES ({placeholders})", tuple(row.values()))
        inserted += 1
    conn.commit()
    conn.close()
    return inserted, start_id


def 编入全局索引(路径列表):
    sys.path.insert(0, str(GLOBAL_INDEX_SERVICE.parent))
    import importlib.util
    spec = importlib.util.spec_from_file_location("global_index_service", GLOBAL_INDEX_SERVICE)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    cfg = mod.Config(mod.CONFIG_PATH)
    db = mod.Database(GLOBAL_INDEX_DB)
    rules = mod.ExclusionRules(cfg)
    extractor = mod.MediaExtractor(cfg)
    indexer = mod.Indexer(cfg, db, rules, extractor)
    root = str(HOME / "longhun-system")
    for p in 路径列表:
        indexer.index_file(Path(p), root, event_type="created")
    indexer.flush()
    return len(路径列表)


