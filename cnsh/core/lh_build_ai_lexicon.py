def _augment_entries():
    for i, e in enumerate(词条清单):
        e.setdefault("entry_id", f"AI-LEX-{i+1:03d}")
        e.setdefault("dna", _dna(e["term_en"]))
        e.setdefault("hype_badge", "🔥" * e["hype_level"] + "░" * (5 - e["hype_level"]))
    return 词条清单


def 写入_json(词条):
    KG_DIR.mkdir(parents=True, exist_ok=True)
    path = KG_DIR / "ai_buzzword_dict.json"
    path.write_text(json.dumps(词条, ensure_ascii=False, indent=2), encoding="utf-8")
    return path


