def 計算社區信任度(
    民生總積分: float,
    活躍分類數: int,
    社區調節因子: float = 1.0
) -> float:
    """
    計算社區信任度 Θ

    公式: Θ = (1 - e^(-α·S_total)) × (1 + β·D) × γ
    其中:
        α = 0.05 (靈敏度參數)
        β = 0.3  (多樣性權重)
        D = 有效行為類別數 / 5 (多樣性指數)
        γ = 社區調節因子 (0.8 ~ 1.0)

    Args:
        民生總積分: S_total, 所有有效行為加權和
        活躍分類數: 參與的行為分類數量 (1~5)
        社區調節因子: γ值, 默認1.0, 範圍[0.8, 1.0]

    Returns:
        社區信任度 Θ, 範圍 [0, 1.0]
    """
    α: float = 0.05
    β: float = 0.3
    D值: float = min(1.0, 活躍分類數 / 5.0)

    theta: float = (1.0 - math.exp(-α * 民生總積分)) * (1.0 + β * D值) * 社區調節因子

    return min(1.0, max(0.0, theta))


def 計算提案優先級(
    社區信任度: float,
    提案質量分: float,
    領域相關積分: float
) -> float:
    """
    計算提案優先級 P

    公式: P_j = Θ_j × Q_j × (1 + ln(1 + S_relevant))

    Args:
        社區信任度: Θ值, 提案人的社區信任度 [0, 1]
        提案質量分: Q值, 由社區評審團獨立評定 [0, 1]
        領域相關積分: S_relevant, 提案人在該領域的相關行為積分

    Returns:
        提案優先級 P值
    """
    return 社區信任度 * 提案質量分 * (1.0 + math.log(1.0 + 領域相關積分))


