def 時間衰減函數(年數: float) -> float:
    """
    時間衰減函數 T(t) = max(0.1, e^(-λt))
    半衰期 = 2年，λ = ln(2)/2 ≈ 0.347

    Args:
        年數: 距離行為發生的年數 (float)

    Returns:
        衰減後的時間係數 (float), 範圍 [0.1, 1.0]
    """
    λ: float = math.log(2) / 2.0  # ≈ 0.34657359
    return max(0.1, math.exp(-λ * 年數))


def 頻率調節因子(年均次數: int) -> float:
    """
    頻率調節因子 F(n) —— 防止刷分

    F(n) = 1.0               當 n ≤ 4
    F(n) = min(1.0, 2/√n)   當 n > 4

    Args:
        年均次數: 每年發生的次數 (int)

    Returns:
        頻率調節係數 (float), 範圍 [0, 1.0]
    """
    if 年均次數 <= 4:
        return 1.0
    return min(1.0, 2.0 / math.sqrt(年均次數))


def 民生熔斷檢查(行為代碼: str, 自願係數: float, 社區驗證係數: float) -> Tuple[bool, str]:
    """
    民生熔斷檢查 —— 判斷行為是否應被阻斷不計分

    熔斷規則:
    - V = 0 (強制行為) → 熔斷
    - C < 0.1 (自說自話) → 熔斷
    - 言論表達類 → 熔斷 (由調用方確保不傳入此類行為)

    Args:
        行為代碼: 行為分類代碼如 "B1"
        自願係數: V值
        社區驗證係數: C值

    Returns:
        (是否熔斷: bool, 原因: str)
    """
    if 自願係數 <= 0.0:
        return True, "🔴 熔斷：強制行為(V=0)，不計入民生行為"
    if 社區驗證係數 < 0.1:
        return True, "🔴 熔斷：無法驗證(C<0.1)，孤證不立"
    if 社區驗證係數 > 1.0 or 自願係數 > 1.0:
        return True, "🔴 熔斷：參數超出合法範圍"
    return False, "🟢 通過：符合民生行為記錄條件"


def 計算行為權重(
    基礎權重: float,
    自願係數: float,
    社區驗證係數: float,
    年數: float,
    年均次數: int,
    社區反響係數: float = 1.0
) -> 計算結果:
    """
    計算單項民生行為權重

    核心公式: W = B × V × C × T(t) × F(n) × R

    Args:
        基礎權重: B值, 行為分類表確定的基礎權重 (3~10)
        自願係數: V值, 0=強制, 1=完全自願
        社區驗證係數: C值, 0~1, 見證等級
        年數: 距離行為發生的年數
        年均次數: 每年發生次數
        社區反響係數: R值, 默認1.0, 範圍[0.8, 1.2]

    Returns:
        計算結果對象，包含主項/副項權重及熔斷信息
    """
    # 熔斷檢查
    是否熔斷, 熔斷原因 = 民生熔斷檢查("", 自願係數, 社區驗證係數)
    if 是否熔斷:
        return 計算結果(
            主項權重=0.0, 副項權重=0.0, 總權重=0.0,
            時間衰減值=0.0, 頻率調節值=0.0,
            是否熔斷=True, 熔斷原因=熔斷原因
        )

    # 計算時間衰減和頻率調節
    T值: float = 時間衰減函數(年數)
    F值: float = 頻率調節因子(年均次數)

    # 核心公式計算
    W: float = 基礎權重 * 自願係數 * 社區驗證係數 * T值 * F值 * 社區反響係數

    return 計算結果(
        主項權重=W,
        副項權重=0.0,
        總權重=W,
        時間衰減值=T值,
        頻率調節值=F值,
        是否熔斷=False,
        熔斷原因=熔斷原因
    )


