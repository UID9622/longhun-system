# 4. 熔断检测引擎
# ============================================================

class 红线熔断器:
    """CNSH 红线词组检测与熔断"""

    def __init__(self):
        self.索引 = 红线索引()
        self.级别顺序 = {
            "P0_伦理红线": 0,
            "P1_锁定红线": 1,
            "P2_收割红线": 2,
            "P3_复杂红线": 3,
        }

    def 检测(self, 文本: str) -> List[Dict]:
        """检测文本中的红线词组，返回命中列表（含本源追溯）"""
        命中列表 = []
        已命中本源 = set()
        原文本 = 文本
        规范化文本 = self.索引._规范化(文本)

        # 1. 精确匹配：遍历所有已知形式，检查是否出现在文本中
        for 形式, 本源词 in self.索引.形式到本源.items():
            if 本源词 in 已命中本源:
                continue

            # 中文形式：子串匹配
            if all('\u4e00' <= c <= '\u9fff' or c.isspace() or c.isdigit() for c in 形式 if c.isalnum()):
                if 形式 in 规范化文本:
                    命中列表.append(self._命中项(本源词, "精确匹配", 形式))
                    已命中本源.add(本源词)
                    continue

            # 英文/混合形式：词边界匹配
            escaped = re.escape(形式)
            pattern = rf'(?<![A-Za-z0-9_]){escaped}(?![A-Za-z0-9_])'
            if re.search(pattern, 规范化文本, flags=re.IGNORECASE):
                命中列表.append(self._命中项(本源词, "英文别名", 形式))
                已命中本源.add(本源词)

        return 命中列表

    def _命中项(self, 本源词: str, 类型: str, 命中形式: str) -> Dict:
        信息 = self.索引.本源映射[本源词]
        return {
            "红线词组": 本源词,
            "级别": 信息["级别"],
            "类型": 类型,
            "命中形式": 命中形式,
            "根概念": 信息.get("根概念", ""),
            "定义": 信息.get("定义", ""),
            "来源DNA": 信息.get("来源DNA", ""),
        }

    def 熔断检查(self, 文本: str, 上下文: str = "") -> Dict:
        """
        执行完整熔断检查。
        返回：{触发: bool, 最高级别: str, 命中: list, DNA: str}
        """
        命中 = self.检测(文本)
        if not 命中:
            return {
                "触发": False,
                "最高级别": None,
                "命中": [],
                "DNA": 生成DNA("REDLINE-CHECK", "PASS"),
            }

        最高级别 = min(命中, key=lambda x: self.级别顺序.get(x["级别"], 99))["级别"]

        return {
            "触发": True,
            "最高级别": 最高级别,
            "命中": 命中,
            "DNA": 生成DNA("REDLINE-CHECK", "TRIP"),
        }

    def 报告(self, 结果: Dict) -> str:
        """生成人类可读的红线熔断报告"""
        if not 结果["触发"]:
            return "🟢 红线扫描通过，未命中任何红线词组。"

        lines = [
            f"🔴 红线熔断触发 · 最高级别：{结果['最高级别']}",
            f"   {结果['DNA']}",
            "   命中明细：",
        ]
        for item in 结果["命中"]:
            lines.append(f"   · [{item['级别']}] {item['红线词组']} ({item['类型']})")
            lines.append(f"     命中形式：{item['命中形式']}")
            lines.append(f"     根概念：{item['根概念']}")
            lines.append(f"     定义：{item['定义']}")
            lines.append(f"     来源：{item['来源DNA']}")
        lines.append("   龍魂系统 AI 拒绝执行/输出上述红线内容。")
        return "\n".join(lines)


