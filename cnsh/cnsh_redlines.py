def main():
    if len(sys.argv) < 2:
        print(__doc__)
        print("\n用法：")
        print("  python3 cnsh_redlines.py \"这段文本包含生态锁定和订阅制陷阱\"")
        print("  python3 cnsh_redlines.py --scan-file article.txt")
        print("  python3 cnsh_redlines.py --list")
        print("  python3 cnsh_redlines.py --trace \"ecosystem lock-in\"")
        return

    熔断器 = 红线熔断器()

    if sys.argv[1] == "--list":
        print("🐉 龍魂 CNSH 红线词组清单（含本源追溯）")
        print("-" * 40)
        for 级别, 词组列表 in 红线分级.items():
            print(f"\n【{级别}】")
            for 词 in 词组列表:
                信息 = 红线本源[词]
                print(f"  · {词}")
                print(f"    根概念：{信息['根概念']}")
                print(f"    来源：{信息['来源DNA']}")
        return

    if sys.argv[1] == "--scan-file":
        if len(sys.argv) < 3:
            print("❌ 请提供文件路径")
            return
        path = Path(sys.argv[2])
        if not path.exists():
            print(f"❌ 文件不存在: {path}")
            return
        with open(path, "r", encoding="utf-8") as f:
            文本 = f.read()
        结果 = 熔断器.熔断检查(文本)
        print(熔断器.报告(结果))
        return

    if sys.argv[1] == "--trace":
        if len(sys.argv) < 3:
            print("❌ 请提供要追溯的词或形式")
            return
        形式 = sys.argv[2]
        本源 = 熔断器.索引.查找本源(形式)
        if 本源:
            信息 = 红线本源[本源]
            print(f"🐉 本源追溯结果")
            print(f"   表面形式：{形式}")
            print(f"   本源词组：{本源}")
            print(f"   级别：{信息['级别']}")
            print(f"   根概念：{信息['根概念']}")
            print(f"   定义：{信息['定义']}")
            print(f"   来源 DNA：{信息['来源DNA']}")
        else:
            print(f"🟡 未找到 '{形式}' 的本源记录")
        return

    文本 = sys.argv[1]
    结果 = 熔断器.熔断检查(文本)
    print(熔断器.报告(结果))


if __name__ == "__main__":
    main()
