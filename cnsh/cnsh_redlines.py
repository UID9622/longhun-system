# 3. 构建检测索引
# ============================================================

class 红线索引:
    """构建从表面形式到本源红线的映射"""

    def __init__(self):
        self.本源映射: Dict[str, Dict] = 红线本源
        self.形式到本源: Dict[str, str] = {}
        self.已处理形式: Set[str] = set()
        self._构建索引()

    def _规范化(self, 文本: str) -> str:
        """统一全角半角、空格、常见填充词"""
        文本 = 文本.lower()
        # 全角转半角（仅数字字母区域）
        结果 = []
        for c in 文本:
            code = ord(c)
            if 0xFF10 <= code <= 0xFF19:  # 全角数字
                结果.append(chr(code - 0xFEE0))
            elif 0xFF21 <= code <= 0xFF3A or 0xFF41 <= code <= 0xFF5A:  # 全角字母
                结果.append(chr(code - 0xFEE0))
            else:
                结果.append(c)
        文本 = "".join(结果)
        # 统一空白与常见分隔符
        文本 = re.sub(r'[\s\-·•]+', ' ', 文本)
        # 去除无意义填充词（中文）
        文本 = re.sub(r'[的|了|地|得|之]', '', 文本)
        # 去除中文字符之间的空格（防绕：生 态 锁 定 → 生态锁定）
        文本 = re.sub(r'(?<=[\u4e00-\u9fff])\s+(?=[\u4e00-\u9fff])', '', 文本)
        return 文本.strip()

    def _添加形式(self, 形式: str, 本源: str):
        形式 = self._规范化(形式)
        if not 形式 or 形式 in self.已处理形式:
            return
        self.形式到本源[形式] = 本源
        self.已处理形式.add(形式)

    def _构建索引(self):
        for 本源词, 信息 in self.本源映射.items():
            # 1. 本源词本身
            self._添加形式(本源词, 本源词)

            # 2. 语义等价
            for 等价 in 信息.get("语义等价", []):
                self._添加形式(等价, 本源词)

            # 3. 多语言别名
            for 语言, 别名列表 in 信息.items():
                if 语言 in ("级别", "定义", "根概念", "来源DNA", "语义等价"):
                    continue
                for 别名 in 别名列表:
                    self._添加形式(别名, 本源词)

    def 查找本源(self, 文本片段: str) -> Optional[str]:
        """给定文本片段，返回对应的本源词"""
        规范化 = self._规范化(文本片段)
        return self.形式到本源.get(规范化)


