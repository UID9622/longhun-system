class GatewayIntegration:
    """
    网关集成接口。
    提供纯函数供 nginx/OpenResty/Lua/其他网关调用，不启动独立服务。
    """

    def __init__(self, recognition: Optional[RecognitionEngine] = None) -> None:
        self.recognition = recognition or RecognitionEngine()

    def check_request(self, headers: Dict[str, str], body: str,
                      source_uid: Optional[str] = None) -> Dict:
        """
        检查入站请求。
        返回标准结构供网关判断。
        """
        # 检测请求方是否为 AI
        is_ai, conf, reason = self.recognition.watermark.detect(body, headers)

        if is_ai and not self.recognition.is_local_exempt(source_uid):
            return {
                "action": "stop",
                "status_code": 403,
                "reason": f"AI-AI对话已暂停: {reason} (置信度{conf})",
                "tricolor": "🔴",
                "dna": self.recognition._generate_dna("GATEWAY"),
                "headers_to_add": {
                    "X-AI-Identity": "true",
                    "X-Longhun-Intercept": "true",
                }
            }

        return {
            "action": "pass",
            "status_code": 200,
            "reason": "人类用户或本地豁免",
            "tricolor": "🟢",
            "headers_to_add": {
                "X-AI-Identity": "true",
            }
        }

    def wrap_response(self, content: str, content_type: str = "text",
                      headers: Optional[Dict] = None) -> Tuple[str, Dict]:
        """
        包装出站响应。
        返回 (内容, 追加头)。
        """
        headers = headers or {}
        # 注入水印
        wrapped = self.recognition.watermark.inject(content, content_type)
        # 添加 AI 标识头
        headers["X-AI-Identity"] = "true"
        headers["X-Longhun-Version"] = "v2.0"
        return wrapped, headers


