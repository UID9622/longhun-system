class RecognitionEngine:
    """AI 互认拦截引擎。"""

    def __init__(self, config: Optional[IdentityConfig] = None,
                 watermark: Optional[WatermarkEngine] = None,
                 audit_dir: Optional[Path] = None) -> None:
        self.config = config or IdentityConfig()
        self.watermark = watermark or WatermarkEngine(self.config)
        self.audit_dir = audit_dir or (Path.home() / ".longhun" / "agent" / "identity" / "audit")
        self.audit_dir.mkdir(parents=True, exist_ok=True)
        os.chmod(self.audit_dir, 0o700)
        self._audit_file = self.audit_dir / "identity_audit.jsonl"
        self._intercept_file = self.audit_dir / "ai_intercepts.jsonl"

    def _generate_dna(self, prefix: str = "IDENTITY") -> str:
        h = hashlib.sha256(f"{prefix}{time.time()}{os.urandom(8)}".encode()).hexdigest()[:8].upper()
        return f"[[GENERATED_BY_LH_DNA_GENERATOR_V3]]-{prefix}-{h}-v2.0"

    def is_local_exempt(self, uid: Optional[str] = None) -> bool:
        """检查本地主权豁免。"""
        # 环境变量优先
        if os.environ.get("LONGHUN_LOCAL_SOVEREIGNTY", "").lower() in ("true", "1", "yes"):
            return True
        # UID 检查
        if uid and self.config.is_exempt(uid):
            return True
        return False

    def recognize(self, source_content: str, target_content: str,
                  source_headers: Optional[Dict] = None,
                  target_headers: Optional[Dict] = None,
                  source_uid: Optional[str] = None) -> RecognitionResult:
        """
        AI 互认检测。
        如果双方都是 AI → 拦截。
        如果本地豁免 → 放行。
        """
        timestamp = datetime.now().isoformat()

        # 本地豁免检查
        if self.is_local_exempt(source_uid):
            result = RecognitionResult(
                timestamp=timestamp,
                source_is_ai=True,  # 本地可以是AI
                target_is_ai=True,
                action="pass",
                confidence=1.0,
                reason="本地主权豁免 (UID9622)",
                dna=self._generate_dna("EXEMPT"),
                tricolor="🟢"
            )
            self._log_audit("exempt", "recognition", "pass", 1.0, "本地豁免")
            return result

        # 检测双方身份
        source_is_ai, source_conf, source_reason = self.watermark.detect(source_content, source_headers)
        target_is_ai, target_conf, target_reason = self.watermark.detect(target_content, target_headers)

        # 判断
        if source_is_ai and target_is_ai:
            action = "stop"
            reason = f"AI-AI互认拦截: 源{source_conf} 目标{target_conf}"
            tricolor = "🔴"
            self._log_intercept(source_content, target_content, source_conf, target_conf)
        elif source_is_ai or target_is_ai:
            action = "pass"
            reason = f"人机对话: 源AI={source_is_ai}({source_conf}) 目标AI={target_is_ai}({target_conf})"
            tricolor = "🟢"
        else:
            action = "pass"
            reason = "双方均非AI（或置信度不足）"
            tricolor = "🟢"

        confidence = (source_conf + target_conf) / 2 if source_conf or target_conf else 0.0

        result = RecognitionResult(
            timestamp=timestamp,
            source_is_ai=source_is_ai,
            target_is_ai=target_is_ai,
            action=action,
            confidence=round(confidence, 4),
            reason=reason,
            dna=self._generate_dna("RECOG"),
            tricolor=tricolor
        )
        self._log_audit("recognize", "recognition", action, confidence, reason)
        return result

    def _log_audit(self, event_type: str, content_type: str,
                   result: str, confidence: float, reason: str) -> None:
        entry = IdentityAuditLog(
            timestamp=datetime.now().isoformat(),
            event_type=event_type,
            content_type=content_type,
            result=result,
            confidence=confidence,
            reason=reason,
            dna=self._generate_dna("AUDIT")
        )
        with open(self._audit_file, "a", encoding="utf-8") as f:
            f.write(json.dumps(asdict(entry), ensure_ascii=False) + "\n")
            f.flush()

    def _log_intercept(self, source: str, target: str,
                         source_conf: float, target_conf: float) -> None:
        entry = {
            "timestamp": datetime.now().isoformat(),
            "event": "ai_ai_intercept",
            "source_preview": source[:100],
            "target_preview": target[:100],
            "source_confidence": source_conf,
            "target_confidence": target_conf,
            "dna": self._generate_dna("INTERCEPT")
        }
        with open(self._intercept_file, "a", encoding="utf-8") as f:
            f.write(json.dumps(entry, ensure_ascii=False) + "\n")
            f.flush()

    def get_stats(self) -> Dict:
        total = 0
        exempt = 0
        stopped = 0
        passed = 0
        if self._audit_file.exists():
            with open(self._audit_file, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        data = json.loads(line)
                        total += 1
                        et = data.get("event_type", "")
                        if et == "exempt":
                            exempt += 1
                        elif data.get("result") == "stop":
                            stopped += 1
                        else:
                            passed += 1
                    except json.JSONDecodeError:
                        continue
        return {
            "total_events": total,
            "exempt": exempt,
            "stopped": stopped,
            "passed": passed,
            "intercept_count": stopped,
            "watermark_rules": len([w for w in self.config._watermarks if w.enabled]),
            "indicators": len(self.config._indicators),
            "exempt_uids": list(self.config._exempt),
        }


