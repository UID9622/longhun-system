@dataclass
class WatermarkRule:
    """水印规则。"""
    content_type: str       # text / code / image / audio / video / api
    prefix: str = ""        # 内容前缀
    suffix: str = ""        # 内容后缀
    header_name: str = ""   # HTTP 头名
    header_value: str = ""  # HTTP 头值
    comment: str = ""       # 代码注释
    enabled: bool = True


@dataclass
class AIIndicator:
    """AI 检测指标。"""
    pattern: str
    weight: float           # 置信度权重
    description: str
    location: str = "any"   # any / prefix / header / metadata


@dataclass
class RecognitionResult:
    """互认检测结果。"""
    timestamp: str
    source_is_ai: bool
    target_is_ai: bool
    action: str             # pass / stop / audit
    confidence: float       # 0-1
    reason: str
    dna: str
    tricolor: str = "🟢"

    def to_dict(self) -> Dict:
        return asdict(self)


@dataclass
class IdentityAuditLog:
    """身份审计日志。"""
    timestamp: str
    event_type: str         # inject / detect / intercept / exempt
    content_type: str
    result: str
    confidence: float
    reason: str
    dna: str



