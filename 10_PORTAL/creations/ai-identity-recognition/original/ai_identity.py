# 2. 水印引擎
# ═══════════════════════════════════════════════════════════════════════════════

class WatermarkEngine:
    """AI 标识水印注入与检测引擎。"""

    def __init__(self, config: Optional[IdentityConfig] = None) -> None:
        self.config = config or IdentityConfig()

    def inject(self, content: str, content_type: str = "text",
               skip_if_present: bool = True) -> str:
        """注入 AI 标识水印。"""
        rule = self.config.get_watermark(content_type)
        if not rule:
            return content

        # 检查是否已有标识（避免重复）
        if skip_if_present and self._has_watermark(content, content_type):
            return content

        if content_type == "text":
            return f"{rule.prefix} {content}"
        elif content_type == "code":
            return f"{rule.comment}\n{content}"
        elif content_type == "api":
            # API 返回的是 HTTP 头字典，这里简化处理
            return content  # 实际由网关层注入头
        elif content_type in ("image", "video"):
            return content  # 图像/视频水印需外部工具处理
        elif content_type == "audio":
            return f"{rule.prefix} {content}"
        return content

    def _has_watermark(self, content: str, content_type: str) -> bool:
        """检查是否已有水印。"""
        rule = self.config.get_watermark(content_type)
        if not rule:
            return False
        if rule.prefix and content.startswith(rule.prefix):
            return True
        if rule.comment and rule.comment in content:
            return True
        return False

    def detect(self, content: str, headers: Optional[Dict[str, str]] = None) -> Tuple[bool, float, str]:
        """检测内容是否为 AI 生成。返回 (是否AI, 置信度, 原因)。"""
        confidence = 0.0
        reasons: List[str] = []

        # 文本/内容检测
        for indicator in self.config._indicators:
            try:
                if re.search(indicator.pattern, content, re.IGNORECASE):
                    confidence += indicator.weight
                    reasons.append(indicator.description)
            except re.error:
                continue

        # HTTP 头检测
        if headers:
            for indicator in self.config._indicators:
                if indicator.location == "header":
                    for k, v in headers.items():
                        header_str = f"{k}: {v}"
                        try:
                            if re.search(indicator.pattern, header_str, re.IGNORECASE):
                                confidence += indicator.weight
                                reasons.append(f"Header {indicator.description}")
                        except re.error:
                            continue

        # 归一化置信度到 0-1
        confidence = min(1.0, confidence)
        is_ai = confidence >= 0.5
        reason = "; ".join(reasons) if reasons else "无AI标识"
        return is_ai, round(confidence, 4), reason

    def strip(self, content: str, content_type: str = "text") -> str:
        """移除水印（仅本地测试使用）。"""
        rule = self.config.get_watermark(content_type)
        if not rule:
            return content
        if rule.prefix and content.startswith(rule.prefix):
            content = content[len(rule.prefix):].strip()
        if rule.comment:
            content = content.replace(rule.comment + "\n", "")
            content = content.replace(rule.comment, "")
        return content


