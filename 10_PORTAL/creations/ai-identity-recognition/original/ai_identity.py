class IdentityConfig:
    """身份标识配置管理器。"""

    DEFAULT_WATERMARKS: List[WatermarkRule] = [
        WatermarkRule("text", prefix="[AI]", enabled=True),
        WatermarkRule("code", comment="// AI-Generated", enabled=True),
        WatermarkRule("api", header_name="X-AI-Identity", header_value="true", enabled=True),
        WatermarkRule("api", header_name="X-Longhun-DNA", header_value="", enabled=True),
        WatermarkRule("image", comment="AI", enabled=True),
        WatermarkRule("audio", prefix="我是AI助手。", enabled=True),
        WatermarkRule("video", comment="AI", enabled=True),
    ]

    DEFAULT_INDICATORS: List[AIIndicator] = [
        AIIndicator(r'^\[AI\]', 0.9, "AI文字前缀", "prefix"),
        AIIndicator(r'^🤖', 0.9, "AI机器人表情", "prefix"),
        AIIndicator(r'^🧠', 0.85, "AI大脑表情", "prefix"),
        AIIndicator(r'我是AI', 0.8, "AI自称", "any"),
        AIIndicator(r'AI助手', 0.8, "AI助手自称", "any"),
        AIIndicator(r'龙魂AI', 0.85, "龙魂AI标识", "any"),
        AIIndicator(r'X-AI-Identity:\s*true', 0.95, "AI身份头", "header"),
        AIIndicator(r'AI-Generated', 0.9, "AI生成注释", "any"),
        AIIndicator(r'generated by ai', 0.85, "AI生成声明", "any"),
    ]

    def __init__(self, config_dir: Optional[Path] = None) -> None:
        self.config_dir = config_dir or (Path.home() / ".longhun" / "agent" / "identity")
        self.config_dir.mkdir(parents=True, exist_ok=True)
        os.chmod(self.config_dir, 0o700)
        self.watermarks_file = self.config_dir / "watermarks.json"
        self.indicators_file = self.config_dir / "indicators.json"
        self.exempt_file = self.config_dir / "exempt_list.json"
        self._watermarks = self._load_watermarks()
        self._indicators = self._load_indicators()
        self._exempt: Set[str] = self._load_exempt()

    def _load_watermarks(self) -> List[WatermarkRule]:
        if self.watermarks_file.exists():
            try:
                with open(self.watermarks_file, "r", encoding="utf-8") as f:
                    data = json.load(f)
                return [WatermarkRule(**w) for w in data.get("watermarks", [])]
            except Exception as exc:
                logging.warning("水印配置加载失败: %s", exc)
        return self.DEFAULT_WATERMARKS[:]

    def _load_indicators(self) -> List[AIIndicator]:
        if self.indicators_file.exists():
            try:
                with open(self.indicators_file, "r", encoding="utf-8") as f:
                    data = json.load(f)
                return [AIIndicator(**i) for i in data.get("indicators", [])]
            except Exception as exc:
                logging.warning("指标配置加载失败: %s", exc)
        return self.DEFAULT_INDICATORS[:]

    def _load_exempt(self) -> Set[str]:
        if self.exempt_file.exists():
            try:
                with open(self.exempt_file, "r", encoding="utf-8") as f:
                    data = json.load(f)
                return set(data.get("exempt_uids", []))
            except Exception as exc:
                logging.warning("豁免列表加载失败: %s", exc)
        return {OWNER_UID}  # 默认豁免 UID9622

    def save(self) -> None:
        for path, data in (
            (self.watermarks_file, {"watermarks": [asdict(w) for w in self._watermarks]}),
            (self.indicators_file, {"indicators": [asdict(i) for i in self._indicators]}),
            (self.exempt_file, {"exempt_uids": list(self._exempt)}),
        ):
            path.parent.mkdir(parents=True, exist_ok=True)
            tmp = path.with_suffix(".tmp")
            with open(tmp, "w", encoding="utf-8") as f:
                json.dump(data, f, indent=2, ensure_ascii=False)
                f.flush()
                os.fsync(f.fileno())
            os.replace(tmp, path)
            os.chmod(path, 0o600)

    def get_watermark(self, content_type: str) -> Optional[WatermarkRule]:
        for w in self._watermarks:
            if w.content_type == content_type and w.enabled:
                return w
        return None

    def is_exempt(self, uid: str) -> bool:
        return uid in self._exempt

    def add_exempt(self, uid: str) -> None:
        self._exempt.add(uid)
        self.save()

    def remove_exempt(self, uid: str) -> None:
        self._exempt.discard(uid)
        self.save()


