def 數字轉卦名(數值):
    """
    🟢 合規：數字(0-63)轉卦名
    【定理 T18】存在雙射 f: {0,..,63} → 64卦
    【輸入】數值 0-63
    【返回】卦名字符串
    """
    if 0 <= 數值 < 64:
        return 六十四卦名表[數值]
    return None


def 卦名轉數字(卦名):
    """
    🟢 合規：卦名轉數字(0-63)
    【定理 T18】逆映射 f⁻¹: 64卦 → {0,..,63}
    """
    try:
        return 六十四卦名表.index(卦名)
    except ValueError:
        return None


def 數字轉六爻(數值):
    """
    🟢 合規：數字轉6位二進制爻象（自下而上）
    【定理】6位二進制可表示64種狀態（2⁶=64）
    【返回】6元組，每個元素為0(陰爻)或1(陽爻)
    """
    if not (0 <= 數值 < 64):
        return None
    爻列表 = []
    臨時值 = 數值
    for _ in range(6):
        爻列表.append(臨時值 % 2)
        臨時值 //= 2
    return tuple(爻列表)


def 六爻轉數字(爻元組):
    """
    🟢 合規：6位二進制爻象轉數字
    【輸入】6元組 (自下而上)
    """
    數值 = 0
    for 索引, 爻 in enumerate(爻元組):
        數值 += 爻 * (2 ** 索引)
    return 數值


def 計算數字根(數值):
    """
    🟢 合規：計算數字根（與洛書矩陣模組一致）
    【定理 T10】dr(n) = 1 + (n-1) % 9
    """
    if 數值 <= 0:
        return 0
    return 1 + (數值 - 1) % 9


def 分析六十四卦數字根分佈():
    """
    🟢 合規：分析64卦索引(0-63)的數字根分佈
    【定理 T19】64卦數字根分佈應與369定理吻合
    【說明】索引0對應卦序1（傳統卦序），使用索引+1計算
    【返回】分佈統計字典
    """
    分佈 = {根: [] for 根 in range(1, 10)}

    for 索引 in range(64):
        卦序 = 索引 + 1  # 卦序從1開始
        根 = 計算數字根(卦序)
        卦名 = 數字轉卦名(索引)
        分佈[根].append({"卦序": 卦序, "卦名": 卦名})

    return 分佈


