def 驗證雙射性():
    """
    🔵 安全：驗證0-63與64卦之間的雙射關係
    【驗證】
      1. 單射：不同的數映射到不同的卦
      2. 滿射：每個卦都有對應的數
    【返回】(是否雙射, 詳細信息)
    """
    # 驗證單射（一對一）
    卦名集合 = set()
    單射通過 = True
    for 索引 in range(64):
        卦名 = 數字轉卦名(索引)
        if 卦名 in 卦名集合:
            單射通過 = False
        卦名集合.add(卦名)

    # 驗證滿射（覆蓋全部64卦）
    滿射通過 = len(卦名集合) == 64

    # 驗證逆映射
    逆映射通過 = True
    for 索引 in range(64):
        卦名 = 數字轉卦名(索引)
        逆索引 = 卦名轉數字(卦名)
        if 逆索引 != 索引:
            逆映射通過 = False

    return 單射通過 and 滿射通過 and 逆映射通過, {
        "單射": 單射通過,
        "滿射": 滿射通過,
        "逆映射": 逆映射通過,
    }


def 獲取卦的先天屬性(卦名):
    """
    🟢 合規：獲取卦的先天八卦屬性
    【輸入】卦名
    【返回】屬性字典
    """
    索引 = 卦名轉數字(卦名)
    if 索引 is None:
        return None

    爻象 = 數字轉六爻(索引)
    # 上卦（外卦）為高三位，下卦（內卦）為低三位
    下卦爻 = 爻象[0:3]
    上卦爻 = 爻象[3:6]

    # 計算上卦和下卦的八卦索引
    下卦索引 = sum(爻 * (2 ** i) for i, 爻 in enumerate(下卦爻))
    上卦索引 = sum(爻 * (2 ** i) for i, 爻 in enumerate(上卦爻))

    # 八卦名稱（按先天序：乾兌離震巽坎艮坤 對應二進制 111 110 101 100 011 010 001 000）
    八卦名表 = ["坤", "艮", "坎", "巽", "震", "離", "兌", "乾"]

    下卦名 = 八卦名表[下卦索引]
    上卦名 = 八卦名表[上卦索引]

    return {
        "卦名": 卦名,
        "索引": 索引,
        "卦序": 索引 + 1,
        "爻象": 爻象,
        "上卦": 上卦名,
        "下卦": 下卦名,
        "上卦符號": 八卦符號.get(上卦名, ""),
        "下卦符號": 八卦符號.get(下卦名, ""),
        "數字根": 計算數字根(索引 + 1),
    }


