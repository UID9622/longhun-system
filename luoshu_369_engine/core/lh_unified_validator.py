def 驗證幻方(矩陣, 期望和):
    """🟢 合規：幻方驗證"""
    維度 = len(矩陣)
    行之和 = [sum(矩陣[行][列] for 列 in range(維度)) for 行 in range(維度)]
    列之和 = [sum(矩陣[行][列] for 行 in range(維度)) for 列 in range(維度)]
    主對角 = sum(矩陣[索引][索引] for 索引 in range(維度))
    副對角 = sum(矩陣[索引][維度 - 1 - 索引] for 索引 in range(維度))
    所有和 = 行之和 + 列之和 + [主對角, 副對角]
    是否幻方 = all(和 == 期望和 for 和 in 所有和)
    return 是否幻方, {
        "行之和": 行之和, "列之和": 列之和,
        "主對角線和": 主對角, "副對角線和": 副對角
    }


