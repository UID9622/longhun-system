def 數字根(數值):
    """🟢 合規：數字根函數"""
    if 數值 <= 0:
        return 0
    return 1 + (數值 - 1) % 9


def 迭代數字根(數值, 最大迭代次數=100):
    """🟢 合規：迭代數字根"""
    路徑 = [數值]
    當前值 = 數值
    for _ in range(最大迭代次數):
        if 當前值 <= 9:
            break
        當前值 = 數字根(當前值)
        路徑.append(當前值)
    return 當前值, 路徑


