# 🔴 心猿意马动力系统模型
# ═══════════════════════════════════════════════════════════════
@dataclass
class 心猿意马状态:
    """
    🔴 心猿(孙悟空)与意马(白龍马)的耦合状态
    
    数学模型:
        dx₁/dt = -α·x₁ + β·x₂·(1 - x₁²) + γ·外魔扰动
        dx₂/dt = -δ·x₂ + ε·x₁·(1 - x₂²) + ζ·唐僧约束
    
    其中 x₁ = 心猿状态(躁动←→收敛), x₂ = 意马状态(狂奔←→平稳)
    """
    心猿状态: float = 1.0   # x₁ ∈ [-1, 1], 1=完全躁动, -1=完全收敛
    意马状态: float = 1.0   # x₂ ∈ [-1, 1], 1=狂奔, -1=平稳
    
    # 🟡 动力系统参数
    收敛系数_心猿: float = 0.15   # α: 心猿自然收敛率
    收敛系数_意马: float = 0.12   # δ: 意马自然收敛率
    耦合强度: float = 0.08        # β, ε: 心猿-意马互相影响
    外魔扰动强度: float = 0.20    # γ: 妖魔扰动
    紧箍咒强度: float = 0.25      # ζ: 唐僧/紧箍咒约束
    
    def 演化一步(self, 外魔扰动: float = 0.0, 紧箍咒激活: bool = False) -> '心猿意马状态':
        """
        🔴 心猿意马状态演化一步 (Euler离散化)
        
        返回值: 新的状态对象
        """
        x1, x2 = self.心猿状态, self.意马状态
        α, δ = self.收敛系数_心猿, self.收敛系数_意马
        βε = self.耦合强度
        γ = self.外魔扰动强度
        ζ = self.紧箍咒强度 if 紧箍咒激活 else 0.0
        
        # 心猿方程: dx₁/dt = -α·x₁ + β·x₂·(1-x₁²) + γ·外魔
        dx1 = -α * x1 + βε * x2 * (1 - x1**2) + γ * 外魔扰动 - ζ * x1
        
        # 意马方程: dx₂/dt = -δ·x₂ + ε·x₁·(1-x₂²) + ζ·约束
        dx2 = -δ * x2 + βε * x1 * (1 - x2**2) + ζ * (0.5 - x2)
        
        # Euler 积分 (步长 0.1)
        dt = 0.1
        新x1 = np.clip(x1 + dx1 * dt, -1.0, 1.0)
        新x2 = np.clip(x2 + dx2 * dt, -1.0, 1.0)
        
        return 心猿意马状态(
            心猿状态=新x1,
            意马状态=新x2,
            收敛系数_心猿=self.收敛系数_心猿,
            收敛系数_意马=self.收敛系数_意马,
            耦合强度=self.耦合强度,
            外魔扰动强度=self.外魔扰动强度,
            紧箍咒强度=self.紧箍咒强度,
        )
    
    def 收敛度(self) -> float:
        """
        🟢 计算当前状态的收敛度 (0=完全躁动, 1=完全收敛)
        
        369意义: 收敛度趋近 0.618 (黄金分割) 时，系统处于最优修行状态
        """
        return (1.0 - abs(self.心猿状态)) * 0.5 + (1.0 - abs(self.意马状态)) * 0.5
    
    def __repr__(self) -> str:
        return f"心猿意马(心猿={self.心猿状态:+.3f}, 意马={self.意马状态:+.3f}, 收敛度={self.收敛度():.3f})"


