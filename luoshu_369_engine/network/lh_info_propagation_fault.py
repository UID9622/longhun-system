# 🔴 传播延迟与信息完整性验证
# ═══════════════════════════════════════════════════════════════
class 传播延迟验证器:
    """
    🔴 验证传播延迟与信息完整性的关系
    
    核心发现: 在369框架下，延迟与完整性满足:
        完整性 = 1 / (1 + k·延迟) · 369修正因子
    """
    
    def __init__(self):
        self.测量记录: List[Dict] = []
    
    def 测量(self, 原始信息: 信息包, 接收信息: Optional[信息包], 实际延迟: float) -> Dict[str, Any]:
        """
        🔴 测量一次传播的延迟与完整性
        """
        if 接收信息 is None:
            完整性 = 0.0
            信息保持率 = 0.0
        else:
            完整性 = 接收信息.完整性评分
            信息保持率 = 接收信息.熵值 / max(原始信息.熵值, 1e-10)
        
        记录 = {
            '标识': 原始信息.标识,
            '延迟_秒': 实际延迟,
            '完整性': 完整性,
            '信息保持率': 信息保持率,
            '原始熵': 原始信息.熵值,
        }
        self.测量记录.append(记录)
        return 记录
    
    def 完整性报告(self) -> Dict[str, Any]:
        """
        🟢 生成完整性统计报告
        """
        if not self.测量记录:
            return {}
        
        完整记录 = [r for r in self.测量记录 if r['完整性'] > 0]
        丢失记录 = [r for r in self.测量记录 if r['完整性'] == 0]
        
        return {
            '总测量数': len(self.测量记录),
            '成功接收': len(完整记录),
            '丢失数': len(丢失记录),
            '平均延迟': np.mean([r['延迟_秒'] for r in self.测量记录]),
            '平均完整性': np.mean([r['完整性'] for r in 完整记录]) if 完整记录 else 0,
            '平均信息保持率': np.mean([r['信息保持率'] for r in 完整记录]) if 完整记录 else 0,
        }


