class 传播系统:
    """
    🟢 完整的三层传播系统
    
    信源层 → 传播层 → 接收层
        ↓         ↓         ↓
      龍芯AI验证 ← 实时监控 ← 反馈
    """
    
    def __init__(self, 截断率: float = 0.10):
        self.信源 = 信源层()
        self.传播 = 传播层(截断率=截断率)
        self.接收 = 接收层()
        self.龍芯验证 = 龍芯AI验证系统()
        self.延迟验证 = 传播延迟验证器()
    
    def 发送(self, 自定义内容: str = "") -> Optional[信息包]:
        """
        🔴 完整的三层传播流程
        
        流程: 信源产生 → 传播层传递 → 接收层消费 → 龍芯验证
        """
        # 信源层: 产生信息
        信息 = self.信源.产生信息(自定义内容)
        
        # 龍芯AI预验证
        预验证结果 = self.龍芯验证.实时验证(信息)
        
        # 传播层: 传递信息 (可能发生截断)
        传播后信息 = self.传播.接收(信息)
        
        # 接收层: 消费信息
        接收后信息 = None
        if 传播后信息 is not None:
            接收后信息 = self.接收.接收(传播后信息)
        
        # 延迟测量
        self.延迟验证.测量(信息, 接收后信息, 0.0)
        
        return 接收后信息
    
    def 批量发送(self, 数量: int) -> Dict[str, Any]:
        """
        🟢 批量发送测试
        """
        成功 = 0
        失败 = 0
        for i in range(数量):
            结果 = self.发送(f"测试信息-{i:03d}-龍魂洛书369")
            if 结果 is not None:
                成功 += 1
            else:
                失败 += 1
        
        return {
            '发送总数': 数量,
            '成功接收': 成功,
            '丢失数': 失败,
            '成功率': 成功 / max(数量, 1),
        }
    
    def 系统统计(self) -> Dict[str, Any]:
        """🟢 全系统统计"""
        return {
            '信源层': self.信源.统计(),
            '传播层': self.传播.统计(),
            '接收层': self.接收.统计(),
            '龍芯验证': self.龍芯验证.统计(),
            '延迟验证': self.延迟验证.完整性报告(),
        }


