# 🔴 核心数据结构 - 信息包
# ═══════════════════════════════════════════════════════════════
@dataclass
class 信息包:
    """
    🔴 信息传播的基本单元
    
    数学表示: 一个信息包 m = (载荷, 元数据, 签名)
    信息熵: H(m) = -Σ p(x) log p(x)
    """
    标识: str
    载荷: str                          # 实际信息内容
    熵值: float = 0.0                  # 信息量 (比特)
    时间戳: float = field(default_factory=time.time)
    数字签名: str = ""                  # 完整性校验
    来源层: str = ""                    # 产生层标识
    当前层: str = ""                    # 当前所在层
    传播路径: List[str] = field(default_factory=list)
    完整性评分: float = 1.0             # 1.0=完整, 0.0=完全丢失
    
    def __post_init__(self):
        if self.熵值 == 0.0 and self.载荷:
            self.熵值 = self._计算熵(self.载荷)
        if not self.数字签名 and self.载荷:
            self.数字签名 = self._签名(self.载荷)
    
    def _计算熵(self, 内容: str) -> float:
        """🟢 计算信息熵 (香农熵)"""
        if not 内容:
            return 0.0
        频率 = {}
        for 字符 in 内容:
            频率[字符] = 频率.get(字符, 0) + 1
        总长 = len(内容)
        熵 = 0.0
        for 计数 in 频率.values():
            概率 = 计数 / 总长
            熵 -= 概率 * np.log2(概率)
        return 熵
    
    def _签名(self, 内容: str) -> str:
        """🟢 生成数字签名 (SHA256)"""
        return hashlib.sha256(内容.encode('utf-8')).hexdigest()[:16]
    
    def 验证签名(self) -> bool:
        """🔴 验证信息完整性"""
        期望签名 = self._签名(self.载荷)
        return self.数字签名 == 期望签名
    
    def 复制(self) -> '信息包':
        """🟢 创建信息包副本"""
        return 信息包(
            标识=self.标识,
            载荷=self.载荷,
            熵值=self.熵值,
            时间戳=self.时间戳,
            数字签名=self.数字签名,
            来源层=self.来源层,
            当前层=self.当前层,
            传播路径=self.传播路径.copy(),
            完整性评分=self.完整性评分,
        )
    
    def __repr__(self) -> str:
        载荷摘要 = self.载荷[:30] + "..." if len(self.载荷) > 30 else self.载荷
        return f"信息包[{self.标识}](载荷='{载荷摘要}', 熵={self.熵值:.2f}, 完整={self.完整性评分:.2f})"


