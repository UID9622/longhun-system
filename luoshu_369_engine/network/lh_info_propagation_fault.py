        # 截断效应: 随机丢失
        if random.random() < self.截断率:
            self.丢失计数 += 1
            记录 = {
                '时间': time.time(),
                '类型': '截断丢失',
                '信息标识': 信息.标识,
                '原因': f'截断率={self.截断率}触发',
            }
            self.处理日志.append(记录)
            return None  # 信息丢失
        
