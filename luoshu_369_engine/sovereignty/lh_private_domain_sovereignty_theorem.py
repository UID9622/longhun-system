@dataclass
class 数字签名:
    """
    🔴 数字签名结构
    
    签名 = H(私钥, 内容, 时间戳, 随机数)
    验证 = 公钥解密(签名) == H(内容)
    """
    签名人: str
    签名值: str
    时间戳: float = field(default_factory=time.time)
    随机盐: str = ""
    
    def __post_init__(self):
        if not self.随机盐:
            self.随机盐 = hashlib.sha256(str(time.time()).encode()).hexdigest()[:8]
    
    def 验证(self, 内容: str, 公钥: str = "") -> bool:
        """🔴 验证签名有效性"""
        期望签名 = hashlib.sha256(
            f"{self.签名人}:{内容}:{self.时间戳}:{self.随机盐}".encode()
        ).hexdigest()[:16]
        return self.签名值 == 期望签名
    
    def __repr__(self) -> str:
        return f"签名({self.签名人}, {self.签名值[:8]}..., t={self.时间戳:.0f})"


@dataclass
class 主权实体:
    """
    🔴 主权实体 - 拥有私域主权的对象
    
    可以是: 设备、数据记录、AI决策实例
    
    结构同构要求:
        设备主权.Owner = 数据主权.Owner = 决策主权.Owner
        (三层主权归属同一主体)
    """
    标识: str
    名称: str
    层级: 主权层级
    所有者: str                           # 主权归属者
    创建时间: float = field(default_factory=time.time)
    数字指纹: str = ""                     # SHA256唯一标识
    元数据: Dict = field(default_factory=dict)
    授权列表: List['授权记录'] = field(default_factory=list)
    变更日志: List[Dict] = field(default_factory=list)
    
    def __post_init__(self):
        if not self.数字指纹:
            self.数字指纹 = self._计算指纹()
    
    def _计算指纹(self) -> str:
        """🟢 计算实体的数字指纹"""
        内容 = f"{self.标识}:{self.名称}:{self.层级.name}:{self.所有者}"
        return hashlib.sha256(内容.encode()).hexdigest()[:16]
    
    def 签名(self, 私钥: str = "") -> 数字签名:
        """🔴 用所有者私钥签名"""
        内容 = f"{self.标识}:{self.数字指纹}"
        签名值 = hashlib.sha256(
            f"{self.所有者}:{内容}:{time.time()}".encode()
        ).hexdigest()[:16]
        签名 = 数字签名(签名人=self.所有者, 签名值=签名值)
        self.变更日志.append({
            '操作': '签名',
            '时间': time.time(),
            '签名': 签名值,
        })
        return 签名
    
    def 验证所有权(self, 声称所有者: str) -> bool:
        """🔴 验证所有权"""
        return self.所有者 == 声称所有者
    
    def 添加授权(self, 授权: '授权记录'):
        """🟢 添加授权记录"""
        self.授权列表.append(授权)
        self.变更日志.append({
            '操作': '授权',
            '时间': time.time(),
            '被授权方': 授权.被授权方,
        })
    
    def __repr__(self) -> str:
        return f"主权实体[{self.标识}]({self.名称}, {self.层级.name}, 属主={self.所有者})"


@dataclass
class 授权记录:
    """
    🔴 传播授权记录
    
    合法传播需要双方签名:
        1. 所有者签名: 我允许传播
        2. 接收者签名: 我承诺合规使用
    
    未授权传播 = 违规 (触发违规检测)
    """
    授权标识: str
    资源标识: str                        # 被授权的资源
    授权方: str                          # 出让主权的一方
    被授权方: str                        # 获得使用权的一方
    授权范围: str = "只读"                # 只读/读写/完全
    有效期: float = 3600.0               # 🟡 授权有效期(秒)
    创建时间: float = field(default_factory=time.time)
    授权方签名: Optional[数字签名] = None
    被授权方签名: Optional[数字签名] = None
    状态: 授权状态 = 授权状态.未授权
    
    def 双方签名完成(self) -> bool:
        """🔴 检查是否完成双方签名"""
        return (self.授权方签名 is not None and 
                self.被授权方签名 is not None)
    
    def 验证合法性(self) -> bool:
        """
        🔴 验证授权是否合法
        
        条件:
            1. 双方签名都存在
            2. 签名在有效期内
            3. 状态为双方授权
        """
        if not self.双方签名完成():
            return False
        if self.状态 != 授权状态.双方授权:
            return False
        if time.time() - self.创建时间 > self.有效期:
            return False
        return True
    
    def 判定状态(self) -> 授权状态:
        """🔴 判定当前授权状态"""
        if self.状态 == 授权状态.已撤销:
            return 授权状态.已撤销
        if not self.双方签名完成():
            return 授权状态.单方授权 if (self.授权方签名 or self.被授权方签名) else 授权状态.未授权
        if self.验证合法性():
            self.状态 = 授权状态.双方授权
            return 授权状态.双方授权
        return 授权状态.未授权
    
    def __repr__(self) -> str:
        状态标记 = {授权状态.未授权: "❌", 授权状态.单方授权: "⏳", 
                   授权状态.双方授权: "✅", 授权状态.已撤销: "🚫"}
        return f"授权[{self.授权标识}]({状态标记.get(self.状态, '?')} {self.授权方}→{self.被授权方})"


