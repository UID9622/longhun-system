class 私域主权管理器:
    """
    🔴 私域主权管理器 - 统一管理三层主权
    
    功能:
        1. 注册主权实体
        2. 管理传播授权
        3. 执行违规检测
        4. 维护369不变量
    """
    
    def __init__(self):
        self.主权注册表: Dict[str, 主权实体] = {}
        self.授权注册表: Dict[str, 授权记录] = {}
        self.违规检测器 = 违规检测器()
        self.不变量计算器 = 不变量计算器()
        self.操作日志: List[Dict] = []
    
    def 注册主权(self, 实体: 主权实体) -> bool:
        """
        🔴 注册一个主权实体
        
        验证:
            1. 标识唯一
            2. 层级合法
            3. 所有者非空
        """
        if 实体.标识 in self.主权注册表:
            return False
        if not 实体.所有者:
            return False
        
        self.主权注册表[实体.标识] = 实体
        self.操作日志.append({
            '操作': '注册主权',
            '实体': 实体.标识,
            '时间': time.time(),
        })
        return True
    
    def 创建授权(self, 
                 授权方标识: str,
                 被授权方标识: str,
                 资源标识: str,
                 范围: str = "只读") -> Optional[授权记录]:
        """
        🔴 创建传播授权
        
        流程:
            1. 验证授权方拥有资源主权
            2. 生成授权记录
            3. 要求双方签名
        """
        # 通过所有者名称查找主权实体
        授权方实体 = None
        for 实体 in self.主权注册表.values():
            if 实体.所有者 == 授权方标识:
                授权方实体 = 实体
                break
        if not 授权方实体:
            return None
        
        # 验证授权方所有权
        if not 授权方实体.验证所有权(授权方实体.所有者):
            return None
        
        授权标识 = f"AUTH-{授权方标识}-{被授权方标识}-{资源标识}-{int(time.time())}"
        授权 = 授权记录(
            授权标识=授权标识,
            资源标识=资源标识,
            授权方=授权方标识,
            被授权方=被授权方标识,
            授权范围=范围,
        )
        
        # 授权方签名
        签名 = 授权方实体.签名()
        授权.授权方签名 = 签名
        
        # 如果被授权方已注册，自动签名
        被授权方实体 = None
        for 实体 in self.主权注册表.values():
            if 实体.所有者 == 被授权方标识:
                被授权方实体 = 实体
                break
        if 被授权方实体:
            被授权签名 = 被授权方实体.签名()
            授权.被授权方签名 = 被授权签名
            授权.状态 = 授权状态.双方授权
        else:
            授权.状态 = 授权状态.单方授权
        
        self.授权注册表[f"{授权方标识}→{被授权方标识}:{资源标识}"] = 授权
        
        # 记录到实体
        授权方实体.添加授权(授权)
        
        self.操作日志.append({
            '操作': '创建授权',
            '授权': 授权标识,
            '时间': time.time(),
        })
        
        return 授权
    
    def 验证传播(self, 源: str, 目标: str, 资源: str) -> Dict:
        """
        🔴 验证一次传播是否合法
        
        返回验证结果
        """
        事件 = {
            '源实体': 源,
            '目标实体': 目标,
            '资源标识': 资源,
            '传播类型': '数据传播',
        }
        
        违规 = self.违规检测器.检测传播事件(
            事件, self.主权注册表, self.授权注册表
        )
        
        return {
            '合法': len(违规) == 0,
            '违规': 违规,
        }
    
    def 获取主权统计(self) -> Dict:
        """🟢 获取主权统计"""
        层级统计 = {层级.name: 0 for 层级 in 主权层级}
        for 实体 in self.主权注册表.values():
            if 实体.层级.name in 层级统计:
                层级统计[实体.层级.name] += 1
        
        授权统计 = {
            '总数': len(self.授权注册表),
            '双方授权': sum(1 for a in self.授权注册表.values() if a.状态 == 授权状态.双方授权),
            '单方授权': sum(1 for a in self.授权注册表.values() if a.状态 == 授权状态.单方授权),
            '未授权': sum(1 for a in self.授权注册表.values() if a.状态 == 授权状态.未授权),
        }
        
        return {
            '主权实体数': len(self.主权注册表),
            '层级分布': 层级统计,
            '授权统计': 授权统计,
            '违规检测': self.违规检测器.统计(),
        }
    
    def 结构同构验证(self, 所有者: str) -> Dict:
        """
        🔴 验证某所有者的三层主权结构同构
        
        同构 = 三层主权形成链式复形 ∂³ = 0
        """
        相关主权 = []
        for 层级 in [主权层级.设备主权, 主权层级.数据主权, 主权层级.决策主权]:
            for 实体 in self.主权注册表.values():
                if 实体.所有者 == 所有者 and 实体.层级 == 层级:
                    相关主权.append(实体)
                    break
        
        if len(相关主权) != 3:
            return {
                '同构': False,
                '原因': f'所有者 {所有者} 缺少某些层级的主权 (仅有{len(相关主权)}层)',
            }
        
        return 不变量计算器.主权一致性验证(相关主权)


