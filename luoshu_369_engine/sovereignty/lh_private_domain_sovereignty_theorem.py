# 🔴 违规检测算法
# ═══════════════════════════════════════════════════════════════
class 违规检测器:
    """
    🔴 违规检测算法
    
    检测类型:
        1. 未授权传播 - 无双方签名的数据传播
        2. 主权越界 - 上层越权访问下层
        3. 369冲突 - 不变量非零的主权结构
        4. 签名伪造 - 数字签名验证失败
    
    算法复杂度: O(n) 其中 n = 待检测事件数
    """
    
    def __init__(self):
        self.违规记录: List[Dict] = []
        self.检测计数 = 0
        self.命中计数 = 0
    
    def 检测传播事件(self, 
                     传播事件: Dict,
                     主权注册表: Dict[str, 主权实体],
                     授权注册表: Dict[str, 授权记录]) -> List[Dict]:
        """
        🔴 检测一次传播事件是否违规
        
        传播事件格式: {
            '源实体': str,
            '目标实体': str,
            '资源标识': str,
            '传播类型': str,
        }
        
        返回: 违规列表 (空列表 = 无违规)
        """
        self.检测计数 += 1
        违规列表 = []
        
        源 = 传播事件.get('源实体', '')
        目标 = 传播事件.get('目标实体', '')
        资源 = 传播事件.get('资源标识', '')
        
        # 检测1: 未授权传播
        授权键 = f"{源}→{目标}:{资源}"
        授权 = 授权注册表.get(授权键)
        
        if 授权 is None:
            违规 = {
                '类型': '未授权传播',
                '严重级别': '高',
                '描述': f'{源} 向 {目标} 传播 {资源}: 无授权记录',
                '时间': time.time(),
            }
            违规列表.append(违规)
        elif not 授权.验证合法性():
            违规 = {
                '类型': '授权无效',
                '严重级别': '高',
                '描述': f'{源}→{目标}: 授权签名不完整或过期',
                '时间': time.time(),
            }
            违规列表.append(违规)
        
        # 检测2: 主权越界 (决策层直接访问设备层)
        源实体 = 主权注册表.get(源)
        目标实体 = 主权注册表.get(目标)
        if 源实体 and 目标实体:
            if (源实体.层级 == 主权层级.决策主权 and 
                目标实体.层级 == 主权层级.设备主权):
                违规 = {
                    '类型': '主权越界',
                    '严重级别': '严重',
                    '描述': f'决策层({源})直接访问设备层({目标}): 违反分层原则',
                    '时间': time.time(),
                }
                违规列表.append(违规)
        
        # 检测3: 369冲突
        if 源实体 and 目标实体:
            # 检查源的三层主权一致性
            相关主权 = [e for e in 主权注册表.values() 
                      if e.所有者 == 源 and 
                      e.层级 in (主权层级.设备主权, 主权层级.数据主权, 主权层级.决策主权)]
            if len(相关主权) == 3:
                验证结果 = 不变量计算器.主权一致性验证(相关主权)
                if not 验证结果['一致']:
                    违规 = {
                        '类型': '369主权冲突',
                        '严重级别': '严重',
                        '描述': f'{源}的三层主权不一致: 不变量={验证结果["369不变量"]}',
                        '时间': time.time(),
                    }
                    违规列表.append(违规)
        
        if 违规列表:
            self.命中计数 += 1
            self.违规记录.extend(违规列表)
        
        return 违规列表
    
    def 批量检测(self,
                 事件列表: List[Dict],
                 主权注册表: Dict[str, 主权实体],
                 授权注册表: Dict[str, 授权记录]) -> Dict:
        """
        🟢 批量检测传播事件
        
        返回: {
            '总事件': int,
            '违规事件': int,
            '违规详情': List[Dict],
        }
        """
        所有违规 = []
        for 事件 in 事件列表:
            违规 = self.检测传播事件(事件, 主权注册表, 授权注册表)
            所有违规.extend(违规)
        
        return {
            '总事件': len(事件列表),
            '违规事件': len([v for v in 所有违规 if v]),
            '违规率': len([v for v in 所有违规 if v]) / max(len(事件列表), 1),
            '违规详情': 所有违规,
        }
    
    def 统计(self) -> Dict:
        """🟢 检测统计"""
        命中率 = self.命中计数 / max(self.检测计数, 1)
        return {
            '总检测': self.检测计数,
            '违规命中': self.命中计数,
            '命中率': 命中率,
            '总违规记录': len(self.违规记录),
        }


