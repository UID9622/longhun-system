class 决策稳定性分析器:
    """
    决策类别稳定性分析 — 分析不同决策类别在369框架下的稳定性
    
    稳定性定义: 多次测量后，结果分布是否保持一致的统计特性
    高稳定性决策: 结果集中在某个不动点 (3/6/9)
    低稳定性决策: 结果在三个基矢间大幅波动
    """

    def __init__(self):
        self.分析历史: List[Dict] = []
        print("🟢 决策稳定性分析器初始化完成")

    def 分析稳定性(self, 量子态实例: 量子态, 测量次数: int = 1000) -> Dict[str, Any]:
        """
        分析给定量子态的决策稳定性
        
        返回:
            - 稳定性评分 (0~1，越高越稳定)
            - 主导基矢 (概率最高的基矢)
            - 香农熵 (衡量不确定性)
            - 三色审计结果
        
        🟢 — 统计验证通过
        """
        # 执行批量测量
        框架 = 测量框架("稳定性分析")
        统计 = 框架.批量测量(量子态实例, 测量次数)

        # 计算频率分布
        频率 = np.array([统计[k]["实验频率"] for k in [3, 6, 9]])
        理论概率 = 量子态实例.概率分布

        # 稳定性评分: 频率与理论概率的吻合度
        偏差 = np.abs(频率 - 理论概率).mean()
        稳定性评分 = max(0, 1 - 偏差 * 5)  # 归一化到0~1

        # 主导基矢
        主导索引 = np.argmax(频率)
        主导基矢 = [3, 6, 9][主导索引]

        # 香农熵 (衡量不确定性，越小越确定)
        香农熵 = -np.sum(频率 * np.log2(频率 + 1e-15))
        最大熵 = np.log2(3)  # 三维均匀分布的熵
        标准化熵 = 香农熵 / 最大熵  # 0=完全确定, 1=完全随机

        # 决策类别判定
        if 稳定性评分 > 0.9 and 主导基矢 in 不动点集:
            决策类别 = "🟢 高稳定性369决策"
            建议 = "可直接执行，风险低"
        elif 稳定性评分 > 0.7:
            决策类别 = "🟡 中等稳定性决策"
            建议 = "需谨慎评估，存在一定波动"
        else:
            决策类别 = "🔴 低稳定性决策"
            建议 = "建议重新分析或获取更多数据"

        分析结果 = {
            "稳定性评分": round(稳定性评分, 4),
            "主导基矢": 主导基矢,
            "主导概率": round(频率[主导索引], 4),
            "香农熵": round(香农熵, 4),
            "标准化熵": round(标准化熵, 4),
            "决策类别": 决策类别,
            "建议": 建议,
            "频率分布": {3: round(频率[0], 4), 6: round(频率[1], 4), 9: round(频率[2], 4)},
            "理论分布": {3: round(理论概率[0], 4), 6: round(理论概率[1], 4), 9: round(理论概率[2], 4)},
        }

        self.分析历史.append(分析结果)
        return 分析结果

    def 比较稳定性(self, 态列表: List[Tuple[str, 量子态]], 测量次数: int = 1000) -> None:
        """
        比较多个量子态的稳定性
        🟢
        """
        print("\n" + "=" * 70)
        print("📊 决策稳定性对比分析")
        print("=" * 70)
        print(f"{'决策名称':<20} {'稳定评分':>8} {'主导':>6} {'主导概率':>10} {'熵':>8} {'类别':<20}")
        print("-" * 70)

        for 名称, 态 in 态列表:
            结果 = self.分析稳定性(态, 测量次数)
            print(f"{名称:<20} {结果['稳定性评分']:>8.4f} "
                  f"{结果['主导基矢']:>6} {结果['主导概率']:>10.4f} "
                  f"{结果['香农熵']:>8.4f} {结果['决策类别']:<20}")

        print("=" * 70)


