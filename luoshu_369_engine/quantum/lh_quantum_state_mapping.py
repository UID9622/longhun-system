@dataclass
class 量子态:
    """
    量子态类 — 表示369三维空间中的量子叠加态
    
    |ψ⟩ = α|3⟩ + β|6⟩ + γ|9⟩
    
    其中 α, β, γ 为复数振幅，满足 |α|² + |β|² + |γ|² = 1
    
    属性:
        振幅: 三维复向量 [α, β, γ]
        标签: 可选的态标签名称
    """
    振幅: np.ndarray
    标签: str = "未命名量子态"

    def __post_init__(self):
        """初始化后自动归一化验证 🟢"""
        self.振幅 = np.array(self.振幅, dtype=complex)
        if len(self.振幅) != 维数:
            raise ValueError(f"🔴 振幅向量维数必须为{维数}，当前为{len(self.振幅)}")
        self.归一化()

    # ── 基本属性 ──

    @property
    def α(self) -> complex:
        """|3⟩ 方向的振幅 🟢"""
        return self.振幅[0]

    @property
    def β(self) -> complex:
        """|6⟩ 方向的振幅 🟢"""
        return self.振幅[1]

    @property
    def γ(self) -> complex:
        """|9⟩ 方向的振幅 🟢"""
        return self.振幅[2]

    @property
    def 概率分布(self) -> np.ndarray:
        """
        测量概率分布: P(i) = |振幅[i]|²
        返回三维概率向量 [P(3), P(6), P(9)]
        🟢
        """
        return np.abs(self.振幅) ** 2

    @property
    def 归一化验证(self) -> bool:
        """验证概率和是否为1（允许浮点误差） 🟢"""
        return np.isclose(np.sum(self.概率分布), 1.0)

    # ── 类方法：构造标准基矢 ──

    @classmethod
    def 基矢三(cls) -> "量子态":
        """构造 |3⟩ 基矢态 🟢"""
        return cls(振幅=[1, 0, 0], 标签="|3⟩")

    @classmethod
    def 基矢六(cls) -> "量子态":
        """构造 |6⟩ 基矢态 🟢"""
        return cls(振幅=[0, 1, 0], 标签="|6⟩")

    @classmethod
    def 基矢九(cls) -> "量子态":
        """构造 |9⟩ 基矢态 🟢"""
        return cls(振幅=[0, 0, 1], 标签="|9⟩")

    @classmethod
    def 等概率叠加态(cls) -> "量子态":
        """
        构造等概率叠加态: |ψ⟩ = (|3⟩ + |6⟩ + |9⟩)/√3
        对应于完全不确定的决策状态 🟢
        """
        幅 = 1.0 / np.sqrt(3)
        return cls(振幅=[幅, 幅, 幅], 标签="等概率叠加态")

    @classmethod
    def 从随机振幅构造(cls, 标签: str = "随机态") -> "量子态":
        """
        从随机复数振幅构造量子态
        用于蒙特卡罗模拟 🟢
        """
        实部 = np.random.randn(维数)
        虚部 = np.random.randn(维数)
        幅 = 实部 + 1j * 虚部
        return cls(振幅=幅, 标签=标签)

    # ── 核心运算 ──

    def 归一化(self) -> None:
        """将态向量归一化 🟢"""
        模 = np.linalg.norm(self.振幅)
        if 模 > 1e-15:
            self.振幅 = self.振幅 / 模

    def 测量(self) -> Tuple[int, float]:
        """
        量子测量模拟 — 波函数坍缩
        
        过程:
          1. 根据概率分布 |振幅|² 随机选择一个基矢
          2. 返回 (测量结果, 对应概率)
        
        返回:
            (测量结果, 概率) — 结果为 3, 6, 或 9
        
        🟢 — 核心算法已通过验证
        """
        概率 = self.概率分布
        结果索引 = np.random.choice(维数, p=概率)
        结果值 = [3, 6, 9][结果索引]
        结果概率 = 概率[结果索引]
        return 结果值, 结果概率

    def 多次测量(self, 次数: int) -> Dict[int, int]:
        """
        进行多次测量，统计频率分布
        
        参数:
            次数: 测量重复次数
        
        返回:
            字典 {测量结果: 出现次数}
        
        🟢 — 大数定律验证通过
        """
        统计 = {3: 0, 6: 0, 9: 0}
        for _ in range(次数):
            结果, _ = self.测量()
            统计[结果] += 1
        return 统计

    def 内积(self, 另一个态: "量子态") -> complex:
        """计算两个量子态的内积 ⟨self|另一个态⟩ 🟢"""
        return np.vdot(self.振幅, 另一个态.振幅)

    def 保真度(self, 另一个态: "量子态") -> float:
        """
        计算两个量子态的保真度 F = |⟨self|另一个态⟩|²
        保真度=1表示完全相同，=0表示正交 🟢
        """
        return np.abs(self.内积(另一个态)) ** 2

    def 应用算符(self, 算符矩阵: np.ndarray) -> "量子态":
        """
        将线性算符作用于当前量子态
        |ψ'⟩ = Û|ψ⟩
        
        参数:
            算符矩阵: 3×3 复矩阵
        
        🟢
        """
        if 算符矩阵.shape != (维数, 维数):
            raise ValueError(f"🔴 算符矩阵必须为{维数}×{维数}")
        新振幅 = 算符矩阵 @ self.振幅
        return 量子态(振幅=新振幅, 标签=f"{self.标签}(变换后)")

    def __repr__(self) -> str:
        """字符串表示 🟢"""
        分量 = []
        for i, (标签, 幅) in enumerate(zip(基矢标签, self.振幅)):
            if abs(幅) > 1e-10:
                分量.append(f"{幅:.4f}{标签}")
        return f"量子态[{self.标签}] = " + " + ".join(分量) if 分量 else "零态"


