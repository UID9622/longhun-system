def 数字根(数值: int) -> int:
    """
    计算一个整数的数字根（Digital Root）。
    数字根是将一个数的各位数字反复相加直到只剩一位数。
    369规律中，数字根为3/6/9的数构成不动点集。
    
    例: 123 -> 1+2+3=6 -> 数字根为6 (🟢 属于不动点集)
        58  -> 5+8=13 -> 1+3=4 -> 数字根为4 (🟡 不属于不动点集)
    """
    if 数值 == 0:
        return 0
    余数 = 数值 % 9
    return 9 if 余数 == 0 else 余数


def 是否不动点(数值: int) -> bool:
    """判断一个数的数字根是否属于369不动点集 🟢"""
    return 数字根(数值) in 不动点集


def 三色标记(数值: int) -> str:
    """
    三色审计系统：根据数字根返回对应标记
    🟢 绿色 = dr ∈ {3,6,9}（低风险，通过）
    🟡 黄色 = dr ∈ {1,2,4,5,7,8}（中风险，警告）
    🔴 红色 = dr = 冲突/违规（高风险，阻断）
    """
    根 = 数字根(数值)
    if 根 in 不动点集:
        return "🟢"
    elif 根 == 0:
        return "🔴"
    else:
        return "🟡"


