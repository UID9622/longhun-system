@dataclass
class 维度配置:
    """单个呼吸维度的配置参数"""
    维度编号: int                           # 1-10
    维度名称: str                           # 如"表意识"、"潜意识"等
    可见性: 维度可见性                      # 公开/指定人/私人
    基础频率: float = 1.0                   # 呼吸频率(Hz)
    深度系数: float = 1.0                   # 呼吸深度(0-10)
    访问白名单: Set[str] = field(default_factory=set)  # 指定人名单


@dataclass
class 呼吸包:
    """一次呼吸循环的数据包"""
    维度编号: int
    呼吸状态: 呼吸状态
    时间戳: float
    数据载荷: Any = None
    元数据: Dict[str, Any] = field(default_factory=dict)


