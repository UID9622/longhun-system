class 呼吸状态(Enum):
    """呼吸三态：吸入、呼出、屏息"""
    吸入 = auto()   # 接收外部信息
    呼出 = auto()   # 输出表达
    屏息 = auto()   # 内部处理


class 维度可见性(Enum):
    """维度可见性分级"""
    公开 = auto()       # 维度1-7: 所有人可见
    指定人 = auto()     # 维度8-9: 授权人员可见
    私人 = auto()       # 维度10: 仅自己可见


class 维度状态(Enum):
    """单个维度的运行状态"""
    活跃 = auto()       # 正常运行中
    休眠 = auto()       # 低功耗待机
    屏蔽 = auto()       # 人为关闭


