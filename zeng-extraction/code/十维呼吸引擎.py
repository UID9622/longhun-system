# 🔴 呼吸循环管理器
# ============================================================

class 呼吸循环:
    """
    管理单个维度的呼吸循环节律
    
    控制吸入->屏息->呼出的完整周期，
    支持可调节的心跳节律。
    """

    def __init__(
        self,
        维度: 呼吸维度,
        吸入时长: float = 1.0,
        屏息时长: float = 0.5,
        呼出时长: float = 1.0
    ) -> None:
        self.维度 = 维度
        self.吸入时长 = 吸入时长
        self.屏息时长 = 屏息时长
        self.呼出时长 = 呼出时长
        self.运行中: bool = False
        self.总循环数: int = 0

    @property
    def 周期时长(self) -> float:
        """一个完整呼吸周期的时长"""
        return self.吸入时长 + self.屏息时长 + self.呼出时长

    @property
    def 当前频率(self) -> float:
        """当前呼吸频率(Hz)"""
        if self.周期时长 > 0:
            return 1.0 / self.周期时长 * self.维度.配置.基础频率
        return 0.0

    async def 运行(self) -> None:
        """
        🔴 核心架构：异步呼吸主循环
        
        持续运行吸入->屏息->呼出的循环，
        直到被停止。
        """
        self.运行中 = True
        print(f"  [呼吸循环] {self.维度.获取维度标识()} 启动 | 频率: {self.当前频率:.2f}Hz")

        while self.运行中:
            try:
                # 🟡 状态控制：吸入阶段
                await asyncio.sleep(self.吸入时长)
                if not self.运行中:
                    break

                # 🟡 状态控制：屏息阶段（处理）
                self.维度.屏息()
                await asyncio.sleep(self.屏息时长)
                if not self.运行中:
                    break

                # 🟡 状态控制：呼出阶段（输出）
                self.维度.呼出()
                await asyncio.sleep(self.呼出时长)

                self.总循环数 += 1

            except asyncio.CancelledError:
                print(f"  [呼吸循环] {self.维度.获取维度标识()} 收到取消信号")
                break
            except Exception as e:
                print(f"  [呼吸循环错误] {e}")
                await asyncio.sleep(0.5)

        print(f"  [呼吸循环] {self.维度.获取维度标识()} 已停止 | 总循环: {self.总循环数}")

    def 停止(self) -> None:
        """停止呼吸循环"""
        self.运行中 = False

    def 调节频率(self, 新频率: float) -> None:
        """
        🟡 调节呼吸频率
        
        新频率: 目标频率(Hz)，范围 0.1-10.0
        """
        新频率 = max(0.1, min(10.0, 新频率))
        目标周期 = 1.0 / 新频率
        # 按比例分配三个阶段
        比例和 = self.吸入时长 + self.屏息时长 + self.呼出时长
        if 比例和 > 0:
            self.吸入时长 = 目标周期 * (self.吸入时长 / 比例和)
            self.屏息时长 = 目标周期 * (self.屏息时长 / 比例和)
            self.呼出时长 = 目标周期 * (self.呼出时长 / 比例和)
        self.维度.配置.基础频率 = 新频率


